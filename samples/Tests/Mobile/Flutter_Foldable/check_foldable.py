"""Foldables end to end (plan MOTION_VARIANTS_FOLDABLES slice E).

1. Writes test/devices_gen.dart from radide/devices.py: every foldable preset x orientation x posture with its
   display features (screen coords) and the TwoPane panes computed by devices.two_pane().
2. `flutter test` (offline): the Flutter TwoPane of lib/main.dart, driven by tester.view.displayFeatures, must
   give the same panes as Python.  SKIP when Flutter is not installed.
3. Android foldable emulator (SKIP when the SDK / emulator is missing, or RADIDE_SKIP_EMULATOR=1): creates the
   AVD "RADIDE_Fold" if it does not exist yet (other AVDs are never touched), boots it headless on port 5600,
   switches Folded / HalfOpened / Flat with features.mobile.set_posture and verifies the device state and that
   the display size changes when folded; the emulator it started is always stopped.

    python samples/Tests/Mobile/Flutter_Foldable/check_foldable.py
"""
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT))
from radide import devices as D  # noqa: E402

NO_WIN = getattr(subprocess, "CREATE_NO_WINDOW", 0)
RESULTS = []


def check(name, cond, detail=""):
    RESULTS.append((name, bool(cond)))
    print(("PASS " if cond else "FAIL ") + name + ("" if cond else f"  [{str(detail)[:1500]}]"), flush=True)


def skip(name, why):
    print(f"SKIP {name}: {why}", flush=True)


# ---------------------------------------------------------------- 1. cases from radide/devices.py
cases = []
for did in D.FOLDABLE_IDS:
    for o in D.ORIENTATIONS:
        for p in D.POSTURES:
            w, h = D.screen_size(did, o, p)
            feats = D.display_features(did, o, p)
            hinge = D.hinge_screen_rect(did, o, p) if D.is_separating(did, p) else None
            res = D.two_pane(w, h, hinge=hinge)
            cases.append({"name": f"{did} {o} {p}", "size": [w, h], "features": feats,
                          "panes": [list(res["panes"][0]), list(res["panes"][1]) if res["panes"][1] else None]})
dart = ["// Generated by check_foldable.py from radide/devices.py - do not edit.",
        "const List<Map<String, Object>> foldCases = ["]
for c in cases:
    dart.append("  " + json.dumps(c).replace("null", "'__null__'").replace('"', "'")
                .replace("'__null__'", "null") + ",")
dart.append("];")
gen = HERE / "test" / "devices_gen.dart"
gen.write_text("\n".join(dart) + "\n", encoding="utf-8")
check("devices_gen.dart written", gen.is_file() and len(cases) == len(D.FOLDABLE_IDS) * 6, len(cases))
check("Duo landscape flat splits at the hinge",
      next(c for c in cases if c["name"] == "surface_duo2 Landscape Flat")["panes"] == [[0, 0, 540, 720],
                                                                                        [566, 0, 540, 720]])

# ---------------------------------------------------------------- 2. flutter test
flutter = shutil.which("flutter") or next((p for p in (r"C:\flutter\bin\flutter.bat",) if Path(p).is_file()), None)
if not flutter:
    skip("flutter test", "Flutter SDK not found")
else:
    def fl(*args, timeout=600):
        return subprocess.run([flutter, *args], cwd=HERE, capture_output=True, text=True, timeout=timeout,
                              creationflags=NO_WIN, encoding="utf-8", errors="replace")
    r = fl("pub", "get", "--offline")
    if r.returncode != 0:
        r = fl("pub", "get")
    check("flutter pub get", r.returncode == 0, r.stdout[-800:] + r.stderr[-800:])
    r = fl("analyze", "--no-fatal-infos")
    check("flutter analyze clean", r.returncode == 0, r.stdout[-1500:])
    r = fl("test", "--reporter", "expanded")
    tail = (r.stdout or "")[-1500:]
    check(f"flutter test ({len(cases)} foldable cases)", r.returncode == 0 and "All tests passed" in r.stdout, tail)

# ---------------------------------------------------------------- 3. Android foldable emulator
if os.environ.get("RADIDE_SKIP_EMULATOR") == "1":
    skip("foldable emulator", "RADIDE_SKIP_EMULATOR=1")
else:
    from radide.features import mobile as FM
    emu, adb = FM.emulator_exe(), FM.adb_exe()
    if not emu or not adb or not FM.avdmanager_exe():
        skip("foldable emulator", "Android SDK emulator / adb / avdmanager not found")
    else:
        before_avds = set(FM.list_avds())
        ok, msg = FM.foldable_avd(FM.FOLD_AVD, log=lambda t: print(t, end=""))
        check("RADIDE_Fold AVD exists", ok and FM.FOLD_AVD in FM.list_avds(), msg)
        check("no other AVD changed", (before_avds - {FM.FOLD_AVD}) <= set(FM.list_avds()))
        serial = "emulator-5600"
        if ok and serial in FM._adb_devices(adb):
            skip("emulator boot", f"{serial} is already in use - not touching it")
        elif ok:
            proc = subprocess.Popen([emu, "-avd", FM.FOLD_AVD, "-port", "5600", "-no-window", "-no-audio",
                                     "-no-boot-anim", "-no-snapshot", "-gpu", "swiftshader_indirect"],
                                    stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, creationflags=NO_WIN)
            try:
                t0, booted = time.time(), False
                while time.time() - t0 < 900 and proc.poll() is None:
                    if serial in FM._adb_devices(adb) and FM._adb(serial, "shell", "getprop",
                                                                  "sys.boot_completed").strip() == "1":
                        booted = True
                        break
                    time.sleep(5)
                check("emulator booted", booted, f"exit={proc.poll()}")
                if booted:
                    time.sleep(10)
                    states = FM.device_states(serial)
                    print("device states:", states, flush=True)
                    check("device states listed", len(states) >= 2, states)
                    sizes = {}
                    for posture in ("Folded", "HalfOpened", "Flat"):
                        good, now = FM.set_posture(serial, posture)
                        time.sleep(4)
                        wm = FM._adb(serial, "shell", "wm", "size").strip()
                        sizes[posture] = wm
                        check(f"posture {posture} -> {now}", good, now)
                    print("wm size per posture:", sizes, flush=True)
                    check("folded screen differs from flat", sizes.get("Folded") != sizes.get("Flat"), sizes)
            finally:
                FM._adb(serial, "emu", "kill")
                try:
                    proc.wait(60)
                except subprocess.TimeoutExpired:
                    proc.kill()
                check("emulator stopped", proc.poll() is not None)

ok = sum(c for _, c in RESULTS)
print(f"{ok}/{len(RESULTS)} passed; FAILED: {[n for n, c in RESULTS if not c] or 'none'}")
sys.exit(0 if ok == len(RESULTS) else 1)
