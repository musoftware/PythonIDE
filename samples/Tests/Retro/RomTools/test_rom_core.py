"""ROM workbench core tests (no Qt): IPS / UPS / BPS against hand-computed vectors and random round trips,
header detection + checksum repair on synthetic ROMs, .tbl tables, the hex buffer (undo / search), the ROM
Hacking project (build, capture edits, original never written) and the command line.

    python samples/Tests/Retro/RomTools/test_rom_core.py

Every ROM here is generated by radide/retro/rom/synth.py (original homebrew bytes) - no game data.
"""
import os
import random
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT))

from radide.retro.rom import patches as P, synth  # noqa: E402
from radide.retro.rom.buffer import HexBuffer, hex_pattern, text_pattern  # noqa: E402
from radide.retro.rom.detect import detect, detect_system, fix_checksum  # noqa: E402
from radide.retro.rom.project import RomProject, new_project  # noqa: E402
from radide.retro.rom.tbl import Table, relative_search, table_from_relative  # noqa: E402

RESULTS = []


def check(name, cond, detail=""):
    RESULTS.append((name, bool(cond)))
    print(("PASS " if cond else "FAIL ") + name + ("" if cond else f"  [{str(detail)[:500]}]"), flush=True)


def le32(v):
    return (v & 0xFFFFFFFF).to_bytes(4, "little")


def crc(b):
    return zlib.crc32(b) & 0xFFFFFFFF


# ------------------------------------------------------------------ VLQ
check("vlq 0", P.vlq_encode(0) == b"\x80")
check("vlq 127", P.vlq_encode(127) == b"\xff")
check("vlq 128", P.vlq_encode(128) == b"\x00\x80")
check("vlq 16512", P.vlq_encode(16512) == b"\x00\x00\x80")
check("vlq round trip", all(P.vlq_decode(P.vlq_encode(v), 0) == (v, len(P.vlq_encode(v)))
                            for v in list(range(0, 70000, 7)) + [2 ** 32, 2 ** 40 + 5]))

# ------------------------------------------------------------------ IPS vectors
src = bytes(8)
tgt = b"\x00\x00\xab\xcd\x00\x00\x00\x00"
want = b"PATCH" + b"\x00\x00\x02" + b"\x00\x02" + b"\xab\xcd" + b"EOF"
check("IPS create: one record", P.ips_create(src, tgt) == want, P.ips_create(src, tgt))
check("IPS apply: one record", P.ips_apply(src, want) == tgt)
src = bytes(64)
tgt = bytes(16) + b"\x11" * 20 + bytes(28)
want = b"PATCH" + b"\x00\x00\x10" + b"\x00\x00" + b"\x00\x14" + b"\x11" + b"EOF"
check("IPS create: RLE record", P.ips_create(src, tgt) == want, P.ips_create(src, tgt))
check("IPS apply: RLE record", P.ips_apply(src, want) == tgt)
src = bytes(range(16))
tgt = bytes(range(8))
want = b"PATCH" + b"EOF" + b"\x00\x00\x08"
check("IPS create: truncation", P.ips_create(src, tgt) == want, P.ips_create(src, tgt))
check("IPS apply: truncation", P.ips_apply(src, want) == tgt)
check("IPS apply: grows the file", P.ips_apply(b"\x01", b"PATCH\x00\x00\x04\x00\x01\x09EOF") == b"\x01\x00\x00\x00\x09")
big_src = bytes(0x454F50)
big_tgt = bytearray(big_src)
big_tgt[0x454F46] = 0x77           # the "EOF" offset
p = P.ips_create(big_src, bytes(big_tgt))
check("IPS: a change at offset 0x454F46 is written from 0x454F45", P.ips_apply(big_src, p) == bytes(big_tgt) and
      b"\x45\x4f\x45" in p and p.count(b"EOF") == 1, p[:20])
try:
    P.ips_apply(b"x", b"PATCH\x00\x00")
    check("IPS: truncated patch raises", False)
except P.PatchError:
    check("IPS: truncated patch raises", True)

# ------------------------------------------------------------------ UPS vectors
src, tgt = b"ABCD", b"ABXD"
body = b"UPS1" + b"\x84" + b"\x84" + b"\x82" + bytes([ord("C") ^ ord("X")]) + b"\x00" + le32(crc(src)) + le32(crc(tgt))
want = body + le32(crc(body))
check("UPS create: vector", P.ups_create(src, tgt) == want, P.ups_create(src, tgt).hex())
check("UPS apply: vector", P.ups_apply(src, want) == tgt)
check("UPS apply: reverse (target -> source)", P.ups_apply(tgt, want) == src)
try:
    P.ups_apply(b"ZZZZ", want)
    check("UPS: wrong source CRC32 raises", False)
except P.PatchError as e:
    check("UPS: wrong source CRC32 raises", "different file" in str(e), e)
bad = bytearray(want)
bad[8] ^= 1
try:
    P.ups_apply(src, bytes(bad))
    check("UPS: damaged patch raises", False)
except P.PatchError as e:
    check("UPS: damaged patch raises", "damaged" in str(e), e)

# ------------------------------------------------------------------ BPS vectors
src, tgt = b"ABCD", b"ABXD"
body = b"BPS1" + b"\x84\x84\x80" + b"\x89" + b"ABX" + b"\x80" + le32(crc(src)) + le32(crc(tgt))
want = body + le32(crc(body))
check("BPS create: vector (TargetRead 3 + SourceRead 1)", P.bps_create(src, tgt) == want, P.bps_create(src, tgt).hex())
check("BPS apply: vector", P.bps_apply(src, want) == tgt)
# hand-written: SourceCopy 4 from +4, TargetRead "A", TargetCopy 3 (overlapping) from 4
src, tgt = b"ABCDEFGH", b"EFGHAAAA"
body = b"BPS1" + b"\x88\x88\x80" + b"\x8e\x88" + b"\x81A" + b"\x8b\x88" + le32(crc(src)) + le32(crc(tgt))
hand = body + le32(crc(body))
check("BPS apply: SourceCopy + TargetCopy (hand-made)", P.bps_apply(src, hand) == tgt)
meta = P.bps_create(b"abc", b"abd", metadata="<author>RAD IDE</author>")
check("BPS metadata kept", P.bps_info(meta).metadata == "<author>RAD IDE</author>" and
      P.bps_apply(b"abc", meta) == b"abd")
try:
    P.bps_apply(b"ABCDEFGX", hand)
    check("BPS: wrong source raises", False)
except P.PatchError:
    check("BPS: wrong source raises", True)

# ------------------------------------------------------------------ random round trips
rnd = random.Random(2026)
ok = True
for trial in range(150):
    s = rnd.randbytes(rnd.randint(0, 4000))
    t = bytearray(s)
    for _ in range(rnd.randint(0, 15)):
        op = rnd.random()
        if op < .4 and t:
            i = rnd.randrange(len(t))
            t[i:i + rnd.randint(1, 30)] = rnd.randbytes(rnd.randint(1, 30))
        elif op < .6:
            i = rnd.randrange(len(t) + 1)
            t[i:i] = bytes([rnd.randrange(256)]) * rnd.randint(1, 90)
        elif op < .8 and len(s) > 50:
            j = rnd.randrange(len(s) - 40)
            i = rnd.randrange(len(t) + 1)
            t[i:i] = s[j:j + 40]
        else:
            k = rnd.randrange(len(t) + 1)
            del t[k:k + rnd.randint(0, 30)]
    t = bytes(t)
    for fmt in ("ips", "ups", "bps"):
        if P.apply_patch(s, P.create_patch(s, t, fmt)) != t:
            ok = False
            print("round trip failed", trial, fmt)
check("150 random round trips x IPS / UPS / BPS", ok)
mb = random.Random(1).randbytes(2 << 20)
mod = bytearray(mb)
mod[100:110] = b"RAD IDE!!!"
mod[1 << 20:1 << 20] = mb[5000:9000]            # inserted block: BPS finds it as SourceCopy
mod = bytes(mod)
bp = P.create_patch(mb, mod, "bps")
check("BPS: 2 MB ROM with an inserted block -> small patch", len(bp) < 200 and P.apply_patch(mb, bp) == mod, len(bp))

# ------------------------------------------------------------------ detection + checksums
expect = {"nes": "nes", "gb": "gb", "gbc": "gbc", "gba": "gba", "snes": "snes", "genesis": "genesis",
          "atari2600": "atari2600", "atari7800": "atari7800", "car": "atari8bit", "atr": "atari8bit",
          "xex": "atari8bit", "prg": "c64", "d64": "c64", "t64": "c64", "tap": "zxspectrum", "tzx": "zxspectrum",
          "sna": "zxspectrum", "exe": "dos", "com": "dos"}
for key, (fn, make) in synth.ALL.items():
    info = detect(make(), fn)
    check(f"detect {fn} -> {expect[key]}", info.system == expect[key], (info.system, info.format, info.rows[:3]))
nes = detect(synth.nes_rom(prg_banks=2, chr_banks=1, mapper=4, battery=True), "x.nes")
rows = dict(nes.rows)
check("NES header: mapper 4, 32 KB PRG, battery", rows.get("Mapper", "").startswith("4 - MMC3") and
      rows.get("PRG ROM") == "32 KB" and "battery yes" in rows.get("Flags 6", ""), rows)
n2 = detect(synth.nes_rom(nes2=True), "x.nes")
check("NES 2.0 recognised", n2.format == "NES 2.0", n2.format)
check("2600 bankswitching: 4K / F8SC / E0 / F6 / F4SC", [detect(d, n).format.split("(")[1][:-1] for d, n in (
    (synth.a26_rom(1), "a.a26"), (synth.a26_rom(2, True), "b.a26"), (synth.a26_e0_rom(), "c.bin"),
    (synth.a26_rom(4), "d.a26"), (synth.a26_rom(8, True), "e.a26"))] == ["4K", "F8SC", "E0", "F6", "F4SC"])
snes_h = detect(synth.snes_rom(hirom=True, size_kb=96, copier=True), "h.smc")
check("SNES HiROM + copier header + non power of two size: checksum OK", snes_h.format == "HiROM" and
      snes_h.checksum_ok, snes_h.rows)
for key in ("gb", "gbc", "snes", "genesis", "car", "gba"):
    fn, make = synth.ALL[key]
    d = bytearray(make())
    if key == "gba":
        d[0xA0] ^= 0x20                         # change the title: the complement check breaks
    else:
        d[len(d) // 2 + 3] ^= 0x5A
    before = detect(bytes(d), fn).checksum_ok
    fixed, msg = fix_checksum(bytes(d), fn)
    after = detect(fixed, fn)
    changed = sum(1 for a, b in zip(fixed, d) if a != b)
    check(f"fix checksum {fn}: broken -> OK, only header bytes changed", before is False and after.checksum_ok and
          0 < changed <= 4, (before, after.checksum_ok, changed, msg))
try:
    fix_checksum(synth.nes_rom(), "x.nes")
    check("fix checksum on NES raises (no checksum)", False)
except ValueError:
    check("fix checksum on NES raises (no checksum)", True)
d64 = detect(synth.d64_image(), "x.d64")
check("D64 directory listing", d64.listing and d64.listing[0][1] == '"HELLO"' and d64.listing[0][2] == "PRG",
      d64.listing)
prg = detect(synth.c64_prg(), "x.prg")
check("C64 PRG: BASIC SYS line", prg.listing and prg.listing[0][0] == "10 SYS2061", prg.listing)
tap = detect(synth.zx_tap(), "x.tap")
check("ZX TAP: header block + checksums", tap.checksum_ok and 'Bytes (CODE): "radide"' in tap.listing[0][2],
      tap.listing)
xex = detect(synth.xex_file(), "x.xex")
check("XEX: segments + run address", dict(xex.rows).get("Run address") == "$2000", xex.rows)
atr = detect(synth.atr_image(), "x.atr")
check("ATR: DOS 2 directory", atr.listing and atr.listing[0][0] == "HELLO.BAS", atr.listing)
mz = detect(synth.dos_mz(), "x.exe")
check("MZ: SS:SP + CS:IP", dict(mz.rows).get("Initial SS:SP") == "0000:0100" and dict(mz.rows).get("Initial CS:IP") == "0000:0000", mz.rows)
ips_info = detect(P.ips_create(bytes(32), b"\x01" + bytes(31)), "x.ips")
check("patch file detected with records listing", ips_info.system == "patch" and len(ips_info.listing) == 1)
tmp = Path(tempfile.mkdtemp(prefix="radide-rom-"))
(tmp / "demo.nes").write_bytes(synth.nes_rom())
(tmp / "demo.sfc").write_bytes(synth.snes_rom())
check("detect_system gives emulator ids", detect_system(tmp / "demo.nes") == "nes" and
      detect_system(tmp / "demo.sfc") == "snes")

# ------------------------------------------------------------------ tables
t = Table.parse("; test\n41=A\n42=B\n4243=BC\n/FF=<end>\n*FE\n$20= \n")
check("tbl decode greedy", t.decode(b"ABCAB\xfe\xff") == "ABCAB\n<end>", t.decode(b"ABCAB\xfe\xff"))
check("tbl encode greedy + raw [XX]", t.encode("BCA[10]") == b"BCA\x10" and t.encode("Z") is None)
words = b"\x00\x01" + bytes([0x80 + i for i in (7, 4, 11, 11, 14)]) + b"\x00"
hits = relative_search(words, "HELLO")
check("relative search finds HELLO with A=0x80", hits and hits[0] == (2, 0x87), hits)
rt = table_from_relative(0x87, "H")
check("table from relative search", rt.decode(words[2:7]) == "HELLO")

# ------------------------------------------------------------------ buffer
b = HexBuffer(b"\x00" * 16)
b.overwrite(2, b"\xaa", merge_key="hexhi")
b.overwrite(2, b"\xab", merge_key="hexlo")
check("buffer: nibble typing is one undo step", len(b.undo_stack) == 1)
b.insert(4, b"XYZ")
b.delete(0, 1)
check("buffer: edits", bytes(b.data[:6]) == b"\x00\xab\x00XYZ" and len(b) == 18, bytes(b.data))
b.undo(); b.undo(); b.undo()
check("buffer: undo restores", bytes(b.data) == bytes(16) and not b.modified)
b.redo()
check("buffer: redo", b.data[2] == 0xAB and b.modified)
b = HexBuffer(b"..A9 05 8D..\xa9\x05\x8d\x00\x20..\xa9\xff\x8d\x01\x20HELLO hello")
hp = hex_pattern("A9 ?? 8D 0? 20")
check("hex search with wildcards", b.find_all(hp) == [(12, 5), (19, 5)], b.find_all(hp))
check("hex search nibble wildcard", b.find_all(hex_pattern("A9 F?")) == [(19, 2)])
check("text search case-insensitive", len(b.find_all(text_pattern("hello", case_sensitive=False))) == 2)
check("text search wildcards", b.find_all(text_pattern("H?LLO", wildcards=True)) == [(24, 5)])
check("find backward wraps", b.find(hp, 5, backward=True) == (19, 5))
n = b.replace_all(hex_pattern("A9 ?? 8D"), b"\xea\xea\xea")
check("replace all", n == 2 and b.data.count(b"\xea\xea\xea") == 2)

# ------------------------------------------------------------------ ROM Hacking project
proj = tmp / "Hack1"
clean = synth.snes_rom()
orig = tmp / "my_own.sfc"
orig.write_bytes(clean)
rp = new_project(proj, "Hack1", orig, copy=True)
check("project: ROM copied into rom/, CRC32 recorded", (proj / "rom" / "my_own.sfc").is_file() and
      rp.rom_crc32 == f"{crc(clean):08X}" and rp.system == "snes")
mod = bytearray(clean)
mod[0x1000:0x1004] = b"RAD!"
(tmp / "p1.bps").write_bytes(P.bps_create(clean, bytes(mod)))
rp.add_patch(tmp / "p1.bps", "first")
mod2 = bytearray(mod)
mod2[0x2000] = 0x42
(tmp / "p2.ips").write_bytes(P.ips_create(bytes(mod), bytes(mod2)))
rp.add_patch(tmp / "p2.ips")
rp.save()
rp = RomProject.load(proj)
out = rp.build(log=lambda s: None)
built = out.read_bytes()
check("project build: patches in order + checksum fixed", built[0x1000:0x1004] == b"RAD!" and built[0x2000] == 0x42
      and detect(built, "x.sfc").checksum_ok)
check("project build: the original and the project copy are unchanged",
      orig.read_bytes() == clean and (proj / "rom" / "my_own.sfc").read_bytes() == clean)
rp.patches[1].enabled = False
check("project: disabled patch skipped", rp.apply_all()[0x2000] != 0x42)
rp.patches[1].enabled = True
w = rp.make_work_copy()
wd = bytearray(w.read_bytes())
wd[0x3000:0x3003] = b"NEW"
w.write_bytes(bytes(wd))
e = rp.capture_edits("ups", "title")
rp.save()
check("project: capture edits -> new UPS patch", e is not None and e.file.endswith(".ups") and
      RomProject.load(proj).apply_all()[0x3000:0x3003] == b"NEW", e)
check("project: no changes -> no patch", rp.capture_edits("ips") is None)
ref = tmp / "Hack2"
rp2 = new_project(ref, "Hack2", orig, copy=False)
check("project: referenced ROM (absolute path)", Path(rp2.rom).is_absolute() and not (ref / "rom").exists())

# ------------------------------------------------------------------ command line
env = dict(os.environ, PYTHONPATH=str(ROOT))


def cli(*args):
    r = subprocess.run([sys.executable, "-m", "radide.retro.rom", *map(str, args)], capture_output=True, text=True,
                       env=env, cwd=str(ROOT), timeout=120)
    return r.returncode, r.stdout + r.stderr


rc, txt = cli("build", proj)
check("cli build", rc == 0 and "Build:" in txt, txt)
rc, txt = cli("info", tmp / "demo.nes")
check("cli info", rc == 0 and "Mapper: 0 - NROM" in txt, txt)
(tmp / "mod.nes").write_bytes(synth.nes_rom(message="CHANGED TEXT HERE!"))
rc, txt = cli("create", tmp / "demo.nes", tmp / "mod.nes", tmp / "x.bps")
rc2, txt2 = cli("apply", tmp / "demo.nes", tmp / "x.bps", tmp / "out.nes")
check("cli create + apply", rc == 0 and rc2 == 0 and (tmp / "out.nes").read_bytes() == (tmp / "mod.nes").read_bytes(),
      txt + txt2)
rc, txt = cli("apply", tmp / "demo.nes", tmp / "x.bps", tmp / "demo.nes")
check("cli apply refuses to overwrite the original", rc == 1 and (tmp / "demo.nes").read_bytes() == synth.nes_rom())
broken = bytearray(synth.gb_rom())
broken[0x200] = 0x99
(tmp / "b.gb").write_bytes(bytes(broken))
rc, txt = cli("fixsum", tmp / "b.gb", tmp / "b_fixed.gb")
check("cli fixsum", rc == 0 and detect((tmp / "b_fixed.gb").read_bytes(), "b.gb").checksum_ok, txt)

ok = sum(1 for _, c in RESULTS if c)
print(f"{ok} / {len(RESULTS)} passed; FAILED: {[n for n, c in RESULTS if not c] or 'none'}")
print("RESULT OK" if ok == len(RESULTS) else "RESULT FAIL")
sys.exit(0 if ok == len(RESULTS) else 1)
