"""Headless RAD IDE commands for scripts and AI coding agents (Claude Code, Codex ...).

    RADIDE.exe --check   <project|solution|folder>            syntax / compile diagnostics (Error List)
    RADIDE.exe --build   <project|solution|folder>            Build > Build Solution (every project)
    RADIDE.exe --run     <project|solution|folder> [--timeout S]  F5 without debugging, program output on stdout
    RADIDE.exe --publish <project folder> [--native]          Publish (exe in the project's publish folder)
    RADIDE.exe --info    <project|solution|folder>            the solution as JSON (projects, languages, forms)
    (source build: python -m radide --build ...)

Each command opens the target exactly as the IDE does (designer files are regenerated by the IDE's save), prints
the Output window text on stdout and exits with 0 on success, 1 on failure, 2 on a usage error. No window is
shown (Qt offscreen) and no extension host / browser is started. ``AGENT_COMMANDS`` lists the options;
radide/app.py main() dispatches here before any window exists."""
from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path

AGENT_COMMANDS = ("--check", "--build", "--run", "--publish", "--info")


def wants(argv: list[str]) -> bool:
    return any(a in AGENT_COMMANDS for a in argv)


def _parse(argv: list[str]):
    import argparse
    ap = argparse.ArgumentParser(prog="radide", description="RAD IDE headless commands")
    g = ap.add_mutually_exclusive_group(required=True)
    for c in AGENT_COMMANDS:
        g.add_argument(c, dest="cmd", action="store_const", const=c[2:])
    ap.add_argument("target", nargs="?", default=".")
    ap.add_argument("--native", action="store_true", help="--publish: a native exe where the language has one")
    ap.add_argument("--timeout", type=float, default=30.0, help="--run: stop the program after S seconds")
    ns, _ = ap.parse_known_args(argv)
    return ns


def cli_hint() -> str:
    """How to call these commands from a shell (the frozen exe, or this interpreter with -m radide)."""
    if getattr(sys, "frozen", False):
        return f'"{sys.executable}"'
    exe = Path(sys.executable)
    py = exe.with_name("python.exe") if exe.name.lower() == "pythonw.exe" else exe
    return f'"{py}" -m radide'


class _Out:
    """win.output replacement target: everything the IDE logs goes to stdout too."""

    def __init__(self):
        self.text: list[str] = []

    def __call__(self, t: str):
        t = str(t)
        self.text.append(t)
        try:
            sys.stdout.write(t if t.endswith("\n") else t + "\n")
            sys.stdout.flush()
        except Exception:  # noqa: BLE001
            pass


def _window(out: _Out):
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    os.environ["RADIDE_NO_VSX"] = "1"                  # no extension host, no marketplace
    os.environ["RADIDE_NO_BROWSER"] = "1"
    os.environ["RADIDE_HEADLESS"] = "1"
    try:
        __import__("PyQt6.QtWebEngineWidgets")
    except ImportError:
        pass
    from PyQt6.QtWidgets import QApplication, QMessageBox
    app = QApplication.instance() or QApplication(sys.argv[:1])
    # no modal dialog may block a headless run: answer them in the log
    QMessageBox.critical = staticmethod(lambda _p, t, m, *a, **k: out(f"*** {t}: {m}") or QMessageBox.StandardButton.Ok)
    QMessageBox.warning = staticmethod(lambda _p, t, m, *a, **k: out(f"*** {t}: {m}") or QMessageBox.StandardButton.Ok)
    QMessageBox.information = staticmethod(lambda _p, t, m, *a, **k: out(f"{t}: {m}") or QMessageBox.StandardButton.Ok)
    QMessageBox.question = staticmethod(lambda *a, **k: QMessageBox.StandardButton.No)
    from .app import MainWindow
    win = MainWindow()
    orig = win.log

    def log(text, _orig=orig):
        out(text)
        try:
            _orig(text)
        except Exception:  # noqa: BLE001
            pass
    win.log = log
    return app, win


def _open(win, target: str, out: _Out) -> bool:
    p = Path(target).resolve()
    if not p.exists():
        out(f"*** not found: {p}")
        return False
    from .single_instance import open_target
    open_target(win, p)
    if getattr(win, "project", None) is None:
        out(f"*** {p} could not be opened as a RAD IDE project / solution")
        return False
    return True


def _info(win) -> dict:
    sln = getattr(win, "sln", None)
    projects = []
    for p in (win.projects() if hasattr(win, "projects") else [win.project]):
        try:
            from .languages import get_plugin
            lang = get_plugin(p.language).display_name
        except Exception:  # noqa: BLE001
            lang = getattr(p, "language", "")
        projects.append({"name": p.name, "folder": str(Path(p.folder).resolve()), "language": getattr(p, "language", ""),
                         "languageName": lang, "kind": getattr(p, "kind", ""), "forms": list(getattr(p, "forms", [])),
                         "modules": list(getattr(p, "modules", [])), "startup": getattr(p, "startup", ""),
                         "library": bool(getattr(p, "is_library", False))})
    return {"solution": getattr(sln, "name", ""), "solutionFile": str(getattr(sln, "file", "") or ""),
            "projects": projects}


def main(argv: list[str]) -> int:
    ns = _parse(argv)
    out = _Out()
    try:
        app, win = _window(out)
    except Exception as e:  # noqa: BLE001
        print(f"*** cannot start RAD IDE headless: {e}", file=sys.stderr)
        return 1
    try:
        if not _open(win, ns.target, out):
            return 1
        if ns.cmd == "info":
            print(json.dumps(_info(win), indent=1))
            return 0
        if ns.cmd == "check":
            from .tools import run_checks
            win.save_all()
            diags = run_checks(win)
            for d in diags:
                out(f"{d.file}({d.line}): {d.severity.lower()}: {d.message}")
            errors = sum(1 for d in diags if d.severity == "Error")
            out(f"========== Check: {errors} error(s), {len(diags) - errors} warning(s) ==========")
            return 1 if errors else 0
        if ns.cmd == "build":
            from .features.solution_ui import build_solution
            from .tools import run_checks
            win.save_all()                      # regenerates *_designer files like the IDE
            diags = [d for d in run_checks(win) if d.severity == "Error"]
            for d in diags:
                out(f"{d.file}({d.line}): error: {d.message}")
            names = [win.sln.name_of(p) for p in win.sln.all_projects()] if getattr(win, "sln", None) else None
            res = build_solution(win, only=names, wait=True) or {}
            bad = [n for n, c in res.items() if c not in (0, None)]
            return 1 if bad or diags else 0
        if ns.cmd == "publish":
            from .deploy import config as dcfg
            from .deploy.build import build
            folder = Path(win.project.folder)
            win.save_all()
            cfg = dcfg.load(folder, win.project.name)
            if ns.native and hasattr(cfg, "native"):
                try:
                    cfg.native = True
                except Exception:  # noqa: BLE001
                    pass
            res = build(folder, cfg, log=out, interpreter=win._configured_interpreter(win.run_plugin())
                        if hasattr(win, "_configured_interpreter") else "")
            out(f"========== Publish succeeded: {getattr(res, 'exe', None) or getattr(res, 'dist', '')} ==========")
            return 0
        if ns.cmd == "run":
            from PyQt6.QtCore import QEventLoop, QTimer
            win.run_project(debug=False)
            s = getattr(win, "session", None)
            if s is None:
                out("*** the program did not start")
                return 1
            loop = QEventLoop()
            code = {"v": None}
            s.output.connect(lambda t: out(str(t).rstrip("\n")) if str(t).strip() else None)
            s.finished.connect(lambda c: (code.update(v=c), loop.quit()))
            s.failed.connect(lambda e: (out(f"*** {e}"), code.update(v=1), loop.quit()))
            if ns.timeout > 0:
                QTimer.singleShot(int(ns.timeout * 1000), loop.quit)
            t0 = time.monotonic()
            if s.running():
                loop.exec()
            if code["v"] is None and s.running():
                out(f"(stopped after {time.monotonic() - t0:.0f} s - --timeout)")
                try:
                    win.stop_project()
                except Exception:  # noqa: BLE001
                    pass
                return 0
            return 0 if code["v"] in (0, None) else 1
        return 2
    except Exception as e:  # noqa: BLE001
        import traceback
        out("*** " + "".join(traceback.format_exception(type(e), e, e.__traceback__)))
        return 1
    finally:
        try:
            win.close()
        except Exception:  # noqa: BLE001
            pass


__all__ = ["main", "wants", "cli_hint", "AGENT_COMMANDS"]
