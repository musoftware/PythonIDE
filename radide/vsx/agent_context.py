"""Context for AI coding agents (Claude Code, Codex, Copilot ...) that work inside RAD IDE.

An agent started from RAD IDE (the Claude Code extension's CLI, a terminal) does not know that the folder is a
RAD IDE project: it looks for Microsoft VB6 / Visual Studio, edits generated files, or builds in its own way.
Two non-intrusive channels tell it:

1. ``RADIDE_CLI`` / ``RADIDE_WORKSPACE`` in the environment of the extension host (and so of every CLI an
   extension starts) - radide/vsx/host_ide.py ``_agent_env``; ``RADIDE_CLI`` runs radide/agent_cli.py
   (``--check`` / ``--build`` / ``--run`` / ``--publish`` / ``--info``).
2. A RAD IDE section in ``.claude/CLAUDE.md`` of the workspace folder (Claude Code reads it as project memory;
   other agents read it as documentation). It is written only with the user's consent: one question per
   folder when an AI agent extension is installed (Tools > Options setting ``ai/agent_context``:
   ``ask`` (default) | ``always`` | ``never``). The section lives between BEGIN/END markers, is refreshed in
   place when the project changes and never touches the user's own text in that file; the file can be
   git-ignored (it is regenerated).

The Claude Code extension has no setting for extra system-prompt text (its ``appendSystemPrompt`` exists only in
managed policy settings), so the memory file is the supported channel.
No Qt import at module level."""
