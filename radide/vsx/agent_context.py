def _t(key: str) -> str:
    try:
        from .. import i18n
        lang = i18n.language() or "en"
    except Exception:  # noqa: BLE001
        lang = "en"
    return TEXTS.get(lang, TEXTS["en"]).get(key) or TEXTS["en"][key]


# ============================================================================ the text
def _plugin(p):
    try:
        from ..languages import get_plugin
        return get_plugin(p.language)
    except Exception:  # noqa: BLE001
        return None


def _lang_name(p) -> str:
    try:
        from ..languages import get_plugin
        return get_plugin(p.language).display_name
    except Exception:  # noqa: BLE001
        return str(getattr(p, "language", ""))


def project_section(win, folder: str, cli: str = "") -> str:
    """The RAD IDE section (Markdown, without the markers) for workspace folder *folder*."""
    if not cli:
        try:
            from ..agent_cli import cli_hint
            cli = cli_hint()
        except Exception:  # noqa: BLE001
            cli = "RADIDE.exe"
    root = Path(folder)
    projects = []
    try:
        projects = [st["project"] for st in win.project_states()]
    except Exception:  # noqa: BLE001
        pass
    mine = []
    for p in projects:
        try:
            pf = Path(p.folder).resolve()
        except (OSError, AttributeError):
            continue
        if pf == root or root in pf.parents:
            mine.append(p)
    sln = getattr(win, "sln", None)
    L = ["# RAD IDE project", "",
         "This folder is opened in **RAD IDE**, a Visual Basic 2005 style RAD IDE (forms designer + code editor) "
         "that builds, runs, debugs and publishes the project itself. Work with its project format and its "
         "command line below - do not look for Visual Studio / Microsoft VB6 / other toolchains to build it.", ""]
    if sln is not None and not getattr(sln, "implicit", True) and getattr(sln, "file", None):
        L += [f"Solution: `{Path(sln.file).name}` ({len(projects)} project(s)).", ""]
    if mine:
        L += ["## Projects", ""]
        for p in mine:
            plug = _plugin(p)
            try:
                rel = Path(p.folder).resolve().relative_to(root).as_posix() or "."
            except ValueError:
                rel = str(p.folder)
            L.append(f"* **{p.name}** - {_lang_name(p)}, folder `{rel}`"
                     + (" (library)" if getattr(p, "is_library", False) else "")
                     + (f", startup `{p.startup}`" if getattr(p, "startup", "") else ""))
            for f in list(getattr(p, "forms", []))[:40]:
                code = des = ""
                if plug is not None:
                    try:
                        code, des = plug.code_file(f), plug.designer_file(f)
                    except Exception:  # noqa: BLE001
                        pass
                extra = f": your code in `{code}`" if code else ""
                if des and des != code and not os.path.isabs(des):
                    extra += f", generated `{des}`"
                L.append(f"  * form `{f}` (`{f}.form`){extra}")
            mods = list(getattr(p, "modules", []))[:40]
            if mods:
                L.append("  * code files: " + ", ".join(f"`{m}`" for m in mods))
        L.append("")
    L += ["## Project format", "",
          "* `project.radproj` (JSON) describes a project: language, forms, modules, startup form, references. "
          "`*.radsln` groups projects into a solution. Edit them only to add/remove files the same way the IDE does.",
          "* `<Form>.form` (JSON) is the form designer document: controls, properties, events. The user edits it "
          "in the designer; you may change it (keep valid JSON, unique control names).",
          "* The designer generates the GUI code file of each form (`<Form>_designer.<ext>`, or the `.frm` of a "
          "BASIC/VB6 project) from the `.form` file on every save - **never edit generated designer files by "
          "hand**; put logic in the form's code file (event handlers such as `Command1_Click`).",
          "* Foreign projects (`.vbp` VB6, `.sln`/`.csproj`/`.vbproj`, Delphi, Lazarus, Qt `.ui` ...) are opened in "
          "place: their own files are the source of truth; RAD IDE keeps its state in a `.radide` folder (do not "
          "edit it).",
          "* VB6 / BASIC projects run on RAD IDE's bundled VB6-compatible runtime and publish as a native exe - "
          "Microsoft Visual Basic 6 is NOT needed and need not be installed.", "",
          "## Check, build, run, publish (headless, prints the IDE's Output window)", "",
          "The environment variable `RADIDE_CLI` holds the command (inside RAD IDE's extension host); else use:", "",
          "```",
          f"{cli} --check   <folder>        # syntax / compile errors (Error List), exit code 1 on errors",
          f"{cli} --build   <folder>        # Build > Build Solution",
          f"{cli} --run     <folder> --timeout 20   # run without debugging, program output on stdout",
          f"{cli} --publish <folder> [--native]     # make the exe (publish folder of the project)",
          f"{cli} --info    <folder>        # projects / languages / forms as JSON",
          "```", "",
          "The user can also press F5 in RAD IDE. After you change files on disk RAD IDE reloads open editors and "
          "designers.", ""]
    docs = Path(__file__).resolve().parents[2] / "docs"
    if docs.is_dir():
        L += [f"RAD IDE documentation: `{docs}` (CONTRACTS.md, PLUGIN_API.md, NATIVE_BUILD.md ...).", ""]
    return "\n".join(L).rstrip() + "\n"


def merge(existing: str | None, section: str) -> str:
    """The file text with the RAD IDE block replaced (or appended); the user's text stays."""
    block = f"{BEGIN}\n{section.rstrip()}\n{END}\n"
    if not existing:
        return block
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    if pat.search(existing):
        return pat.sub(lambda _m: block, existing, count=1)
    return existing.rstrip("\n") + "\n\n" + block


def write(win, folder: str) -> Path | None:
    path = Path(folder) / FILE
    try:
        old = path.read_text("utf-8") if path.is_file() else None
        new = merge(old, project_section(win, folder))
        if new != old:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(new, "utf-8")
        return path
    except OSError:
        return None


def has_block(folder: str) -> bool:
    p = Path(folder) / FILE
    try:
        return p.is_file() and BEGIN in p.read_text("utf-8")
    except OSError:
        return False


# ============================================================================ when to write
def agent_installed() -> bool:
    try:
        from .contrib_common import enabled_extensions
        ids = {e.id.lower() for e in enabled_extensions()}
    except Exception:  # noqa: BLE001
        return False
    return any(a in ids for a in AGENT_EXTENSIONS)


def mode(win) -> str:
    try:
        v = str(win.settings.value("ai/agent_context", "ask") or "ask").lower()
    except Exception:  # noqa: BLE001
        v = "ask"
    return v if v in ("ask", "always", "never") else "ask"


def _key(folder: str) -> str:
    return "ai/agent_context_folders/" + os.path.normcase(str(Path(folder))).replace("\\", "|").replace("/", "|").replace(":", "")


def consider(win, folders: list[str]) -> None:
    """The workspace changed: refresh existing RAD IDE blocks; ask (once per folder) where there is none."""
    if not folders:
        return
    m = mode(win)
    for folder in folders[:1]:                      # the workspace root the agent starts in
        if has_block(folder):
            write(win, folder)                      # keep it current (projects / forms changed)
            continue
        if m == "never" or not agent_installed():
            continue
        if m == "always":
            p = write(win, folder)
            if p is not None:
                win.statusBar().showMessage(_t("done").format(path=p), 6000)
            continue
        try:
            answered = str(win.settings.value(_key(folder), "") or "")
        except Exception:  # noqa: BLE001
            answered = ""
        if answered:
            continue
        _ask(win, folder)


def _answer(win, folder: str, ans: str) -> None:
    try:
        win.settings.setValue(_key(folder), ans)
        if ans == "never":
            win.settings.setValue("ai/agent_context", "never")
    except Exception:  # noqa: BLE001
        pass
    if ans == "yes":
        p = write(win, folder)
        if p is not None:
            try:
                win.log(_t("done").format(path=p))
            except Exception:  # noqa: BLE001
                pass


def _ask(win, folder: str) -> None:
    if TEST_HOOK is not None:
        _answer(win, folder, TEST_HOOK(folder))
        return
    if os.environ.get("QT_QPA_PLATFORM") == "offscreen":
        return                                       # never a dialog in headless runs
    from PyQt6.QtWidgets import QMessageBox
    box = QMessageBox(win)
    box.setWindowTitle(_t("title"))
    box.setIcon(QMessageBox.Icon.Question)
    box.setText(_t("ask").format(folder=folder))
    yes = box.addButton(_t("yes"), QMessageBox.ButtonRole.AcceptRole)
    box.addButton(_t("no"), QMessageBox.ButtonRole.RejectRole)
    never = box.addButton(_t("never"), QMessageBox.ButtonRole.DestructiveRole)

    def done(_r=None):
        b = box.clickedButton()
        _answer(win, folder, "yes" if b is yes else "never" if b is never else "no")
    box.finished.connect(done)
    box.open()                                       # not modal for the IDE's event loop


def install(win) -> None:
    """Watch the workspace folders (host_ide's poll keeps svc._last_folders)."""
    from PyQt6.QtCore import QTimer
    state = {"last": None}

    def tick():
        svc = getattr(win, "vsx_host", None)
        try:
            folders = svc.folders() if svc is not None else []
        except Exception:  # noqa: BLE001
            return
        if folders == state["last"]:
            return
        state["last"] = folders
        try:
            consider(win, folders)
        except Exception as e:  # noqa: BLE001
            try:
                win.log(f"[agent context] {e}")
            except Exception:  # noqa: BLE001
                pass
    t = QTimer(win)
    t.setInterval(1500)
    t.timeout.connect(tick)
    t.start()
    win._agent_context_timer = t


