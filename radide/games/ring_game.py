"""Ring game projects (CONTRACTS 10.2 "Ring Game (RingRayLib)"): the same ``<Scene>.scene`` files as the pygame /
HTML5 / Godot games, played by ``radgame.ring`` (radide/games/runtime/radgame.ring) with RingRayLib (raylib 5,
shipped with Ring in C:\\ring\\ring\\bin\\ring_raylib.dll).

A project folder holds::

    project.radproj         language "ring-game", startup "main", extra "scenes": ["Level1", ...]
    main.ring               starts the game: rg_run("Level1", "My Game", "")
    Level1.scene            the scene (scene designer)
    Level1.ring             YOUR code: VB-style handlers  func Player_Collide oOther
    Level1_designer.ring    AUTO-GENERATED: one global per scene object (Player, Coin1 ...)
    _scenes.ring            AUTO-GENERATED: loads every scene's designer + code file
    radgame.ring            the runtime (refreshed on every run)
    assets/                 images, sprite sheets, tilesets, sounds

Ring has one global namespace: use different object names in different scenes, or check ``game.scene_name``.
Pure Python (no Qt).
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from . import codegen

RUNTIME_RING = Path(__file__).resolve().parent / "runtime" / "radgame.ring"
SCENES_FILE = "_scenes.ring"
HEADER = "# AUTO-GENERATED by RAD IDE from {scene}.scene - do not edit (rewritten when the scene is saved)."
EVENT_ARGS = {"Load": "", "Update": "dt", "KeyDown": "key", "KeyUp": "key", "Draw": "", "Collide": "oOther",
              "Click": "", "Tick": "", "AnimationEnd": "", "OutOfWorld": "", "Jump": "", "Bounce": "",
              "MouseDown": "", "MouseUp": ""}


def _ident(name: str) -> bool:
    return bool(re.match(r"^[A-Za-z_]\w*$", name or ""))


# ====================================================================== handlers (Ring)
def find_handler(code: str, name: str) -> int:
    rx = re.compile(rf"^\s*(?:func|def)\s+{re.escape(name)}\b", re.I)
    for i, line in enumerate(code.splitlines()):
        if rx.match(line):
            return i
    return -1


def handler_stub(name: str, args: str | None = None, body: list[str] | None = None) -> list[str]:
    event = name.rpartition("_")[2]
    owner = name.rpartition("_")[0]
    if args is None:
        args = EVENT_ARGS.get(event, "")
    doc = codegen.EVENT_DOCS.get(event)
    out = [f"# {owner if owner != 'Scene' else 'the scene'}: {doc}"] if doc else []
    out.append(f"func {name}" + (f" {args}" if args else ""))
    out += ["    " + ln if ln else "" for ln in (body or [""])]
    return out


def add_handler(code: str, name: str, args: str | None = None) -> tuple[str, int]:
    lines = code.rstrip("\n").splitlines() if code.strip() else []
    lines += [""] + handler_stub(name, args)
    text = "\n".join(lines) + "\n"
    return text, find_handler(text, name) + 1


def new_scene_code(scene, handlers: list[tuple[str | None, str]] | None = None, body: dict | None = None,
                   globals_code: str = "") -> str:
    d = codegen.scene_dict(scene)
    name = d.get("name") or "Scene1"
    handlers = handlers if handlers is not None else [(None, "Load"), (None, "Update"), (None, "KeyDown")]
    body = body or {}
    L = [f"# {name} - your game code (Ring). Double-click an object in the scene designer to add its handler.",
         "# Every object of the scene is a global by its name (Player.x, Coin1.visible, ScoreText.text).",
         "# Helpers: game.score, game.lives, AddScore(n), RestartScene(), GoToScene(name), Quit(),",
         '# ShowMessage(text, seconds), PlayGameSound(id), IsKeyHeld("left"), FindObject(name), FindGroup(group),',
         "# AddTimer(name, ms), StopTimer(name). Object methods: destroy() show() hide() right() bottom() play(anim)."]
    if globals_code:
        L += ["", globals_code.rstrip("\n")]
    for owner, event in handlers:
        h = codegen.handler_name(owner, event)
        L.append("")
        L += handler_stub(h, None, body.get(h))
    return "\n".join(L) + "\n"


# ====================================================================== files
def designer_code(scene) -> str:
    d = codegen.scene_dict(scene)
    name = d.get("name") or "Scene1"
    objs = [o["name"] for o in codegen.scene_objects(d) if _ident(o.get("name", ""))]
    L = [HEADER.format(scene=name), f"# The objects of scene {name}: use them by name in {name}.ring.", ""]
    L += [f"{n} = NULL" for n in objs]
    L += ["", f"func rg_bind_{name}"]
    L += [f'    {n} = rg_ref("{n}")' for n in objs] or ["    return"]
    return "\n".join(L) + "\n"


def scenes_code(folder: Path) -> str:
    L = ["# AUTO-GENERATED by RAD IDE: the scenes of the game (designer + code files)."]
    for n in codegen.project_scenes(folder):
        L.append(f'load "{n}_designer.ring"')
        if (Path(folder) / f"{n}.ring").exists():
            L.append(f'load "{n}.ring"')
    return "\n".join(L) + "\n"


def main_code(start_scene: str, title: str = "") -> str:
    return (f"# Starts the game - F5 in RAD IDE runs this file. Change the first scene or the title here.\n"
            f'load "radgame.ring"\nload "{SCENES_FILE}"\n\n'
            f"func main\n"
            f'    rg_run("{start_scene}", "{(title or start_scene).replace(chr(34), chr(39))}", "")\n')


def _write(path: Path, text: str) -> Path | None:
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
        return path
    return None


def copy_runtime(folder: Path) -> Path:
    dst = Path(folder) / "radgame.ring"
    if not dst.exists() or dst.read_bytes() != RUNTIME_RING.read_bytes():
        shutil.copy2(RUNTIME_RING, dst)
    return dst


def sync_scene(folder: Path, name: str) -> list[Path]:
    folder = Path(folder)
    d = codegen.scene_dict(folder / f"{name}.scene")
    d.setdefault("name", name)
    out = [p for p in (_write(folder / f"{name}_designer.ring", designer_code(d)),) if p]
    user = folder / f"{name}.ring"
    if not user.exists():
        user.write_text(new_scene_code(d), encoding="utf-8")
        out.append(user)
    return out


def sync_project(folder: Path) -> list[Path]:
    folder = Path(folder)
    out: list[Path] = []
    for n in codegen.project_scenes(folder):
        out += sync_scene(folder, n)
    p = _write(folder / SCENES_FILE, scenes_code(folder))
    if p:
        out.append(p)
    out.append(copy_runtime(folder))
    return out


# ====================================================================== templates
PLATFORMER_GLOBALS = 'StartScore = 0\nNextMessage = "Collect the coins and reach the flag!"'
PLATFORMER_RING = {
    "Scene_Load": ["StartScore = game.score          # score when the level started",
                   "ShowMessage(NextMessage, 2)",
                   'NextMessage = "Collect the coins and reach the flag!"'],
    "Scene_KeyDown": ['if key = "escape"', "    Quit()", 'but key = "r"', "    RestartScene()", "ok"],
    "Player_Jump": ['PlayGameSound("jump")'],
    "Player_Collide": ['if oOther.group = "Enemy"',
                       "    if Player.vy > 0 and Player.bottom() - oOther.y < 14     # landed on its head: stomp",
                       "        oOther.destroy()",
                       "        Player.vy = -320",
                       "        AddScore(5)",
                       "    else",
                       "        LoseLife()",
                       "    ok",
                       'but oOther.name = "Goal"',
                       '    ShowMessage("You win! Score: " + game.score, 3)',
                       "    Player.clear_behaviours()                  # stop the player",
                       '    AddTimer("WinTimer", 3000)',
                       "ok"],
    "Player_OutOfWorld": ["LoseLife()"],
    "WinTimer_Tick": ["StopTimer(\"WinTimer\")", "game.score = 0", "game.lives = 3", "RestartScene()"],
}
LOSE_LIFE_RING = """
# back to the start of the level with one life less (and the score it started with)
func LoseLife
    game.lives -= 1
    game.score = StartScore
    if game.lives <= 0
        NextMessage = "Game over - try again!"
        game.lives = 3
        game.score = 0
    ok
    RestartScene()
"""
TOPDOWN_RING = {
    "Scene_Load": ['ShowMessage("Collect all the gems!", 2)'],
    "Scene_KeyDown": ['if key = "escape" Quit() ok'],
    "Hero_Collide": ['if oOther.group = "Enemy"', "    game.score = 0", "    RestartScene()",
                     'but len(FindGroup("Gem")) = 0', '    ShowMessage("All gems collected!", 3)', "ok"],
}


def create_files(folder: Path, name: str, template: str = "platformer", title: str = "") -> tuple[str, list[str]]:
    from . import art, templates
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    if template == "platformer":
        scene = templates.platformer_scene("Level1", art.write_platformer_assets(folder),
                                           "Arrows move - Space jumps - R restarts")
        handlers = [(None, "Load"), (None, "KeyDown"), ("Player", "Jump"), ("Player", "Collide"),
                    ("Player", "OutOfWorld"), ("WinTimer", "Tick")]
        code = new_scene_code({"name": "Level1"}, handlers, PLATFORMER_RING, PLATFORMER_GLOBALS) + LOSE_LIFE_RING
    elif template == "topdown":
        scene = templates.topdown_scene("Room1", art.write_topdown_assets(folder))
        code = new_scene_code({"name": "Room1"}, [(None, "Load"), (None, "KeyDown"), ("Hero", "Collide")],
                              TOPDOWN_RING)
    elif template == "empty":
        scene = templates.empty_scene("Scene1")
        code = new_scene_code(scene)
    else:
        raise ValueError(f"unknown game template {template!r}")
    templates.write_scene(folder, scene)
    (folder / f"{scene['name']}.ring").write_text(code, encoding="utf-8")
    (folder / "main.ring").write_text(main_code(scene["name"], title or name), encoding="utf-8")
    sync_project(folder)
    return scene["name"], [scene["name"]]


