"""HTML5 Canvas game projects (CONTRACTS 10.2): the same ``<Scene>.scene`` files as the pygame / Godot games,
played in the browser by ``radgame.js`` (radide/games/runtime/radgame.js, same Behaviours as radgame.py).

A project folder holds::

    project.radproj   language "html5-game", kind "website" (served by the IDE DevServer + Preview dock)
    index.html        the page: <canvas id="game"> + radgame.js + scenes.js + RadGame.run("Level1")
    Level1.scene      the scene (scene designer)
    Level1.js         YOUR code: VB-style handlers  function Player_Collide(other) { ... }
    scenes.js         AUTO-GENERATED: RadGame.addScene({...}) for every scene (index.html works from disk too)
    radgame.js        the runtime (copied from radide/games/runtime, refreshed on every run)
    assets/           images, sprite sheets, tilesets, sounds

Pure Python (no Qt).
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

from . import codegen

RUNTIME_JS = Path(__file__).resolve().parent / "runtime" / "radgame.js"
SCENES_JS = "scenes.js"
SCENES_HEADER = "// AUTO-GENERATED by RAD IDE from the .scene files - do not edit (rewritten when a scene is saved).\n"
EVENT_ARGS = dict(codegen.EVENT_ARGS, Draw="ctx")


# ====================================================================== handlers (JavaScript)
def find_handler(code: str, name: str) -> int:
    """0-based line of ``function name(`` at the start of a line (-1 = none)."""
    rx = re.compile(rf"^\s*(?:async\s+)?function\s+{re.escape(name)}\s*\(")
    for i, line in enumerate(code.splitlines()):
        if rx.match(line):
            return i
    return -1


def handler_stub(name: str, args: str | None = None, body: list[str] | None = None) -> list[str]:
    event = name.rpartition("_")[2]
    owner = name.rpartition("_")[0]
    if args is None:
        args = EVENT_ARGS.get(event, "")
    doc = codegen.EVENT_DOCS.get(event)
    out = [f"// {owner if owner != 'Scene' else 'the scene'}: {doc}"] if doc else []
    out.append(f"function {name}({args}) {{")
    out += ["    " + ln if ln else "" for ln in (body or [""])]
    out.append("}")
    return out


def add_handler(code: str, name: str, args: str | None = None) -> tuple[str, int]:
    """Append ``function name(args) { }``. Returns (code, 0-based line of the body)."""
    lines = code.rstrip("\n").splitlines() if code.strip() else []
    lines += [""] + handler_stub(name, args)
    text = "\n".join(lines) + "\n"
    return text, find_handler(text, name) + 1


def new_scene_code(scene, handlers: list[tuple[str | None, str]] | None = None, body: dict | None = None) -> str:
    """The user file ``<Scene>.js`` of a new scene."""
    d = codegen.scene_dict(scene)
    name = d.get("name") or "Scene1"
    handlers = handlers if handlers is not None else [(None, "Load"), (None, "Update"), (None, "KeyDown")]
    body = body or {}
    L = [f"// {name} - your game code (JavaScript). Double-click an object in the scene designer to add its",
         "// event handler. Every object of the scene is a global by its name (Player.x, Coin1.visible,",
         "// ScoreText.text). Helpers: game.score, game.lives, game.vars, GoToScene(name), RestartScene(),",
         '// PlaySound(id), ShowMessage(text, seconds), AddScore(n), IsKeyDown("left"), Find(name),',
         '// FindGroup("Coin"), Clone(obj, x, y), AddTimer(name, ms), Random(a, b), Quit().']
    for owner, event in handlers:
        h = codegen.handler_name(owner, event)
        L.append("")
        L += handler_stub(h, None, body.get(h))
    return "\n".join(L) + "\n"


# ====================================================================== files
def copy_runtime(folder: Path) -> Path:
    dst = Path(folder) / "radgame.js"
    if not dst.exists() or dst.read_bytes() != RUNTIME_JS.read_bytes():
        shutil.copy2(RUNTIME_JS, dst)
    return dst


def scenes_js(folder: Path) -> str:
    folder = Path(folder)
    parts = [SCENES_HEADER]
    for name in codegen.project_scenes(folder):
        try:
            d = codegen.scene_dict(folder / f"{name}.scene")
        except (OSError, ValueError) as e:
            parts.append(f"console.error({json.dumps(f'{name}.scene: {e}')});\n")
            continue
        d.setdefault("name", name)
        parts.append(f"RadGame.addScene({json.dumps(d, separators=(',', ':'))});\n")
    return "".join(parts)


def write_scenes_js(folder: Path) -> Path:
    p = Path(folder) / SCENES_JS
    text = scenes_js(folder)
    if not p.exists() or p.read_text(encoding="utf-8") != text:
        p.write_text(text, encoding="utf-8")
    return p


def sync_project(folder: Path) -> list[Path]:
    """Before a run / after a save: runtime + scenes.js (+ a <Scene>.js for a scene without code)."""
    folder = Path(folder)
    out = [copy_runtime(folder), write_scenes_js(folder)]
    for name in codegen.project_scenes(folder):
        user = folder / f"{name}.js"
        if not user.exists():
            user.write_text(new_scene_code(folder / f"{name}.scene"), encoding="utf-8")
            out.append(user)
    return out


def index_html(title: str, start_scene: str) -> str:
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>{title}</title>
    <style>
        html, body {{ margin: 0; height: 100%; background: #111; }}
        body {{ display: flex; align-items: center; justify-content: center; }}
        #game {{ max-width: 100vw; max-height: 100vh; image-rendering: pixelated; outline: none;
                 aspect-ratio: auto; object-fit: contain; }}
    </style>
</head>
<body>
    <canvas id="game" width="800" height="480"></canvas>
    <!-- radgame.js = the game runtime, scenes.js = your scenes (both written by RAD IDE).
         The code of each scene (<Scene>.js) is loaded by the runtime when the scene starts. -->
    <script src="radgame.js"></script>
    <script src="scenes.js"></script>
    <script>
        RadGame.run({json.dumps(start_scene)}, {{ title: {json.dumps(title)} }});
    </script>
</body>
</html>
"""


# ====================================================================== templates (JavaScript bodies)
PLATFORMER_JS = {
    "Scene_Load": ["game.vars.start_score = game.score;       // score when the level started",
                   'ShowMessage(game.vars.message || "Collect the coins and reach the flag!", 2);',
                   "delete game.vars.message;"],
    "Scene_KeyDown": ['if (key === "escape") {', "    Quit();", '} else if (key === "r") {', "    RestartScene();",
                      "}"],
    "Player_Jump": ['PlaySound("jump");'],
    "Player_Collide": ['if (other.group === "Enemy") {',
                       "    if (Player.vy > 0 && Player.bottom - other.y < 14) {   // landed on its head: stomp",
                       "        other.destroy();",
                       "        Player.vy = -320;",
                       "        AddScore(5);",
                       "    } else {",
                       "        LoseLife();",
                       "    }",
                       '} else if (other.name === "Goal") {',
                       '    ShowMessage("You win! Score: " + game.score, 3);',
                       "    Player.behaviours.length = 0;                  // stop the player",
                       '    AddTimer("WinTimer", 3000);',
                       "}"],
    "Player_OutOfWorld": ["LoseLife();"],
    "WinTimer_Tick": ["game.score = 0;", "game.lives = 3;", "RestartScene();"],
}

LOSE_LIFE_JS = """
// back to the start of the level with one life less (and the score it started with)
function LoseLife() {
    game.lives -= 1;
    game.score = game.vars.start_score || 0;
    if (game.lives <= 0) {
        game.vars.message = "Game over - try again!";
        game.lives = 3;
        game.score = 0;
    }
    RestartScene();
}
"""

TOPDOWN_JS = {
    "Scene_Load": ['ShowMessage("Collect all the gems!", 2);'],
    "Scene_KeyDown": ['if (key === "escape") Quit();'],
    "Hero_Collide": ['if (other.group === "Enemy") {', "    game.score = 0;", "    RestartScene();",
                     '} else if (FindGroup("Gem").length === 0) {', '    ShowMessage("All gems collected!", 3);', "}"],
}


def create_files(folder: Path, name: str, template: str = "platformer", title: str = "") -> tuple[str, list[str]]:
    """Scenes, art, JS code, index.html, runtime and scenes.js of a template. Returns (first scene, scenes)."""
    from . import art, templates
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    if template == "platformer":
        scene = templates.platformer_scene("Level1", art.write_platformer_assets(folder),
                                           "Arrows move - Space jumps - R restarts")
        handlers = [(None, "Load"), (None, "KeyDown"), ("Player", "Jump"), ("Player", "Collide"),
                    ("Player", "OutOfWorld"), ("WinTimer", "Tick")]
        code = new_scene_code({"name": "Level1"}, handlers, PLATFORMER_JS) + LOSE_LIFE_JS
    elif template == "topdown":
        scene = templates.topdown_scene("Room1", art.write_topdown_assets(folder))
        code = new_scene_code({"name": "Room1"}, [(None, "Load"), (None, "KeyDown"), ("Hero", "Collide")], TOPDOWN_JS)
    elif template == "empty":
        scene = templates.empty_scene("Scene1")
        code = new_scene_code(scene)
    else:
        raise ValueError(f"unknown game template {template!r}")
    templates.write_scene(folder, scene)
    (folder / f"{scene['name']}.js").write_text(code, encoding="utf-8")
    index = folder / "index.html"
    if not index.exists():
        index.write_text(index_html(title or name, scene["name"]), encoding="utf-8")
    sync_project(folder)
    return scene["name"], [scene["name"]]


