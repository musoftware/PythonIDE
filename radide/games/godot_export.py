"""Export RAD IDE scenes (``<Scene>.scene``, CONTRACTS 10.4) to a Godot 4 project and run it.

For every scene ``<Scene>.tscn`` is generated (TileMap per tile layer with its TileSet, Sprite2D /
AnimatedSprite2D with SpriteFrames from the sprite sheets, Label for text, Node2D for areas, a
CanvasLayer for UI layers). Each object node carries its Behaviours as metadata and the root node's
script is the user file ``<Scene>.gd`` which extends ``res://radgame/radgame_scene.gd`` - the Godot
twin of radgame.py (same behaviours, same VB-style handlers ``Player_Collide(other)``).

``export_project(folder)`` writes project.godot, the runtime and every .tscn (the .tscn files are
regenerated on each export, the .gd user files are created once).  ``godot_exe()`` finds Godot.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import struct
import subprocess
from pathlib import Path

from . import codegen

RUNTIME_GD = Path(__file__).resolve().parent / "runtime" / "radgame_scene.gd"
GODOT_NAMES = ["godot", "godot4", "Godot_v4.2.2-stable_win64.exe", "Godot_v4.2.2-stable_win64_console.exe"]
TSCN_HEADER = "; AUTO-GENERATED by RAD IDE from {scene}.scene - edit the scene in RAD IDE (this file is rewritten)."


def godot_exe(configured: str = "") -> str:
    if configured and Path(configured).exists():
        return configured
    for n in GODOT_NAMES:
        p = shutil.which(n)
        if p:
            real = os.path.realpath(p)       # WinGet links -> the real Godot_v4...exe (and its file-name case)
            return real if Path(real).exists() else p
    for base in (os.environ.get("LOCALAPPDATA", ""), os.environ.get("ProgramFiles", ""), "C:\\Godot"):
        if base:
            for p in sorted(Path(base).glob("Godot*/Godot_v4*.exe")):
                return str(p)
    return ""


# ====================================================================== Variant text
def var(v) -> str:
    """Python value -> Godot Variant text (as used in .tscn files)."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(float(v)) if not v.is_integer() else f"{v:.1f}"
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, dict):
        return "{" + ", ".join(f"{json.dumps(str(k))}: {var(x)}" for k, x in v.items()) + "}"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(var(x) for x in v) + "]"
    return json.dumps(str(v))


def png_size(path: Path) -> tuple[int, int]:
    try:
        with open(path, "rb") as f:
            head = f.read(24)
        if head[:8] == b"\x89PNG\r\n\x1a\n":
            return struct.unpack(">II", head[16:24])
    except OSError:
        pass
    return 0, 0


def _res(rel: str) -> str:
    return "res://" + str(rel).replace("\\", "/").lstrip("/")


def _node_name(n: str) -> str:
    return re.sub(r"[.:@/\"%]", "_", n) or "Node"


# ====================================================================== scene -> .tscn
class _Tscn:
    def __init__(self):
        self.ext: list[tuple[str, str, str]] = []        # (type, path, id)
        self.sub: list[tuple[str, str, list[str]]] = []  # (type, id, lines)
        self.nodes: list[str] = []

    def ext_id(self, rtype: str, path: str) -> str:
        for t, p, i in self.ext:
            if p == path:
                return i
        i = f"{len(self.ext) + 1}_{re.sub(r'[^A-Za-z0-9]', '', Path(path).stem)[:12]}"
        self.ext.append((rtype, path, i))
        return i

    def add_sub(self, rtype: str, sid: str, lines: list[str]) -> str:
        if not any(s[1] == sid for s in self.sub):
            self.sub.append((rtype, sid, lines))
        return sid

    def text(self, scene_name: str) -> str:
        out = [f'[gd_scene load_steps={len(self.ext) + len(self.sub) + 1} format=3]', "",
               TSCN_HEADER.format(scene=scene_name), ""]
        for t, p, i in self.ext:
            out.append(f'[ext_resource type="{t}" path="{p}" id="{i}"]')
        out.append("")
        for t, i, lines in self.sub:
            out.append(f'[sub_resource type="{t}" id="{i}"]')
            out += lines
            out.append("")
        out += self.nodes
        return "\n".join(out) + "\n"


def export_scene(folder: Path, scene) -> str:
    """The .tscn text of one scene."""
    folder = Path(folder)
    d = codegen.scene_dict(scene)
    name = d.get("name") or "Scene1"
    assets = d.get("assets") or {}
    t = _Tscn()
    script = t.ext_id("Script", f"res://{name}.gd")

    # sprite sheets -> AtlasTexture per frame + SpriteFrames
    sheets: dict[str, dict] = {}
    for sid, sh in (assets.get("spritesheets") or {}).items():
        img = sh.get("image", "")
        fw, fh = int(sh.get("frame_w") or 32), int(sh.get("frame_h") or 32)
        iw, ih = png_size(folder / img)
        cols = max(1, iw // fw) if iw else 1
        tex = t.ext_id("Texture2D", _res(img))
        anims = sh.get("animations") or {"default": {"frames": [0], "fps": 5, "loop": True}}
        frame_ids: dict[int, str] = {}
        for an in anims.values():
            for fi in an.get("frames") or [0]:
                fi = int(fi)
                if fi not in frame_ids:
                    aid = f"at_{_node_name(sid)}_{fi}"
                    x, y = (fi % cols) * fw, (fi // cols) * fh
                    t.add_sub("AtlasTexture", aid, [f'atlas = ExtResource("{tex}")', f"region = Rect2({x}, {y}, {fw}, {fh})"])
                    frame_ids[fi] = aid
        items = []
        for an_name, an in anims.items():
            frames = ", ".join(f'{{"duration": 1.0, "texture": SubResource("{frame_ids[int(fi)]}")}}'
                               for fi in an.get("frames") or [0])
            items.append(f'{{"frames": [{frames}], "loop": {var(bool(an.get("loop", True)))}, '
                         f'"name": &{json.dumps(an_name)}, "speed": {float(an.get("fps") or 5):.1f}}}')
        sfid = t.add_sub("SpriteFrames", f"sf_{_node_name(sid)}", [f"animations = [{', '.join(items)}]"])
        sheets[sid] = {"id": sfid, "fw": fw, "fh": fh, "first": next(iter(anims), "default")}

    # tilesets -> TileSetAtlasSource + TileSet
    tilesets: dict[str, dict] = {}
    for tid, ts in (assets.get("tilesets") or {}).items():
        img = ts.get("image", "")
        tw, th = int(ts.get("tile_w") or 32), int(ts.get("tile_h") or 32)
        iw, ih = png_size(folder / img)
        cols, rows = max(1, iw // tw) if iw else 1, max(1, ih // th) if ih else 1
        tex = t.ext_id("Texture2D", _res(img))
        lines = [f'texture = ExtResource("{tex}")', f"texture_region_size = Vector2i({tw}, {th})"]
        lines += [f"{c}:{r}/0 = 0" for r in range(rows) for c in range(cols)]
        src = t.add_sub("TileSetAtlasSource", f"src_{_node_name(tid)}", lines)
        tsid = t.add_sub("TileSet", f"ts_{_node_name(tid)}", [f"tile_size = Vector2i({tw}, {th})",
                                                            f'sources/0 = SubResource("{src}")'])
        tilesets[tid] = {"id": tsid, "cols": cols, "tw": tw, "th": th}

    # world size (as radgame.py: window, or the biggest tile layer)
    ww, wh = int(d.get("width") or 800), int(d.get("height") or 600)
    for ly in d.get("layers") or []:
        if ly.get("type") == "tiles":
            ts = tilesets.get(ly.get("tileset") or "", {"tw": 32, "th": 32})
            ww = max(ww, max((len(r) for r in ly.get("data") or []), default=0) * ts["tw"])
            wh = max(wh, len(ly.get("data") or []) * ts["th"])
    follow = (d.get("camera") or {}).get("follow")
    settings = {"width": int(d.get("width") or 800), "height": int(d.get("height") or 600),
                "background": d.get("background") or "#6EC1E4", "gravity": float(d.get("gravity", 900) or 0),
                "fps": int(d.get("fps") or 60), "follow": follow, "world_w": ww, "world_h": wh,
                "timers": d.get("timers") or [], "report": follow or "",
                "sounds": {k: _res(v) for k, v in (assets.get("sounds") or {}).items()}}
    t.nodes += [f'[node name="{_node_name(name)}" type="Node2D"]', f'script = ExtResource("{script}")',
                f"metadata/rad_scene = {var(settings)}", ""]

    images = assets.get("images") or {}
    for li, ly in enumerate(d.get("layers") or []):
        lname = _node_name(ly.get("name") or f"Layer{li + 1}")
        ltype = ly.get("type") or "sprites"
        visible = "" if ly.get("visible", True) else "visible = false\n"
        if ltype == "tiles":
            ts = tilesets.get(ly.get("tileset") or "")
            node = [f'[node name="{lname}" type="TileMap" parent="."]']
            if ts:
                node.append(f'tile_set = SubResource("{ts["id"]}")')
            node.append("format = 2")
            cells = []
            for r, row in enumerate(ly.get("data") or []):
                for c, tile in enumerate(row):
                    tile = int(tile)
                    if tile < 0:
                        continue
                    cols = ts["cols"] if ts else 1
                    ax, ay = tile % cols, tile // cols
                    cells += [((r & 0xFFFF) << 16) | (c & 0xFFFF), 0 | (ax << 16), ay]
            cells = [x - (1 << 32) if x >= (1 << 31) else x for x in cells]
            node.append(f"layer_0/tile_data = PackedInt32Array({', '.join(map(str, cells))})")
            if visible:
                node.append("visible = false")
            node.append(f"metadata/collision = {var(bool(ly.get('collision')))}")
            t.nodes += node + [""]
            continue
        parent = "."
        t.nodes += [f'[node name="{lname}" type="{"CanvasLayer" if ltype == "ui" else "Node2D"}" parent="."]']
        if visible:
            t.nodes.append("visible = false")
        t.nodes.append("")
        parent = lname
        for o in sorted(ly.get("objects") or [], key=lambda o: int(o.get("z") or 0)):
            t.nodes += _object_node(o, parent, sheets, images, folder, t) + [""]
    return t.text(name)


def _object_node(o: dict, parent: str, sheets: dict, images: dict, folder: Path, t: _Tscn) -> list[str]:
    name = _node_name(o.get("name") or "Object")
    kind = o.get("kind") or "sprite"
    scale = float(o.get("scale") or 1)
    x, y = float(o.get("x") or 0), float(o.get("y") or 0)
    w, h = float(o.get("w") or 0), float(o.get("h") or 0)
    props = o.get("props") or {}
    meta = []
    lines: list[str]
    if kind == "text":
        text = str(o.get("text", props.get("Text", "")) or "")
        fs = int(props.get("FontSize") or 24)
        w = w or max(40, len(text) * fs * 0.6)
        h = h or fs * 1.4
        lines = [f'[node name="{name}" type="Label" parent="{parent}"]',
                 f"offset_left = {x:.1f}", f"offset_top = {y:.1f}", f"offset_right = {x + w * scale:.1f}",
                 f"offset_bottom = {y + h * scale:.1f}", f"text = {var(text)}",
                 f"theme_override_font_sizes/font_size = {fs}"]
        col = props.get("ForeColor") or props.get("color")
        if col:
            lines.append(f"theme_override_colors/font_color = Color({_color(col)})")
        align = str(props.get("Align") or props.get("TextAlign") or "left").lower()
        if "center" in align:
            lines.append("horizontal_alignment = 1")
        elif "right" in align:
            lines.append("horizontal_alignment = 2")
        meta.append(f"metadata/template = {var(text)}")
    elif kind == "area":
        lines = [f'[node name="{name}" type="Node2D" parent="{parent}"]', f"position = Vector2({x:.1f}, {y:.1f})"]
    else:
        sheet = sheets.get(o.get("spritesheet") or "")
        img = images.get(o.get("image") or "")
        if sheet:
            w, h = w or sheet["fw"], h or sheet["fh"]
            anim = o.get("animation") or sheet["first"]
            lines = [f'[node name="{name}" type="AnimatedSprite2D" parent="{parent}"]',
                     f'sprite_frames = SubResource("{sheet["id"]}")', f"animation = &{json.dumps(anim)}",
                     f"autoplay = {json.dumps(anim)}",
                     f"scale = Vector2({w * scale / sheet['fw']:.4f}, {h * scale / sheet['fh']:.4f})"]
        elif img:
            iw, ih = png_size(folder / img)
            iw, ih = iw or 32, ih or 32
            w, h = w or iw, h or ih
            tex = t.ext_id("Texture2D", _res(img))
            lines = [f'[node name="{name}" type="Sprite2D" parent="{parent}"]', f'texture = ExtResource("{tex}")',
                     f"scale = Vector2({w * scale / iw:.4f}, {h * scale / ih:.4f})"]
        else:
            w, h = w or 32, h or 32
            col = props.get("color") or props.get("BackColor") or "#E65050"
            lines = [f'[node name="{name}" type="Polygon2D" parent="{parent}"]',
                     f"color = Color({_color(col)})",
                     f"polygon = PackedVector2Array({-w * scale / 2:.1f}, {-h * scale / 2:.1f}, {w * scale / 2:.1f}, "
                     f"{-h * scale / 2:.1f}, {w * scale / 2:.1f}, {h * scale / 2:.1f}, {-w * scale / 2:.1f}, "
                     f"{h * scale / 2:.1f})"]
        lines.append(f"position = Vector2({x + w * scale / 2:.1f}, {y + h * scale / 2:.1f})")
        if o.get("rotation"):
            lines.append(f"rotation = {float(o['rotation']) * 3.141592653589793 / 180:.5f}")
        meta.append("metadata/rad_centered = true")
    template = str(props.get("template", "")).lower() in ("1", "true", "yes", "on")
    if not o.get("visible", True) or template:          # spawn templates are hidden (spawn() copies them)
        lines.append("visible = false")
    if props:
        meta.append(f"metadata/props = {var(props)}")
    group = props.get("group") or re.sub(r"\d+$", "", o.get("name") or "") or name
    meta += [f"metadata/rad_kind = {var(kind)}", f"metadata/rad_size = Vector2({w * scale:.1f}, {h * scale:.1f})",
             f"metadata/behaviours = {var(o.get('behaviours') or [])}", f"metadata/group = {var(group)}"]
    return lines + meta


def _color(c) -> str:
    c = str(c).lstrip("#")
    if len(c) in (6, 8) and re.fullmatch(r"[0-9A-Fa-f]+", c):
        vals = [int(c[i:i + 2], 16) / 255 for i in range(0, len(c), 2)]
        if len(vals) == 3:
            vals.append(1.0)
        return ", ".join(f"{v:.3f}" for v in vals)
    return "1, 1, 1, 1"


# ====================================================================== user scripts
GD_DOCS = codegen.EVENT_DOCS
GD_ARGS = {"Load": "", "Update": "dt", "KeyDown": "key", "KeyUp": "key", "MouseDown": "x, y, button",
           "Collide": "other", "Click": "", "Tick": "", "OutOfWorld": "", "Jump": "", "Bounce": "",
           "AnimationEnd": "", "Draw": "", "Flap": ""}


def gd_handler(name: str, body: list[str] | None = None) -> str:
    event = name.rpartition("_")[2]
    owner = name.rpartition("_")[0]
    doc = GD_DOCS.get(event)
    lines = [f"# {owner if owner != 'Scene' else 'the scene'}: {doc}"] if doc else []
    lines.append(f"func {name}({GD_ARGS.get(event, '')}):")
    lines += ["\t" + ln for ln in (body or ["pass"])]
    return "\n".join(lines) + "\n"


def user_script(scene_name: str, template: str = "empty") -> str:
    head = (f"# {scene_name} - your game code (Godot 4). The scene {scene_name}.tscn is generated from "
            f"{scene_name}.scene;\n# double-click an object in the RAD IDE scene designer to add its handler.\n"
            "# Helpers: find(\"Player\"), group_of(node), score, lives, add_score(n), go_to_scene(\"Level2\"),\n"
            "# restart_scene(), play_sound(\"coin\"), show_message(\"text\", 2), add_timer(\"Timer1\", 1000).\n"
            'extends "res://radgame/radgame_scene.gd"\n\n\n')
    if template == "platformer":
        hs = [("Scene_Load", ['show_message("Collect the coins and reach the flag!", 2)']),
              ("Scene_KeyDown", ['if key == "escape":', '\tquit_game()', 'elif key == "r":', '\trestart_scene()']),
              ("Player_Jump", ['play_sound("jump")']),
              ("Player_Collide", ['var player := find("Player")',
                                  'if group_of(other) == "Enemy":',
                                  '\tif velocity(player).y > 0 and rect_of(player).end.y - rect_of(other).position.y < 14:',
                                  '\t\tdestroy(other)',
                                  '\t\tset_velocity(player, Vector2(0, -320))',
                                  '\t\tadd_score(5)',
                                  '\telse:',
                                  '\t\tlose_life()',
                                  'elif other.name == "Goal":',
                                  '\tshow_message("You win! Score: %d" % score, 3)',
                                  '\tplayer.set_meta("behaviours", [])',
                                  '\tadd_timer("WinTimer", 3000)']),
              ("Player_OutOfWorld", ["lose_life()"]),
              ("WinTimer_Tick", ["score = 0", "lives = 3", "restart_scene()"])]
        extra = ("\nfunc lose_life():\n\tlives -= 1\n\tif lives <= 0:\n\t\tlives = 3\n\t\tscore = 0\n"
                 "\trestart_scene()\n")
    elif template == "topdown":
        hs = [("Scene_Load", ['show_message("Collect all the gems!", 2)']),
              ("Scene_KeyDown", ['if key == "escape":', '\tquit_game()']),
              ("Hero_Collide", ['if group_of(other) == "Enemy":', '\tscore = 0', '\trestart_scene()',
                                'elif find_group("Gem").is_empty():', '\tshow_message("All gems collected!", 3)'])]
        extra = ""
    else:
        hs = [("Scene_Load", None), ("Scene_Update", None), ("Scene_KeyDown", None)]
        extra = ""
    return head + "\n\n".join(gd_handler(n, b) for n, b in hs) + extra


def write_user_scripts(folder: Path, scenes: list[str], template: str = "empty") -> None:
    for s in scenes:
        p = Path(folder) / f"{s}.gd"
        if not p.exists():
            p.write_text(user_script(s, template), encoding="utf-8")


def find_gd_handler(code: str, name: str) -> int:
    rx = re.compile(rf"^func\s+{re.escape(name)}\s*\(")
    for i, line in enumerate(code.splitlines()):
        if rx.match(line):
            return i
    return -1


def add_gd_handler(code: str, name: str) -> tuple[str, int]:
    text = code.rstrip("\n") + "\n\n\n" + gd_handler(name)
    return text, find_gd_handler(text, name) + 1


# ====================================================================== pygame project -> Godot project
def runtime_names() -> set[str]:
    """Members (var / const / func / signal) of radgame_scene.gd and of Node2D that matter."""
    try:
        text = RUNTIME_GD.read_text(encoding="utf-8")
    except OSError:
        text = ""
    names = set(re.findall(r"^(?:static\s+)?(?:var|const|func|signal)\s+(\w+)", text, re.M))
    return names | {"name", "position", "rotation", "scale", "visible", "owner", "process_mode", "transform"}


def gd_from_python(scene_name: str, code: str) -> str:
    """A ``<Scene>.gd`` for a scene whose code is Python (a pygame project exported to Godot): every
    handler / function becomes a GDScript ``func`` with the same name and arguments; its Python body is kept
    as comments to translate (the runtime helpers have GDScript twins: Spawn -> spawn, SaveData -> save_data
    ...). The scene, the behaviours and the art work in Godot as they are."""
    import ast
    head = user_script(scene_name).split('extends "res://radgame/radgame_scene.gd"')[0]
    out = [head.rstrip("\n"),
           "# Exported from the pygame version: translate the Python lines (comments) under each func.",
           'extends "res://radgame/radgame_scene.gd"', ""]
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return "\n".join(out + [f"# the Python code has a syntax error ({e}); nothing was converted", ""])
    lines = code.splitlines()
    taken = runtime_names()          # names of radgame_scene.gd: a script that extends it cannot reuse them

    def gd_name(name: str) -> str:
        return f"{name}_" if name in taken else name
    glob = [n for n in tree.body if isinstance(n, (ast.Assign, ast.AnnAssign))]
    for n in glob:
        for ln in lines[n.lineno - 1:n.end_lineno]:
            out.append("# " + ln)
        targets = n.targets if isinstance(n, ast.Assign) else [n.target]
        for t in targets:
            for nm in ([t] if isinstance(t, ast.Name) else getattr(t, "elts", [])):
                if isinstance(nm, ast.Name):
                    out.append(f"var {gd_name(nm.id)}" + (f"   # renamed: '{nm.id}' is a name of the runtime"
                                                          if nm.id in taken else ""))
    for n in tree.body:
        if not isinstance(n, ast.FunctionDef):
            continue
        event = n.name.rpartition("_")[2]
        if "_" in n.name and event in GD_ARGS:
            args = GD_ARGS[event]
        else:
            args = ", ".join(a.arg for a in n.args.args)
        out += ["", ""]
        doc = GD_DOCS.get(event) if "_" in n.name else None
        if doc:
            owner = n.name.rpartition("_")[0]
            out.append(f"# {owner if owner != 'Scene' else 'the scene'}: {doc}")
        if n.name in taken:
            out.append(f"# renamed: '{n.name}' is a name of the runtime")
        out.append(f"func {gd_name(n.name)}({', '.join(gd_name(a.strip()) for a in args.split(',') if a.strip())}):")
        start = n.body[0].lineno if n.body else n.lineno + 1
        for ln in lines[start - 1:n.end_lineno]:
            out.append("\t# " + ln[4:] if ln.startswith("    ") else "\t# " + ln)
        out.append("\tpass")
    return "\n".join(out) + "\n"


def export_from_pygame(src: Path, dest: Path | None = None, title: str = "") -> tuple[Path, list[str]]:
    """Export a pygame game project to a Godot 4 project in *dest* (default: ``<project>_Godot`` next to
    it): the scenes, the assets, project.godot, the .tscn scenes and a ``<Scene>.gd`` per scene made from
    the Python code (see gd_from_python - existing .gd files are kept). Returns (dest, report lines)."""
    src = Path(src)
    try:
        pd = json.loads((src / "project.radproj").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        pd = {}
    name = pd.get("name") or src.name
    dest = Path(dest) if dest else src.parent / f"{name}_Godot"
    dest.mkdir(parents=True, exist_ok=True)
    scenes = codegen.project_scenes(src)
    if not scenes:
        raise FileNotFoundError("the project has no .scene file")
    report = []
    files: set[str] = set()
    for s in scenes:
        d = codegen.scene_dict(src / f"{s}.scene")
        for kind, items in (d.get("assets") or {}).items():
            for v in (items or {}).values():
                rel = v if isinstance(v, str) else (v or {}).get("image", "")
                if rel and not Path(rel).is_absolute():
                    files.add(rel)
        shutil.copy2(src / f"{s}.scene", dest / f"{s}.scene")
    if (src / "assets").is_dir():
        files.update(p.relative_to(src).as_posix() for p in (src / "assets").rglob("*") if p.is_file())
    for rel in sorted(files):
        if (src / rel).is_file():
            (dest / rel).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src / rel, dest / rel)
    report.append(f"{len(scenes)} scene(s) and {len(files)} asset file(s) copied")
    for s in scenes:
        gd = dest / f"{s}.gd"
        py = src / f"{s}.py"
        if gd.exists():
            report.append(f"{gd.name} kept (already exists)")
        elif py.exists():
            gd.write_text(gd_from_python(s, py.read_text(encoding="utf-8")), encoding="utf-8")
            report.append(f"{gd.name}: handlers made from {py.name} (the Python code is in comments - translate it)")
    game = dict(pd.get("game") or {})
    game.setdefault("start_scene", scenes[0])
    game.setdefault("title", title or name)
    proj = {"name": f"{name}_Godot", "language": "godot", "forms": [], "startup": game["start_scene"],
            "modules": [f"{s}.gd" for s in scenes], "scenes": scenes, "game": game}
    (dest / "project.radproj").write_text(json.dumps(proj, indent=2) + "\n", encoding="utf-8")
    export_project(dest, title or game.get("title") or name)
    report.append("project.godot, radgame/radgame_scene.gd and the .tscn scenes written")
    return dest, report


