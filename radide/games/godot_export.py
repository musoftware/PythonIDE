def export_project(folder: Path, title: str = "") -> list[Path]:
    """Write project.godot, res://radgame/radgame_scene.gd and a .tscn for every scene."""
    folder = Path(folder)
    scenes = codegen.project_scenes(folder)
    if not scenes:
        raise FileNotFoundError("the project has no .scene file")
    start = scenes[0]
    try:
        pd = json.loads((folder / "project.radproj").read_text(encoding="utf-8"))
        title = title or (pd.get("game") or {}).get("title") or pd.get("name") or ""
        start = (pd.get("game") or {}).get("start_scene") or start
    except (OSError, ValueError):
        pass
    first = codegen.scene_dict(folder / f"{start}.scene")
    out = []
    pg = folder / "project.godot"
    pg.write_text(project_godot(title or start, start, first.get("width") or 800, first.get("height") or 600),
                  encoding="utf-8")
    out.append(pg)
    rt = folder / "radgame" / "radgame_scene.gd"
    rt.parent.mkdir(exist_ok=True)
    if not rt.exists() or rt.read_bytes() != RUNTIME_GD.read_bytes():
        shutil.copy2(RUNTIME_GD, rt)
    out.append(rt)
    for s in scenes:
        p = folder / f"{s}.tscn"
        p.write_text(export_scene(folder, folder / f"{s}.scene"), encoding="utf-8")
        out.append(p)
    write_user_scripts(folder, scenes)
    gi = folder / ".gitignore"
    if not gi.exists():
        gi.write_text(".godot/\n__pycache__/\n", encoding="utf-8")
    return out


def needs_import(folder: Path) -> bool:
    """True when assets changed since Godot last imported them (or never did)."""
    folder = Path(folder)
    stamp = folder / ".godot" / "radide_import.stamp"
    if not stamp.exists():
        return True
    t = stamp.stat().st_mtime
    return any(p.stat().st_mtime > t for p in folder.rglob("*")
               if p.suffix.lower() in (".png", ".jpg", ".jpeg", ".wav", ".ogg", ".mp3", ".webp")
               and ".godot" not in p.parts)


def import_assets(folder: Path, godot: str = "", timeout: int = 180) -> subprocess.CompletedProcess:
    """Run Godot's importer headless once (textures and sounds must be imported before running)."""
    folder = Path(folder)
    exe = godot or godot_exe()
    if not exe:
        raise FileNotFoundError("Godot was not found (install Godot 4 or set Tools > Interpreter Path)")
    r = subprocess.run([exe, "--headless", "--path", str(folder), "--import"], capture_output=True, text=True,
                       timeout=timeout, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    stamp = folder / ".godot" / "radide_import.stamp"
    if stamp.parent.exists():
        stamp.write_text("imported by RAD IDE\n", encoding="utf-8")
    return r


