"""Code generation for pygame game projects (CONTRACTS 10.2 / 10.4).

A game project folder holds::

    project.radproj      language "pygame", startup "main", extra "scenes": ["Level1", ...]
    main.py              starts the game: radgame.run("Level1", title=...)
    Level1.scene         the scene (JSON, edited in the scene designer)
    Level1.py            YOUR code: VB-style handlers Scene_Load, Player_Collide(other) ...
    Level1_designer.py   AUTO-GENERATED: the scene's object names (IntelliSense, pyflakes)
    radgame.py           the runtime (copied from radide/games/runtime, refreshed on every run)
    assets/              images, sprite sheets, tilesets, sounds

Pure Python (no Qt) so the plugin, the scene designer and the tests can all use it.
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

RUNTIME = Path(__file__).resolve().parent / "runtime" / "radgame.py"
HEADER = "# AUTO-GENERATED by RAD IDE from {scene}.scene - do not edit (rewritten when the scene is saved)."

# event -> Python parameters of its handler (matches radide.games.model.EVENT_ARGS)
EVENT_ARGS = {"Load": "", "Update": "dt", "KeyDown": "key", "KeyUp": "key", "MouseDown": "x, y, button",
              "MouseUp": "x, y, button", "Draw": "screen", "Collide": "other", "Click": "", "Tick": "",
              "AnimationEnd": "", "OutOfWorld": "", "Jump": "", "Bounce": "", "Flap": ""}
EVENT_DOCS = {"Load": "the scene starts", "Update": "every frame (dt = seconds since the last frame)",
              "KeyDown": "a key goes down (key = 'left', 'space', 'a', 'enter', 'escape' ...)",
              "KeyUp": "a key goes up", "MouseDown": "a mouse button goes down (screen pixels)",
              "MouseUp": "a mouse button goes up", "Draw": "after the scene is drawn (draw extra things on screen)",
              "Collide": "touches another object (other)", "Click": "is clicked",
              "Tick": "the timer interval elapsed", "AnimationEnd": "a non-looping animation finished",
              "OutOfWorld": "fell below the level", "Jump": "jumps (platformer)",
              "Bounce": "bounces off something", "Flap": "flaps upwards (flap behaviour)"}
SCENE_EVENTS = ["Load", "Update", "KeyDown", "KeyUp", "MouseDown", "MouseUp", "Draw"]
OBJECT_EVENTS = {"sprite": ["Collide", "Click", "AnimationEnd", "OutOfWorld", "Jump", "Bounce", "Flap"],
                 "text": ["Click"], "area": ["Collide", "Click"]}
_CLASS = {"sprite": "Sprite", "text": "TextObject", "area": "Area"}


def _ident(name: str) -> bool:
    return bool(re.match(r"^[A-Za-z_]\w*$", name or ""))


def scene_dict(scene) -> dict:
    """Accept a radide.games.model.Scene, a dict or a path to a .scene file."""
    if isinstance(scene, dict):
        return scene
    if isinstance(scene, (str, Path)):
        return json.loads(Path(scene).read_text(encoding="utf-8"))
    return scene.to_dict()


def scene_objects(scene) -> list[dict]:
    d = scene_dict(scene)
    return [o for ly in d.get("layers") or [] for o in (ly.get("objects") or []) if isinstance(o, dict)]


# ====================================================================== handlers
def handler_name(owner: str | None, event: str) -> str:
    """Scene events -> Scene_<Event>; object events -> <Object>_<Event>."""
    return f"{owner or 'Scene'}_{event}"


def event_args(event: str) -> str:
    return EVENT_ARGS.get(event, "")


def find_handler(code: str, name: str) -> int:
    """0-based line of ``def name(`` at module level (-1 = none)."""
    rx = re.compile(rf"^def\s+{re.escape(name)}\s*\(")
    for i, line in enumerate(code.splitlines()):
        if rx.match(line):
            return i
    return -1


def add_handler(code: str, name: str, args: str | None = None) -> tuple[str, int]:
    """Append ``def name(args):`` (args None = from the event name). Returns (code, line of the body)."""
    if args is None:
        args = event_args(name.rpartition("_")[2])
    event = name.rpartition("_")[2]
    owner = name.rpartition("_")[0]
    doc = EVENT_DOCS.get(event)
    stub = ([f"# {owner if owner != 'Scene' else 'the scene'}: {doc}"] if doc else []) + \
        [f"def {name}({args}):", "    pass"]
    lines = code.rstrip("\n").splitlines()
    # keep an `if __name__ == "__main__":` block at the end
    idx = next((i for i, ln in enumerate(lines) if re.match(r"^if\s+__name__\s*==", ln)), None)
    if idx is None:
        lines += ["", ""] + stub
    else:
        while idx > 0 and not lines[idx - 1].strip():
            idx -= 1
        lines[idx:idx] = ["", ""] + stub + [""]
    text = "\n".join(lines) + "\n"
    return text, find_handler(text, name) + 1


# ====================================================================== files
def designer_code(scene) -> str:
    """``<Scene>_designer.py``: one typed name per scene object (and timer) for the editor."""
    d = scene_dict(scene)
    name = d.get("name") or "Scene1"
    objs = [o for o in scene_objects(d) if _ident(o.get("name", ""))]
    timers = [t for t in d.get("timers") or [] if _ident(t.get("name", ""))]
    classes = sorted({_CLASS.get(o.get("kind", "sprite"), "Sprite") for o in objs} | ({"Timer"} if timers else set()))
    L = [HEADER.format(scene=name),
         f'"""The objects of scene {name}: use them by name in {name}.py (Player.x += 4, ScoreText.text = "...").',
         'While the game runs each name is the real object of the running scene."""',
         f"from radgame import {', '.join(classes + ['objref'])}" if classes else "from radgame import objref",
         ""]
    for o in objs:
        L.append(f"{o['name']}: {_CLASS.get(o.get('kind', 'sprite'), 'Sprite')} = objref({o['name']!r})")
    for t in timers:
        L.append(f"{t['name']}: Timer = objref({t['name']!r})")
    names = [o["name"] for o in objs] + [t["name"] for t in timers]
    L += ["", "__all__ = [" + ", ".join(repr(n) for n in names) + "]", ""]
    return "\n".join(L)


def new_scene_code(scene, handlers: list[tuple[str | None, str]] | None = None, body: dict | None = None) -> str:
    """The user file ``<Scene>.py`` of a new scene. *handlers* = [(object or None, event)] to start with,
    *body* = {handler name: code lines} to put inside them instead of ``pass``."""
    d = scene_dict(scene)
    name = d.get("name") or "Scene1"
    handlers = handlers if handlers is not None else [(None, "Load"), (None, "Update"), (None, "KeyDown")]
    body = body or {}
    L = [f'"""{name} - your game code. Double-click an object in the scene designer to add its event handler.',
         "",
         "Every object of the scene is a name here (Player.x, Coin1.visible, ScoreText.text). Useful helpers:",
         "game.score, game.lives, game.vars, GoToScene(name), RestartScene(), PlaySound(id), ShowMessage(text),",
         'AddScore(n), IsKeyDown("left"), Find(name), FindGroup("Coin"), Clone(obj, x, y), AddTimer(name, ms)."""',
         "from radgame import *  # noqa: F401,F403 - the game helpers",
         f"from {name}_designer import *  # noqa: F401,F403 - the objects of the scene"]
    for owner, event in handlers:
        h = handler_name(owner, event)
        doc = EVENT_DOCS.get(event)
        L += ["", ""]
        if doc:
            L.append(f"# {owner or 'the scene'}: {doc}")
        L.append(f"def {h}({event_args(event)}):")
        lines = body.get(h) or ["pass"]
        L += ["    " + ln if ln else "" for ln in lines]
    return "\n".join(L) + "\n"


def main_code(start_scene: str, title: str = "", width: int | None = None, height: int | None = None) -> str:
    size = f", width={int(width)}, height={int(height)}" if width and height else ""
    return (f'"""Starts the game - F5 in RAD IDE runs this file. Change the first scene or the title here."""\n'
            f"import os\n\nimport radgame\n\n"
            f'if __name__ == "__main__":\n'
            f"    radgame.run({start_scene!r}, title={(title or start_scene)!r}{size},\n"
            f"                folder=os.path.dirname(os.path.abspath(__file__)))\n")


def copy_runtime(folder: Path) -> Path:
    """Copy (refresh) radgame.py into the project."""
    dst = Path(folder) / "radgame.py"
    if not dst.exists() or dst.read_bytes() != RUNTIME.read_bytes():
        shutil.copy2(RUNTIME, dst)
    for extra in ("radgame_particles.py", "radgame_physics.py"):      # particles / pymunk physics (optional)
        src, out = RUNTIME.parent / extra, Path(folder) / extra
        if src.exists() and (not out.exists() or out.read_bytes() != src.read_bytes()):
            shutil.copy2(src, out)
    return dst


def project_scenes(folder: Path) -> list[str]:
    """Scenes of a game project: project.radproj "scenes" (in order), plus any other *.scene file."""
    folder = Path(folder)
    names: list[str] = []
    try:
        data = json.loads((folder / "project.radproj").read_text(encoding="utf-8"))
        names = [str(s) for s in data.get("scenes") or []]
    except (OSError, ValueError):
        pass
    for p in sorted(folder.glob("*.scene")):
        if p.stem not in names:
            names.append(p.stem)
    return [n for n in names if (folder / f"{n}.scene").exists()]


def sync_scene(folder: Path, name: str) -> list[Path]:
    """After a scene was saved: rewrite ``<name>_designer.py``, create ``<name>.py`` if missing and
    refresh radgame.py. Returns the files written."""
    folder = Path(folder)
    d = scene_dict(folder / f"{name}.scene")
    d.setdefault("name", name)
    out = []
    des = folder / f"{name}_designer.py"
    text = designer_code(d)
    if not des.exists() or des.read_text(encoding="utf-8") != text:
        des.write_text(text, encoding="utf-8")
        out.append(des)
    user = folder / f"{name}.py"
    if not user.exists():
        user.write_text(new_scene_code(d), encoding="utf-8")
        out.append(user)
    out.append(copy_runtime(folder))
    return out


def sync_project(folder: Path) -> None:
    for name in project_scenes(folder):
        sync_scene(folder, name)
    copy_runtime(folder)


