"""Setup step of Build > Publish: an Inno Setup script (.iss) for a built program, compiled with ISCC.exe.

publish(folder, cfg) runs the whole chain used by the Publish dialog and by tests:

    build (deploy/build.py)  ->  sign the exe (optional)  ->  CheckForUpdates.ps1 (optional)
    ->  <exe>-<version>-setup.exe (Inno Setup)  ->  sign the setup (optional)
    ->  portable .zip (optional)  ->  version.json (optional)

The setup installs per user by default (no admin rights: {autopf} = %LOCALAPPDATA%\\Programs), can still be
switched to "all users" in its first page, adds Start menu / desktop shortcuts, an uninstaller in
"Apps & features", optional file association, and runs silently with the standard Inno Setup switches:

    setup.exe /VERYSILENT /SUPPRESSMSGBOXES /NORESTART /CURRENTUSER [/DIR="..."]
    unins000.exe /VERYSILENT /SUPPRESSMSGBOXES /NORESTART
"""
from __future__ import annotations

import os
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from . import tools
from .config import PublishConfig, resolve

NO_WINDOW = 0x08000000 if os.name == "nt" else 0


class SetupError(Exception):
    pass


@dataclass
class PublishResult:
    dist: Path                                   # the program folder (what the setup installs)
    exe: str                                     # main exe relative to dist
    setup: Path | None = None                    # <out>/<exe>-<version>-setup.exe
    zip: Path | None = None
    version_json: Path | None = None
    notes: list[str] = field(default_factory=list)


def _q(text: str) -> str:
    """A value inside double quotes in an .iss file: quotes doubled, '{' escaped (Inno constants)."""
    return str(text).replace('"', '""').replace("{", "{{")


def _v(text: str) -> str:
    """An unquoted [Setup] value: '{' escaped."""
    return str(text).replace("{", "{{").replace("\n", " ")


def setup_name(cfg: PublishConfig) -> str:
    return f"{cfg.exe_base()}-{cfg.version}-setup"


def language_lines(cfg: PublishConfig, iscc: str = "") -> list[str]:
    """[Languages] entries; unknown names are skipped (English is always there)."""
    have = {n.lower(): n for n in tools.inno_languages(iscc)}
    lines, seen = [], set()
    for name in (cfg.languages or ["English"]):
        real = have.get(str(name).strip().lower())
        if not real or real.lower() in seen:
            continue
        seen.add(real.lower())
        msg = "compiler:Default.isl" if real == "English" else f"compiler:Languages\\{real}.isl"
        lines.append(f'Name: "{real.lower()}"; MessagesFile: "{msg}"')
    if not lines:
        lines.append('Name: "english"; MessagesFile: "compiler:Default.isl"')
    return lines


def script(folder: Path, cfg: PublishConfig, dist: Path, exe: str, out_dir: Path, iscc: str = "",
           icon: Path | None = None, is64: bool = True) -> str:
    """The .iss text for installing *dist* (with main program *exe*)."""
    folder = Path(folder)
    app = cfg.app_name or folder.name
    app_id = cfg.ensure_id()
    exe_rel = exe.replace("/", "\\")
    L = ["; Generated by RAD IDE (Build > Publish). Regenerated on every Publish.", "", "[Setup]",
         f"AppId={_v(app_id)}", f"AppName={_v(app)}", f"AppVersion={_v(cfg.version)}",
         f"AppVerName={_v(app)} {_v(cfg.version)}", f"VersionInfoVersion={cfg.numeric_version()}"]
    if cfg.publisher:
        L.append(f"AppPublisher={_v(cfg.publisher)}")
    if cfg.url:
        L += [f"AppPublisherURL={_v(cfg.url)}", f"AppSupportURL={_v(cfg.url)}"]
    L += [f"DefaultDirName={{autopf}}\\{_v(app)}", f"DefaultGroupName={_v(app)}", "DisableProgramGroupPage=yes",
          f"OutputDir={out_dir}", f"OutputBaseFilename={_v(setup_name(cfg))}",
          f"Compression={cfg.compression or 'lzma2/max'}", "SolidCompression=yes", "WizardStyle=modern",
          f"UninstallDisplayIcon={{app}}\\{exe_rel}", f"UninstallDisplayName={_v(app)}"]
    if cfg.per_user:
        L += ["PrivilegesRequired=lowest", "PrivilegesRequiredOverridesAllowed=dialog commandline"]
    else:
        L += ["PrivilegesRequired=admin"]
    if is64:
        L += ["ArchitecturesAllowed=x64compatible", "ArchitecturesInstallIn64BitMode=x64compatible"]
    if icon is not None and Path(icon).is_file():
        L.append(f"SetupIconFile={icon}")
    lic = resolve(folder, cfg.license_file) if cfg.license_file else None
    if lic and lic.is_file():
        L.append(f"LicenseFile={lic}")
    info = resolve(folder, cfg.readme_file) if cfg.readme_file else None
    if info and info.is_file():
        L.append(f"InfoBeforeFile={info}")
    ext = cfg.file_ext.strip()
    if ext:
        ext = ext if ext.startswith(".") else "." + ext
        L.append("ChangesAssociations=yes")
    L += ["", "[Languages]", *language_lines(cfg, iscc), "", "[Tasks]"]
    if cfg.desktop_icon:
        L.append('Name: "desktopicon"; Description: "{cm:CreateDesktopIcon}"; '
                 'GroupDescription: "{cm:AdditionalIcons}"')
    L += ["", "[Files]",
          f'Source: "{dist}\\*"; DestDir: "{{app}}"; Flags: ignoreversion recursesubdirs createallsubdirs',
          "", "[Icons]"]
    if cfg.start_menu:
        L.append(f'Name: "{{group}}\\{_q(app)}"; Filename: "{{app}}\\{exe_rel}"')
        L.append(f'Name: "{{group}}\\{{cm:UninstallProgram,{_q(app)}}}"; Filename: "{{uninstallexe}}"')
        if cfg.update.enabled and cfg.update.url and (Path(dist) / "CheckForUpdates.ps1").is_file():
            L.append(f'Name: "{{group}}\\Check for Updates"; Filename: "powershell.exe"; '
                     f'Parameters: "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File '
                     f'""{{app}}\\CheckForUpdates.ps1"""; IconFilename: "{{app}}\\{exe_rel}"')
    if cfg.desktop_icon:
        L.append(f'Name: "{{autodesktop}}\\{_q(app)}"; Filename: "{{app}}\\{exe_rel}"; Tasks: desktopicon')
    if ext:
        prog = cfg.exe_base() + ext.replace(".", "_")
        L += ["", "[Registry]",
              f'Root: HKA; Subkey: "Software\\Classes\\{ext}"; ValueType: string; ValueName: ""; '
              f'ValueData: "{prog}"; Flags: uninsdeletevalue uninsdeletekeyifempty',
              f'Root: HKA; Subkey: "Software\\Classes\\{prog}"; ValueType: string; ValueName: ""; '
              f'ValueData: "{_q(cfg.file_desc or app)}"; Flags: uninsdeletekey',
              f'Root: HKA; Subkey: "Software\\Classes\\{prog}\\DefaultIcon"; ValueType: string; ValueName: ""; '
              f'ValueData: "{{app}}\\{exe_rel},0"',
              f'Root: HKA; Subkey: "Software\\Classes\\{prog}\\shell\\open\\command"; ValueType: string; '
              f'ValueName: ""; ValueData: """{{app}}\\{exe_rel}"" ""%1"""']
    if cfg.run_after_install:
        L += ["", "[Run]",
              f'Filename: "{{app}}\\{exe_rel}"; Description: "{{cm:LaunchProgram,{_q(app)}}}"; '
              f'Flags: nowait postinstall skipifsilent']
    return "\n".join(L) + "\n"


def compile_setup(iss: Path, iscc: str, log=print) -> int:
    log(f'"{iscc}" /Q "{iss}"')
    p = subprocess.Popen([iscc, "/Q", str(iss)], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         text=True, encoding="utf-8", errors="replace", creationflags=NO_WINDOW)
    for line in p.stdout:
        line = line.rstrip()
        if line:
            log(line)
    return p.wait()


def publish(folder: Path, cfg: PublishConfig, log=print, interpreter: str = "", build_result=None,
            iscc: str = "") -> PublishResult:
    """Build the program and make its setup (see the module doc). Raises BuildError / SetupError."""
    from . import build as B
    folder = Path(folder).resolve()
    res = build_result or B.build(folder, cfg, log, interpreter)
    out = B.out_root(folder, cfg)
    out.mkdir(parents=True, exist_ok=True)
    result = PublishResult(Path(res.dist), res.exe, notes=list(res.notes))
    main_exe = Path(res.dist) / res.exe
    if cfg.sign.enabled and main_exe.is_file():
        from .sign import sign_file
        sign_file(folder, cfg, main_exe, log)
    if cfg.update.enabled and cfg.update.url:
        from .update import write_ps1
        write_ps1(cfg, Path(res.dist))
    if cfg.make_installer:
        iscc = iscc or tools.find_iscc() or tools.install_innosetup(log)
        if not iscc:
            raise SetupError("Inno Setup (ISCC.exe) is not available: the setup cannot be made. "
                             f"Get it from {tools.INNO_SITE} or let RAD IDE download it.")
        gen = out / "build" / "gen"
        gen.mkdir(parents=True, exist_ok=True)
        icon = B.make_icon(folder, cfg, gen, log)
        is64 = B.is_64bit(main_exe) if main_exe.is_file() else True
        iss = out / "build" / f"{cfg.exe_base()}.iss"
        iss.write_text(script(folder, cfg, Path(res.dist), res.exe, out, iscc, icon, is64), encoding="utf-8-sig")
        log(f"------ Setup (Inno Setup): {iss.name}")
        code = compile_setup(iss, iscc, log)
        setup = out / (setup_name(cfg) + ".exe")
        if code != 0 or not setup.is_file():
            raise SetupError(f"Inno Setup failed (exit code {code}); see the output above. Script: {iss}")
        if cfg.sign.enabled:
            from .sign import sign_file
            sign_file(folder, cfg, setup, log)
        result.setup = setup
        log(f"Setup created: {setup}  ({setup.stat().st_size // 1024} KB)")
    if cfg.make_zip:
        base = out / f"{cfg.exe_base()}-{cfg.version}-portable"
        result.zip = Path(shutil.make_archive(str(base), "zip", root_dir=res.dist))
        log(f"Portable zip: {result.zip}")
    if cfg.update.enabled and cfg.update.url:
        from .update import write_version_json
        result.version_json = write_version_json(cfg, out, result.setup.name if result.setup else "")
        log(f"Upload {result.version_json.name} and the setup to {cfg.update.url.rsplit('/', 1)[0]}/")
    for n in result.notes:
        log(f"Note: {n}")
    return result


def silent_install_args(target_dir: Path | None = None) -> list[str]:
    args = ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART", "/CURRENTUSER", "/SP-"]
    if target_dir is not None:
        args.append(f"/DIR={target_dir}")
    return args


SILENT_UNINSTALL_ARGS = ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART"]

__all__ = ["PublishResult", "SILENT_UNINSTALL_ARGS", "SetupError", "compile_setup", "language_lines", "publish",
           "script", "setup_name", "silent_install_args"]
