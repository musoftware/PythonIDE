"""Native builds of script GUI Bridge projects with an embedded interpreter: Lua ("lua-bridge").

One small exe = Lua 5.4 (MIT, compiled from the official lua.org source tarball, SHA-256 checked) + a C
host + radforms, all static, built with the IDE's MinGW-w64. The project's scripts (form code, modules,
pure-Lua LuaRocks packages from lua_modules) are embedded as one RCDATA resource ("RADLUA") and found by a
package searcher, so require("Helpers") / rad.load_file("Form1.lua") work as in the IDE. rad.lua is used
in a native variant (generated from runtimes/clients/lua/rad.lua): rad.set / rad.get / rad.call /
rad.msgbox / rad.input / rad.show / rad.hide / rad.quit / ui.<control> / rad.run call radforms directly
instead of the stdin/stdout protocol; the rest of rad.lua (JSON, ui sugar, handler lookup) is unchanged.

Not embedded (they stay on the bridge build, with the reason): radcall (RAD Hub), C modules (DLL rocks),
console scripts. JavaScript / TypeScript are built as Node.js single executables (node_sea.py); a small
QuickJS variant and Ruby (mruby) are not done (their bridge clients use Node / CRuby APIs: process,
child_process, sockets, net/http); Perl / PHP are too big to embed small.
"""
