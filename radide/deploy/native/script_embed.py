LANGS = ("lua-bridge",)
NAME = "native exe with embedded Lua 5.4 (radforms)"

LUA_VERSION = "5.4.9"
LUA_URL = f"https://www.lua.org/ftp/lua-{LUA_VERSION}.tar.gz"
LUA_SHA256 = "2335b6c582a52654f94612bf10d2f4672805d05329aa6568b1d8cd9e5c6fb8e6"
RAD_LUA = Path(__file__).resolve().parents[2] / "runtimes" / "clients" / "lua" / "rad.lua"
LUA_CFLAGS = ["-std=gnu99", "-c", "-Os", "-ffunction-sections", "-fno-asynchronous-unwind-tables",
              "-DLUA_COMPAT_5_3"]

HOST_C = r'''/* AUTO-GENERATED by RAD IDE - native exe host for a Lua project: Lua 5.4 + radforms, scripts embedded
 * as the RCDATA resource "RADLUA" (records: name NUL length NUL bytes). */
#include <windows.h>
#include <stdlib.h>
#include <string.h>
#include "lua.h"
#include "lauxlib.h"
#include "lualib.h"
#include "radforms.h"

static const char *g_pack;
static DWORD g_pack_len;

static int find_script(const char *name, const char **data, size_t *len)
{
    const char *p = g_pack, *end = g_pack + g_pack_len;
    while (p && p < end) {
        const char *n = p;
        size_t nl = strlen(n);
        const char *l = n + nl + 1;
        size_t sz = (size_t)strtoul(l, NULL, 10);
        const char *d = l + strlen(l) + 1;
        if (_stricmp(n, name) == 0) { *data = d; *len = sz; return 1; }
        p = d + sz;
    }
    return 0;
}

static void load_pack(void)
{
    HRSRC r = FindResourceA(NULL, "RADLUA", MAKEINTRESOURCEA(10));
    HGLOBAL g = r ? LoadResource(NULL, r) : NULL;
    g_pack = g ? (const char *)LockResource(g) : NULL;
    g_pack_len = r ? SizeofResource(NULL, r) : 0;
}

/* package searcher: module "a.b" -> embedded "a/b.lua", "a/b/init.lua", lua_modules ... */
static int searcher(lua_State *L)
{
    const char *mod = luaL_checkstring(L, 1);
    static const char *pats[] = { "%s.lua", "%s/init.lua", "lua_modules/share/lua/5.4/%s.lua",
                                  "lua_modules/share/lua/5.4/%s/init.lua", NULL };
    char path[1024], name[900];
    const char *data;
    size_t len, i;
    strncpy(name, mod, sizeof name - 1);
    name[sizeof name - 1] = 0;
    if (!(strlen(name) > 4 && strcmp(name + strlen(name) - 4, ".ref") == 0))   /* MathLib.ref stays a file name */
        for (i = 0; name[i]; i++) if (name[i] == '.') name[i] = '/';
    for (i = 0; pats[i]; i++) {
        snprintf(path, sizeof path, pats[i], name);
        if (find_script(path, &data, &len)) {
            char chunk[1040];
            snprintf(chunk, sizeof chunk, "@%s", path);
            if (luaL_loadbuffer(L, data, len, chunk) != LUA_OK) return lua_error(L);
            lua_pushstring(L, path);
            return 2;
        }
    }
    lua_pushfstring(L, "\n\tno embedded script '%s.lua'", name);
    return 1;
}

/* _RADNATIVE.loadfile(name) -> chunk | nil, message (embedded first, then the file system) */
static int n_loadfile(lua_State *L)
{
    const char *f = luaL_checkstring(L, 1);
    const char *data;
    size_t len;
    char chunk[1040];
    if (strncmp(f, "./", 2) == 0) f += 2;
    if (find_script(f, &data, &len)) {
        snprintf(chunk, sizeof chunk, "@%s", f);
        if (luaL_loadbuffer(L, data, len, chunk) != LUA_OK) { lua_pushnil(L); lua_insert(L, -2); return 2; }
        return 1;
    }
    if (luaL_loadfile(L, f) != LUA_OK) { lua_pushnil(L); lua_insert(L, -2); return 2; }
    return 1;
}

static const char *opt(lua_State *L, int i) { return luaL_optstring(L, i, ""); }
static int n_set(lua_State *L) { rad_set(opt(L, 1), opt(L, 2), opt(L, 3)); return 0; }
static int n_get(lua_State *L) { lua_pushstring(L, rad_get(opt(L, 1), opt(L, 2))); return 1; }
static int n_call(lua_State *L) { lua_pushstring(L, rad_call(opt(L, 1), opt(L, 2), opt(L, 3))); return 1; }
static int n_msgbox(lua_State *L) { rad_msgbox(opt(L, 1)); return 0; }
static int n_input(lua_State *L) { lua_pushstring(L, rad_input(opt(L, 1))); return 1; }
static int n_show(lua_State *L) { rad_show(opt(L, 1)); return 0; }
static int n_hide(lua_State *L) { rad_hide(opt(L, 1)); return 0; }
static int n_quit(lua_State *L) { (void)L; rad_end(); return 0; }
static int n_handlers(lua_State *L) { rad_handlers(opt(L, 1)); return 0; }
static int n_done(lua_State *L) { (void)L; rad_done(); return 0; }
static int n_next_event(lua_State *L)
{
    if (!rad_next_event()) return 0;
    lua_pushstring(L, rad_obj);
    lua_pushstring(L, rad_ev);
    lua_pushstring(L, rad_args);
    return 3;
}
static int n_print(lua_State *L)
{
    luaL_Buffer b;
    int i, n = lua_gettop(L);
    luaL_buffinit(L, &b);
    for (i = 1; i <= n; i++) {
        if (i > 1) luaL_addchar(&b, '\t');
        luaL_tolstring(L, i, NULL);
        luaL_addvalue(&b);
    }
    luaL_pushresult(&b);
    rad_print(lua_tostring(L, -1));
    return 0;
}

static const luaL_Reg native_fns[] = {
    {"set", n_set}, {"get", n_get}, {"call", n_call}, {"msgbox", n_msgbox}, {"input", n_input},
    {"show", n_show}, {"hide", n_hide}, {"quit", n_quit}, {"handlers", n_handlers}, {"done", n_done},
    {"next_event", n_next_event}, {"print", n_print}, {"loadfile", n_loadfile}, {NULL, NULL}
};

static void fail(lua_State *L, const char *what)
{
    const char *msg = lua_tostring(L, -1);
    char text[2048];
    snprintf(text, sizeof text, "%s:\n%s", what, msg ? msg : "(error object is not a string)");
    rad_print(text);
    rad_msgbox_ex(text, "Lua error", 16);
}

int main(void)
{
    lua_State *L = luaL_newstate();
    const char *data;
    size_t len;
    if (!L) return 1;
    luaL_openlibs(L);
    load_pack();
    luaL_newlib(L, native_fns);
    lua_setglobal(L, "_RADNATIVE");
    lua_pushcfunction(L, n_print);
    lua_setglobal(L, "print");
    /* package.searchers: ours right after the preload searcher */
    lua_getglobal(L, "package");
    lua_getfield(L, -1, "searchers");
    {
        lua_Integer i, n = (lua_Integer)luaL_len(L, -1);
        for (i = n; i >= 2; i--) { lua_rawgeti(L, -1, i); lua_rawseti(L, -2, i + 1); }
        lua_pushcfunction(L, searcher);
        lua_rawseti(L, -2, 2);
    }
    lua_pop(L, 2);
    if (!find_script("_radmain.lua", &data, &len)) {
        rad_msgbox_ex("The program's scripts are missing (resource RADLUA)", "Lua", 16);
        return 1;
    }
    if (luaL_loadbuffer(L, data, len, "@_radmain.lua") != LUA_OK || lua_pcall(L, 0, 0, 0) != LUA_OK) {
        fail(L, "_radmain.lua");
        lua_close(L);
        return 1;
    }
    lua_close(L);
    return 0;
}
'''

NATIVE_BLOCK = r'''-- ------------------------------------------------------------------ native exe (AUTO-GENERATED by RAD IDE)
-- The forms are drawn in process by radforms (C host + Lua 5.4 + radforms in one exe): the functions
-- above that spoke the stdin/stdout protocol are replaced by direct calls.
local N = _RADNATIVE
local function text(v) if v == nil then return "" end return tostring(v) end

function rad.set(obj, prop, value) N.set(obj, prop, text(value)) end
function rad.get(obj, prop) return N.get(obj, prop) end
function rad.call(obj, method, ...)
  local n, parts = select("#", ...), {}
  for i = 1, n do parts[i] = text((select(i, ...))) end
  return N.call(obj, method, table.concat(parts, "\t"))
end
function rad.msgbox(t) N.msgbox(text(t)); return "1" end
function rad.input(prompt) return N.input(text(prompt)) end
function rad.show(form) N.show(form) end
function rad.hide(form) N.hide(form) end
function rad.quit() N.quit(); os.exit(0) end
rad["end"] = rad.quit
function rad.radcall(name)
  error("radcall(" .. tostring(name) .. "): RAD Hub is not available in a native exe", 2)
end

function rad.load_file(file)
  local chunk, e = N.loadfile(file)
  if not chunk then N.print("[Lua] error in " .. file .. ": " .. tostring(e)); return end
  local ok, e2 = pcall(chunk)
  if not ok then N.print("[Lua] error in " .. file .. ": " .. tostring(e2)) end
end

function rad.run()
  local names = {}
  for k, v in pairs(_G) do
    if type(k) == "string" and type(v) == "function" and k:find("_", 2, true) then names[#names + 1] = k end
  end
  N.handlers(table.concat(names, ","))
  while true do
    local obj, ev, rest = N.next_event()
    if not obj then break end
    local h = find_handler(obj .. "_" .. ev)
    if h then
      local a = {}
      for w in (rest .. " "):gmatch("([^ ]*) ") do a[#a + 1] = w end
      local e = { X = tonumber(a[1]) or 0, Y = tonumber(a[2]) or 0, Button = tonumber(a[3]) or 0,
        KeyCode = tonumber(a[4]) or 0, KeyChar = a[5] or "", args = rest, object = obj, event = ev }
      local ok, err = xpcall(function() return h(e) end, debug.traceback)
      if not ok then N.print("[Lua] error in " .. obj .. "_" .. ev .. ": " .. tostring(err)) end
    end
    N.done()
  end
  os.exit(0)
end

'''


def native_rad_lua(src: str | None = None) -> str:
    """rad.lua with the native block inserted before its globals (same module, same API)."""
    text = src if src is not None else RAD_LUA.read_text(encoding="utf-8")
    marker = "-- globals for form code"
    if marker not in text or "local function find_handler" not in text:
        raise NativeUnsupported("rad.lua changed: the native variant cannot be made")
    i = text.index(marker)
    return "-- AUTO-GENERATED by RAD IDE from rad.lua - native exe variant (radforms)\n" + text[:i] + \
        NATIVE_BLOCK + text[i:]


# ------------------------------------------------------------------ Lua source
def lua_root() -> Path:
    from ...languages.bridgebase import toolchains_root
    return toolchains_root() / "lua-src" / f"lua-{LUA_VERSION}"


def ensure_lua_source(log=print) -> Path:
    """The src folder of the official Lua tarball (downloaded once into toolchains\\lua-src, SHA-256 checked)."""
    src = lua_root() / "src"
    if (src / "lua.h").is_file() and (src / "lapi.c").is_file():
        return src
    base = lua_root().parent
    dl = base / "_download"
    dl.mkdir(parents=True, exist_ok=True)
    tgz = dl / f"lua-{LUA_VERSION}.tar.gz"
    log(f"Downloading {LUA_URL} ...")
    try:
        with urllib.request.urlopen(urllib.request.Request(LUA_URL, headers={"User-Agent": "RAD-IDE"}),
                                    timeout=120) as r:
            data = r.read()
    except OSError as e:
        raise NativeUnsupported(f"the Lua source could not be downloaded ({e})")
    if hashlib.sha256(data).hexdigest() != LUA_SHA256:
        raise NativeUnsupported("the downloaded Lua source has a wrong SHA-256 - not used")
    tgz.write_bytes(data)
    log("SHA-256 OK, unpacking ...")
    with tarfile.open(tgz, "r:gz") as t:
        for m in t.getmembers():
            if m.name.startswith("/") or ".." in Path(m.name).parts or not (m.isfile() or m.isdir()):
                raise NativeUnsupported(f"unsafe entry in the Lua tarball: {m.name}")
        t.extractall(base, filter="data")
    tgz.unlink(missing_ok=True)
    (lua_root() / "RADIDE-SOURCE.json").write_text(json.dumps({"url": LUA_URL, "sha256": LUA_SHA256}, indent=1),
                                                   encoding="utf-8")
    if not (src / "lua.h").is_file():
        raise NativeUnsupported("the Lua tarball has no src/lua.h")
    return src


def lua_library(tc: dict, log) -> Path:
    """liblua.a (the core + standard libraries, no lua.c / luac.c), built once per gcc."""
    from ..build import BuildError
    src = ensure_lua_source(log)
    gcc_id = hashlib.sha1(str(Path(tc["cc"]).resolve()).lower().encode()).hexdigest()[:8]
    out = lua_root() / f"build-{gcc_id}"
    lib = out / "liblua.a"
    if lib.is_file():
        return lib
    out.mkdir(parents=True, exist_ok=True)
    env = _ffi.tool_env(Path(tc["cc"]).parent)
    objs = []
    for c in sorted(src.glob("*.c")):
        if c.name in ("lua.c", "luac.c", "onelua.c", "ltests.c"):
            continue
        o = out / (c.stem + ".o")
        if _ffi.run([tc["cc"], *LUA_CFLAGS, str(c), "-o", str(o)], out, lambda s: None, env) != 0:
            raise BuildError(f"Lua: {c.name} did not compile")
        objs.append(str(o))
    ar = str(Path(tc["cc"]).with_name("ar.exe"))
    if _ffi.run([ar, "rcs", str(lib), *objs], out, log, env) != 0:
        raise BuildError("ar failed for liblua.a")
    log(f"Lua {LUA_VERSION} library: {lib} ({lib.stat().st_size // 1024} KB)")
    return lib


# ------------------------------------------------------------------ project
SKIP_DIRS = {"_build", "Publish", "_radworker", ".git", ".vs", "node_modules", "__pycache__"}


def _plugin():
    from ...languages import get_plugin
    return get_plugin("lua-bridge")


def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def project_scripts(folder: Path, cfg=None) -> dict[str, Path]:
    """{name inside the exe (posix, relative): file} of the project's Lua files (+ lua_modules)."""
    from ..build import out_root
    out = {}
    pub = out_root(folder, cfg).resolve() if cfg is not None else None
    for p in sorted(folder.rglob("*.lua")):
        rel = p.relative_to(folder)
        if any(part in SKIP_DIRS for part in rel.parts[:-1]) or (pub and pub in p.resolve().parents):
            continue
        if rel.as_posix().lower() in ("rad.lua", "radworker.lua", "_radmain.lua"):
            continue
        out[rel.as_posix()] = p
    return out


def _strip_lua_comments(text: str) -> str:
    text = re.sub(r"--\[(=*)\[.*?\]\1\]", " ", text, flags=re.S)
    return re.sub(r"--[^\n]*", "", text)


SET_RX = r"""\brad\.(?:set|get|getnum)\s*\(\s*["']([^"']*)["']\s*,\s*["']([^"']+)["']"""
CALL_RX = r"""\brad\.call\s*\(\s*["']([^"']*)["']\s*,\s*["']([^"']+)["']"""
STD_MODULES = {"rad", "string", "table", "math", "os", "io", "utf8", "coroutine", "debug", "package"}


def check(folder, project, cfg) -> list[str]:
    folder = Path(folder)
    from ..build import startup_language
    lang = startup_language(project)
    if lang not in LANGS:
        return [f"{lang} is not a Lua project"]
    reasons = _ffi.common_reasons(folder, project, lang)
    scripts = project_scripts(folder, cfg)
    srcs = {n: _strip_lua_comments(_read(p)) for n, p in scripts.items() if not n.startswith("lua_modules/")}
    reasons += _ffi.literal_api_reasons(srcs, SET_RX, CALL_RX)
    names = {n.lower() for n in scripts}
    for f, text in srcs.items():
        if re.search(r"\bradcall\s*\(", text):
            reasons.append(f"{f}: radcall (RAD Hub) is not available in a native exe")
        for mod in re.findall(r"""\brequire\s*\(?\s*["']([\w.]+)["']""", text):
            if mod in STD_MODULES or mod.endswith(".ref"):
                if mod.endswith(".ref"):
                    reasons.append(f"{f}: require(\"{mod}\") references another project (RAD Hub)")
                continue
            p = mod.replace(".", "/").lower()
            if not {f"{p}.lua", f"{p}/init.lua", f"lua_modules/share/lua/5.4/{p}.lua",
                    f"lua_modules/share/lua/5.4/{p}/init.lua"} & names:
                reasons.append(f"{f}: require(\"{mod}\") is not a Lua file of the project (C modules are not "
                               "embedded)")
    if any((folder / "lua_modules" / "lib").rglob("*.dll")) if (folder / "lua_modules" / "lib").is_dir() else False:
        reasons.append("lua_modules has C modules (DLLs): not embedded in a native exe")
    return reasons


def pack(scripts: dict[str, bytes]) -> bytes:
    out = bytearray()
    for name, data in scripts.items():
        out += name.encode("utf-8") + b"\0" + str(len(data)).encode("ascii") + b"\0" + data
    return bytes(out)


def build(folder, project, cfg, work, log):
    from ..build import BuildError
    folder = Path(folder).absolute()     # not resolve(): a deep project builds through its short alias (paths.short_alias)
    plugin = _plugin()
    tc = _ffi.mingw(log)
    liblua = lua_library(tc, log)
    nat = Path(work) / "native_lua"
    gen = _ffi.fresh(nat / "gen")
    notes = _ffi.update_note(cfg, log)
    scripts = {n: p.read_bytes() for n, p in project_scripts(folder, cfg).items()}
    scripts["rad.lua"] = native_rad_lua().encode("utf-8")
    scripts["_radmain.lua"] = plugin.main_source(project)[1].replace(
        "main program for the GUI Bridge", "main program (native exe, radforms)").encode("utf-8")
    (gen / "scripts.bin").write_bytes(pack(scripts))
    res = _ffi.resources(gen, project, folder, cfg, log, tc["windres"], fmt="coff",
                         rcdata={"RADLUA": gen / "scripts.bin"})
    lib_dir, objs = _ffi.mingw_radforms(nat, project, tc, log)
    host = nat / "_radluahost.c"
    host.write_text(HOST_C, encoding="utf-8")
    nomf = _ffi.no_default_manifest(nat, tc["cc"], log)
    dist = _ffi.dist_folder(work, cfg)
    exe = dist / (cfg.exe_base() + ".exe")
    cmd = [tc["cc"], "-B", str(nomf) + "\\", "-std=gnu99", "-Os", "-s", "-mwindows", "-ffunction-sections",
           "-fno-asynchronous-unwind-tables", "-Wl,--gc-sections", "-fno-ident", "-Wl,--build-id=none",
           "-I", str(liblua.parent.parent / "src"), "-I", str(lib_dir), str(host), *map(str, objs), str(res),
           "-L", str(lib_dir), "-lradforms", str(liblua), "-static", *(f"-l{x}" for x in _ffi.WIN_LIBS), "-lm",
           "-o", str(exe)]
    if _ffi.run(cmd, nat, log, _ffi.tool_env(Path(tc["cc"]).parent)) != 0:
        raise BuildError("The native Lua build failed (see the output above)")
    log(f"Embedded scripts: {', '.join(sorted(n for n in scripts if n not in ('rad.lua', '_radmain.lua')))}")
    return _ffi.finish(exe, dist, folder, cfg, log, notes,
                       f"Lua {LUA_VERSION} (MIT) + C host + radforms, MinGW-w64 gcc, static")


