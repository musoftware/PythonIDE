def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def project_files(folder: Path, cfg=None) -> list[str]:
    """Relative posix paths of the project's script / JSON files (embedded as SEA assets)."""
    from ..build import out_root
    pub = out_root(folder, cfg).resolve() if cfg is not None else None
    out = []
    for p in sorted(folder.rglob("*")):
        if not p.is_file() or p.suffix.lower() not in SCRIPT_EXT:
            continue
        rel = p.relative_to(folder)
        if any(part in SKIP_DIRS or part.startswith(".") for part in rel.parts[:-1]):
            continue
        if pub and pub in p.resolve().parents:
            continue
        low = rel.as_posix().lower()
        if low in ("_radmain.js", "radgui.js", "radworker.js", "radgui.d.ts") or low.endswith(".d.ts") or \
                low in ("package-lock.json", "tsconfig.json", "publish.json", "project.radproj"):
            continue
        out.append(rel.as_posix())
    return out


def _strip_js_comments(text: str) -> str:
    return _ffi.strip_c_comments(text)


def _builtins(node: str) -> set[str]:
    try:
        out = subprocess.run([node, "-p", "require('module').builtinModules.join(',')"], capture_output=True,
                             text=True, timeout=60).stdout
        return {b.strip() for b in out.split(",") if b.strip()}
    except (OSError, subprocess.SubprocessError):
        return {"fs", "path", "os", "util", "events", "child_process", "crypto", "http", "https", "url",
                "stream", "zlib", "net", "readline", "assert", "buffer", "worker_threads", "vm", "module"}


def _package_dir(folder: Path, name: str) -> Path:
    parts = name.split("/")
    pkg = "/".join(parts[:2]) if name.startswith("@") else parts[0]
    return folder / "node_modules" / pkg


def npm_requires(folder: Path, files: list[str], builtins: set[str]) -> tuple[list[str], list[str]]:
    """(npm package names required by the scripts, reasons)."""
    pkgs, reasons = [], []
    for f in files:
        if f.lower().endswith(".json"):
            continue
        raw = _read(folder / f)
        text = raw
        for _q, name in _REQ_RX.findall(text):
            if name.startswith((".", "/")) or name.startswith("node:") or name.split("/")[0] in builtins:
                continue
            if name not in pkgs:
                pkgs.append(name)
        for a, b in _IMPORT_RX.findall(text):
            reasons.append(f"{f}: ES module import ('{a or b}') - the scripts are loaded like in the IDE; use require()")
    return pkgs, reasons


def check(folder, project, cfg) -> list[str]:
    folder = Path(folder)
    from ..build import startup_language
    lang = startup_language(project)
    if lang not in LANGS:
        return [f"{lang} is not a JavaScript / TypeScript project"]
    reasons = _ffi.common_reasons(folder, project, lang)
    files = project_files(folder, cfg)
    srcs = {f: _strip_js_comments(_read(folder / f)) for f in files if not f.lower().endswith(".json")}
    reasons += _ffi.literal_api_reasons(
        srcs, r"""(?<![\w.$])(?:set|get|getNum)\s*\(\s*["'`]([^"'`]*)["'`]\s*,\s*["'`]([^"'`]+)["'`]""",
        r"""(?<![\w.$])call\s*\(\s*["'`]([^"'`]*)["'`]\s*,\s*["'`]([^"'`]+)["'`]""")
    for f, text in srcs.items():
        if re.search(r"(?<![\w.$])radcall\s*\(", text):
            reasons.append(f"{f}: radcall (RAD Hub) is not available in a native exe")
    if any(f.lower().endswith((".ref.js", ".ref.ts")) for f in files):
        reasons.append("the project references other projects (RAD Hub): not possible in one native exe")
    node = find_node(download=False)
    pkgs, rs = npm_requires(folder, files, _builtins(node) if node else set())
    reasons += rs
    for name in pkgs:
        d = _package_dir(folder, name)
        if not d.is_dir():
            reasons.append(f"npm package '{name}' is not installed in node_modules (npm install)")
        elif any(d.rglob("*.node")):
            reasons.append(f"npm package '{name}' has a native addon (.node): not bundled into a single exe")
    return reasons


