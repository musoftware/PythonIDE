def download_node(log=print) -> str:
    """The latest LTS node.exe from nodejs.org (zip, SHA-256 from the release's SHASUMS256.txt) into
    %LOCALAPPDATA%\\RADIDE\\toolchains\\node - portable, no admin rights."""
    try:
        with urllib.request.urlopen(urllib.request.Request(NODE_LTS_INDEX, headers={"User-Agent": "RAD-IDE"}),
                                    timeout=30) as r:
            index = json.loads(r.read().decode("utf-8"))
        rel = next(v for v in index if v.get("lts") and "win-x64-zip" in v.get("files", []))
        ver = rel["version"]
        base = f"https://nodejs.org/dist/{ver}/"
        name = f"node-{ver}-win-x64.zip"
        with urllib.request.urlopen(urllib.request.Request(base + "SHASUMS256.txt", headers={"User-Agent": "RAD-IDE"}),
                                    timeout=30) as r:
            sums = r.read().decode("ascii", "replace")
        m = re.search(rf"^([0-9a-f]{{64}})\s+{re.escape(name)}$", sums, re.M)
        if not m:
            raise ValueError("no SHA-256 for " + name)
        log(f"Downloading {base + name} ...")
        with urllib.request.urlopen(urllib.request.Request(base + name, headers={"User-Agent": "RAD-IDE"}),
                                    timeout=600) as r:
            data = r.read()
    except (OSError, ValueError, StopIteration, KeyError) as e:
        log(f"Node.js download failed: {e}")
        return ""
    if hashlib.sha256(data).hexdigest() != m.group(1):
        log("Node.js: SHA-256 mismatch - not used")
        return ""
    dest = _toolchains() / "node"
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for info in z.infolist():
            if info.filename.startswith("/") or ".." in Path(info.filename).parts:
                log("unsafe path in the Node.js zip")
                return ""
        tmp = dest.with_name("node_tmp")
        shutil.rmtree(tmp, ignore_errors=True)
        z.extractall(tmp)
    inner = next(tmp.iterdir())
    shutil.rmtree(dest, ignore_errors=True)
    shutil.move(str(inner), str(dest))
    shutil.rmtree(tmp, ignore_errors=True)
    (dest / "RADIDE-SOURCE.json").write_text(json.dumps({"url": base + name, "sha256": m.group(1)}), encoding="utf-8")
    return str(dest / "node.exe")


def find_node(log=print, download: bool = True) -> str:
    """node.exe that supports single executable applications (Node 20.12+): PATH / the JavaScript plugin's
    locations, %LOCALAPPDATA%\\RADIDE\\toolchains\\node, else the LTS is downloaded from nodejs.org."""
    from ...languages import get_plugin
    cands = [get_plugin("javascript").tool(), str(_toolchains() / "node" / "node.exe")]
    for c in cands:
        if c and Path(c).is_file() and _node_version(c)[:2] >= MIN_NODE:
            return c
    if not download:
        return ""
    log("Node.js 20.12 or newer was not found: downloading the LTS from nodejs.org ...")
    return download_node(log)


