"""Native builds of JavaScript / TypeScript GUI Bridge projects as a Node.js single executable application.

The exe IS Node.js (the official nodejs.org binary, V8, every Node API, npm packages): the project's scripts
run exactly as under the IDE, only the forms are not drawn by the IDE's Python host but by a tiny native
**radforms host** (C + radforms, ~100 KB, built per app with the forms, images, manifest and icon as
resources) that is embedded in the exe as a SEA asset. At start-up the program extracts it once to
%LOCALAPPDATA%\\RADIDE\\apps\\<hash>\\ and talks to it over a named pipe with the GUI Bridge line protocol
(the host serves it in process with rad_command / rad_event_line). No Python anywhere.

    one exe = node.exe + SEA blob { main: radgui.js (native variant) + _radmain,
                                    assets: the project's scripts (TypeScript transpiled at build time
                                            with Node's own type stripper, like the IDE runs it),
                                            npm dependencies bundled by esbuild, the radforms host }

Why a second process and not an N-API addon: an addon must be loaded from disk with process.dlopen and
imports its napi_* functions from "node.exe" (a SEA exe has another name: MSVC delay-load hooks, not
available with MinGW) - the host process needs nothing from Node and keeps the client's synchronous model
(fs.readSync / writeSync on the pipe), so every Node version that supports SEA works.

Build steps: node --experimental-sea-config (Node 20+), then the blob is added as the RCDATA resource
NODE_SEA_BLOB with the Windows resource API, the SEA fuse is flipped (what postject does), the signature of
node.exe is removed (invalid after the edit), the app's icon / version resources replace Node's, and the
subsystem is set to Windows GUI (no console window).
"""
