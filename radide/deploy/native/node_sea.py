def find_esbuild(log=print, download: bool = True) -> str:
    p = shutil.which("esbuild")
    if p:
        return p
    root = _toolchains() / "esbuild"
    found = sorted(root.glob("*/esbuild.exe")) if root.is_dir() else []
    if found:
        return str(found[-1])
    if not download:
        return ""
    import base64
    try:
        with urllib.request.urlopen(urllib.request.Request(ESBUILD_META, headers={"User-Agent": "RAD-IDE"}),
                                    timeout=30) as r:
            meta = json.loads(r.read().decode("utf-8"))
        url, integrity, ver = meta["dist"]["tarball"], meta["dist"]["integrity"], meta["version"]
        if not url.startswith("https://registry.npmjs.org/@esbuild/win32-x64/") or not integrity.startswith("sha512-"):
            raise ValueError("unexpected esbuild package data")
        log(f"Downloading {url} ...")
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "RAD-IDE"}), timeout=300) as r:
            data = r.read()
    except (OSError, ValueError, KeyError) as e:
        log(f"esbuild download failed: {e}")
        return ""
    if base64.b64encode(hashlib.sha512(data).digest()).decode() != integrity[7:]:
        log("esbuild: SHA-512 mismatch - not used")
        return ""
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as t:
        m = t.getmember("package/esbuild.exe")
        f = t.extractfile(m)
        dest = root / ver
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "esbuild.exe").write_bytes(f.read())
    (dest / "RADIDE-SOURCE.json").write_text(json.dumps({"url": url, "integrity": integrity}), encoding="utf-8")
    return str(dest / "esbuild.exe")


