HOST_C = r'''/* AUTO-GENERATED by RAD IDE - radforms host of a Node.js single executable: serves the GUI Bridge line
 * protocol on a named pipe (argv[1]) with radforms (rad_command / rad_event_line) in process.
 *   from Node: SET/GET/CALL/MSGBOX/INPUT/SHOW/HIDE/DONE/END lines, "ESC <command>" (\\ \n \r escaped) and
 *              NEXT (= wait for the next event); answers of GET/CALL/MSGBOX/INPUT go back as one line. */
#include <windows.h>
#include <shellapi.h>
#include <stdlib.h>
#include <string.h>
#include "radforms.h"

static HANDLE g_pipe = INVALID_HANDLE_VALUE;
static volatile LONG g_connected;
static char *g_in;
static size_t g_len, g_cap;

static DWORD WINAPI watchdog(LPVOID p) { (void)p; Sleep(30000); if (!g_connected) ExitProcess(3); return 0; }

static char *read_line(void)
{
    for (;;) {
        char *nl = g_len ? memchr(g_in, '\n', g_len) : NULL;
        if (nl) {
            size_t n = (size_t)(nl - g_in);
            char *line = (char *)malloc(n + 1);
            memcpy(line, g_in, n);
            line[n] = 0;
            if (n && line[n - 1] == '\r') line[n - 1] = 0;
            memmove(g_in, nl + 1, g_len - n - 1);
            g_len -= n + 1;
            return line;
        }
        if (g_cap - g_len < 4096) {
            g_cap = g_cap ? g_cap * 2 : 65536;
            g_in = (char *)realloc(g_in, g_cap);
        }
        {
            DWORD got = 0;
            if (!ReadFile(g_pipe, g_in + g_len, (DWORD)(g_cap - g_len), &got, NULL) || got == 0) return NULL;
            g_len += got;
        }
    }
}

static void write_line(const char *s)
{
    DWORD n;
    size_t len = strlen(s ? s : "");
    char *b = (char *)malloc(len + 2);
    memcpy(b, s ? s : "", len);
    b[len] = '\n';
    WriteFile(g_pipe, b, (DWORD)len + 1, &n, NULL);
    free(b);
}

static char *unesc(const char *s)
{
    char *o = (char *)malloc(strlen(s) + 1), *d = o;
    for (; *s; s++) {
        if (*s == '\\' && (s[1] == 'n' || s[1] == 'r' || s[1] == '\\')) {
            s++;
            *d++ = *s == 'n' ? '\n' : *s == 'r' ? '\r' : '\\';
        } else *d++ = *s;
    }
    *d = 0;
    return o;
}

static char *esc(const char *s)
{
    char *o = (char *)malloc(strlen(s) * 2 + 1), *d = o;
    for (; *s; s++) {
        if (*s == '\\') { *d++ = '\\'; *d++ = '\\'; }
        else if (*s == '\n') { *d++ = '\\'; *d++ = 'n'; }
        else if (*s == '\r') { *d++ = '\\'; *d++ = 'r'; }
        else *d++ = *s;
    }
    *d = 0;
    return o;
}

static int answers(const char *line)
{
    static const char *cmds[] = { "GET ", "CALL ", "MSGBOX", "INPUT", NULL };
    int i;
    for (i = 0; cmds[i]; i++) if (_strnicmp(line, cmds[i], strlen(cmds[i])) == 0) return 1;
    return 0;
}

int main(void)
{
    int argc = 0;
    wchar_t **argv = CommandLineToArgvW(GetCommandLineW(), &argc);
    char *line;
    if (argc < 2) {
        rad_msgbox_ex("This is the forms host of a RAD IDE program: start the program itself.", "RAD IDE", 64);
        return 2;
    }
    g_pipe = CreateNamedPipeW(argv[1], PIPE_ACCESS_DUPLEX | FILE_FLAG_FIRST_PIPE_INSTANCE,
                              PIPE_TYPE_BYTE | PIPE_READMODE_BYTE | PIPE_WAIT | PIPE_REJECT_REMOTE_CLIENTS,
                              1, 65536, 65536, 0, NULL);
    if (g_pipe == INVALID_HANDLE_VALUE) return 4;
    CreateThread(NULL, 0, watchdog, NULL, 0, NULL);
    if (!ConnectNamedPipe(g_pipe, NULL) && GetLastError() != ERROR_PIPE_CONNECTED) return 5;
    InterlockedExchange(&g_connected, 1);
    while ((line = read_line()) != NULL) {
        if (strcmp(line, "NEXT") == 0) {
            const char *ev = rad_event_line();
            int quit = strcmp(ev, "QUIT") == 0;
            write_line(ev);
            free(line);
            if (quit) break;
            continue;
        }
        if (strncmp(line, "ESC ", 4) == 0) {
            char *cmd = unesc(line + 4);
            int want = answers(cmd);
            const char *r = rad_command(cmd);
            if (want) { char *e = esc(r ? r : ""); write_line(e); free(e); }
            free(cmd);
        } else {
            int want = answers(line);
            const char *r = rad_command(line);
            if (want) write_line(r ? r : "");
        }
        free(line);
    }
    /* Node has quit (or the forms were closed): give it a moment to read QUIT, then end */
    FlushFileBuffers(g_pipe);
    return 0;
}
'''

NATIVE_JS = r'''
// ------------------------------------------------------------------ native exe (AUTO-GENERATED by RAD IDE)
// Node.js single executable: the scripts are SEA assets, npm packages are bundled (rad/deps.js), and the
// forms are drawn by the native radforms host (rad/radhost.exe, extracted once) behind a named pipe.
const radSea = require('node:sea');
const RAD_DIR = path.dirname(process.execPath);
try { process.chdir(RAD_DIR); } catch (e) { /* read-only / network folder */ }
{
  // a GUI exe has no console: writes to stdout / stderr (console.log, error reports) are dropped, or
  // appended to the file named by the environment variable RAD_LOG
  const ws = fs.writeSync;
  const logFile = process.env.RAD_LOG || '';
  fs.writeSync = function (fd, ...a) {
    if (fd !== 1 && fd !== 2) return ws.call(fs, fd, ...a);
    if (logFile) {
      try { fs.appendFileSync(logFile, typeof a[0] === 'string' ? a[0] : a[0].subarray(a[1] || 0, (a[1] || 0) + (a[2] === undefined ? a[0].length : a[2]))); } catch (e) { /* ignore */ }
    }
    try { return ws.call(fs, fd, ...a); } catch (e) {
      return typeof a[0] === 'string' ? Buffer.byteLength(a[0]) : (typeof a[2] === 'number' ? a[2] : a[0].length);
    }
  };
}
const RAD_MANIFEST = JSON.parse(radSea.getAsset('rad/manifest.json', 'utf8'));
const radLower = new Map(RAD_MANIFEST.files.map((f) => [f.toLowerCase(), f]));
function radAssetKey(full) {
  return radLower.get(path.relative(RAD_DIR, path.resolve(full)).split(path.sep).join('/').toLowerCase());
}
function radIsAsset(full) { return radAssetKey(full) !== undefined; }
function radReadSource(full) {
  const k = radAssetKey(full);
  return k !== undefined ? radSea.getAsset('src/' + k, 'utf8') : fs.readFileSync(full, 'utf8');
}
let RAD_DEPS = null;
function radDeps() {
  if (RAD_DEPS === null) {
    RAD_DEPS = {};
    if (RAD_MANIFEST.deps) {
      const m = { exports: {} };
      vm.runInThisContext('(function (module, exports, require) {' + radSea.getAsset('rad/deps.js', 'utf8') + '\n})',
                          { filename: path.join(RAD_DIR, 'rad-deps.js') })(m, m.exports, require);
      RAD_DEPS = m.exports;
    }
  }
  return RAD_DEPS;
}
const radModules = new Map();
function radLoadModule(k) {
  if (radModules.has(k)) return radModules.get(k).exports;
  const m = { exports: {}, id: k, filename: path.join(RAD_DIR, k), loaded: false };
  radModules.set(k, m);
  let code = radSea.getAsset('src/' + k, 'utf8');
  if (code.charCodeAt(0) === 0xfeff) code = code.slice(1);
  if (/\.json$/i.test(k)) { m.exports = JSON.parse(code); return m.exports; }
  const dir = path.posix.dirname(k) === '.' ? '' : path.posix.dirname(k);
  const fn = vm.runInThisContext('(function (exports, require, module, __filename, __dirname) {' + code + '\n})',
                                 { filename: m.filename });
  fn.call(m.exports, m.exports, (n) => radRequireFrom(dir, n), m, m.filename, path.dirname(m.filename));
  m.loaded = true;
  return m.exports;
}
function radRequireFrom(base, name) {
  const deps = radDeps();
  if (Object.prototype.hasOwnProperty.call(deps, name)) return deps[name];
  if (/^\.{1,2}[\\/]/.test(name)) {
    const t = path.posix.normalize(path.posix.join(base, name.replace(/\\/g, '/')));
    for (const c of [t, t + '.js', t + '.ts', t + '.json', t + '/index.js', t + '/index.ts']) {
      const k = radLower.get(c.toLowerCase());
      if (k !== undefined) return radLoadModule(k);
    }
    return require('module').createRequire(path.join(RAD_DIR, 'package.json'))(path.join(RAD_DIR, base, name));
  }
  return require(name);
}
function radNativeRequire(name) { return radRequireFrom('', name); }
function radStartHost() {
  const bytes = Buffer.from(radSea.getAsset('rad/radhost.exe'));
  const tryDirs = [path.join(process.env.LOCALAPPDATA || require('os').tmpdir(), 'RADIDE', 'apps', RAD_MANIFEST.host),
                   path.join(require('os').tmpdir(), 'RADIDE-apps', RAD_MANIFEST.host)];
  let exe = null, lastErr = null;
  for (const dir of tryDirs) {
    const f = path.join(dir, RAD_MANIFEST.hostName);
    try {
      if (!fs.existsSync(f) || fs.statSync(f).size !== bytes.length) {
        fs.mkdirSync(dir, { recursive: true });
        const tmp = f + '.' + process.pid + '.tmp';
        fs.writeFileSync(tmp, bytes);
        try { fs.renameSync(tmp, f); } catch (e) { fs.rmSync(tmp, { force: true }); if (!fs.existsSync(f)) throw e; }
      }
      exe = f;
      break;
    } catch (e) { lastErr = e; }
  }
  if (!exe) throw lastErr;
  const pipe = '\\\\.\\pipe\\radforms-' + process.pid + '-' + require('crypto').randomBytes(8).toString('hex');
  require('child_process').spawn(exe, [pipe], { stdio: 'ignore', windowsHide: false });
  const end = Date.now() + 20000;
  for (;;) {
    try { return fs.openSync(pipe, 'r+'); } catch (e) {
      if (Date.now() > end) throw new Error('the forms host did not start: ' + e.message);
      sleepMs(15);
    }
  }
}
const RAD_FD = radStartHost();

'''


def native_client(src: str | None = None) -> str:
    """radgui.js with its stdin/stdout I/O, file loading and require replaced (same API, same loader)."""
    text = src if src is not None else RADGUI_JS.read_text(encoding="utf-8")
    subs = [
        ("fs.readSync(0, CHUNK", "fs.readSync(RAD_FD, CHUNK"),
        ("writeFd(1, text + '\\n');", "writeFd(RAD_FD, text + '\\n');"),
        ("let code = fs.readFileSync(full, 'utf8');", "let code = radReadSource(full);"),
        ("if (/\\.(ts|mts|cts)$/i.test(full)) code = stripTypes(code, full);",
         "if (/\\.(ts|mts|cts)$/i.test(full) && !radIsAsset(full)) code = stripTypes(code, full);"),
        ("g.require = createRequire(path.join(folder, 'package.json'));", "g.require = radNativeRequire;"),
        ("  for (;;) {\n    const line = readLine();\n", "  for (;;) {\n    writeLine('NEXT');\n    const line = readLine();\n"),
    ]
    for old, new in subs:
        if text.count(old) != 1:
            raise NativeUnsupported(f"radgui.js changed: '{old.splitlines()[0]}' not found once for the native variant")
        text = text.replace(old, new)
    marker = "// ------------------------------------------------------------------ protocol"
    if text.count(marker) != 1:
        raise NativeUnsupported("radgui.js changed: no protocol section for the native variant")
    return text.replace(marker, NATIVE_JS + marker)


