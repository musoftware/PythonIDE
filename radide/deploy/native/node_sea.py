TRANSPILE_JS = r'''// RAD IDE: TypeScript -> JavaScript like the IDE runs it (Node's type stripper, else the typescript package)
const fs = require('fs'); const path = require('path'); const mod = require('module');
const [, , folder, out, ...files] = process.argv;
let ts = null;
for (const f of files) {
  let code = fs.readFileSync(path.join(folder, f), 'utf8');
  if (code.charCodeAt(0) === 0xfeff) code = code.slice(1);
  let js;
  if (typeof mod.stripTypeScriptTypes === 'function') {
    try { js = mod.stripTypeScriptTypes(code, { mode: 'transform', sourceUrl: f }); }
    catch (e) { if (!/mode|transform/i.test(String(e && e.message))) throw new Error(f + ': ' + e.message);
                js = mod.stripTypeScriptTypes(code, { mode: 'strip', sourceUrl: f }); }
  } else {
    if (!ts) ts = mod.createRequire(path.join(folder, 'package.json'))('typescript');
    js = ts.transpileModule(code, { fileName: f, compilerOptions: { target: ts.ScriptTarget.ES2022,
                                                                   module: ts.ModuleKind.None } }).outputText;
  }
  const dst = path.join(out, f);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, js);
}
'''


def _host(nat: Path, project, folder: Path, cfg, tc: dict, log) -> Path:
    from ..build import BuildError
    gen = _ffi.fresh(nat / "host_gen")
    res = _ffi.resources(gen, project, folder, cfg, log, tc["windres"], fmt="coff")
    lib_dir, objs = _ffi.mingw_radforms(nat, project, tc, log)
    (nat / "_radhost.c").write_text(HOST_C, encoding="utf-8")
    nomf = _ffi.no_default_manifest(nat, tc["cc"], log)
    exe = nat / "radhost.exe"
    cmd = [tc["cc"], "-B", str(nomf) + os.sep, "-std=gnu99", "-Os", "-s", "-mwindows", "-ffunction-sections",
           "-fno-asynchronous-unwind-tables", "-Wl,--gc-sections", "-fno-ident", "-Wl,--build-id=none",
           "-I", str(lib_dir), str(nat / "_radhost.c"), *map(str, objs), str(res), "-L", str(lib_dir), "-lradforms",
           "-static", *(f"-l{x}" for x in _ffi.WIN_LIBS), "-lm", "-o", str(exe)]
    if _ffi.run(cmd, nat, log, _ffi.tool_env(Path(tc["cc"]).parent)) != 0 or not exe.is_file():
        raise BuildError("The radforms host did not build (see the output above)")
    return exe


def _app_resources(nat: Path, folder: Path, cfg, tc: dict, log) -> list:
    """Icon (if any) + version info of the app, as resource entries replacing Node's."""
    from ..build import make_icon
    from . import radforms_gen as rg
    d = _ffi.fresh(nat / "app_res")
    rc = rg.write_resources(d, None, folder, cfg, log, gui=False, icon=make_icon(folder, cfg, d / "icon", log))
    text = rc.read_text(encoding="utf-8").replace('1 24 "app.manifest"\n', "")   # keep Node's manifest
    rc.write_text(text, encoding="utf-8")
    out = d / "app.res"
    r = subprocess.run([tc["windres"], "--input-format=rc", "--output-format=res", "-c", "65001", "-i", rc.name,
                        "-o", out.name], cwd=str(d), capture_output=True, text=True,
                       env=_ffi.tool_env(Path(tc["windres"]).parent))
    if r.returncode != 0 or not out.is_file():
        log("windres (app resources) failed: " + (r.stdout + r.stderr).strip())
        return []
    return _pefix.res_file_entries(out)


def build(folder, project, cfg, work, log):
    from ..build import BuildError
    folder = Path(folder).resolve()
    lang = project.form_languages.get(project.startup, project.language) if project.startup else project.language
    plugin = _plugin(lang)
    node = find_node(log)
    if not node:
        raise NativeUnsupported("Node.js 20.12+ was not found and could not be downloaded")
    nver = _node_version(node)
    log(f"Node.js {'.'.join(map(str, nver))}: {node}")
    tc = _ffi.mingw(log)
    nat = Path(work) / "native_node"
    nat.mkdir(parents=True, exist_ok=True)
    src = _ffi.fresh(nat / "src")
    notes = _ffi.update_note(cfg, log)

    # 1. the forms host
    host = _host(nat, project, folder, cfg, tc, log)
    log(f"radforms host: {host.stat().st_size // 1024} KB")

    # 2. scripts (TypeScript transpiled now, like the IDE does at run time)
    files = project_files(folder, cfg)
    ts = [f for f in files if f.lower().endswith(".ts")]
    for f in files:
        if f not in ts:
            (src / f).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(folder / f, src / f)
    if ts:
        (nat / "_transpile.js").write_text(TRANSPILE_JS, encoding="utf-8")
        if _ffi.run([node, "--no-warnings", str(nat / "_transpile.js"), str(folder), str(src), *ts], nat, log) != 0:
            raise BuildError("TypeScript could not be turned into JavaScript (see the output above)")

    # 3. npm dependencies -> one CommonJS bundle (esbuild)
    pkgs, _r = npm_requires(folder, files, _builtins(node))
    if pkgs:
        esb = find_esbuild(log)
        if not esb:
            raise NativeUnsupported("esbuild (to bundle the npm packages) was not found and could not be downloaded")
        entry = nat / "_deps_entry.js"
        entry.write_text("module.exports = {\n" + "".join(f"  {json.dumps(p)}: require({json.dumps(p)}),\n"
                                                          for p in pkgs) + "};\n", encoding="utf-8")
        deps = nat / "deps.js"
        cmd = [esb, str(entry), "--bundle", "--platform=node", "--format=cjs", "--minify-syntax",
               "--log-level=warning", f"--outfile={deps}"]
        # the entry lives in the build folder (maybe outside the project): esbuild resolves through NODE_PATH
        env = dict(os.environ, NODE_PATH=str(folder / "node_modules"))
        if _ffi.run(cmd, folder, log, env) != 0:
            raise BuildError("esbuild could not bundle the npm packages (see the output above)")
        log(f"npm packages bundled: {', '.join(pkgs)} ({deps.stat().st_size // 1024} KB)")

    # 4. main script + SEA config
    code_files = plugin.code_files(project)
    main = nat / "sea_main.js"
    main.write_text(native_client() + "\n// ---- start (AUTO-GENERATED by RAD IDE)\n"
                    f"module.exports.runMain({json.dumps(code_files)}, RAD_DIR);\n", encoding="utf-8")
    host_bytes = host.read_bytes()
    manifest = {"files": files, "deps": bool(pkgs), "host": hashlib.sha256(host_bytes).hexdigest()[:16],
                "hostName": re.sub(r"[^A-Za-z0-9_.-]", "", cfg.exe_base()) + "-forms.exe"}
    (nat / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
    assets = {"rad/manifest.json": str(nat / "manifest.json"), "rad/radhost.exe": str(host)}
    if pkgs:
        assets["rad/deps.js"] = str(nat / "deps.js")
    for f in files:
        assets["src/" + f] = str(src / f)
    blob = nat / "sea-prep.blob"
    seacfg = {"main": str(main), "output": str(blob), "disableExperimentalSEAWarning": True, "useSnapshot": False,
              "useCodeCache": False, "assets": assets}
    (nat / "sea-config.json").write_text(json.dumps(seacfg, indent=1), encoding="utf-8")
    blob.unlink(missing_ok=True)
    if _ffi.run([node, "--experimental-sea-config", str(nat / "sea-config.json")], nat, log) != 0 or not blob.is_file():
        raise BuildError("node --experimental-sea-config failed (see the output above)")

    # 5. node.exe + blob -> the program
    dist = _ffi.dist_folder(work, cfg)
    exe = dist / (cfg.exe_base() + ".exe")
    shutil.copy2(node, exe)
    try:
        _pefix.strip_signature(exe)
        items = [(_pefix.RT_RCDATA, "NODE_SEA_BLOB", 0, blob.read_bytes())]
        items += _app_resources(nat, folder, cfg, tc, log)
        _pefix.add_resources(exe, items)
        _pefix.flip_fuse(exe, SEA_FUSE)
        _pefix.set_gui_subsystem(exe)
    except (OSError, ValueError) as e:
        raise BuildError(f"The Node.js single executable could not be made: {e}")
    lic = Path(node).with_name("LICENSE")
    if lic.is_file():                   # Node.js is MIT and bundles V8, OpenSSL, ICU ...: their notices travel along
        shutil.copy2(lic, dist / "Node.js-LICENSE.txt")
        notes.append("The program contains Node.js: Node.js-LICENSE.txt (MIT and the licences of the libraries "
                     "Node.js includes) must be distributed with it.")
    return _ffi.finish(exe, dist, folder, cfg, log, notes,
                       f"Node.js {'.'.join(map(str, nver))} single executable + radforms host "
                       f"({host.stat().st_size // 1024} KB, MinGW-w64)")


