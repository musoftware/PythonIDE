"""Native Go builds of Go GUI Bridge projects ("go-bridge"): one standalone exe with the forms inside.

The project's Go files are compiled unchanged with a native variant of radlib.go (same API: Set / Get /
GetNum / Call / MsgBox / Input / Show / Hide / End / RadEvent / radRun) that calls radforms through cgo
instead of speaking the bridge protocol on stdin/stdout. radforms is linked statically from libradforms.a
built with the IDE's MinGW-w64 (the same gcc is cgo's C compiler and Go's external linker):

    go build -trimpath -ldflags "-s -w -H windowsgui -extldflags=-static"

Go itself is found like the Go plugin finds it (PATH, %LOCALAPPDATA%\\RADIDE\\toolchains\\go\\bin ...).
The package is a copy of the project's .go files in <Publish>/build/native_go (the project folder is never
changed); go.mod / go.sum are copied so the project's modules are used.
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from . import NativeUnsupported
from . import _ffi

LANGS = ("go-bridge",)
NAME = "native Go exe (cgo + radforms)"

RADLIB_NATIVE = r'''// RAD IDE - Go client, NATIVE EXE VARIANT (AUTO-GENERATED by RAD IDE from radlib.go; do not edit).
//
// Same API as radlib.go, but the forms are drawn in process by radforms (Win32), linked statically
// through cgo: no IDE, no Python, no stdin/stdout protocol.
package main

/*
#include <stdlib.h>
extern char rad_obj[256];
extern char rad_ev[256];
extern char rad_args[1024];
int rad_next_event(void);
void rad_done(void);
void rad_set(const char *obj, const char *prop, const char *value);
const char *rad_get(const char *obj, const char *prop);
const char *rad_call(const char *obj, const char *method, const char *args);
void rad_msgbox(const char *text);
const char *rad_input(const char *prompt);
void rad_show(const char *form);
void rad_hide(const char *form);
void rad_end(void);
void rad_print(const char *text);
void rad_handlers(const char *csv);
*/
import "C"

import (
	"fmt"
	"os"
	"runtime"
	"strconv"
	"strings"
	"unsafe"
)

// RadEvent holds the event arguments (mouse/key events; zeros otherwise).
type RadEvent struct {
	Object, Event, Args string
	X, Y, Button, KeyCode int
	KeyChar               string
}

func init() {
	runtime.LockOSThread() // windows belong to the thread that made them: the event loop stays on main's thread
}

func radC(s string) *C.char { return C.CString(strings.ReplaceAll(s, "\x00", "")) }

func radStr(v any) string { return fmt.Sprint(v) }

// Set sets a property: Set("lblOut", "Caption", "Hi").
func Set(obj, prop string, value any) {
	o, p, v := radC(obj), radC(prop), radC(radStr(value))
	C.rad_set(o, p, v)
	C.free(unsafe.Pointer(o))
	C.free(unsafe.Pointer(p))
	C.free(unsafe.Pointer(v))
}

// Get reads a property as text: Get("txtA", "Text").
func Get(obj, prop string) string {
	o, p := radC(obj), radC(prop)
	r := C.GoString(C.rad_get(o, p))
	C.free(unsafe.Pointer(o))
	C.free(unsafe.Pointer(p))
	return r
}

// GetNum reads a property as a number (0 when it is not numeric).
func GetNum(obj, prop string) float64 {
	s := strings.TrimSpace(Get(obj, prop))
	end := 0
	for end < len(s) && strings.ContainsRune("+-0123456789.eE", rune(s[end])) {
		end++
	}
	for end > 0 {
		if f, err := strconv.ParseFloat(s[:end], 64); err == nil {
			return f
		}
		end--
	}
	return 0
}

// Call calls a method: Call("lstLog", "AddItem", "text"). Returns the answer as text.
func Call(obj, method string, args ...any) string {
	parts := make([]string, len(args))
	for i, a := range args {
		parts[i] = radStr(a)
	}
	o, m, a := radC(obj), radC(method), radC(strings.Join(parts, "\t"))
	r := C.GoString(C.rad_call(o, m, a))
	C.free(unsafe.Pointer(o))
	C.free(unsafe.Pointer(m))
	C.free(unsafe.Pointer(a))
	return r
}

// MsgBox shows a message box and waits for OK.
func MsgBox(text any) string {
	t := radC(radStr(text))
	C.rad_msgbox(t)
	C.free(unsafe.Pointer(t))
	return "1"
}

// Input shows an input box and returns the text.
func Input(prompt any) string {
	p := radC(radStr(prompt))
	r := C.GoString(C.rad_input(p))
	C.free(unsafe.Pointer(p))
	return r
}

// Show shows a form.
func Show(form string) {
	f := radC(form)
	C.rad_show(f)
	C.free(unsafe.Pointer(f))
}

// Hide hides a form.
func Hide(form string) {
	f := radC(form)
	C.rad_hide(f)
	C.free(unsafe.Pointer(f))
}

// End quits the program.
func End() {
	C.rad_end()
	os.Exit(0)
}

func radPrint(s string) {
	t := radC(s)
	C.rad_print(t)
	C.free(unsafe.Pointer(t))
}

// radcallE: RAD Hub is not part of a native exe (the build falls back when the code uses radcall).
func radcallE(name string, args ...any) (any, error) {
	return nil, fmt.Errorf("radcall(%s): RAD Hub is not available in a native exe", name)
}

func radcall(name string, args ...any) any {
	r, err := radcallE(name, args...)
	if err != nil {
		panic(err)
	}
	return r
}

// ------------------------------------------------------------------ main loop
func radParseEvent(obj, ev, rest string) RadEvent {
	e := RadEvent{Object: obj, Event: ev, Args: rest}
	p := strings.SplitN(rest, " ", 5)
	num := func(i int) int {
		if i >= len(p) {
			return 0
		}
		f, _ := strconv.ParseFloat(p[i], 64)
		return int(f)
	}
	e.X, e.Y, e.Button, e.KeyCode = num(0), num(1), num(2), num(3)
	if len(p) > 4 {
		e.KeyChar = p[4]
	}
	return e
}

func radRunHandler(name string, h func(RadEvent), e RadEvent) {
	defer func() {
		if r := recover(); r != nil {
			radPrint(fmt.Sprintf("[Go] error in %s: %v", name, r))
		}
	}()
	h(e)
}

// radRun runs the radforms event loop and calls the matching handler for every event.
func radRun(handlers map[string]func(RadEvent)) {
	lower := map[string]func(RadEvent){}
	names := make([]string, 0, len(handlers))
	for k, v := range handlers {
		lower[strings.ToLower(k)] = v
		names = append(names, k)
	}
	csv := radC(strings.Join(names, ","))
	C.rad_handlers(csv)
	C.free(unsafe.Pointer(csv))
	for C.rad_next_event() != 0 {
		obj := C.GoString(&C.rad_obj[0])
		ev := C.GoString(&C.rad_ev[0])
		rest := C.GoString(&C.rad_args[0])
		name := obj + "_" + ev
		h, ok := handlers[name]
		if !ok {
			h, ok = lower[strings.ToLower(name)]
		}
		if ok {
			radRunHandler(name, h, radParseEvent(obj, ev, rest))
		}
		C.rad_done()
	}
	os.Exit(0)
}

var _ = []any{Set, Get, GetNum, Call, MsgBox, Input, Show, Hide, End, radcall, radcallE, radRun}
'''


def _plugin():
    from ...languages import get_plugin
    return get_plugin("go-bridge")


def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


SET_RX = r"""(?<![\w.])(?:Set|Get|GetNum)\s*\(\s*"([^"]*)"\s*,\s*"([^"]+)\""""
CALL_RX = r"""(?<![\w.])Call\s*\(\s*"([^"]*)"\s*,\s*"([^"]+)\""""


def _go_files(folder: Path) -> list[Path]:
    return [p for p in sorted(folder.glob("*.go"))
            if p.name not in ("radlib.go", "radmain_gen.go") and not p.name.endswith("_test.go")
            and not p.name.startswith(("_", "."))]


def check(folder, project, cfg) -> list[str]:
    folder = Path(folder)
    from ..build import startup_language
    lang = startup_language(project)
    if lang not in LANGS:
        return [f"{lang} is not a Go project"]
    plugin = _plugin()
    reasons = _ffi.common_reasons(folder, project, lang)
    if plugin.console_program(project):
        reasons.append("console program (no forms): it keeps the normal build")
    srcs = {p.name: _ffi.strip_c_comments(_read(p)) for p in _go_files(folder)}
    reasons += _ffi.literal_api_reasons(srcs, SET_RX, CALL_RX)
    for f, text in srcs.items():
        if re.search(r"\bradcallE?\s*\(", text):
            reasons.append(f"{f}: radcall (RAD Hub) is not available in a native exe")
        if re.search(r'^\s*import\s+"C"', text, re.M) or re.search(r'^\s*"C"\s*$', text, re.M):
            reasons.append(f"{f}: the project uses cgo itself (not supported by the native build)")
    if any(p.name.endswith("_ref.go") for p in folder.glob("*_ref.go")):
        reasons.append("the project references other projects (RAD Hub): not possible in one native exe")
    if not plugin.tool():
        reasons.append("Go was not found: " + plugin.install_hint)
    return reasons


def native_main(plugin, project) -> str:
    main = plugin.main_source(project)
    if main is None:
        raise NativeUnsupported("console program")
    return main[1].replace("main program for the GUI Bridge", "native exe main program (radforms)", 1)


def build(folder, project, cfg, work, log):
    from ..build import BuildError
    folder = Path(folder).absolute()     # not resolve(): a deep project builds through its short alias (paths.short_alias)
    plugin = _plugin()
    go = plugin.tool()
    if not go:
        raise NativeUnsupported("Go was not found")
    tc = _ffi.mingw(log)
    nat = Path(work) / "native_go"
    pkg = _ffi.fresh(nat / "pkg")
    gen = _ffi.fresh(nat / "gen")
    notes = _ffi.update_note(cfg, log)
    res = _ffi.resources(gen, project, folder, cfg, log, tc["windres"], fmt="coff")
    lib_dir, objs = _ffi.mingw_radforms(nat, project, tc, log)

    for p in _go_files(folder):
        shutil.copy2(p, pkg / p.name)
    for extra in ("go.mod", "go.sum"):
        if (folder / extra).is_file():
            shutil.copy2(folder / extra, pkg / extra)
    if not (pkg / "go.mod").is_file():
        (pkg / "go.mod").write_text(f"module radapp\n\ngo {plugin.go_version()}\n", encoding="utf-8")
    if (folder / "vendor").is_dir():
        shutil.copytree(folder / "vendor", pkg / "vendor")
    (pkg / "radlib.go").write_text(RADLIB_NATIVE, encoding="utf-8")
    (pkg / "radmain_gen.go").write_text(native_main(plugin, project), encoding="utf-8")

    def q(p) -> str:
        return '"' + str(p).replace("\\", "/") + '"'
    # CGO_LDFLAGS (libraries) is split with quoting and may appear twice on the gcc line; objects that must
    # be linked exactly once (_radmodules.o, the resources) go through -extldflags. Paths may contain spaces
    # ("RAD IDE Projects"): double quotes inside the single-quoted -extldflags value of -ldflags.
    if any("'" in str(p) for p in [*objs, res, lib_dir]):
        raise NativeUnsupported("the build folder path contains a ' (not possible with go build -ldflags)")
    libs = " ".join([q("-L" + str(lib_dir).replace("\\", "/")), "-lradforms", *(f"-l{lib}" for lib in _ffi.WIN_LIBS)])
    nomf = _ffi.no_default_manifest(nat, tc["cc"], log)
    ext = " ".join(["-static", "-Wl,--gc-sections", "-B", q(str(nomf).replace("\\", "/") + "/"),
                    *(q(o) for o in objs), q(res)])
    env = _ffi.tool_env(Path(tc["cc"]).parent)
    env.update(CGO_ENABLED="1", CC=tc["cc"], CGO_CFLAGS="-Os", CGO_LDFLAGS=libs, GOOS="windows",
               GOARCH="amd64", GOFLAGS="")
    dist = _ffi.dist_folder(work, cfg)
    exe = dist / (cfg.exe_base() + ".exe")
    cmd = [go, "build", "-trimpath", "-buildvcs=false", f"-ldflags=-s -w -H windowsgui -extldflags '{ext}'",
           "-o", str(exe), "."]
    if _ffi.run(cmd, pkg, log, env) != 0:
        raise BuildError("The native Go build failed (see the output above)")
    return _ffi.finish(exe, dist, folder, cfg, log, notes,
                       "Go + cgo, MinGW-w64 gcc as C compiler and external linker, libradforms.a, static")


__all__ = ["LANGS", "NAME", "RADLIB_NATIVE", "build", "check", "native_main"]
