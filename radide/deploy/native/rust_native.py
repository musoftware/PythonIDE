"""Native Rust builds of Rust GUI Bridge projects ("rust-bridge"): one standalone exe with the forms inside.

In the GUI Bridge design the Rust program only speaks the line protocol on stdin/stdout and the IDE's
Python/Tk host draws the forms - so the radapp.exe of a normal build shows nothing without the IDE. Here the
project's own code is compiled unchanged against a variant of radgui.rs whose I/O layer calls radforms
through extern "C" FFI (same module name, same functions: set / get / call / msgbox / input / show / hide /
end / print / num / str / event_args / Json ...), and radforms is linked statically:

    x86_64-pc-windows-msvc (rustc's usual host)  radforms.lib built with cl /Zl, link.exe of Visual C++,
                                                 +crt-static (no VCRUNTIME DLL), resources as app.res
    x86_64-pc-windows-gnu  (no Visual C++)       libradforms.a + the IDE's MinGW gcc as the linker
                                                 (only when rustup already has the target / can add it)

cargo build --release with opt-level "z", fat LTO, codegen-units 1, panic "abort", strip; the crate is a
copy of the project's .rs files in <Publish>/build/native_rust (the project folder is never changed), its
Cargo.toml keeps the project's [dependencies].
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

from . import NativeUnsupported
from . import _ffi

LANGS = ("rust-bridge",)
NAME = "native Rust exe (cargo + radforms)"

RADGUI_RS = Path(__file__).resolve().parents[2] / "runtimes" / "clients" / "rust" / "radgui.rs"
MSVC = "x86_64-pc-windows-msvc"
GNU = "x86_64-pc-windows-gnu"

NATIVE_HEAD = r'''//! RAD IDE GUI Bridge - Rust client, NATIVE EXE VARIANT (AUTO-GENERATED by RAD IDE from radgui.rs).
//!
//! Same API as radgui.rs, but the forms are drawn in process by radforms (Win32), linked statically:
//! no IDE, no Python, no stdin/stdout protocol.
#![allow(dead_code)]

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::ffi::{CStr, CString};
use std::fmt;
use std::io::{self, BufRead, Write};
use std::os::raw::{c_char, c_int};

unsafe extern "C" {
    static rad_obj: [c_char; 256];
    static rad_ev: [c_char; 256];
    static rad_args: [c_char; 1024];
    fn rad_next_event() -> c_int;
    fn rad_done();
    fn rad_set(obj: *const c_char, prop: *const c_char, value: *const c_char);
    fn rad_get(obj: *const c_char, prop: *const c_char) -> *const c_char;
    fn rad_call(obj: *const c_char, method: *const c_char, args: *const c_char) -> *const c_char;
    fn rad_msgbox(text: *const c_char);
    fn rad_input(prompt: *const c_char) -> *const c_char;
    fn rad_show(form: *const c_char);
    fn rad_hide(form: *const c_char);
    fn rad_end();
    fn rad_print(text: *const c_char);
    fn rad_handlers(csv: *const c_char);
}

thread_local! {
    static ARGS: RefCell<String> = RefCell::new(String::new());
}

fn cs(s: &str) -> CString {
    CString::new(s.replace('\0', "")).unwrap_or_default()
}

fn rs(p: *const c_char) -> String {
    if p.is_null() {
        String::new()
    } else {
        unsafe { CStr::from_ptr(p) }.to_string_lossy().into_owned()
    }
}

fn read_line() -> Option<String> {
    let mut s = String::new();
    match io::stdin().lock().read_line(&mut s) {
        Ok(0) | Err(_) => None,
        Ok(_) => Some(s.trim_end_matches(['\r', '\n']).to_string()),
    }
}

/// Used by the generated main program: only these handlers' events are reported.
pub fn native_handlers(csv: &str) {
    let c = cs(csv);
    unsafe { rad_handlers(c.as_ptr()) }
}

/// Used by the generated main program: next "<obj>_<event>" key, None = quit.
pub fn next_event() -> Option<String> {
    unsafe {
        if rad_next_event() == 0 {
            return None;
        }
        let obj = rs(std::ptr::addr_of!(rad_obj) as *const c_char);
        let ev = rs(std::ptr::addr_of!(rad_ev) as *const c_char);
        let args = rs(std::ptr::addr_of!(rad_args) as *const c_char);
        ARGS.with(|a| *a.borrow_mut() = args);
        Some(format!("{}_{}", obj, ev))
    }
}

pub fn done() {
    unsafe { rad_done() }
}

/// Event arguments of mouse/key events: "X Y Button KeyCode KeyChar".
pub fn event_args() -> String {
    ARGS.with(|a| a.borrow().clone())
}

/// One event argument (0-based): 0=X 1=Y 2=Button 3=KeyCode 4=KeyChar.
pub fn event_arg(i: usize) -> String {
    event_args().split_whitespace().nth(i).unwrap_or("").to_string()
}

// ------------------------------------------------------------------ GUI
pub fn set(obj: &str, prop: &str, value: impl fmt::Display) {
    let (o, p, v) = (cs(obj), cs(prop), cs(&value.to_string()));
    unsafe { rad_set(o.as_ptr(), p.as_ptr(), v.as_ptr()) }
}

pub fn get(obj: &str, prop: &str) -> String {
    let (o, p) = (cs(obj), cs(prop));
    rs(unsafe { rad_get(o.as_ptr(), p.as_ptr()) })
}

pub fn get_num(obj: &str, prop: &str) -> f64 {
    num(&get(obj, prop))
}

pub fn call(obj: &str, method: &str, args: &[&str]) -> String {
    let (o, m, a) = (cs(obj), cs(method), cs(&args.join("\t")));
    rs(unsafe { rad_call(o.as_ptr(), m.as_ptr(), a.as_ptr()) })
}

pub fn msgbox(text: impl fmt::Display) {
    let t = cs(&text.to_string());
    unsafe { rad_msgbox(t.as_ptr()) }
}

pub fn input(prompt: &str) -> String {
    let p = cs(prompt);
    rs(unsafe { rad_input(p.as_ptr()) })
}

pub fn show(form: &str) {
    let f = cs(form);
    unsafe { rad_show(f.as_ptr()) }
}

pub fn hide(form: &str) {
    let f = cs(form);
    unsafe { rad_hide(f.as_ptr()) }
}

/// Quit the program (after the current handler).
pub fn end() {
    unsafe { rad_end() }
}

/// A line for the debugger output (OutputDebugString) / stdout when there is one.
pub fn print(text: impl fmt::Display) {
    let t = cs(&text.to_string());
    unsafe { rad_print(t.as_ptr()) }
}

pub fn num(text: &str) -> f64 {
    text.trim().parse::<f64>().unwrap_or(0.0)
}

pub fn str(x: f64) -> String {
    format!("{}", x)
}

'''

NATIVE_RADCALL = r'''
// ------------------------------------------------------------------ RAD Hub
/// RAD Hub is not part of a native exe (the build falls back to the GUI Bridge when the code uses radcall).
pub fn radcall(name: &str, _args: &[Json]) -> Result<Json, String> {
    Err(format!("radcall({}): RAD Hub is not available in a native exe", name))
}

'''


def native_radgui(src: str | None = None) -> str:
    """radgui.rs with its protocol / GUI / RAD Hub parts replaced by radforms FFI (JSON + worker kept)."""
    text = src if src is not None else RADGUI_RS.read_text(encoding="utf-8")
    i_json = text.find("// ------------------------------------------------------------------ JSON")
    i_hub = text.find("// ------------------------------------------------------------------ RAD Hub")
    i_worker = text.find("// ------------------------------------------------------------------ worker")
    if min(i_json, i_hub, i_worker) < 0 or not i_json < i_hub < i_worker:
        raise NativeUnsupported("radgui.rs changed: its sections were not found for the native variant")
    return NATIVE_HEAD + text[i_json:i_hub] + NATIVE_RADCALL + text[i_worker:]


def _plugin():
    from ...languages import get_plugin
    return get_plugin("rust-bridge")


def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def find_cargo() -> str:
    from ...languages.rust_bridge import find_cargo as fc
    return fc()


def _sibling(cargo: str, name: str) -> str:
    p = Path(cargo).with_name(name + (".exe" if os.name == "nt" else ""))
    return str(p) if p.is_file() else (shutil.which(name) or "")


# ------------------------------------------------------------------ check
SET_RX = r"""(?<![\w.])(?:radgui::)?(?:set|get|get_num)\s*\(\s*"([^"]*)"\s*,\s*"([^"]+)\""""
CALL_RX = r"""(?<![\w.])(?:radgui::)?call\s*\(\s*"([^"]*)"\s*,\s*"([^"]+)\""""


def check(folder, project, cfg) -> list[str]:
    folder = Path(folder)
    from ..build import startup_language
    lang = startup_language(project)
    if lang not in LANGS:
        return [f"{lang} is not a Rust project"]
    plugin = _plugin()
    reasons = _ffi.common_reasons(folder, project, lang)
    files = plugin.form_files(project) + plugin.module_files(project)
    srcs = {f: _ffi.strip_c_comments(_read(folder / f)) for f in files if (folder / f).is_file()}
    reasons += _ffi.literal_api_reasons(srcs, SET_RX, CALL_RX)
    for f, text in srcs.items():
        if re.search(r"\bradcall\s*\(", text):
            reasons.append(f"{f}: radcall (RAD Hub) is not available in a native exe")
    if plugin.proxy_modules(folder, project):
        reasons.append("the project references other projects (RAD Hub): not possible in one native exe")
    if (folder / "build.rs").is_file():
        reasons.append("the project has its own build.rs (not used by the native build)")
    if not find_cargo():
        reasons.append("cargo (Rust) was not found: " + plugin.install_hint)
    return reasons


# ------------------------------------------------------------------ crate
def _tables(text: str) -> list[list[str]]:
    tables, cur = [], []
    for line in text.splitlines():
        if re.match(r"^\s*\[", line):
            tables.append(cur)
            cur = []
        cur.append(line)
    tables.append(cur)
    return [t for t in tables if t]


def cargo_toml(user_text: str, crate: str) -> str:
    """The project's Cargo.toml for the native crate: its [package] (+ build script) and [dependencies]
    kept, [[bin]] / [profile] / [workspace] replaced."""
    out, has_pkg = [], False
    for t in _tables(user_text):
        head = t[0].strip()
        if re.match(r"^\[\[\s*bin\s*\]\]", head) or re.match(r"^\[\s*(profile|workspace)\b", head):
            continue
        if re.match(r"^\[\s*package\s*\]", head):
            has_pkg = True
            body = [ln for ln in t[1:] if not re.match(r"^\s*(build|autobins|default-run)\s*=", ln)]
            t = [t[0], 'build = "_radbuild.rs"', "autobins = false", *body]
        elif not re.match(r"^\[", head):         # text before the first table (comments)
            continue
        out.append("\n".join(t).rstrip())
    if not has_pkg:
        out.insert(0, f'[package]\nname = "{crate}"\nversion = "0.1.0"\nedition = "2021"\n'
                      'build = "_radbuild.rs"\nautobins = false')
    out += ["[workspace]",
            '[[bin]]\nname = "radapp"\npath = "_radnative_main.rs"',
            '[profile.release]\nopt-level = "z"\nlto = true\ncodegen-units = 1\npanic = "abort"\nstrip = true\n'
            'debug = false\nincremental = false']
    return "# AUTO-GENERATED by RAD IDE - native exe build of the project (do not edit)\n" + "\n\n".join(out) + "\n"


def native_main(plugin, project) -> str:
    """The plugin's _radmain.rs with #![windows_subsystem] and the handler list for radforms."""
    _name, text = plugin.main_source(project)
    handlers = [h for h, _f in getattr(plugin, "_handler_files", [])]
    text = text.replace("// AUTO-GENERATED by RAD IDE - GUI Bridge main program (do not edit)",
                        "// AUTO-GENERATED by RAD IDE - native exe main program (radforms; do not edit)\n"
                        '#![windows_subsystem = "windows"]', 1)
    marker = "fn main() {\n"
    if marker not in text:
        raise NativeUnsupported("unexpected Rust main program (no fn main)")
    return text.replace(marker, marker + f'    radgui::native_handlers("{",".join(handlers)}");\n', 1)


def build_rs(lib_dir: Path, lib_name: str, objs: list[Path], res: Path, msvc: bool) -> str:
    L = ["// AUTO-GENERATED by RAD IDE - links radforms + the resources into the native exe", "fn main() {",
         f'    println!(r#"cargo:rustc-link-search=native={lib_dir}"#);',
         f'    println!("cargo:rustc-link-lib=static={lib_name}");']
    for o in [*objs, res]:
        L.append(f'    println!(r#"cargo:rustc-link-arg-bins={o}"#);')
    for lib in _ffi.WIN_LIBS:
        L.append(f'    println!("cargo:rustc-link-lib=dylib={lib}");')
    if msvc:
        L.append('    println!("cargo:rustc-link-arg-bins=/MANIFEST:NO");')
    L += ['    println!("cargo:rerun-if-changed=_radbuild.rs");', "}", ""]
    return "\n".join(L)


def _targets(cargo: str) -> set[str]:
    rustup = _sibling(cargo, "rustup")
    if not rustup:
        return set()
    try:
        r = subprocess.run([rustup, "target", "list", "--installed"], capture_output=True, text=True, timeout=60)
        return set(r.stdout.split())
    except (OSError, subprocess.SubprocessError):
        return set()


def _host(cargo: str) -> str:
    try:
        r = subprocess.run([_sibling(cargo, "rustc") or "rustc", "-vV"], capture_output=True, text=True, timeout=60)
        m = re.search(r"^host:\s*(\S+)", r.stdout, re.M)
        return m.group(1) if m else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def choose_target(cargo: str, log) -> str:
    """MSVC target when Visual C++ is installed (rustc's link.exe), else the GNU target with MinGW."""
    from ...languages.c_bridge import find_vcvars
    host = _host(cargo)
    installed = _targets(cargo)
    if find_vcvars() and (host == MSVC or MSVC in installed):
        return MSVC
    if GNU in installed or host == GNU:
        return GNU
    rustup = _sibling(cargo, "rustup")
    if rustup:
        log(f"Visual C++ not found: adding the Rust target {GNU} (rustup, no admin rights) ...")
        if _ffi.run([rustup, "target", "add", GNU], Path.cwd(), log) == 0:
            return GNU
    raise NativeUnsupported("neither Visual C++ (for the msvc target) nor the x86_64-pc-windows-gnu Rust target "
                            "is available")


def build(folder, project, cfg, work, log):
    from ..build import BuildError
    folder = Path(folder).absolute()     # not resolve(): a deep project builds through its short alias (paths.short_alias)
    plugin = _plugin()
    cargo = find_cargo()
    if not cargo:
        raise NativeUnsupported("cargo was not found")
    target = choose_target(cargo, log)
    msvc = target == MSVC
    tc = _ffi.mingw(log)                         # windres (+ gcc / ar for the GNU target)
    nat = Path(work) / "native_rust"
    crate = nat / "crate"
    nat.mkdir(parents=True, exist_ok=True)
    # sources: a fresh copy (the target folder is kept between builds: cargo rebuilds only what changed)
    for p in list(crate.glob("*")) if crate.is_dir() else []:
        if p.is_file():
            p.unlink()
    crate.mkdir(parents=True, exist_ok=True)
    gen = _ffi.fresh(nat / "gen")
    notes = _ffi.update_note(cfg, log)
    res = _ffi.resources(gen, project, folder, cfg, log, tc["windres"], fmt="res" if msvc else "coff")
    if msvc:
        built = _ffi.msvc_radforms(nat, project, log)
        if built is None:
            raise NativeUnsupported("radforms.lib could not be built with Visual C++")
        lib_dir, objs = built
    else:
        lib_dir, objs = _ffi.mingw_radforms(nat, project, tc, log)

    for f in plugin.form_files(project) + plugin.module_files(project):
        src = folder / f
        if src.is_file():
            dst = crate / f
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
    (crate / "radgui.rs").write_text(native_radgui(), encoding="utf-8")
    (crate / "_radnative_main.rs").write_text(native_main(plugin, project), encoding="utf-8")
    from ...languages.rust_bridge import crate_name
    user_toml = _read(folder / "Cargo.toml")
    (crate / "Cargo.toml").write_text(cargo_toml(user_toml, crate_name(project.name)), encoding="utf-8")
    if (folder / "Cargo.lock").is_file():
        shutil.copy2(folder / "Cargo.lock", crate / "Cargo.lock")
    (crate / "_radbuild.rs").write_text(build_rs(lib_dir, "radforms", objs, res, msvc), encoding="utf-8")
    conf = crate / ".cargo"
    conf.mkdir(exist_ok=True)
    toml = [f'[target.{MSVC}]', 'rustflags = ["-C", "target-feature=+crt-static"]', ""]
    if not msvc:
        nomf = str(_ffi.no_default_manifest(nat, tc["cc"], log)).replace("\\", "/") + "/"
        toml += [f"[target.{GNU}]", f"linker = '{tc['cc']}'",
                 f"rustflags = ['-C', 'target-feature=+crt-static', '-C', 'link-arg=-Wl,--gc-sections', "
                 f"'-C', 'link-arg=-B{nomf}']", ""]
    (conf / "config.toml").write_text("\n".join(toml), encoding="utf-8")

    # a short target folder of its own (%LOCALAPPDATA%\RADIDE\cache\cargo\<hash>): under a deep publish folder
    # target\<triple>\release\build\... passes 260 characters and link.exe fails with LNK1104
    from ...languages.rust_bridge import cargo_cache_dir
    tdir = cargo_cache_dir(nat)
    env = dict(os.environ, CARGO_TARGET_DIR=str(tdir))
    env.pop("RUSTFLAGS", None)
    if not msvc:
        env = _ffi.tool_env(Path(tc["cc"]).parent, env)
    cmd = [cargo, "build", "--release", "--bin", "radapp", "--target", target]
    if _ffi.run(cmd, crate, log, env) != 0:
        raise BuildError("The native Rust build failed (see the output above)")
    built_exe = tdir / target / "release" / "radapp.exe"
    if not built_exe.is_file():
        raise BuildError("cargo did not create radapp.exe")
    dist = _ffi.dist_folder(work, cfg)
    exe = dist / (cfg.exe_base() + ".exe")
    shutil.copy2(built_exe, exe)
    how = (f"rustc {target}, " + ("link.exe + radforms.lib (cl /Zl), static CRT" if msvc
                                  else "MinGW gcc + libradforms.a, static"))
    return _ffi.finish(exe, dist, folder, cfg, log, notes, how)


