"""Simple auto-update check generated into published programs.

The publisher uploads ``version.json`` (written next to the setup by Publish) to the URL in the settings:

    {"version": "1.2.0", "url": "https://example.com/MyApp-1.2.0-setup.exe", "notes": "What is new"}

* Python based builds (Python Tk/Qt, VB6, GUI Bridge languages) get ``radupdate.py`` compiled in: a
  background check at start-up (when "check on start" is on) that asks "Download it now?" with a native
  message box, and ``import radupdate; radupdate.check(interactive=True)`` for a "Check for Updates" menu.
* Every build also gets ``CheckForUpdates.ps1`` + a Start menu shortcut "Check for Updates" (works for
  Ring / Flutter / prebuilt programs too).
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .config import PublishConfig

RADUPDATE = r'''"""radupdate - update check generated by RAD IDE (Build > Publish). Do not edit: regenerated on Publish."""
import json
import os
import re
import sys
import threading
import urllib.request
import webbrowser

APP_NAME = {app!r}
CURRENT_VERSION = {version!r}
UPDATE_URL = {url!r}


def _ver(s):
    return tuple(int(n) for n in re.findall(r"\d+", str(s))[:4]) or (0,)


def latest(timeout=8):
    """(version, download_url, notes) from the version JSON, or None when it cannot be read."""
    if not UPDATE_URL:
        return None
    req = urllib.request.Request(UPDATE_URL, headers={{"User-Agent": APP_NAME + "/" + CURRENT_VERSION}})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        data = json.loads(r.read().decode("utf-8-sig"))
    return str(data.get("version", "")), data.get("url") or "", data.get("notes") or ""


def _box(text, flags):
    if sys.platform == "win32":
        import ctypes
        return ctypes.windll.user32.MessageBoxW(0, text, APP_NAME + " - Update", flags | 0x40000)
    print(text)
    return 7


def check(interactive=False):
    """Check now. interactive=True also reports "up to date" and errors (for a menu command)."""
    try:
        info = latest()
    except Exception as ex:  # noqa: BLE001 - offline, bad URL, bad JSON
        if interactive:
            _box("Could not check for updates:\n" + str(ex), 0x30)
        return False
    if not info:
        return False
    new, url, notes = info
    if _ver(new) > _ver(CURRENT_VERSION):
        msg = APP_NAME + " " + new + " is available (you have " + CURRENT_VERSION + ")."
        if notes:
            msg += "\n\n" + notes
        msg += "\n\nDownload it now?"
        if _box(msg, 0x24) == 6:
            webbrowser.open(url or UPDATE_URL)
        return True
    if interactive:
        _box(APP_NAME + " " + CURRENT_VERSION + " is up to date.", 0x40)
    return False


def start():
    """Background check at start-up (never blocks or breaks the program)."""
    if os.environ.get("RADAPP_NO_UPDATE_CHECK"):
        return
    threading.Thread(target=check, daemon=True).start()
'''

HOOK = "import radupdate\nradupdate.start()\n"

PS1 = r'''# Check for updates - generated by RAD IDE (Build > Publish)
$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Windows.Forms
$app = {app}
$current = {version}
$url = {url}
function V($s) {{ $n = [regex]::Matches([string]$s, "\d+") | Select-Object -First 4 | ForEach-Object {{ [int]$_.Value }}; while ($n.Count -lt 4) {{ $n += 0 }}; return $n }}
try {{
  $j = Invoke-RestMethod -Uri $url -UseBasicParsing -TimeoutSec 15
}} catch {{
  [System.Windows.Forms.MessageBox]::Show("Could not check for updates:`n" + $_.Exception.Message, "$app - Update") | Out-Null
  exit 1
}}
$a = V $j.version; $b = V $current; $newer = $false
for ($i = 0; $i -lt 4; $i++) {{ if ($a[$i] -gt $b[$i]) {{ $newer = $true; break }}; if ($a[$i] -lt $b[$i]) {{ break }} }}
if ($newer) {{
  $msg = "$app $($j.version) is available (you have $current)."
  if ($j.notes) {{ $msg += "`n`n" + $j.notes }}
  $r = [System.Windows.Forms.MessageBox]::Show($msg + "`n`nDownload it now?", "$app - Update", "YesNo", "Information")
  if ($r -eq "Yes") {{ if ($j.url) {{ Start-Process $j.url }} else {{ Start-Process $url }} }}
}} else {{
  [System.Windows.Forms.MessageBox]::Show("$app $current is up to date.", "$app - Update") | Out-Null
}}
'''


def _ps(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def radupdate_source(cfg: PublishConfig) -> str:
    return RADUPDATE.format(app=cfg.app_name, version=cfg.version, url=cfg.update.url)


def write_python_files(cfg: PublishConfig, gen: Path) -> tuple[Path, Path | None]:
    """radupdate.py (+ the runtime hook when check_on_start) into *gen*; returns (module, hook or None)."""
    gen.mkdir(parents=True, exist_ok=True)
    mod = gen / "radupdate.py"
    mod.write_text(radupdate_source(cfg), encoding="utf-8")
    hook = None
    if cfg.update.check_on_start:
        hook = gen / "radupdate_hook.py"
        hook.write_text(HOOK, encoding="utf-8")
    return mod, hook


def write_ps1(cfg: PublishConfig, folder: Path) -> Path:
    p = Path(folder) / "CheckForUpdates.ps1"
    p.write_text(PS1.format(app=_ps(cfg.app_name), version=_ps(cfg.version), url=_ps(cfg.update.url)),
                 encoding="utf-8-sig")
    return p


def write_version_json(cfg: PublishConfig, out_dir: Path, setup_name: str = "") -> Path:
    url = cfg.update.download_url
    if not url and cfg.update.url and setup_name:
        url = re.sub(r"[^/]*$", setup_name, cfg.update.url)        # same folder as version.json
    p = Path(out_dir) / "version.json"
    p.write_text(json.dumps({"version": cfg.version, "url": url, "notes": ""}, indent=2) + "\n",
                 encoding="utf-8")
    return p


__all__ = ["radupdate_source", "write_ps1", "write_python_files", "write_version_json"]
