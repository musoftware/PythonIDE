"""``<Scene>.scene3d`` -> Ursina code: ``<Scene>_designer.py`` (generated, rewritten on every save / F5) and the
user file ``main.py`` (written once by the template; VB-style handlers ``Scene_Update(dt)``, ``Player_Collect``).
The runtime ``rad3d.py`` is copied into the project like the 2D ``radgame.py``.
"""
from __future__ import annotations

import shutil
from pathlib import Path

from .model import EXT, Scene3D

RUNTIME = Path(__file__).with_name("runtime") / "rad3d.py"

_MODEL = {"cube": "'cube'", "sphere": "'sphere'", "plane": "'plane'",
          "capsule": "Capsule(height=2)", "cylinder": "Cylinder(resolution=24, start=-0.5, height=1)"}
_COLLIDER = {"cube": "'box'", "sphere": "'sphere'", "plane": "'box'", "capsule": "'box'", "cylinder": "'box'"}


def _v(v) -> str:
    return "(" + ", ".join(f"{float(x):g}" for x in v) + ")"


def designer_code(scene: Scene3D) -> str:
    lines = [f'"""{scene.name}_designer.py - AUTO-GENERATED by RAD IDE from {scene.name}{EXT}.',
             "Do not edit: change the scene in the 3D scene view; write your code in main.py.\"\"\"",
             "from ursina import AmbientLight, DirectionalLight, Entity, camera, color, window  # noqa: F401",
             "from ursina.models.procedural.capsule import Capsule  # noqa: F401",
             "from ursina.models.procedural.cylinder import Cylinder  # noqa: F401",
             "",
             f"GRAVITY = {float(scene.gravity):g}",
             "",
             "",
             "def build(rad3d):",
             '    """Create the entities; returns {name: entity}."""',
             f"    window.color = rad3d.hexcolor({scene.sky!r})",
             "    AmbientLight(color=color.rgba(0.45, 0.45, 0.5, 1))",
             "    e = {}"]
    for ent in scene.entities:
        n = ent.name
        if ent.kind == "camera":
            lines += [f"    camera.position = {_v(ent.position)}", f"    camera.rotation = {_v(ent.rotation)}",
                      f"    camera.fov = {float(ent.props.get('fov', 60)):g}", f"    e[{n!r}] = camera"]
            continue
        if ent.kind == "light":
            # no position: a moved shadow-casting DirectionalLight makes Panda3D invert a singular matrix
            lines += [f"    e[{n!r}] = DirectionalLight(shadows=True, rotation={_v(ent.rotation)}, "
                      f"color=rad3d.hexcolor({ent.color!r}))"]
            continue
        args = [f"name={n!r}"]
        if ent.kind in _MODEL:
            args.append(f"model={_MODEL[ent.kind]}")
            args.append(f"color=rad3d.hexcolor({ent.color!r})")
            if any(b in ent.behaviours for b in ("solid", "collectible", "player")):
                args.append(f"collider={_COLLIDER[ent.kind]}")
        args += [f"position={_v(ent.position)}", f"rotation={_v(ent.rotation)}", f"scale={_v(ent.scale)}"]
        lines.append(f"    e[{n!r}] = Entity({', '.join(args)})")
        lines.append(f"    e[{n!r}].rad_behaviours = {tuple(ent.behaviours)!r}")
        lines.append(f"    e[{n!r}].rad_kind = {ent.kind!r}")
    lines += ["    return e", ""]
    return "\n".join(lines)


def main_code(title: str, scene: str) -> str:
    return f'''"""{title} - a 3D game made with Ursina (https://www.ursinaengine.org, MIT licence) in RAD IDE.

The scene ({scene}{EXT}) is edited in the IDE's 3D scene view; {scene}_designer.py is generated from it.
Write your game code here - VB-style handlers are called by rad3d.py:
    Scene_Load()          once, before the first frame
    Scene_Update(dt)      every frame
    Player_Collect(item)  the player touched a "collectible" entity
Keys: WASD / arrows move, Space jumps.
"""
import rad3d

app = rad3d.start({title!r})
scene = rad3d.load_scene({scene!r})


def Scene_Load():
    print("Collect the coins!", flush=True)


def Scene_Update(dt):
    pass


def Player_Collect(item):
    print(f"Collected {{item.name}} - score {{rad3d.score}}", flush=True)


rad3d.run(globals())
'''


def write_runtime(folder: Path) -> Path:
    dest = Path(folder) / "rad3d.py"
    if not dest.exists() or dest.read_bytes() != RUNTIME.read_bytes():
        shutil.copyfile(RUNTIME, dest)
    return dest


def sync_scene(folder: Path, scene_file: Path | str) -> Path:
    folder = Path(folder)
    path = folder / scene_file if not Path(scene_file).is_absolute() else Path(scene_file)
    scene = Scene3D.load(path)
    out = folder / f"{path.stem}_designer.py"
    text = designer_code(scene)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        out.write_text(text, encoding="utf-8")
    return out


def sync_project(folder: Path) -> list[Path]:
    folder = Path(folder)
    out = [write_runtime(folder)]
    for p in sorted(folder.glob(f"*{EXT}")):
        out.append(sync_scene(folder, p))
    return out


__all__ = ["designer_code", "main_code", "sync_project", "sync_scene", "write_runtime"]
