"""GUI Bridge code generation for Assembly forms (NASM, x64 Windows).

Files of a form project (docs/ASSEMBLY.md, "Windows Forms"):

    Form1.asm     the user's code: ``handler <Control>_<Event>`` ... ``endhandler`` blocks. Never regenerated.
    Form1.inc     generated on every save of the form (the plugin's designer file): the names of the form and
                  its controls as string constants (``%define btnAdd "btnAdd"``) and numeric control IDs
                  (``CTL_btnAdd equ 2``) - so ``rad_set lblOut, "Text", "Hi"`` is checked by the assembler.
    _radmain.asm  generated when the program runs: ``main`` (C runtime entry) = rad_init, then the event loop
                  ``rad_next_event`` -> look the handler up in a table -> call it -> ``rad_done``.
    radgui.inc    the macros (rad_set, rad_get_int, handler ...), radgui.c / radgui.h (the C client of the
                  GUI Bridge) and radasm.c (integer helpers) - copied into the project.

The handler table holds "<Control>_<Event>" names; the loop builds the same key from rad_obj / rad_ev with
sprintf and compares it with _stricmp (the GUI Bridge sends the names as they are in the form).

Flavors (``flavor_for(settings)``) - the same files in each assembler's own syntax:

    nasm64   NASM x64     radgui.inc        Form1.inc (%define)   _radmain.asm   gcc + radgui.c
    nasm32   NASM x86     radgui32.inc      Form1.inc (%define)   _radmain.asm   gcc -m32 -c + ld i386pe + ucrtbase.dll
    fasm64   FASM x64     radgui_fasm.inc   Form1.inc (equ)       _radmain.asm   format MS64 COFF objects + gcc
    gas64    GNU as AT&T  radgui_att.inc    Form1.inc (.equ IDs)  _radmain.s     as --64 + gcc
    gas64i   GNU as Intel radgui_intel.inc  Form1.inc (.equ IDs)  _radmain.s     as --64 + gcc
"""
from __future__ import annotations

import re

HANDLER_RX = re.compile(r"^[ \t]*handler[ \t]+(\w+_\w+)\b|^[ \t]*(\w+_\w+)[ \t]*:(?![:=])", re.M)
GLOBAL_RX = re.compile(r"^[ \t]*(?:global|\.globl|\.global|public)[ \t]+([\w, \t]+)", re.M | re.I)


def handlers_in(text: str) -> list[str]:
    """Handler names of a form's code: ``handler X_Y`` blocks, or ``X_Y:`` labels that are declared global."""
    code = "\n".join(l.split(";", 1)[0] for l in text.splitlines())
    globals_: set[str] = set()
    for m in GLOBAL_RX.finditer(code):
        globals_ |= {g.strip().lower() for g in m.group(1).split(",") if g.strip()}
    out: list[str] = []
    for m in HANDLER_RX.finditer(code):
        name = m.group(1) or m.group(2)
        if m.group(2) and name.lower() not in globals_:
            continue
        if name not in out:
            out.append(name)
    return out


def designer_include(form, ids_from: int = 1) -> str:
    """Form1.inc: names and IDs of the form and its controls (and of its menu items)."""
    from ..controls import menu_leaves
    name = form.name
    guard = re.sub(r"\W", "_", name.upper()) + "_INC"
    L = [f"; AUTO-GENERATED by RAD IDE - the objects of form {name} (do not edit: rewritten when the form is saved).",
         "; Use the names with the GUI Bridge macros of radgui.inc:  rad_set lblOut, \"Text\", \"Hello\"",
         f"%ifndef {guard}", f"%define {guard}", "",
         f'%define {name} "{name}"', f"CTL_{name} equ 0"]
    n = ids_from
    for c in form.controls:
        L.append(f'%define {c.name} "{c.name}"'.ljust(48) + f"; {c.type}")
        L.append(f"CTL_{c.name} equ {n}")
        n += 1
        if c.type in ("MenuStrip", "ToolStrip"):
            for it in menu_leaves(c.props.get("Items", [])):
                nm = it.get("Name", "")
                if nm and re.fullmatch(r"[A-Za-z_]\w*", nm):
                    L.append(f'%define {nm} "{nm}"' + f"   ; menu item of {c.name}")
                    L.append(f"CTL_{nm} equ {n}")
                    n += 1
    ident = re.sub(r"\W", "_", name)
    L += [f"CTL_COUNT_{ident} equ {n - ids_from}", "", "%endif", ""]
    return "\n".join(L)


def main_program(handlers: list[str]) -> str:
    """_radmain.asm: the event loop and the dispatch table (NASM, win64, called through the C runtime)."""
    L = ["; AUTO-GENERATED by RAD IDE - GUI Bridge main program for Assembly (do not edit: rewritten on every run).",
         "; main: rad_init, then for each event: key = rad_obj + \"_\" + rad_ev, find it in rad_handlers, call it,",
         "; rad_done. The handlers are the 'handler <Control>_<Event>' blocks of the form files.",
         "default rel", "global main",
         "extern rad_init, rad_next_event, rad_done, rad_obj, rad_ev, sprintf, _stricmp"]
    if handlers:
        L.append("extern " + ", ".join(handlers))
    L += ["", "section .rdata", 'rad_keyfmt: db "%s_%s", 0']
    for i, h in enumerate(handlers):
        L.append(f'rad_hname{i}: db "{h}", 0')
    L += ["", "section .data", "align 8", "rad_handlers:"]
    for i, h in enumerate(handlers):
        L.append(f"    dq rad_hname{i}, {h}")
    L += ["    dq 0, 0", "", "section .bss", "rad_key: resb 600", "", "section .text",
          "main:",
          "    push rbp",
          "    mov rbp, rsp",
          "    push rbx",
          "    sub rsp, 40                     ; shadow space, RSP 16-byte aligned",
          "    call rad_init",
          ".next_event:",
          "    call rad_next_event",
          "    test eax, eax",
          "    jz .quit",
          "    lea rax, [rad_obj]",
          "    cmp byte [rax], 0",
          "    je .done",
          "    lea rcx, [rad_key]",
          "    lea rdx, [rad_keyfmt]",
          "    lea r8, [rad_obj]",
          "    lea r9, [rad_ev]",
          "    call sprintf",
          "    lea rbx, [rad_handlers]",
          ".find:",
          "    mov rdx, [rbx]",
          "    test rdx, rdx",
          "    jz .done",
          "    lea rcx, [rad_key]",
          "    call _stricmp",
          "    test eax, eax",
          "    jz .found",
          "    add rbx, 16",
          "    jmp .find",
          ".found:",
          "    call [rbx + 8]",
          ".done:",
          "    call rad_done",
          "    jmp .next_event",
          ".quit:",
          "    xor eax, eax",
          "    add rsp, 40",
          "    pop rbx",
          "    pop rbp",
          "    ret", ""]
    return "\n".join(L)


# ====================================================================== flavors (NASM x86, FASM, GNU as)
FLAVORS = ("nasm64", "nasm32", "fasm64", "gas64", "gas64i")
RUNTIME_INCLUDE = {"nasm64": "radgui.inc", "nasm32": "radgui32.inc", "fasm64": "radgui_fasm.inc",
                   "gas64": "radgui_att.inc", "gas64i": "radgui_intel.inc"}


def flavor_for(settings: dict, folder=None, forms=()) -> str:
    """The GUI Bridge flavor of a project's "asm" settings ("" = forms are not available for it).

    GNU as: ``"syntax": "intel"`` (or a form file that starts with ``.intel_syntax``) = gas64i, else gas64."""
    a, arch = settings.get("assembler", "nasm"), settings.get("arch", "x64")
    if a == "nasm":
        return "nasm32" if arch == "x86" else "nasm64"
    if a == "fasm" and arch == "x64":
        return "fasm64"
    if a == "gas" and arch == "x64":
        syntax = str(settings.get("syntax") or "").lower()
        if not syntax and folder is not None:
            from pathlib import Path
            for f in forms:
                try:
                    head = (Path(folder) / f"{f}.s").read_text(encoding="utf-8", errors="replace")[:4000]
                except OSError:
                    continue
                if re.search(r"^\s*\.intel_syntax\b", head, re.M):
                    syntax = "intel"
                    break
        return "gas64i" if syntax == "intel" else "gas64"
    return ""


def main_name(flavor: str) -> str:
    return "_radmain.s" if flavor.startswith("gas") else "_radmain.asm"


def designer_include_for(form, flavor: str) -> str:
    """Form1.inc in the syntax of *flavor* (nasm64 / nasm32: ``designer_include``)."""
    if flavor in ("nasm64", "nasm32", ""):
        return designer_include(form)
    from ..controls import menu_leaves
    name = form.name
    objs = [(name, "Form", 0)]
    n = 1
    for c in form.controls:
        objs.append((c.name, c.type, n))
        n += 1
        if c.type in ("MenuStrip", "ToolStrip"):
            for it in menu_leaves(c.props.get("Items", [])):
                nm = it.get("Name", "")
                if nm and re.fullmatch(r"[A-Za-z_]\w*", nm):
                    objs.append((nm, f"menu item of {c.name}", n))
                    n += 1
    ident = re.sub(r"\W", "_", name)
    if flavor == "fasm64":
        L = [f"; AUTO-GENERATED by RAD IDE - the objects of form {name} (do not edit: rewritten when the form is saved).",
             "; Use the names with the GUI Bridge macros of radgui_fasm.inc:  rad_set lblOut, 'Text', 'Hello'"]
        for nm, typ, i in objs:
            L.append(f"{nm} equ '{nm}'".ljust(48) + f"; {typ}")
            L.append(f"CTL_{nm} = {i}")
        L += [f"CTL_COUNT_{ident} = {n - 1}", ""]
        return "\n".join(L)
    # GNU as: names are text anyway (the macros take a bare word as text) - only the numeric IDs
    L = [f"# AUTO-GENERATED by RAD IDE - the objects of form {name} (do not edit: rewritten when the form is saved).",
         "# The GUI Bridge macros take a control name as text:  rad_set lblOut, Text, \"Hello\""]
    for nm, typ, i in objs:
        L.append(f"        .equ CTL_{nm}, {i}".ljust(48) + f"# {typ}")
    L += [f"        .equ CTL_COUNT_{ident}, {n - 1}", ""]
    return "\n".join(L)


def main_program_for(handlers: list[str], flavor: str) -> str:
    """_radmain.asm / _radmain.s of *flavor* (nasm64: ``main_program``)."""
    if flavor in ("nasm64", ""):
        return main_program(handlers)
    head = ["AUTO-GENERATED by RAD IDE - GUI Bridge main program for Assembly (do not edit: rewritten on every run).",
            "main: rad_init, then for each event: key = rad_obj + \"_\" + rad_ev, find it in the handler table,",
            "call it, rad_done. The handlers are the 'handler <Control>_<Event>' blocks of the form files."]
    if flavor == "nasm32":
        L = ["; " + h for h in head]
        L += ["; 32-bit: entry point _main (GNU ld -e _main), C functions of ucrtbase.dll, ExitProcess at the end.",
              "global _main",
              "extern _rad_init, _rad_next_event, _rad_done, _rad_obj, _rad_ev",
              "extern _strcpy, _strcat, __stricmp, _fflush, _ExitProcess@4"]
        if handlers:
            L.append("extern " + ", ".join(handlers))
        L += ["", "section .rdata", 'rad_sep: db "_", 0']
        L += [f'rad_hname{i}: db "{h}", 0' for i, h in enumerate(handlers)]
        L += ["", "section .data", "align 4", "rad_handlers:"]
        L += [f"    dd rad_hname{i}, {h}" for i, h in enumerate(handlers)]
        L += ["    dd 0, 0", "", "section .bss", "rad_key: resb 600", "", "section .text",
              "_main:",
              "    push ebx",
              "    call _rad_init",
              ".next_event:",
              "    call _rad_next_event",
              "    test eax, eax",
              "    jz .quit",
              "    cmp byte [_rad_obj], 0",
              "    je .done",
              "    push _rad_obj                   ; key = rad_obj + \"_\" + rad_ev",
              "    push rad_key",
              "    call _strcpy",
              "    push rad_sep",
              "    push rad_key",
              "    call _strcat",
              "    push _rad_ev",
              "    push rad_key",
              "    call _strcat",
              "    add esp, 24",
              "    mov ebx, rad_handlers",
              ".find:",
              "    mov edx, [ebx]",
              "    test edx, edx",
              "    jz .done",
              "    push edx",
              "    push rad_key",
              "    call __stricmp",
              "    add esp, 8",
              "    test eax, eax",
              "    jz .found",
              "    add ebx, 8",
              "    jmp .find",
              ".found:",
              "    call [ebx + 4]",
              ".done:",
              "    call _rad_done",
              "    jmp .next_event",
              ".quit:",
              "    push 0",
              "    call _fflush",
              "    add esp, 4",
              "    push 0",
              "    call _ExitProcess@4", ""]
        return "\n".join(L)
    if flavor == "fasm64":
        L = ["; " + h for h in head]
        L += ["format MS64 COFF", "",
              "extrn rad_init", "extrn rad_next_event", "extrn rad_done", "extrn rad_obj", "extrn rad_ev",
              "extrn sprintf", "extrn _stricmp"]
        L += [f"extrn {h}" for h in handlers]
        L += ["public main", "",
              "section '.text' code readable executable",
              "main:",
              "    push rbp",
              "    mov rbp, rsp",
              "    push rbx",
              "    sub rsp, 40                     ; shadow space, RSP 16-byte aligned",
              "    call rad_init",
              "  .next_event:",
              "    call rad_next_event",
              "    test eax, eax",
              "    jz .quit",
              "    lea rax, [rad_obj]",
              "    cmp byte [rax], 0",
              "    je .done",
              "    lea rcx, [rad_key]",
              "    lea rdx, [rad_keyfmt]",
              "    lea r8, [rad_obj]",
              "    lea r9, [rad_ev]",
              "    call sprintf",
              "    lea rbx, [rad_handlers]",
              "  .find:",
              "    mov rdx, [rbx]",
              "    test rdx, rdx",
              "    jz .done",
              "    lea rcx, [rad_key]",
              "    call _stricmp",
              "    test eax, eax",
              "    jz .found",
              "    add rbx, 16",
              "    jmp .find",
              "  .found:",
              "    call qword [rbx + 8]",
              "  .done:",
              "    call rad_done",
              "    jmp .next_event",
              "  .quit:",
              "    xor eax, eax",
              "    add rsp, 40",
              "    pop rbx",
              "    pop rbp",
              "    ret", "",
              "section '.rdata' data readable",
              "rad_keyfmt db '%s_%s', 0"]
        L += [f"rad_hname{i} db '{h}', 0" for i, h in enumerate(handlers)]
        L += ["", "section '.data' data readable writeable align 8", "rad_handlers:"]
        L += [f"    dq rad_hname{i}, {h}" for i, h in enumerate(handlers)]
        L += ["    dq 0, 0", "rad_key rb 600", ""]
        return "\n".join(L)
    # GNU as (either syntax: the generated file is Intel syntax on its own)
    L = ["# " + h for h in head]
    L += ["        .intel_syntax noprefix", "        .globl  main", ""]
    L += ["        .section .rdata,\"dr\"", "rad_keyfmt: .asciz \"%s_%s\""]
    L += [f"rad_hname{i}: .asciz \"{h}\"" for i, h in enumerate(handlers)]
    L += ["", "        .data", "        .p2align 3", "rad_handlers:"]
    L += [f"        .quad   rad_hname{i}, {h}" for i, h in enumerate(handlers)]
    L += ["        .quad   0, 0", "", "        .bss", "rad_key: .space 600", "", "        .text",
          "main:",
          "        push    rbp",
          "        mov     rbp, rsp",
          "        push    rbx",
          "        sub     rsp, 40                 # shadow space, RSP 16-byte aligned",
          "        call    rad_init",
          ".Lnext_event:",
          "        call    rad_next_event",
          "        test    eax, eax",
          "        jz      .Lquit",
          "        lea     rax, [rip + rad_obj]",
          "        cmp     BYTE PTR [rax], 0",
          "        je      .Ldone",
          "        lea     rcx, [rip + rad_key]",
          "        lea     rdx, [rip + rad_keyfmt]",
          "        lea     r8, [rip + rad_obj]",
          "        lea     r9, [rip + rad_ev]",
          "        call    sprintf",
          "        lea     rbx, [rip + rad_handlers]",
          ".Lfind:",
          "        mov     rdx, [rbx]",
          "        test    rdx, rdx",
          "        jz      .Ldone",
          "        lea     rcx, [rip + rad_key]",
          "        call    _stricmp",
          "        test    eax, eax",
          "        jz      .Lfound",
          "        add     rbx, 16",
          "        jmp     .Lfind",
          ".Lfound:",
          "        call    QWORD PTR [rbx + 8]",
          ".Ldone:",
          "        call    rad_done",
          "        jmp     .Lnext_event",
          ".Lquit:",
          "        xor     eax, eax",
          "        add     rsp, 40",
          "        pop     rbx",
          "        pop     rbp",
          "        ret", ""]
    return "\n".join(L)
