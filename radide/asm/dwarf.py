"""Source-line debug information that gdb can read, for NASM objects on Windows.

NASM's only debug format for win32 / win64 objects is CodeView 8 (-g -F cv8), which gdb ignores, and
converting an ELF + DWARF object to COFF with objcopy breaks the relocations. So RAD IDE builds the DWARF
itself (docs/ASSEMBLY.md, "Debug information"):

1. the source is assembled with ``-P <anchor.inc>`` - a pre-included file that defines the global label
   ``__radsec_<module>`` at offset 0 of ``.text`` - and with a listing (``-l``);
2. ``parse_listing`` reads the listing: the offset in ``.text`` of every source line of the module
   (macro expansions belong to the line that calls the macro; lines of %include files are skipped);
3. ``line_program`` writes a GNU as source with ``.debug_abbrev`` / ``.debug_info`` / ``.debug_line``
   (DWARF 3: one compile unit, one line table) whose addresses are relocations against the anchor;
4. ``as`` turns it into a COFF object that is linked next to the NASM object: gdb then knows file:line for
   every instruction (breakpoints by line, step / next, the current line), while stepi / disassembly work
   as usual.
"""
from __future__ import annotations

import re
from pathlib import Path

ANCHOR_PREFIX = "__radsec_"
DW_LANG_MIPS_ASSEMBLER = 0x8001

_LST_RX = re.compile(r"^\s*(\d+)\s(.{8})\s(\S*)\s+(<\d+>)?(.*)$")
_SECTION_RX = re.compile(r"^\s*\[?\s*(?:section|segment)\s+([.\w$@]+)", re.I)


def anchor_name(module: str) -> str:
    return ANCHOR_PREFIX + re.sub(r"\W", "_", Path(module).stem)


def anchor_source(module: str) -> str:
    """The pre-included file (nasm -P): a global label at offset 0 of .text."""
    a = anchor_name(module)
    return f"; AUTO-GENERATED by RAD IDE - debug-line anchor for {module}\nglobal {a}\n{a}:\n"


def _byte_count(hexpart: str) -> int:
    """Bytes of one listing line: "488B05(00000000)", "90<rep 3h>", "[00000000]", "E8(00000000)"."""
    rep = 1
    m = re.search(r"<rep\s+([0-9A-Fa-f]+)h>", hexpart)
    if m:
        rep = int(m.group(1), 16)
        hexpart = hexpart[:m.start()]
    digits = re.sub(r"[^0-9A-Fa-f]", "", hexpart)
    return (len(digits) // 2) * rep


def parse_listing(text: str, source_lines: list[str] | None = None,
                  code_sections: tuple[str, ...] = (".text",)) -> tuple[list[tuple[int, int]], int]:
    """[(1-based source line, offset in .text)] of the module's own lines, and the size of its .text.

    The listing comes from ``nasm -l`` of the module assembled with the anchor pre-included (``-P``):
    the anchor file shows up at depth <1> before the first line of the module."""
    rows: list[tuple[int, int]] = []
    section = ".text"
    end = 0
    last_top = 0                 # last top-level line (macro calls own their expansion)
    top_is_include = False
    module_started = False
    prev_depth0_line = 0
    for raw in text.splitlines():
        m = _LST_RX.match(raw)
        if not m:
            continue
        line_no, off, hexpart, depth, src = int(m.group(1)), m.group(2), m.group(3), m.group(4), m.group(5)
        if depth is None:
            if not module_started or line_no < prev_depth0_line:
                module_started = True
            prev_depth0_line = line_no
            last_top = line_no
            body = src
            if source_lines is not None and 0 < line_no <= len(source_lines):
                body = source_lines[line_no - 1]
            top_is_include = bool(re.match(r"^\s*%\s*include\b", body, re.I))
            sm = _SECTION_RX.match(body)
            if sm:
                section = sm.group(1).lower()
                continue
        if not module_started:
            continue
        off = off.strip()
        if not re.fullmatch(r"[0-9A-Fa-f]{8}", off):
            continue
        if section not in code_sections:
            continue
        if depth is not None and top_is_include:
            continue                                  # code of an included file
        target = line_no if depth is None else last_top
        o = int(off, 16)
        n = _byte_count(hexpart)
        end = max(end, o + n)
        if n and (not rows or rows[-1] != (target, o)) and not (rows and rows[-1][1] == o and rows[-1][0] == target):
            rows.append((target, o))
    # one row per address: keep the first line that starts at an address
    seen: set[int] = set()
    out = []
    for ln, o in rows:
        if o in seen:
            continue
        seen.add(o)
        out.append((ln, o))
    out.sort(key=lambda r: r[1])
    return out, end


def _sleb(v: int) -> str:
    return f".sleb128 {v}"


def line_program(module_path: str, comp_dir: str, rows: list[tuple[int, int]], text_size: int,
                 bits: int = 64) -> str:
    """GNU as source (COFF, x86-64 or i386) with the DWARF 3 compile unit + line table of one module."""
    a = anchor_name(module_path)
    addr = ".quad" if bits == 64 else ".long"
    asz = 8 if bits == 64 else 4
    name = Path(module_path).name.replace("\\", "/").replace('"', "")
    comp = str(comp_dir).replace("\\", "/").replace('"', "")
    L = [f"# AUTO-GENERATED by RAD IDE - DWARF line information for {name} (radide/asm/dwarf.py)",
         '\t.section .debug_abbrev,"dr"', "Lrad_abbrev:",
         "\t.uleb128 1", "\t.uleb128 0x11", "\t.byte 0",              # compile_unit, no children
         "\t.uleb128 0x10", "\t.uleb128 0x06",                         # stmt_list: data4
         "\t.uleb128 0x11", "\t.uleb128 0x01",                         # low_pc: addr
         "\t.uleb128 0x12", "\t.uleb128 0x01",                         # high_pc: addr (DWARF 3)
         "\t.uleb128 0x03", "\t.uleb128 0x08",                         # name: string
         "\t.uleb128 0x1b", "\t.uleb128 0x08",                         # comp_dir: string
         "\t.uleb128 0x25", "\t.uleb128 0x08",                         # producer: string
         "\t.uleb128 0x13", "\t.uleb128 0x05",                         # language: data2
         "\t.byte 0", "\t.byte 0", "\t.byte 0",
         '\t.section .debug_info,"dr"',
         "\t.long Lrad_info_end - Lrad_info_start", "Lrad_info_start:",
         "\t.short 3", "\t.secrel32 Lrad_abbrev", f"\t.byte {asz}",
         "\t.uleb128 1", "\t.secrel32 Lrad_line",
         f"\t{addr} {a}", f"\t{addr} {a}+{max(text_size, 1)}",
         f'\t.asciz "{name}"', f'\t.asciz "{comp}"', '\t.asciz "RAD IDE (NASM + radide/asm/dwarf.py)"',
         f"\t.short {DW_LANG_MIPS_ASSEMBLER}", "Lrad_info_end:",
         '\t.section .debug_line,"dr"', "Lrad_line:",
         "\t.long Lrad_line_end - Lrad_line_start", "Lrad_line_start:",
         "\t.short 3", "\t.long Lrad_hdr_end - Lrad_hdr_start", "Lrad_hdr_start:",
         "\t.byte 1", "\t.byte 1", "\t.byte -5", "\t.byte 14", "\t.byte 13",
         "\t.byte 0,1,1,1,1,0,0,0,1,0,0,1",
         "\t.byte 0",                                                  # no include directories
         f'\t.asciz "{name}"', "\t.uleb128 0", "\t.uleb128 0", "\t.uleb128 0",
         "\t.byte 0", "Lrad_hdr_end:"]
    line = 1
    for ln, off in rows:
        L += ["\t.byte 0", f"\t.uleb128 {1 + asz}", "\t.byte 2", f"\t{addr} {a}+{off}"]    # DW_LNE_set_address
        if ln != line:
            L += ["\t.byte 3", f"\t{_sleb(ln - line)}"]                                    # DW_LNS_advance_line
            line = ln
        L.append("\t.byte 1")                                                              # DW_LNS_copy
    L += ["\t.byte 0", f"\t.uleb128 {1 + asz}", "\t.byte 2", f"\t{addr} {a}+{max(text_size, 1)}",
          "\t.byte 0", "\t.uleb128 1", "\t.byte 1",                                        # DW_LNE_end_sequence
          "Lrad_line_end:", ""]
    return "\n".join(L)
