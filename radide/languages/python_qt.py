def _qt_filter(value):
    """'Text files|*.txt|All|*.*' -> 'Text files (*.txt);;All (*.*)'."""
    parts = [p.strip() for p in str(value or "").split("|")]
    pairs = [f"{parts[i]} ({parts[i + 1].replace(';', ' ')})" for i in range(0, len(parts) - 1, 2)]
    return ";;".join(pairs) or "All files (*.*)"


