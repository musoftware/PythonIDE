def _fill_tree(tree, nodes):
    """nodes = [(path, text), ...] with parents first ("Root", "Root/Child")."""
    items = {}
    for path, text in nodes:
        parent = items.get(path.rpartition("/")[0])
        item = QTreeWidgetItem([text])
        if parent is None:
            tree.addTopLevelItem(item)
        else:
            parent.addChild(item)
        items[path] = item
    tree.expandAll()


def _fill_table(table, columns, rows):
    table.setColumnCount(max([len(columns)] + [len(r) for r in rows]))
    table.setHorizontalHeaderLabels(columns)
    table.setRowCount(len(rows))
    for r, row in enumerate(rows):
        for c, text in enumerate(row):
            table.setItem(r, c, QTableWidgetItem(text))
