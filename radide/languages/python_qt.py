HEADER = "# AUTO-GENERATED by RAD IDE from {form}.form - do not edit (changes will be lost)\n"

QT_CLASS = {"Button": "QPushButton", "Label": "QLabel", "TextBox": "QLineEdit",
            "CheckBox": "QCheckBox", "RadioButton": "QRadioButton", "ListBox": "QListWidget",
            "ComboBox": "QComboBox", "PictureBox": "QLabel", "ProgressBar": "QProgressBar",
            "NumericUpDown": "QSpinBox", "TrackBar": "QSlider", "Panel": "QFrame", "GroupBox": "QGroupBox"}
SIGNALS = {
    ("Button", "Click"): "clicked", ("TextBox", "TextChanged"): "textChanged",
    ("CheckBox", "CheckedChanged"): "toggled", ("RadioButton", "CheckedChanged"): "toggled",
    ("ListBox", "SelectedIndexChanged"): "currentRowChanged",
    ("ComboBox", "SelectedIndexChanged"): "currentIndexChanged",
    ("ComboBox", "TextChanged"): "currentTextChanged",
    ("NumericUpDown", "ValueChanged"): "valueChanged", ("TrackBar", "ValueChanged"): "valueChanged",
}
QEVENT = {"Click": "MouseButtonRelease", "DoubleClick": "MouseButtonDblClick",
          "MouseDown": "MouseButtonPress", "MouseUp": "MouseButtonRelease", "MouseMove": "MouseMove",
          "MouseEnter": "Enter", "MouseLeave": "Leave", "MouseWheel": "Wheel",
          "KeyDown": "KeyPress", "KeyPress": "KeyPress", "KeyUp": "KeyRelease",
          "GotFocus": "FocusIn", "LostFocus": "FocusOut", "Resize": "Resize",
          "Activated": "WindowActivate", "Deactivate": "WindowDeactivate"}
ALIGN = {"Left": "AlignLeft", "Center": "AlignHCenter", "Right": "AlignRight"}

RUNTIME = '''

class EventArgs:
    """Event data passed to handlers: X, Y, Button, Delta, KeyCode, KeyChar, Cancel."""

    def __init__(self, ev=None):
        self.raw = ev
        self.X = self.Y = self.Delta = 0
        self.Button = 0
        self.KeyCode = 0
        self.KeyChar = ""
        self.Cancel = False
        if ev is None:
            return
        if hasattr(ev, "position"):
            p = ev.position()
            self.X, self.Y = int(p.x()), int(p.y())
        if hasattr(ev, "button"):
            self.Button = {Qt.MouseButton.LeftButton: 1, Qt.MouseButton.MiddleButton: 2,
                           Qt.MouseButton.RightButton: 3}.get(ev.button(), 0)
        if hasattr(ev, "angleDelta"):
            self.Delta = ev.angleDelta().y()
        if hasattr(ev, "key"):
            self.KeyCode = ev.key()
            self.KeyChar = ev.text()


class _Events(QObject):
    """Event filter that routes Qt events to VB-style handlers."""

    def __init__(self, owner, widget, table):
        super().__init__(widget)
        self.owner, self.table = owner, table      # {QEvent.Type: [(handler, kind, chars_only)]}
        widget.installEventFilter(self)

    def eventFilter(self, obj, ev):
        for name, kind, chars in self.table.get(ev.type(), ()):
            if chars and not ev.text():
                continue
            fn = getattr(self.owner, name, None)
            if fn is not None:
                fn(EventArgs(ev)) if kind else fn()
        return False
'''

DISPATCH = '''
    # ---------------------------------------------------------------- runtime
    def _ev(self, name):
        def call(*_a):
            fn = getattr(self, name, None)
            if fn is not None:
                fn()
        return call

    def _res(self, path):
        return os.path.join(os.path.dirname(os.path.abspath(__file__)), path)

    def closeEvent(self, event):
        e = EventArgs()
        fn = getattr(self, "{form}_FormClosing", None)
        if fn is not None:
            fn(e)
        if e.Cancel:
            event.ignore()
            return
        event.accept()
        fn = getattr(self, "{form}_FormClosed", None)
        if fn is not None:
            fn()
'''


def _style(p) -> str:
    rules = []
    if p.get("BackColor"):
        rules.append(f"background-color:{p['BackColor']};")
    if p.get("ForeColor"):
        rules.append(f"color:{p['ForeColor']};")
    return "".join(rules)


class PythonQtPlugin(PythonTkPlugin):
    id = "python-qt"
    display_name = "Python (PySide6 / Qt)"

    def generate_designer(self, form: Form, user_code: str) -> str:
        n, fp = form.name, form.props
        used = lambda c: set(self.used_events(form, c, user_code))
        menu = form.menu()
        items = menu.props.get("Items", []) if menu else []
        mh = 22 if items else 0
        w, h = int(fp["Width"]), int(fp["Height"])
        L = [HEADER.format(form=n), "import os", "",
             "from PySide6.QtCore import QObject, QEvent, Qt, QTimer",
             "from PySide6.QtGui import QAction, QFont, QIcon, QPixmap",
             "from PySide6.QtWidgets import *  # noqa: F401,F403",
             RUNTIME.rstrip("\n"), "", "",
             f"class {n}Designer(QWidget):",
             "    def __init__(self, parent=None):",
             "        super().__init__(parent)",
             f"        self.setWindowTitle({fp['Text']!r})",
             f"        self.resize({w}, {h + mh})"]
        if fp.get("FormBorderStyle") == "FixedSingle":
            L.append(f"        self.setFixedSize({w}, {h + mh})")
        if fp.get("TopMost"):
            L.append("        self.setWindowFlag(Qt.WindowType.WindowStaysOnTopHint, True)")
        if fp.get("BackColor"):
            L.append(f"        self.setStyleSheet(\"{n}Designer, #client {{ background-color:{fp['BackColor']}; }}\")")
        if fp.get("Icon"):
            L.append(f"        self.setWindowIcon(QIcon(self._res({fp['Icon']!r})))")
        client = "self"
        if mh:
            L += [f"        self.{menu.name} = QMenuBar(self)",
                  f"        self.{menu.name}.setGeometry(0, 0, {w}, {mh})",
                  "        self._client = QWidget(self)",
                  "        self._client.setObjectName(\"client\")",
                  f"        self._client.setGeometry(0, {mh}, {w}, {h})"]
            client = "self._client"
            L += ["        " + s for s in self._menu(menu, items)]
        for c in self._tab_order(form):
            L.append("")
            L += ["        " + s for s in self._control(c, f"self.{c.parent}" if c.parent else client, used(c))]
        for t in form.nonvisual():
            if t.type == "Timer":
                L += ["", f"        self.{t.name} = QTimer(self)",
                      f"        self.{t.name}.setInterval({int(t.props['Interval'])})",
                      f"        self.{t.name}.timeout.connect(self._ev(\"{t.name}_Tick\"))"]
                if t.props.get("Enabled"):
                    L.append(f"        self.{t.name}.start()")
        L += self._filter("self", n, None, used(None), form)
        L += ["", f"        QTimer.singleShot(0, self._ev(\"{n}_Load\"))",
              DISPATCH.replace("{form}", n).rstrip("\n"), ""]
        return "\n".join(L)

    def _filter(self, var, owner, ctrl, events, form) -> list[str]:
        table: dict[str, list[str]] = {}
        native = {e for (t, e) in SIGNALS if ctrl is not None and t == ctrl.type}
        for e in sorted(events - native):
            if e not in QEVENT:
                continue
            handler = self.handler_for(form, ctrl, e)
            kind = event_args(e)
            table.setdefault(QEVENT[e], []).append(f"({handler!r}, {kind!r}, {e == 'KeyPress'})")
        if not table:
            return []
        body = ", ".join(f"QEvent.Type.{k}: [{', '.join(v)}]" for k, v in table.items())
        out = [f"        _Events(self, {var}, {{{body}}})"]
        if "MouseMove" in table:
            out.append(f"        {var}.setMouseTracking(True)")
        return out

    def _menu(self, menu, items) -> list[str]:
        out: list[str] = []
        counter = [0]

        def build(var, its):
            for it in its:
                if it.get("Text") == "-":
                    out.append(f"{var}.addSeparator()")
                elif it.get("Items"):
                    counter[0] += 1
                    sub = f"_m{counter[0]}"
                    out.append(f"{sub} = {var}.addMenu({it['Text']!r})")
                    build(sub, it["Items"])
                else:
                    a = it["Name"]
                    out.append(f"self.{a} = QAction({it['Text']!r}, self)")
                    out.append(f"self.{a}.triggered.connect(self._ev(\"{a}_Click\"))")
                    out.append(f"{var}.addAction(self.{a})")
        build(f"self.{menu.name}", items)
        return out

    def _control(self, c, parent: str, used: set[str]) -> list[str]:
        p, n, t = c.props, c.name, c.type
        cls = QT_CLASS[t]
        multiline = t == "TextBox" and p.get("Multiline")
        if multiline:
            cls = "QPlainTextEdit"
        out = [f"self.{n} = {cls}({parent})"]
        if t == "TrackBar":
            out.append(f"self.{n}.setOrientation(Qt.Orientation.Horizontal)")
        if t == "GroupBox":
            out.append(f"self.{n}.setTitle({p['Text']!r})")
        elif multiline:
            out.append(f"self.{n}.setPlainText({p['Text']!r})")
        elif "Text" in p and t not in ("ListBox", "ComboBox", "Panel", "PictureBox"):
            out.append(f"self.{n}.setText({p['Text']!r})")
        out.append(f"self.{n}.setGeometry({int(p['Left'])}, {int(p['Top'])}, {int(p['Width'])}, {int(p['Height'])})")
        f = [repr(p.get("FontName") or "Segoe UI"), str(int(p.get("FontSize", 9)))]
        out.append(f"_f = QFont({', '.join(f)}); _f.setBold({bool(p.get('FontBold'))}); "
                   f"_f.setItalic({bool(p.get('FontItalic'))}); self.{n}.setFont(_f)")
        style = _style(p)
        if style:
            out.append(f"self.{n}.setStyleSheet(\"{cls} {{ {style} }}\")")
        if t in ("Label", "TextBox") and not multiline and p.get("TextAlign") in ALIGN:
            out.append(f"self.{n}.setAlignment(Qt.AlignmentFlag.{ALIGN[p['TextAlign']]} | "
                       f"Qt.AlignmentFlag.AlignVCenter)")
        if t in ("CheckBox", "RadioButton") and p.get("Checked"):
            out.append(f"self.{n}.setChecked(True)")
        if t == "TextBox":
            if p.get("ReadOnly"):
                out.append(f"self.{n}.setReadOnly(True)")
            if not multiline and p.get("PasswordChar"):
                out.append(f"self.{n}.setEchoMode(QLineEdit.EchoMode.Password)")
            if not multiline and int(p.get("MaxLength") or 0) > 0:
                out.append(f"self.{n}.setMaxLength({int(p['MaxLength'])})")
        if t in ("ListBox", "ComboBox"):
            its = split_items(p.get("Items", ""))
            if its:
                out.append(f"self.{n}.addItems({its!r})")
            if t == "ComboBox" and p.get("DropDownStyle") == "DropDown":
                out.append(f"self.{n}.setEditable(True)")
        if t == "PictureBox" and p.get("Image"):
            out.append(f"self.{n}.setPixmap(QPixmap(self._res({p['Image']!r})))")
        if t in ("ProgressBar", "NumericUpDown", "TrackBar"):
            out.append(f"self.{n}.setRange({int(p['Minimum'])}, {int(p['Maximum'])})")
            out.append(f"self.{n}.setValue({int(p['Value'])})")
        if p.get("ToolTip"):
            out.append(f"self.{n}.setToolTip({p['ToolTip']!r})")
        if not p.get("Enabled", True):
            out.append(f"self.{n}.setEnabled(False)")
        if not p.get("Visible", True):
            out.append(f"self.{n}.hide()")
        for (ct, ev), sig in SIGNALS.items():
            if ct == t and ev in used:
                signal = "textChanged" if multiline and sig == "textChanged" else sig
                out.append(f"self.{n}.{signal}.connect(self._ev(\"{n}_{ev}\"))")
        out += self._filter_ctrl(c, used)
        return out

    def _filter_ctrl(self, c, used):
        table: dict[str, list[str]] = {}
        native = {e for (t, e) in SIGNALS if t == c.type}
        for e in sorted(used - native):
            if e in QEVENT:
                table.setdefault(QEVENT[e], []).append(
                    f"('{c.name}_{e}', {event_args(e)!r}, {e == 'KeyPress'})")
        if not table:
            return []
        body = ", ".join(f"QEvent.Type.{k}: [{', '.join(v)}]" for k, v in table.items())
        out = [f"_Events(self, self.{c.name}, {{{body}}})"]
        if "MouseMove" in table:
            out.append(f"self.{c.name}.setMouseTracking(True)")
        return out

    def new_code(self, form: Form, is_startup: bool) -> str:
        n = form.name
        return (f"import sys\n\n"
                f"from PySide6.QtWidgets import QApplication, QMessageBox  # noqa: F401\n\n"
                f"from {n}_designer import {n}Designer, EventArgs  # noqa: F401\n\n\n"
                f"class {n}({n}Designer):\n"
                f"    \"\"\"Write your event handlers here.\"\"\"\n\n"
                f"    def {n}_Load(self):\n"
                f"        pass\n\n\n"
                f"if __name__ == \"__main__\":\n"
                f"    app = QApplication.instance() or QApplication(sys.argv)\n"
                f"    form = {n}()\n"
                f"    form.show()\n"
                f"    sys.exit(app.exec())\n")

    def on_form_added(self, startup_code: str, form_name: str) -> str:
        return self._insert_import(startup_code, f"from {form_name} import {form_name}  "
                                                 f"# show with: self.f2 = {form_name}(); self.f2.show()")


PLUGIN = PythonQtPlugin()

