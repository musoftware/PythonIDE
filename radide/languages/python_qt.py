def _style(p) -> str:
    rules = []
    if p.get("BackColor"):
        rules.append(f"background-color:{p['BackColor']};")
    if p.get("ForeColor"):
        rules.append(f"color:{p['ForeColor']};")
    return "".join(rules)


def _date_value(value: str, fmt: str) -> str | None:
    """Normalised design-time Value of a DateTimePicker (None = now)."""
    v = str(value or "").strip()
    if fmt == "Time":
        m = re.search(r"(\d{1,2}):(\d{2})(?::(\d{2}))?", v)
        return f"{int(m.group(1)):02d}:{m.group(2)}:{m.group(3) or '00'}" if m else None
    m = re.match(r"(\d{4})-(\d{1,2})-(\d{1,2})", v)
    return f"{m.group(1)}-{int(m.group(2)):02d}-{int(m.group(3)):02d}" if m else None


def _spec(place) -> str:
    vals = (place.x, place.y, place.w, place.h, place.rx, place.ry, place.rw, place.rh)
    return "(" + ", ".join(str(int(v)) if float(v).is_integer() else repr(round(float(v), 4))
                           for v in vals) + ")"


class PythonQtPlugin(PythonTkPlugin):
    id = "python-qt"
    display_name = "Python (PySide6 / Qt)"
    # package_manager (pip) is inherited from PythonTkPlugin
    _has_pyside: dict[str, bool] = {}

    @classmethod
    def _pyside_ok(cls, exe: str) -> bool:
        if exe not in cls._has_pyside:
            import subprocess
            try:
                r = subprocess.run([exe, "-c", "import PySide6.QtWidgets"], capture_output=True, timeout=20)
                cls._has_pyside[exe] = r.returncode == 0
            except (OSError, subprocess.TimeoutExpired):
                cls._has_pyside[exe] = False
        return cls._has_pyside[exe]

    def find_interpreter(self, configured: str = "") -> str:
        """A Python that can import PySide6: the configured one, PATH's, or the IDE's own."""
        import sys
        cands = [c for c in (configured, super().find_interpreter(""), sys.executable) if c]
        for c in dict.fromkeys(cands):
            if self._pyside_ok(c):
                return c
        return cands[0] if cands else sys.executable

