    @staticmethod
    def _parent_expr(form: Form, c, client: str) -> str:
        if not c.parent:
            return client
        pc = form.find(c.parent)
        if pc is not None and pc.type == "TabControl":
            pages = max(1, len(split_items(pc.props.get("TabPages", ""))))
            return f"self.{pc.name}_Page{min(max(tab_page(c), 0), pages - 1)}"
        return f"self.{c.parent}"

    def _dialog(self, t) -> str:
        p, cls = t.props, DIALOG_CLASS[t.type]
        if t.type in ("OpenFileDialog", "SaveFileDialog"):
            args = (f"save={t.type == 'SaveFileDialog'}, Title={p.get('Title', '')!r}, "
                    f"Filter={p.get('Filter', '')!r}, FileName={p.get('FileName', '')!r}, "
                    f"InitialDirectory={p.get('InitialDirectory', '')!r}")
        elif t.type == "ColorDialog":
            args = f"Color={p.get('Color') or '#000000'!r}"
        elif t.type == "FontDialog":
            args = f"FontName={p.get('FontName') or 'Segoe UI'!r}, FontSize={int(p.get('FontSize') or 9)}"
        else:
            args = f"SelectedPath={p.get('SelectedPath', '')!r}"
        return f"self.{t.name} = {cls}(self, {args})"

    def _toolstrip(self, ts) -> list[str]:
        out = []
        for it in ts.props.get("Items", []):
            if it.get("Text") == "-":
                out.append(f"self.{ts.name}.addSeparator()")
            elif it.get("Name"):
                a = it["Name"]
                out += [f"self.{a} = QAction({it.get('Text', a)!r}, self)",
                        f"self.{a}.triggered.connect(self._ev(\"{a}_Click\"))",
                        f"self.{ts.name}.addAction(self.{a})"]
        return out

    def _filter(self, var, owner, ctrl, events, form) -> list[str]:
        table: dict[str, list[str]] = {}
        native = {e for (t, e) in SIGNALS if ctrl is not None and t == ctrl.type}
        for e in sorted(events - native):
            if e not in QEVENT:
                continue
            handler = self.handler_for(form, ctrl, e)
            kind = event_args(e)
            table.setdefault(QEVENT[e], []).append(f"({handler!r}, {kind!r}, {e == 'KeyPress'})")
        if not table:
            return []
        body = ", ".join(f"QEvent.Type.{k}: [{', '.join(v)}]" for k, v in table.items())
        out = [f"        _Events(self, {var}, {{{body}}})"]
        if "MouseMove" in table:
            out.append(f"        {var}.setMouseTracking(True)")
        return out

    def _menu(self, menu, items) -> list[str]:
        out: list[str] = []
        counter = [0]

        def build(var, its):
            for it in its:
                if it.get("Text") == "-":
                    out.append(f"{var}.addSeparator()")
                elif it.get("Items"):
                    counter[0] += 1
                    sub = f"_m{counter[0]}"
                    out.append(f"{sub} = {var}.addMenu({it['Text']!r})")
                    build(sub, it["Items"])
                else:
                    a = it["Name"]
                    out.append(f"self.{a} = QAction({it['Text']!r}, self)")
                    out.append(f"self.{a}.triggered.connect(self._ev(\"{a}_Click\"))")
                    out.append(f"{var}.addAction(self.{a})")
        build(f"self.{menu.name}", items)
        return out

    def _control(self, c, parent: str, used: set[str]) -> list[str]:
        p, n, t = c.props, c.name, c.type
        from ..usercontrols import is_user_type, qt_control_lines
        if is_user_type(t):                     # an instance of a user control
            return qt_control_lines(self, c, parent, used)
        from ..components import codegen as _comp      # component packages (radide/components)
        if _comp.handles(t):
            return _comp.qt_control_lines(self, c, parent, used)
        cls = QT_CLASS[t]
        multiline = t == "TextBox" and p.get("Multiline")
        fmt = p.get("Format", "Short") if t == "DateTimePicker" else ""
        if multiline:
            cls = "QPlainTextEdit"
        if fmt == "Time":
            cls = "QTimeEdit"
        if t == "ActiveX":
            out = [f"self.{n} = _activex({parent}, {str(p.get('ProgID') or '')!r})"]
        elif t == "ReportViewer":
            rf = str(p.get("ReportFile") or "")
            out = [f"self.{n} = QtReportViewer({parent}, ReportFile={f'self._res({rf!r})' if rf else repr('')}, "
                   f"Zoom={int(p.get('Zoom') or 100)}, ShowToolbar={bool(p.get('ShowToolbar', True))}, "
                   f"AutoLoad={bool(p.get('AutoLoad', True))})"]
        else:
            out = [f"self.{n} = {cls}({parent})"]
        if t == "TrackBar":
            out.append(f"self.{n}.setOrientation(Qt.Orientation.Horizontal)")
        if t == "GroupBox":
            out.append(f"self.{n}.setTitle({p['Text']!r})")
        elif multiline:
            out.append(f"self.{n}.setPlainText({p['Text']!r})")
        elif t == "LinkLabel":
            color = p.get("LinkColor") or "#0066CC"
            link = f'<a href="#" style="color:{color};">{html.escape(str(p.get("Text", "")))}</a>'
            out += [f"self.{n}.setText({link!r})",
                    f"self.{n}.setOpenExternalLinks(False)",
                    f"self.{n}.setCursor(Qt.CursorShape.PointingHandCursor)"]
        elif "Text" in p and t not in ("ListBox", "ComboBox", "Panel", "PictureBox") and cls not in (
                "QTabWidget", "QTreeWidget", "QTableWidget", "QDateEdit", "QTimeEdit", "QAxWidget"):
            out.append(f"self.{n}.setText({p['Text']!r})")
        out.append(f"self.{n}.setGeometry({int(p['Left'])}, {int(p['Top'])}, {int(p['Width'])}, {int(p['Height'])})")
        f = [repr(p.get("FontName") or "Segoe UI"), str(int(p.get("FontSize", 9)))]
        out.append(f"_f = QFont({', '.join(f)}); _f.setBold({bool(p.get('FontBold'))}); "
                   f"_f.setItalic({bool(p.get('FontItalic'))}); self.{n}.setFont(_f)")
        style = _style(p)
        if t == "StatusBar":
            style = "border-top:1px solid palette(mid); padding-left:4px;" + style
        if style:
            sel = "QWidget" if t == "ActiveX" else cls
            out.append(f"self.{n}.setStyleSheet(\"{sel} {{ {style} }}\")")
        if t in ("Label", "TextBox") and not multiline and p.get("TextAlign") in ALIGN:
            out.append(f"self.{n}.setAlignment(Qt.AlignmentFlag.{ALIGN[p['TextAlign']]} | "
                       f"Qt.AlignmentFlag.AlignVCenter)")
        if t == "StatusBar":
            out.append(f"self.{n}.setAlignment(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter)")
        if t in ("CheckBox", "RadioButton") and p.get("Checked"):
            out.append(f"self.{n}.setChecked(True)")
        if t == "TextBox":
            if p.get("ReadOnly"):
                out.append(f"self.{n}.setReadOnly(True)")
            if not multiline and p.get("PasswordChar"):
                out.append(f"self.{n}.setEchoMode(QLineEdit.EchoMode.Password)")
            if not multiline and int(p.get("MaxLength") or 0) > 0:
                out.append(f"self.{n}.setMaxLength({int(p['MaxLength'])})")
        if t in ("ListBox", "ComboBox"):
            its = split_items(p.get("Items", ""))
            if its:
                out.append(f"self.{n}.addItems({its!r})")
            if t == "ComboBox" and p.get("DropDownStyle") == "DropDown":
                out.append(f"self.{n}.setEditable(True)")
        if t == "PictureBox" and p.get("Image"):
            out.append(f"self.{n}.setPixmap(QPixmap(self._res({p['Image']!r})))")
        if t in ("ProgressBar", "NumericUpDown", "TrackBar"):
            out.append(f"self.{n}.setRange({int(p['Minimum'])}, {int(p['Maximum'])})")
            out.append(f"self.{n}.setValue({int(p['Value'])})")
        out += self._new_control(c, fmt)
        if p.get("ToolTip"):
            out.append(f"self.{n}.setToolTip({p['ToolTip']!r})")
        if not p.get("Enabled", True):
            out.append(f"self.{n}.setEnabled(False)")
        if not p.get("Visible", True):
            out.append(f"self.{n}.hide()")
        for (ct, ev), sig in SIGNALS.items():
            if ct == t and ev in used:
                signal = "textChanged" if multiline and sig == "textChanged" else sig
                if fmt == "Time" and sig == "dateChanged":
                    signal = "timeChanged"
                out.append(f"self.{n}.{signal}.connect(self._ev(\"{n}_{ev}\"))")
        if t == "ActiveX" and "Click" in used:
            # COM controls draw in their own native window: use their Click() event when they have one
            out.append(f"_ax_event(self.{n}, \"Click()\", self._ev(\"{n}_Click\")) or "
                       f"_Events(self, self.{n}, {{QEvent.Type.MouseButtonRelease: [('{n}_Click', None, False)]}})")
            used = used - {"Click"}
        out += self._filter_ctrl(c, used)
        return out

    def _new_control(self, c, fmt: str) -> list[str]:
        """Content of the controls of CONTRACTS section 4."""
        p, n, t = c.props, c.name, c.type
        out: list[str] = []
        if t == "TabControl":
            pages = split_items(p.get("TabPages", "")) or ["TabPage1"]
            for i, title in enumerate(pages):
                out += [f"self.{n}_Page{i} = QWidget()",
                        f"self.{n}.addTab(self.{n}_Page{i}, {title!r})"]
            idx = int(p.get("SelectedIndex") or 0)
            if 0 < idx < len(pages):
                out.append(f"self.{n}.setCurrentIndex({idx})")
        elif t == "TreeView":
            out.append(f"self.{n}.setHeaderHidden(True)")
            nodes = tree_paths(p.get("Nodes", ""))
            if nodes:
                out.append(f"_fill_tree(self.{n}, {nodes!r})")
        elif t in ("ListView", "DataGridView"):
            cols = split_items(p.get("Columns", ""))
            rows = split_rows(p.get("Items" if t == "ListView" else "Rows", ""))
            if t == "ListView" and p.get("View") == "List":
                cols, rows = cols[:1] or [""], [r[:1] for r in rows]
                out.append(f"self.{n}.horizontalHeader().hide()")
            out.append(f"_fill_table(self.{n}, {cols!r}, {rows!r})")
            out.append(f"self.{n}.horizontalHeader().setStretchLastSection(True)")
            if t == "ListView":
                out += [f"self.{n}.verticalHeader().hide()",
                        f"self.{n}.setShowGrid(False)",
                        f"self.{n}.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)",
                        f"self.{n}.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)",
                        f"self.{n}.setSelectionMode(QAbstractItemView.SelectionMode.SingleSelection)"]
            elif p.get("ReadOnly"):
                out.append(f"self.{n}.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)")
        elif t == "DateTimePicker":
            out.append(f"self.{n}.setDisplayFormat({DATE_FORMATS.get(fmt, DATE_FORMATS['Short'])!r})")
            v = _date_value(p.get("Value", ""), fmt)
            if fmt == "Time":
                out.append(f"self.{n}.setTime(QTime.fromString({v!r}, 'HH:mm:ss'))" if v
                           else f"self.{n}.setTime(QTime.currentTime())")
            else:
                out.append(f"self.{n}.setCalendarPopup(True)")
                out.append(f"self.{n}.setDate(QDate.fromString({v!r}, 'yyyy-MM-dd'))" if v
                           else f"self.{n}.setDate(QDate.currentDate())")
        return out

    def _filter_ctrl(self, c, used):
        table: dict[str, list[str]] = {}
        native = {e for (t, e) in SIGNALS if t == c.type}
        for e in sorted(used - native):
            if e in QEVENT:
                table.setdefault(QEVENT[e], []).append(
                    f"('{c.name}_{e}', {event_args(e)!r}, {e == 'KeyPress'})")
        if not table:
            return []
        targets = {f"self.{c.name}": table}
        if c.type in ITEM_VIEWS:        # mouse events of item views arrive on their viewport
            mouse = {k: v for k, v in table.items() if k in MOUSE_QEVENTS}
            targets = {f"self.{c.name}": {k: v for k, v in table.items() if k not in MOUSE_QEVENTS},
                       f"self.{c.name}.viewport()": mouse}
        out = []
        for var, tab in targets.items():
            if not tab:
                continue
            body = ", ".join(f"QEvent.Type.{k}: [{', '.join(v)}]" for k, v in tab.items())
            out.append(f"_Events(self, {var}, {{{body}}})")
            if "MouseMove" in tab:
                out.append(f"{var}.setMouseTracking(True)")
        return out

