"""Base class for languages that get their forms through the GUI Bridge
(see runtimes/bridge.py and docs/CONTRACTS.md).

A subclass describes the language (extension, syntax, templates) and how to
build/run the generated main program. The IDE's bridge host draws the forms;
the program receives "EVENT obj ev args" lines on stdin and answers with
SET/GET/CALL/MSGBOX/... lines, ending each event with DONE.

Subclasses usually only implement:
    client_files()         -> {target file name: source Path}  (copied into the project)
    main_source(project)   -> (file name, text) of the generated entry program
    build_command(folder, project) -> shell command string or None (interpreted languages)
    run_command(folder, project)   -> argv list that starts the program
    new_code / add_handler / find_handler / handler_regex
"""
from __future__ import annotations

import os
import re
import shutil
import sys
from pathlib import Path

from ..controls import FORM_EVENTS
from ..model import Form, Project
from .base import Completion, LanguagePlugin, RunSpec

from ..paths import python_root as _python_root  # noqa: E402
IDE_ROOT = _python_root()   # a real Python imports radide from here (not _internal in a release build)
CLIENTS = IDE_ROOT / "radide" / "runtimes" / "clients"   # through IDE_ROOT: a real Python must not see _internal


def toolchains_root() -> Path:
    """%LOCALAPPDATA%\\RADIDE\\toolchains - private folder of downloaded language toolchains."""
    return Path(os.environ.get("LOCALAPPDATA") or (Path.home() / "AppData" / "Local")) / "RADIDE" / "toolchains"


def find_in_toolchains(subdirs: list[str], names: list[str]) -> str:
    """First ``<toolchains>/<subdir>/<name>[.exe|.cmd|.bat]`` that exists, or ""."""
    root = toolchains_root()
    exts = ("", ".exe", ".cmd", ".bat") if os.name == "nt" else ("",)
    for sub in subdirs:
        d = root / sub
        if not d.is_dir():
            continue
        for n in names:
            for ext in exts:
                p = d / (n + ext)
                if p.is_file():
                    from ..paths import ansi_safe   # an Arabic user name on an English Windows: 8.3 name
                    return ansi_safe(p)
    return ""


class BridgeLanguagePlugin(LanguagePlugin):
    """GUI-Bridge language. Handler names are neutral: <Control>_<Event>, <Form>_Load ..."""

    @property
    def supports_debug(self) -> bool:
        """F5/F9 debugging through radide/bridgedebug.py (gdb, netcoredbg, js-debug, dart DAP)."""
        from ..bridgedebug import engine_for
        return engine_for(self) is not None

    # regex with one group = handler name, used to find which events the program handles
    handler_regex = r"^\s*(?:function|def|sub|subroutine|void|static\s+void|public\s+static\s+void)\s+(\w+_\w+)\s*\("
    tool_names: list[str] = []          # executables looked up for build/run (first found wins)
    tool_hints: list[str] = []
    # bin folders under %LOCALAPPDATA%\RADIDE\toolchains searched after PATH (e.g. "go/bin")
    toolchain_bins: list[str] = []
    install_hint = ""                   # shown when the tool is missing

    # ------------------------------------------------------------ tools
    def tool(self) -> str:
        for n in self.tool_names:
            p = shutil.which(n)
            if p:
                return p
        if self.toolchain_bins:
            p = find_in_toolchains(self.toolchain_bins, list(self.tool_names))
            if p:
                return p
        for h in self.tool_hints:
            if Path(h).exists():
                return h
        return ""

    def find_interpreter(self, configured: str = "") -> str:
        return sys.executable           # the bridge host is the IDE's Python

    # ------------------------------------------------------------ events / names
    def handler_for(self, form, ctrl, event):
        if ctrl is not None and ctrl.type in ("MenuStrip", "ToolStrip"):
            return f"{event}_Click"
        return f"{ctrl.name if ctrl else form.name}_{event}"

    def events_for(self, ctrl):
        if ctrl is None:
            return list(FORM_EVENTS)
        return super().events_for(ctrl)

    def generate_designer(self, form: Form, user_code: str) -> str:
        """Most bridge languages dispatch dynamically: the designer file is informational."""
        lines = [f"{self.line_comments[0] if self.line_comments else '#'} AUTO-GENERATED by RAD IDE - form "
                 f"{form.name} is drawn by the IDE (GUI Bridge). Controls:"]
        for c in form.controls:
            lines.append(f"{self.line_comments[0] if self.line_comments else '#'}   {c.name}: {c.type}")
        return "\n".join(lines) + "\n"

    # ------------------------------------------------------------ to implement
    def client_files(self) -> dict[str, Path]:
        return {}

    def main_source(self, project: Project) -> tuple[str, str] | None:
        return None

    def build_command(self, folder: Path, project: Project) -> str | None:
        return None

    def run_command(self, folder: Path, project: Project) -> list[str]:
        raise NotImplementedError

    # ------------------------------------------------------------ run
    def code_files(self, project: Project) -> list[str]:
        forms = project.forms_in(self.id) if hasattr(project, "forms_in") else project.forms
        files = [self.code_file(f) for f in forms]          # forms of other languages run elsewhere
        files += [m for m in project.modules if m.endswith(self.code_ext)]
        return files

    def handlers_in_project(self, folder: Path, project: Project) -> list[str]:
        out = []
        rx = re.compile(self.handler_regex, re.I | re.M)
        for f in self.code_files(project):
            p = folder / f
            if p.exists():
                out += rx.findall(p.read_text(encoding="utf-8", errors="replace"))
        return out

    def prepare(self, folder: Path, project: Project) -> None:
        for target, src in self.client_files().items():
            shutil.copy2(src, folder / target)
        main = self.main_source(project)
        if main is not None:
            name, text = main
            (folder / name).write_text(text, encoding="utf-8")

    def run_spec(self, folder: Path, startup_form: str, interpreter: str) -> RunSpec:
        project = Project.load(folder)
        self.prepare(folder, project)
        build = self.build_command(folder, project)
        if not self.tool():
            build = f"echo {self.display_name}: required tool not found ({', '.join(self.tool_names)}). " \
                    f"{self.install_hint} && exit 1"
        from ..paths import ansi_env              # the build step runs ANSI tools (gcc ...): TEMP they can open
        env = ansi_env(dict(os.environ, PYTHONPATH=str(IDE_ROOT), PYTHONUNBUFFERED="1", PYTHONIOENCODING="utf-8",
                            RAD_HANDLERS=",".join(self.handlers_in_project(folder, project))))
        # the native forms host (radide/runtimes/native_host.py, radbridge.exe: C + radforms, no Python) when the
        # project's forms allow it; otherwise the Python host below, and the reason goes to the Output window
        why = "the program's tool is missing" if not self.tool() else ""
        if not why:
            from ..runtimes import native_host as NH
            try:
                why = NH.why_not(folder, project, self)
                if not why:
                    forms = NH.write_forms(folder, project)
                    env["RAD_BASE_DIR"] = str(folder)
                    return RunSpec(str(NH.host_path()),
                                   NH.radbridge_args(forms, build, self.run_command(folder, project)), folder, env)
            except Exception as e:  # noqa: BLE001 - never stop F5: the Python host still runs it
                why = f"native forms host: {e}"
        env["RAD_HOST_NOTE"] = why
        args = ["-u", "-m", "radide.runtimes.bridge", str(folder)]
        if build:
            args += ["--build", build]
        args += ["--"] + self.run_command(folder, project)
        return RunSpec(sys.executable, args, folder, env)

    def debug_spec(self, folder: Path, startup_form: str, interpreter: str, breakpoints) -> RunSpec:
        """The run spec; radide.bridgedebug.BridgeDebugSession adds the debug build/attach parts."""
        return self.run_spec(folder, startup_form, interpreter)

    # ------------------------------------------------------------ IntelliSense (basic)
    def completions(self, code, line, col, path, names=None):
        out = [Completion(k, "keyword") for k in self.keywords]
        out += [Completion(b, "function") for b in self.builtins]
        out += [Completion(n, "control", t) for n, t in (names or {}).items()]
        return out
