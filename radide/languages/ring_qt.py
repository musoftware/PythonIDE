def copy_ring_client(folder: Path) -> None:
    """Put radcall.ring (RAD Hub client) into the project; every .ring file is loaded by main."""
    target = folder / "radcall.ring"
    src = RING_CLIENT.read_bytes()
    if not target.exists() or target.read_bytes() != src:
        target.write_bytes(src)


def write_runtime(folder: Path) -> None:
    """Put the RingQt runtime helpers (dialog classes, Anchor/Dock) next to the designer files."""
    target = folder / RT_FILE
    try:
        if not target.exists() or target.read_text(encoding="utf-8") != RING_RT:
            target.write_text(RING_RT, encoding="utf-8")
    except OSError:
        pass


def _style(p) -> str:
    parts = []
    if p.get("BackColor"):
        parts.append(f"background-color:{p['BackColor']};")
    if p.get("ForeColor"):
        parts.append(f"color:{p['ForeColor']};")
    parts.append(f"font-family:'{p.get('FontName') or 'Segoe UI'}';font-size:{int(p.get('FontSize', 9))}pt;")
    if p.get("FontBold"):
        parts.append("font-weight:bold;")
    if p.get("FontItalic"):
        parts.append("font-style:italic;")
    return "".join(parts)


