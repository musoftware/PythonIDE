QT_CLASS = {"Button": "qPushButton", "Label": "qLabel", "TextBox": "qLineEdit",
            "CheckBox": "qCheckBox", "RadioButton": "qRadioButton",
            "ListBox": "qListWidget", "ComboBox": "qComboBox", "PictureBox": "qLabel",
            "ProgressBar": "qProgressBar", "NumericUpDown": "qSpinBox", "TrackBar": "qSlider",
            "Panel": "qFrame", "GroupBox": "qGroupBox"}

# neutral event -> setter of the widget's own signal
NATIVE = {
    ("Button", "Click"): "setClickEvent",
    ("TextBox", "TextChanged"): "setTextChangedEvent",
    ("CheckBox", "CheckedChanged"): "setStateChangedEvent",
    ("RadioButton", "CheckedChanged"): "setToggledEvent",
    ("ListBox", "SelectedIndexChanged"): "setCurrentRowChangedEvent",
    ("ComboBox", "SelectedIndexChanged"): "setCurrentIndexChangedEvent",
    ("ComboBox", "TextChanged"): "setEditTextChangedEvent",
    ("NumericUpDown", "ValueChanged"): "setValueChangedEvent",
    ("TrackBar", "ValueChanged"): "setValueChangedEvent",
    ("Timer", "Tick"): "setTimeoutEvent",
}
# neutral event -> qAllEvents setter (event filter)
FILTER = {
    "Click": "setMouseButtonReleaseEvent", "DoubleClick": "setMouseButtonDblClickEvent",
    "MouseDown": "setMouseButtonPressEvent", "MouseUp": "setMouseButtonReleaseEvent",
    "MouseMove": "setMouseMoveEvent", "MouseEnter": "setEnterEvent", "MouseLeave": "setLeaveEvent",
    "MouseWheel": "setWheelEvent", "KeyDown": "setKeyPressEvent", "KeyPress": "setKeyPressEvent",
    "KeyUp": "setKeyReleaseEvent", "GotFocus": "setFocusInEvent", "LostFocus": "setFocusOutEvent",
    "Resize": "setResizeEvent", "Activated": "setWindowActivateEvent",
    "Deactivate": "setWindowDeactivateEvent", "FormClosing": "setCloseEvent",
    "FormClosed": "setCloseEvent",
}
ALIGN = {"Left": 129, "Center": 132, "Right": 130}     # Qt::AlignLeft/HCenter/Right | AlignVCenter
ARG_HELP = {"mouse": "e.getx()  e.gety()  e.getbutton()  e.getWheelDelta()",
            "key": "e.getKeyCode()  e.getKeyText()",
            "cancel": "call e.ignore() to keep the form open"}


def _style(p) -> str:
    parts = []
    if p.get("BackColor"):
        parts.append(f"background-color:{p['BackColor']};")
    if p.get("ForeColor"):
        parts.append(f"color:{p['ForeColor']};")
    parts.append(f"font-family:'{p.get('FontName') or 'Segoe UI'}';font-size:{int(p.get('FontSize', 9))}pt;")
    if p.get("FontBold"):
        parts.append("font-weight:bold;")
    if p.get("FontItalic"):
        parts.append("font-style:italic;")
    return "".join(parts)


class RingQtPlugin(LanguagePlugin):
    id = "ring-qt"
    display_name = "Ring (RingQt)"
    code_ext = ".ring"
    interpreter_names = ["ring"]
    interpreter_hints = [r"C:\ring\ring\bin\ring.exe", r"C:\ring\bin\ring.exe"]
    supports_debug = True

    case_sensitive = False
    line_comments = ["#", "//"]
    block_comment = ("/*", "*/")
    string_quotes = ['"', "'", "`"]
    keywords = """again and but bye call case catch changeringkeyword changeringoperator
        class def do done else elseif end endclass endfor endfunc endif endpackage
        endswitch endtry endwhile exit for from func get give if import in load
        loadsyntax loop new next not off ok on or other package private put return
        see step switch to try while break continue self this null true false nl
        foreach""".split()
    builtins = """len add del find sort reverse substr lower upper trim number string
        isstring isnumber islist isobject isnull type copy random clock time date
        sqrt pow floor ceil abs list str2list list2str raise eval""".split()

    def events_for(self, ctrl):
        events = super().events_for(ctrl)
        if ctrl is None or ctrl.type == "MenuStrip":
            return [e for e in events if ctrl is not None or e in FILTER or e == "Load"]
        return [e for e in events if (ctrl.type, e) in NATIVE or e in FILTER]

    # ------------------------------------------------------------ generation
    def generate_designer(self, form: Form, user_code: str) -> str:
        n, fp = form.name, form.props
        q = lambda s: quote(s, RING_QUOTES)
        has = lambda h: self.find_handler(user_code, h) >= 0
        menu = form.menu()
        items = menu.props.get("Items", []) if menu else []
        mh = 22 if items else 0
        w, h = int(fp["Width"]), int(fp["Height"])
        client = f"{n}_Client" if mh else n

        globals_ = [n, f"{n}_Events"] + ([client, f"{n}_MenuBar"] if mh else [])
        for c in form.controls:
            if c.type != "MenuStrip":
                globals_ += [c.name, f"{c.name}_Events"]
        globals_ += [it["Name"] for it in menu_leaves(items)]
        L = [HEADER.format(form=n), 'load "guilib.ring"', ""]
        L += [f"{g} = NULL" for g in globals_]
        L += ["", f"func {n}_Create",
              f"    {n} = new qWidget()",
              f"    {n}.setWindowTitle({q(fp['Text'])})",
              f"    {n}.resize({w}, {h + mh})"]
        if fp.get("FormBorderStyle") == "FixedSingle":
            L.append(f"    {n}.setFixedSize({w}, {h + mh})")
        if fp.get("TopMost"):
            L.append(f"    {n}.setWindowFlags(262145)    # Qt::Window | WindowStaysOnTopHint")
        if fp.get("BackColor"):
            L.append(f"    {n}.setStyleSheet(\"background-color:{fp['BackColor']};\")")
        if fp.get("Icon"):
            L.append(f"    {n}.setWindowIcon(new qIcon(new qPixmap({q(fp['Icon'])})))")
        if mh:
            L += [f"    {client} = new qFrame({n}, 0)",
                  f"    {client}.setGeometry(0, {mh}, {w}, {h})",
                  f"    {n}_MenuBar = new qMenuBar({n})",
                  f"    {n}_MenuBar.setGeometry(0, 0, {w}, {mh})"]
            L += ["    " + s for s in self._menu(n, items, has)]
        ordered = form.ordered()
        by_tab = self._tab_order(form)
        for c in by_tab:
            L.append("")
            L += ["    " + s for s in self._control(c.parent or client, c, form, user_code)]
        if [c.name for c in by_tab] != [c.name for c in ordered]:
            L.append("")
            L += [f"    {c.name}.raise()" for c in ordered]
        for t in form.nonvisual():
            if t.type != "Timer":
                continue
            L += ["", f"    {t.name} = new qTimer({n})",
                  f"    {t.name}.setInterval({int(t.props['Interval'])})"]
            if has(f"{t.name}_Tick"):
                L.append(f"    {t.name}.setTimeoutEvent(\"{t.name}_Tick()\")")
            if t.props.get("Enabled"):
                L.append(f"    {t.name}.start()")
        L += ["    " + s for s in self._filter(n, n, None, form, user_code)]
        if has(f"{n}_Load"):
            L += ["", f"    {n}_Load()"]
        show = "showMaximized" if fp.get("WindowState") == "Maximized" else "show"
        L += ["", f"func {n}_Show", f"    if isNull({n}) {n}_Create() ok", f"    {n}.{show}()", ""]
        return "\n".join(L)

    @staticmethod
    def _tab_order(form: Form):
        out = []

        def visit(parent):
            for c in sorted(form.children(parent), key=lambda c: int(c.props.get("TabIndex", 0))):
                out.append(c)
                if c.ctype.container:
                    visit(c.name)
        visit("")
        return out

    def _filter(self, var: str, owner: str, ctrl, form: Form, user_code: str) -> list[str]:
        """qAllEvents event filter for the generic events that have handlers."""
        calls: dict[str, list[str]] = {}
        native = {e for (t, e) in NATIVE if ctrl is not None and t == ctrl.type}
        for e in self.used_events(form, ctrl, user_code):
            if e in native or e not in FILTER:
                continue
            handler = self.handler_for(form, ctrl, e)
            arg = f"{owner}_Events" if event_args(e) else ""
            calls.setdefault(FILTER[e], []).append(f"{handler}({arg})")
        if not calls:
            return []
        out = [f"{owner}_Events = new qAllEvents({var})"]
        for setter, cs in calls.items():
            out.append(f"{owner}_Events.{setter}(\"{' '.join(cs)}\")")
        if "setMouseMoveEvent" in calls:
            out.append(f"{var}.setMouseTracking(true)")
        out.append(f"{var}.installEventFilter({owner}_Events)")
        return out

    def _menu(self, form_name: str, items: list, has) -> list[str]:
        q = lambda s: quote(s, RING_QUOTES)
        out: list[str] = []
        counter = [0]

        def build(var: str, items: list):
            for it in items:
                if it.get("Text") == "-":
                    out.append(f"{var}.addSeparator()")
                elif it.get("Items") or var.endswith("_MenuBar"):
                    counter[0] += 1
                    sub = f"oMenu{counter[0]}"
                    out.append(f"{sub} = {var}.addMenu({q(it['Text'])})")
                    build(sub, it["Items"] if it.get("Items") else [it])
                else:
                    a = it["Name"]
                    out.append(f"{a} = new qAction({form_name})")
                    out.append(f"{a}.setText({q(it['Text'])})")
                    if has(f"{a}_Click"):
                        out.append(f"{a}.setClickEvent(\"{a}_Click()\")")
                    out.append(f"{var}.addAction({a})")
        build(f"{form_name}_MenuBar", items)
        return out

    def _control(self, parent: str, c, form: Form, user_code: str) -> list[str]:
        p, n, t = c.props, c.name, c.type
        q = lambda s: quote(s, RING_QUOTES)
        cls = QT_CLASS[t]
        multiline = t == "TextBox" and p.get("Multiline")
        if multiline:
            cls = "qTextEdit"
        extra = ", 0" if t == "Panel" else ""   # RingQt: qFrame(parent, flags)
        out = [f"{n} = new {cls}({parent}{extra})"]
        if t == "GroupBox":
            out.append(f"{n}.setTitle({q(p['Text'])})")
        elif multiline:
            out.append(f"{n}.setPlainText({q(p['Text'])})")
        elif "Text" in p and t not in ("ListBox", "ComboBox", "Panel", "PictureBox"):
            out.append(f"{n}.setText({q(p['Text'])})")
        out.append(f"{n}.setGeometry({int(p['Left'])}, {int(p['Top'])}, "
                   f"{int(p['Width'])}, {int(p['Height'])})")
        style = _style(p)
        if t == "Button" and p.get("TextAlign", "Center") != "Center":
            style += f"text-align:{p['TextAlign'].lower()};"
        out.append(f"{n}.setStyleSheet(\"{style}\")")
        if t in ("Label", "TextBox") and not multiline and p.get("TextAlign") in ALIGN:
            out.append(f"{n}.setAlignment({ALIGN[p['TextAlign']]})")
        if t in ("CheckBox", "RadioButton") and p.get("Checked"):
            out.append(f"{n}.setChecked(true)")
        if t == "TextBox":
            if p.get("ReadOnly"):
                out.append(f"{n}.setReadOnly(true)")
            if not multiline and p.get("PasswordChar"):
                out.append(f"{n}.setEchoMode(2)")
            if not multiline and int(p.get("MaxLength") or 0) > 0:
                out.append(f"{n}.setMaxLength({int(p['MaxLength'])})")
        if t == "ListBox":
            out += [f"{n}.addItem({q(it)})" for it in split_items(p["Items"])]
        if t == "ComboBox":
            if p.get("DropDownStyle") == "DropDown":
                out.append(f"{n}.setEditable(true)")
            out += [f"{n}.addItem({q(it)}, 0)" for it in split_items(p["Items"])]
        if t == "PictureBox" and p.get("Image"):
            out.append(f"{n}.setPixmap(new qPixmap({q(p['Image'])}))")
        if t in ("ProgressBar", "NumericUpDown", "TrackBar"):
            if t == "TrackBar":
                out.append(f"{n}.setOrientation(1)")
            out.append(f"{n}.setRange({int(p['Minimum'])}, {int(p['Maximum'])})")
            out.append(f"{n}.setValue({int(p['Value'])})")
        if p.get("ToolTip"):
            out.append(f"{n}.setToolTip({q(p['ToolTip'])})")
        if not p["Enabled"]:
            out.append(f"{n}.setEnabled(false)")
        if not p["Visible"]:
            out.append(f"{n}.hide()")
        # events: widget signals first, then the generic event filter
        has = lambda h: self.find_handler(user_code, h) >= 0
        for (ctype, event), setter in NATIVE.items():
            if ctype == t and has(f"{n}_{event}"):
                if multiline and event == "TextChanged":
                    setter = "settextChangedEvent"
                out.append(f"{n}.{setter}(\"{n}_{event}()\")")
        out += self._filter(n, n, c, form, user_code)
        return out

    def new_code(self, form: Form, is_startup: bool) -> str:
        n = form.name
        return (f"load \"{self.designer_file(n)}\"\n\n"
                f"# Show this form with:  {n}_Show()\n\n"
                f"# ---------------- Event handlers ----------------\n\n"
                f"func {n}_Load\n"
                f"    # runs after the form is created\n")

    def module_template(self, name: str) -> str:
        return f"# {name} - shared code for the project\n\n"

    # ---------------------------------------------------------------- events
    def find_handler(self, code: str, name: str) -> int:
        return self._find_line(code, rf"^\s*(func|def)\s+{re.escape(name)}\b", re.I)

    def add_handler(self, code: str, name: str, form: Form, args: str | None = None) -> tuple[str, int]:
        lines = code.rstrip("\n").splitlines()
        if args:
            lines += ["", f"func {name} e", f"    # {ARG_HELP[args]}", "    "]
        else:
            lines += ["", f"func {name}", "    "]
        return "\n".join(lines) + "\n", len(lines) - 1

    # ------------------------------------------------------------ IntelliSense
    CONTROL_CLASS = {**QT_CLASS, "Form": "qWidget", "Timer": "qTimer", "MenuStrip": "qMenuBar"}

    def _class_of(self, obj: str, code: str, names: dict[str, str], line: int) -> str | None:
        low = obj.lower()
        for n, t in (names or {}).items():
            if n.lower() == low:
                return self.CONTROL_CLASS.get(t)
            if f"{n}_events".lower() == low:
                return "qAllEvents"
        m = re.search(rf"\b{re.escape(obj)}\s*=\s*new\s+(\w+)", code, re.I)
        if m:
            return m.group(1)
        if low == "e":       # handler parameter of mouse/key events
            for ln in reversed(code.splitlines()[:line + 1]):
                if re.match(r"^\s*func\s+\w+\s+e\b", ln, re.I):
                    return "qAllEvents"
                if re.match(r"^\s*func\b", ln, re.I):
                    break
        return None

    def _user_funcs(self, code: str) -> dict[str, str]:
        out = {}
        for m in re.finditer(r"^\s*func\s+(\w+)[ \t]*([^\n]*)", code, re.I | re.M):
            out[m.group(1)] = f"{m.group(1)}({m.group(2).strip()})"
        return out

    def completions(self, code, line, col, path, names=None):
        from .. import ringqt_index as rq
        from .base import Completion
        lines = code.splitlines()
        before = lines[line][:col] if line < len(lines) else ""
        m = re.search(r"(\w+)\s*\.\s*(\w*)$", before)
        if m:                                   # member list after "obj."
            cls = self._class_of(m.group(1), code, names or {}, line)
            if not cls:
                return []
            return [Completion(n, "method", sig) for n, sig in sorted(rq.class_methods(cls).items(),
                                                                       key=lambda kv: kv[0].lower())]
        if re.search(r"\bnew\s+\w*$", before, re.I):
            return [Completion(c, "class") for c in sorted(rq.class_names(), key=str.lower)]
        out = [Completion(k, "keyword") for k in self.keywords]
        out += [Completion(n, "function", sig) for n, sig in self._user_funcs(code).items()]
        out += [Completion(n, "control", f"{t} ({self.CONTROL_CLASS.get(t, '')})") for n, t in (names or {}).items()]
        out += [Completion(f, "function", RING_SIGS.get(f, "")) for f in rq.load_index()["functions"]]
        out += [Completion(f, "function", s) for f, s in RING_SIGS.items()]
        seen, uniq = set(), []
        for c in out:
            if c.name.lower() not in seen:
                seen.add(c.name.lower())
                uniq.append(c)
        current = (re.search(r"\w*$", before).group() or "").lower()
        for w in re.findall(r"\b[A-Za-z_]\w{2,}\b", code):
            if w.lower() not in seen and w.lower() != current:
                seen.add(w.lower())
                uniq.append(Completion(w, "variable"))
        return uniq

    def calltip(self, code, line, col, path, names=None):
        from .. import ringqt_index as rq
        lines = code.splitlines()
        before = lines[line][:col] if line < len(lines) else ""
        depth = 0
        for i in range(len(before) - 1, -1, -1):        # find the unmatched "("
            ch = before[i]
            if ch == ")":
                depth += 1
            elif ch == "(":
                if depth == 0:
                    head = before[:i]
                    m = re.search(r"(?:(\w+)\s*\.\s*)?(\w+)\s*$", head)
                    if not m:
                        return ""
                    obj, fn = m.group(1), m.group(2)
                    if obj:
                        cls = self._class_of(obj, code, names or {}, line)
                        meths = rq.class_methods(cls) if cls else {}
                        for k, v in meths.items():
                            if k.lower() == fn.lower():
                                return v
                        return ""
                    funcs = self._user_funcs(code)
                    for k, v in {**RING_SIGS, **funcs}.items():
                        if k.lower() == fn.lower():
                            return v
                    if fn.lower().startswith("q"):
                        ctor = rq.load_index()["classes"].get(fn.lower())
                        if ctor:
                            return f"new {fn}(...)  - {ctor.get('parent') or ''}"
                    return ""
                depth -= 1
        return ""

    # ------------------------------------------------------------------- run
    def _main_file(self, folder: Path, startup_form: str, debug: bool) -> str:
        files = sorted(f.name for f in folder.glob("*.ring")
                       if not f.name.startswith("_") and not f.stem.endswith("_designer"))
        legacy_main = any(self.find_handler(
            (folder / f).read_text(encoding="utf-8", errors="replace"), "main") >= 0 for f in files)
        start = self.code_file(startup_form)
        files.sort(key=lambda f: f != start)            # startup file first
        L = ["# generated by RAD IDE - safe to delete"]
        if debug:
            L.append(f"load \"{str(AGENT).replace(chr(92), '/')}\"")
        L += [f"load \"{f}\"" for f in files]
        if not legacy_main:
            L += ["", "func main", "    oApp = new qApp", f"    {startup_form}_Show()", "    oApp.exec()"]
        name = DEBUG_MAIN if debug else RUN_MAIN
        (folder / name).write_text("\n".join(L) + "\n", encoding="utf-8")
        return name

    def run_spec(self, folder: Path, startup_form: str, interpreter: str) -> RunSpec:
        return RunSpec(interpreter, [self._main_file(folder, startup_form, False)], folder)

    def debug_spec(self, folder, startup_form, interpreter, breakpoints) -> RunSpec:
        env = dict(os.environ, RADDBG_BP=self.breakpoints_env(breakpoints))
        return RunSpec(interpreter, [self._main_file(folder, startup_form, True)], folder, env)


