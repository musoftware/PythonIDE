    def _proxy_funcs(self, path) -> dict[str, str]:
        """Functions of the reference proxies next to *path* (for IntelliSense)."""
        from . import _refs
        out: dict[str, str] = {}
        if not path:
            return out
        for p in _refs.proxy_files(Path(path).parent, "*.ref.ring"):
            try:
                text = p.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            doc = ""
            for ln in text.splitlines():
                s = ln.strip()
                m = re.match(r"^func\s+(\w+)[ \t]*(.*)$", s, re.I)
                if m:
                    out[m.group(1)] = f"{m.group(1)}({m.group(2).strip()})" + (f"  - {doc}" if doc else "")
                doc = s.lstrip("# ").strip() if s.startswith("#") else ""
        return out

