    # ------------------------------------------------------------ solution references (CONTRACTS 7.2)
    _FUNC_RX = re.compile(r"^\s*(?:func|def)\s+(\w+)\s*\(?([^)#\n]*?)\)?\s*(?:(?:#|//).*)?$", re.I)

    def exported_functions(self, path: Path, text: str) -> list:
        """Top-level ``func``s of a library file: not inside a class, not ``main``, not
        starting with "_", not ``<Object>_<Event>`` handlers."""
        from . import _refs
        path = Path(path)
        low = path.name.lower()
        if (low.startswith("_") or low == "radcall.ring" or path.stem.lower().endswith("_designer")
                or low in (RUN_MAIN.lower(), DEBUG_MAIN.lower()) or _refs.is_proxy_text(text)):
            return []
        out, seen = [], set()
        in_class = in_block = False
        comments: list[str] = []
        lines = text.splitlines()
        for i, raw in enumerate(lines):
            line = raw.strip()
            if in_block:
                if "*/" in line:
                    in_block = False
                continue
            if line.startswith("/*"):
                in_block = "*/" not in line[2:]
                continue
            if line.startswith(("#", "//")):
                comments.append(line.lstrip("#/ ").strip())
                continue
            word = line.split(None, 1)[0].lower() if line else ""
            if word in ("class", "package"):
                in_class = in_class or word == "class"
            elif word in ("endclass", "endpackage"):
                in_class = False
            m = self._FUNC_RX.match(raw)
            if m and not in_class:
                name = m.group(1)
                params = [p.strip() for p in m.group(2).split(",") if p.strip()]
                ok = (not name.startswith("_") and name.lower() != "main" and name.lower() not in seen
                      and not _refs.is_event_handler(name) and all(re.fullmatch(r"\w+", p) for p in params))
                if ok:
                    seen.add(name.lower())
                    doc = next((c for c in comments if c), "")
                    if not doc:                       # first comment line of the body
                        for nxt in lines[i + 1:i + 4]:
                            s = nxt.strip()
                            if s.startswith(("#", "//")):
                                doc = s.lstrip("#/ ").strip()
                                break
                            if s:
                                break
                    body = []
                    for nxt in lines[i + 1:]:
                        if self._FUNC_RX.match(nxt) or re.match(r"^\s*class\b", nxt, re.I):
                            break
                        body.append(nxt)
                    returns = any(re.match(r"^\s*return\s+\S", b, re.I) for b in body)
                    out.append(_refs.make_function(name, params, path.stem, doc,
                                                   "function" if returns else "sub"))
            if line:
                comments = []
        return out

    def _ring_ident(self, name: str) -> str:
        s = re.sub(r"\W", "_", str(name)) or "p"
        if s[0].isdigit():
            s = "p" + s
        return s + "_" if s.lower() in {k.lower() for k in self.keywords} else s

    def reference_proxy(self, lib: str, functions: list) -> dict[str, str]:
        """``<Lib>.ref.ring`` in the consumer project (loaded automatically when it runs):
        ``x = <Lib>_Add(2, 3)`` forwards to ``radcall("<module>.Add", [2, 3])``."""
        L = [self.proxy_header(lib).rstrip("\n"),
             f"# {lib} - reference to the {lib} project of the solution.",
             f"# Call its functions as   x = {lib}_<function>(args)",
             "# (the IDE loads this file and radcall.ring when the program runs; calls go through RAD Hub)",
             ""]
        prefix = self._ring_ident(lib).rstrip("_")
        seen = set()
        for f in functions:
            fn = f"{prefix}_{re.sub(r'\W', '_', f.name)}"
            if fn.lower() in seen:
                continue
            seen.add(fn.lower())
            params, used = [], set()
            for p in f.params:
                q = self._ring_ident(p)
                while q.lower() in used:
                    q += "_"
                used.add(q.lower())
                params.append(q)
            target = f"{f.module}.{f.name}".replace('"', "")
            call = f'radcall("{target}", [{", ".join(params)}])'
            doc = (f.doc or "").replace("\n", " ")
            L += [f"# {doc}" if doc else f"# {lib}: {target}({', '.join(f.params)})",
                  f"func {fn}" + (f" {', '.join(params)}" if params else ""),
                  f"\treturn {call}" if f.kind != "sub" else f"\t{call}",
                  ""]
        return {f"{lib}.ref.ring": "\n".join(L)}

