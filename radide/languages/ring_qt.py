    def _main_file(self, folder: Path, startup_form: str, debug: bool) -> str:
        if any("radcall" in f.read_text(encoding="utf-8", errors="replace") for f in folder.glob("*.ring")
               if not f.name.startswith("_") and f.name != "radcall.ring"):
            copy_ring_client(folder)          # RAD Hub client for cross-language calls
        files = sorted(f.name for f in folder.glob("*.ring")
                       if not f.name.startswith("_") and not f.stem.endswith("_designer"))
        legacy_main = any(self.find_handler(
            (folder / f).read_text(encoding="utf-8", errors="replace"), "main") >= 0 for f in files)
        start = self.code_file(startup_form)
        files.sort(key=lambda f: f != start)            # startup file first
        L = ["# generated by RAD IDE - safe to delete"]
        if debug:
            L.append(f"load \"{str(AGENT).replace(chr(92), '/')}\"")
        L += [f"load \"{f}\"" for f in files]
        if not legacy_main:
            L += ["", "func main", "    oApp = new qApp", f"    {startup_form}_Show()", "    oApp.exec()"]
        name = DEBUG_MAIN if debug else RUN_MAIN
        (folder / name).write_text("\n".join(L) + "\n", encoding="utf-8")
        write_runtime(folder)
        return name

