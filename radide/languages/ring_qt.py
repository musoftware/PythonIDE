    # ------------------------------------------------------------ IntelliSense
    CONTROL_CLASS = {**QT_CLASS, "Form": "qWidget", "Timer": "qTimer", "MenuStrip": "qMenuBar"}

    def _class_of(self, obj: str, code: str, names: dict[str, str], line: int) -> str | None:
        low = obj.lower()
        for n, t in (names or {}).items():
            if n.lower() == low:
                return self.CONTROL_CLASS.get(t)
            if f"{n}_events".lower() == low:
                return "qAllEvents"
        m = re.search(rf"\b{re.escape(obj)}\s*=\s*new\s+(\w+)", code, re.I)
        if m:
            return m.group(1)
        if low == "e":       # handler parameter of mouse/key events
            for ln in reversed(code.splitlines()[:line + 1]):
                if re.match(r"^\s*func\s+\w+\s+e\b", ln, re.I):
                    return "qAllEvents"
                if re.match(r"^\s*func\b", ln, re.I):
                    break
        return None

    def _user_funcs(self, code: str) -> dict[str, str]:
        out = {}
        for m in re.finditer(r"^\s*func\s+(\w+)[ \t]*([^\n]*)", code, re.I | re.M):
            out[m.group(1)] = f"{m.group(1)}({m.group(2).strip()})"
        return out

    def completions(self, code, line, col, path, names=None):
        from .. import ringqt_index as rq
        from .base import Completion
        lines = code.splitlines()
        before = lines[line][:col] if line < len(lines) else ""
        m = re.search(r"(\w+)\s*\.\s*(\w*)$", before)
        if m:                                   # member list after "obj."
            cls = self._class_of(m.group(1), code, names or {}, line)
            if not cls:
                return []
            return [Completion(n, "method", sig) for n, sig in sorted(rq.class_methods(cls).items(),
                                                                       key=lambda kv: kv[0].lower())]
        if re.search(r"\bnew\s+\w*$", before, re.I):
            return [Completion(c, "class") for c in sorted(rq.class_names(), key=str.lower)]
        out = [Completion(k, "keyword") for k in self.keywords]
        out += [Completion(n, "function", sig) for n, sig in {**self._proxy_funcs(path), **self._user_funcs(code)}.items()]
        out += [Completion(n, "control", f"{t} ({self.CONTROL_CLASS.get(t, '')})") for n, t in (names or {}).items()]
        out += [Completion(f, "function", RING_SIGS.get(f, "")) for f in rq.load_index()["functions"]]
        out += [Completion(f, "function", s) for f, s in RING_SIGS.items()]
        seen, uniq = set(), []
        for c in out:
            if c.name.lower() not in seen:
                seen.add(c.name.lower())
                uniq.append(c)
        current = (re.search(r"\w*$", before).group() or "").lower()
        for w in re.findall(r"\b[A-Za-z_]\w{2,}\b", code):
            if w.lower() not in seen and w.lower() != current:
                seen.add(w.lower())
                uniq.append(Completion(w, "variable"))
        return uniq

    def calltip(self, code, line, col, path, names=None):
        from .. import ringqt_index as rq
        lines = code.splitlines()
        before = lines[line][:col] if line < len(lines) else ""
        depth = 0
        for i in range(len(before) - 1, -1, -1):        # find the unmatched "("
            ch = before[i]
            if ch == ")":
                depth += 1
            elif ch == "(":
                if depth == 0:
                    head = before[:i]
                    m = re.search(r"(?:(\w+)\s*\.\s*)?(\w+)\s*$", head)
                    if not m:
                        return ""
                    obj, fn = m.group(1), m.group(2)
                    if obj:
                        cls = self._class_of(obj, code, names or {}, line)
                        meths = rq.class_methods(cls) if cls else {}
                        for k, v in meths.items():
                            if k.lower() == fn.lower():
                                return v
                        return ""
                    funcs = {**self._proxy_funcs(path), **self._user_funcs(code)}
                    for k, v in {**RING_SIGS, **funcs}.items():
                        if k.lower() == fn.lower():
                            return v
                    if fn.lower().startswith("q"):
                        ctor = rq.load_index()["classes"].get(fn.lower())
                        if ctor:
                            return f"new {fn}(...)  - {ctor.get('parent') or ''}"
                    return ""
                depth -= 1
        return ""

