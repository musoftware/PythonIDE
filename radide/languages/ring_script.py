"""Ring script projects - a plain Ring program (console, RingQt code, RayLib, LibSDL, WebLib ...) whose
startup is a .ring FILE that runs as it is, like ``ring.exe main.ring``.

Used by the Ring Samples gallery ("Open as Project", radide/features/ring_samples.py): a sample folder of
the installed Ring often holds several independent programs, so unlike ring-qt (which loads every .ring
file of the folder and starts a form) only the startup file runs. The startup may sit in a sub folder
("core/ex1_basicwindow") - it runs in its own folder so relative paths to images/fonts keep working.
F5 debugs with the same Ring agent as ring-qt (radide/debug/raddbg.ring): breakpoints, stepping, locals.
IntelliSense, highlighting and RingPM come from RingQtPlugin.
"""
from __future__ import annotations

import os
from pathlib import Path

from ..model import Project
from .base import RunSpec
from .ring_qt import AGENT, DEBUG_MAIN, RingQtPlugin


class RingScriptPlugin(RingQtPlugin):
    id = "ring-script"
    display_name = "Ring (script)"
    code_ext = ".ring"
    supports_debug = True
    foreign_only = True            # made by the Ring Samples gallery, not offered in New Project
    project_name_base = "RingScript"

    def project_templates(self) -> list[tuple[str, str, str, str]]:
        return []

    def create_new_project(self, folder: Path, name: str, template: str = "") -> Project:
        folder = Path(folder)
        folder.mkdir(parents=True, exist_ok=True)
        main = folder / "main.ring"
        if not main.exists():
            main.write_text(f'# {name}\n\nsee "Hello from Ring!" + nl\n', encoding="utf-8")
        project = Project(folder, name, self.id, [], "main", ["main.ring"])
        project.save()
        return project

    # ------------------------------------------------------------------ run
    def _startup_file(self, folder: Path, startup: str) -> Path:
        folder = Path(folder)
        s = (startup or "main").replace("\\", "/")
        f = folder / (s if s.lower().endswith(".ring") else s + ".ring")
        if not f.exists():                       # fall back to main.ring / the first .ring file
            cands = [folder / "main.ring"] + sorted(folder.glob("*.ring"))
            f = next((c for c in cands if c.exists() and not c.name.startswith("_rad")), f)
        return f

    def run_spec(self, folder: Path, startup_form: str, interpreter: str) -> RunSpec:
        f = self._startup_file(folder, startup_form)
        return RunSpec(interpreter, [f.name], f.parent)

    def debug_spec(self, folder, startup_form, interpreter, breakpoints) -> RunSpec:
        f = self._startup_file(folder, startup_form)
        agent = str(AGENT).replace("\\", "/")
        (f.parent / DEBUG_MAIN).write_text(f"# generated by RAD IDE - safe to delete\nload \"{agent}\"\n"
                                           f"load \"{f.name}\"\n", encoding="utf-8")
        env = dict(os.environ, RADDBG_BP=self.breakpoints_env(breakpoints))
        return RunSpec(interpreter, [DEBUG_MAIN], f.parent, env)


PLUGIN = RingScriptPlugin()
