"""Add Reference support for C#, Java and PowerShell (docs/CONTRACTS.md section 7.2).

Library side: ``*_exports(path, text)`` list the public functions of a code file.
Consumer side: ``*_proxy(lib, functions)`` write a proxy class/functions so that code calls
``MathLib.Add(2, 3)`` natively; every proxy forwards to the language's radcall client.

Exports found in typed languages (C#, Java) carry two extra attributes used by typed proxies:
``ret_type`` and ``param_types`` - JSON kinds "double", "int", "long", "string", "bool", "void", "any".
Untyped libraries (Python, Ring, ...) give "any": C# proxies then return ``dynamic``, Java ``Object``.
(This module's name starts with "_" so the plugin registry does not load it as a plugin.)
"""
from __future__ import annotations

import importlib
import re
from dataclasses import dataclass, field
from pathlib import Path

HEADER = "AUTO-GENERATED by RAD IDE (reference to {lib})"


# ====================================================================== ExportedFunction
@dataclass
class _LocalExportedFunction:            # same fields as the solution-core dataclass (fallback)
    name: str
    params: list[str] = field(default_factory=list)
    module: str = ""
    doc: str = ""
    kind: str = "function"


def _ef_class():
    for modname in ("radide.references", "radide.solution", "radide.languages.base"):
        try:
            cls = getattr(importlib.import_module(modname), "ExportedFunction", None)
        except Exception:  # noqa: BLE001 - module missing / being written by another agent
            cls = None
        if cls is not None:
            return cls
    return _LocalExportedFunction


def make_export(name: str, params: list[str], module: str, doc: str = "", kind: str = "function",
                ret_type: str = "any", param_types: list[str] | None = None):
    cls = _ef_class()
    try:
        fn = cls(name=name, params=list(params), module=module, doc=doc, kind=kind)
    except TypeError:
        fn = _LocalExportedFunction(name, list(params), module, doc, kind)
    try:
        fn.ret_type = ret_type
        fn.param_types = list(param_types) if param_types is not None else ["any"] * len(params)
    except AttributeError:      # slots dataclass: typed info is optional
        pass
    return fn


def _known_events() -> set[str]:
    try:
        from ..controls import CONTROL_TYPES, FORM_EVENTS
        ev = {e.lower() for e in FORM_EVENTS}
        for ct in CONTROL_TYPES.values():
            ev |= {e.lower() for e in ct.all_events()}
        return ev
    except Exception:  # noqa: BLE001
        return {"click", "load", "change", "textchanged", "dblclick", "doubleclick", "timer", "tick"}


_EVENTS: set[str] | None = None


def is_handler(name: str) -> bool:
    """X_Event names are GUI event handlers, not library functions."""
    global _EVENTS
    if _EVENTS is None:
        _EVENTS = _known_events()
    owner, sep, ev = name.rpartition("_")
    return bool(sep and owner and ev.lower() in _EVENTS)


def is_proxy_file(path: Path | str, text: str = "") -> bool:
    return ".ref." in Path(path).name.lower() or "AUTO-GENERATED by RAD IDE (reference to" in text[:400]


# ====================================================================== C-like source scanning
def blank_code(text: str, verbatim_at: bool = False) -> str:
    """Replace comments and string/char literal contents by spaces (positions and newlines kept)."""
    out = list(text)
    i, n = 0, len(text)

    def blank(a: int, b: int) -> None:
        for k in range(a, min(b, n)):
            if out[k] not in "\r\n":
                out[k] = " "

    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            blank(i, j)
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            blank(i, j)
            i = j
        elif text.startswith('"""', i):
            j = text.find('"""', i + 3)
            j = n if j < 0 else j + 3
            blank(i + 1, j - 1)
            i = j
        elif c == '"' and verbatim_at and i > 0 and text[i - 1] == "@" or \
                c == '"' and verbatim_at and i > 1 and text[i - 2:i] in ("$@", "@$"):
            j = i + 1
            while j < n:
                if text[j] == '"':
                    if j + 1 < n and text[j + 1] == '"':
                        j += 2
                        continue
                    break
                j += 1
            blank(i + 1, j)
            i = j + 1
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            blank(i + 1, j)
            i = j + 1
        else:
            i += 1
    return "".join(out)


def _match_brace(code: str, start: int) -> int:
    depth = 0
    for k in range(start, len(code)):
        if code[k] == "{":
            depth += 1
        elif code[k] == "}":
            depth -= 1
            if depth == 0:
                return k
    return len(code)


def _top_level(body: str) -> str:
    """Keep only depth-0 text of a class body (method bodies and nested types blanked)."""
    out, depth = [], 0
    for ch in body:
        if ch == "{":
            depth += 1
            out.append(" ")
        elif ch == "}":
            depth -= 1
            out.append(";" if depth == 0 else " ")
        else:
            out.append(ch if depth == 0 or ch == "\n" else " ")
    return "".join(out)


def split_params(s: str) -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out if p.strip()]


_INT = {"int", "short", "byte", "sbyte", "uint", "ushort", "integer", "int32", "int16"}
_LONG = {"long", "ulong", "int64"}
_DOUBLE = {"double", "float", "decimal", "single", "bigdecimal", "number"}
_STRING = {"string", "char", "character", "charsequence"}
_BOOL = {"bool", "boolean"}


def type_kind(t: str) -> str:
    t = re.sub(r"\s+", "", t or "")
    m = re.fullmatch(r"(?:System\.Threading\.Tasks\.)?(?:Task|ValueTask)<(.+)>", t)
    if m:
        return type_kind(m.group(1))
    if t in ("void", "Task", "ValueTask"):
        return "void"
    base = t.rstrip("?").split(".")[-1].lower()
    if base in _INT:
        return "int"
    if base in _LONG:
        return "long"
    if base in _DOUBLE:
        return "double"
    if base in _STRING:
        return "string"
    if base in _BOOL:
        return "bool"
    return "any"


def _doc_above(text: str, pos: int, java: bool) -> str:
    """First line of the doc comment (///, /** */ or //) right above position *pos*."""
    lines = text[:pos].splitlines()
    if lines and lines[-1].strip() and not re.fullmatch(r"\s*(?:\[.*\]|@\w+.*)?\s*", lines[-1]):
        lines = lines[:-1]      # the declaration line itself
    block: list[str] = []
    while lines:
        s = lines[-1].strip()
        if s.startswith("[") and s.endswith("]") or (java and s.startswith("@")):
            lines.pop()
            continue
        if s.startswith("//") or s.startswith("*") or s.startswith("/**") or s.startswith("/*"):
            block.insert(0, s)
            lines.pop()
            if s.startswith("/*"):
                break
            continue
        break
    text = " ".join(re.sub(r"^(/\*\*|/\*|\*/|\*|///|//)\s?", "", b).replace("*/", "") for b in block)
    text = re.sub(r"</?\w+[^>]*>", "", text)          # <summary> ...
    text = re.sub(r"\s+", " ", text).strip()
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    return (m.group(1) if m else text)[:200]


def _parse_param(p: str, java: bool) -> tuple[str, str, bool, str | None]:
    """'double a = 1' -> (name, type, is_variadic, default literal or None)."""
    p = re.sub(r"^\s*(?:\[[^\]]*\]\s*)+", "", p) if not java else re.sub(r"@\w+(\([^)]*\))?\s*", "", p)
    p, eq, default = p.partition("=")
    p, default = p.strip(), (default.strip() if eq else None)
    variadic = False
    if java:
        p = re.sub(r"\bfinal\s+", "", p)
        if "..." in p:
            variadic = True
            p = p.replace("...", "[] ")
    else:
        p = re.sub(r"^(this|ref|out|in|scoped)\s+", "", p)
        if p.startswith("params "):
            variadic, p = True, p[7:]
    m = re.match(r"^(.*?)[\s]*\b@?(\w+)\s*$", p, re.S)
    if not m:
        return p, "", variadic, default
    return m.group(2), m.group(1).strip(), variadic, default


def _class_exports(path: Path, text: str, java: bool) -> list:
    stem = Path(path).stem
    if is_proxy_file(path, text) or stem.endswith("_designer"):
        return []
    code = blank_code(text, verbatim_at=not java)
    out, seen = [], set()
    for cm in re.finditer(r"\b((?:(?:public|internal|static|partial|sealed|abstract|final|unsafe)\s+)*)"
                          r"(?:class|record)\s+(\w+)", code):
        mods, cname = cm.group(1).split(), cm.group(2)
        if cname.lower() != stem.lower():
            continue
        if java and "public" not in mods or not java and "internal" in mods and "public" not in mods:
            continue
        brace = code.find("{", cm.end())
        if brace < 0:
            continue
        end = _match_brace(code, brace)
        body = _top_level(code[brace + 1:end])
        base = brace + 1
        rx = (r"(?:^|[;}\n])\s*((?:(?:public|private|protected|static|final|synchronized|native|strictfp)\s+)+)"
              r"(?:<[^>]*>\s*)?([\w.<>\[\],?\s]+?)\s+(\w+)\s*\(([^)]*)\)") if java else \
             (r"(?:^|[;}\n\]])\s*((?:(?:public|private|protected|internal|static|async|unsafe|extern|new|override)\s+)+)"
              r"([\w.<>\[\],?\s()]+?)\s+@?(\w+)\s*(?:<[^>]*>)?\s*\(([^)]*)\)")
        for mm in re.finditer(rx, body):
            mods = mm.group(1).split()
            rtype, name = mm.group(2).strip(), mm.group(3)
            params = text[base + mm.start(4):base + mm.end(4)]     # original text: default values kept
            if "public" not in mods or "static" not in mods:
                continue
            if name in ("main", "Main") or name.startswith("_") or is_handler(name) or name == cname:
                continue
            plist = [_parse_param(p, java) for p in split_params(params)]
            key = (name.lower(), len(plist))
            if key in seen:
                continue
            seen.add(key)
            names = [p[0] for p in plist]
            if plist and plist[-1][2]:
                names[-1] = "*" + names[-1]
            ptypes = [("any" if v else type_kind(t)) for _n, t, v, _d in plist]
            rk = type_kind(rtype)
            doc = _doc_above(text, base + mm.start(3), java)
            fn = make_export(name, names, stem, doc, "sub" if rk == "void" else "function", rk, ptypes)
            try:
                fn.param_defaults = [d for _n, _t, _v, d in plist]
            except AttributeError:
                pass
            out.append(fn)
    return out


def cs_exports(path: Path, text: str) -> list:
    """Public static methods of the class named like the file (the RAD Hub module = file stem)."""
    return _class_exports(Path(path), text, java=False)


def java_exports(path: Path, text: str) -> list:
    return _class_exports(Path(path), text, java=True)


def ps_exports(path: Path, text: str) -> list:
    """Top-level PowerShell functions (not _private, not X_Event handlers, not proxies)."""
    path = Path(path)
    if is_proxy_file(path, text) or path.stem.endswith("_designer"):
        return []
    out, seen = [], set()
    lines = text.splitlines()
    depth = 0
    in_block_comment = False
    for i, line in enumerate(lines):
        s = line.strip()
        if in_block_comment:
            if "#>" in s:
                in_block_comment = False
            continue
        if s.startswith("<#") and "#>" not in s[2:]:
            in_block_comment = True
            continue
        m = re.match(r"^\s*function\s+(?:global:|script:)?([\w-]+)\s*(\(([^)]*)\))?", line, re.I)
        if m and depth == 0:
            name = m.group(1)
            if not name.startswith("_") and not is_handler(name) and name.lower() not in seen:
                if m.group(2) is not None:
                    raw = m.group(3)
                else:       # function X { param($a, $b) ... }
                    tail = "\n".join(lines[i:i + 30])
                    pm = re.search(r"\bparam\s*\(((?:[^()]|\([^()]*\))*)\)", tail, re.I)
                    raw = pm.group(1) if pm else ""
                params = re.findall(r"\$(\w+)", re.sub(r"\[[^\]]*\]", "", raw))
                doc = ""
                k = i - 1
                while k >= 0 and lines[k].strip().startswith("#"):
                    doc = lines[k].strip().lstrip("#").strip() or doc
                    k -= 1
                if not doc:     # comment-based help .SYNOPSIS
                    hm = re.search(r"\.SYNOPSIS\s*\n\s*(.+)", "\n".join(lines[i:i + 15]), re.I)
                    doc = hm.group(1).strip() if hm else ""
                seen.add(name.lower())
                out.append(make_export(name, params, path.stem, doc[:200]))
        code = re.sub(r"#.*$", "", re.sub(r"'[^']*'|\"[^\"]*\"", "", line))
        depth = max(0, depth + code.count("{") - code.count("}"))
    return out


# ====================================================================== consumer proxies
CS_KEYWORDS = set("""abstract as base bool break byte case catch char checked class const continue decimal default
    delegate do double else enum event explicit extern false finally fixed float for foreach goto if implicit
    in int interface internal is lock long namespace new null object operator out override params private
    protected public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this
    throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while""".split())
JAVA_KEYWORDS = set("""abstract assert boolean break byte case catch char class const continue default do double
    else enum extends final finally float for goto if implements import instanceof int interface long native new
    package private protected public return short static strictfp super switch synchronized this throw throws
    transient try void volatile while true false null var record yield""".split())


def ident(name: str, keywords: set[str], escape: str = "") -> str:
    s = re.sub(r"\W", "_", name.lstrip("*&"))
    if not s or s[0].isdigit():
        s = "_" + s
    if s in keywords:
        s = escape + s if escape else s + "_"
    return s


def _params_of(fn) -> list[tuple[str, str, bool]]:
    """[(raw name, kind, variadic)] - variadic = '*args' style."""
    kinds = list(getattr(fn, "param_types", None) or [])
    out = []
    for i, p in enumerate(fn.params or []):
        raw = str(p)
        variadic = raw.startswith("*") and not raw.startswith("**")
        if raw.startswith("**"):
            continue                    # keyword arguments cannot be passed through JSON lists
        name = re.split(r"[=:\s]", raw.lstrip("*&$@"), maxsplit=1)[0] or f"arg{i}"
        out.append((name, kinds[i] if i < len(kinds) else "any", variadic))
    return out


def _ret_of(fn) -> str:
    rt = getattr(fn, "ret_type", None) or "any"
    if getattr(fn, "kind", "function") == "sub":
        return "void"
    return rt


def _unique(functions) -> list:
    seen, out = set(), []
    for fn in functions:
        key = (fn.name.lower(), len(fn.params or []))
        if key not in seen:
            seen.add(key)
            out.append(fn)
    return out


def _xml(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


CS_TYPES = {"double": "double", "int": "int", "long": "long", "string": "string", "bool": "bool",
            "void": "void", "any": "dynamic"}


_CS_STR = r'@?"(?:[^"\\]|\\.)*"'


def _cs_literal_ok(d: str, t: str) -> bool:
    """A default value that can be copied into the proxy signature."""
    d = d.strip()
    if d == "null":
        return t in ("object", "string")
    if t == "bool":
        return d in ("true", "false")
    if t == "string":
        return bool(re.fullmatch(_CS_STR, d))
    if t in ("double", "int", "long"):
        return bool(re.fullmatch(r"-?\d+(\.\d+)?[dDfFmMlL]?", d)) and not (t != "double" and "." in d)
    if t == "object":
        return bool(re.fullmatch(r"-?\d+(\.\d+)?|true|false", d) or re.fullmatch(_CS_STR, d))
    return False


def cs_proxy(lib: str, functions) -> dict[str, str]:
    cls = ident(lib, CS_KEYWORDS, "@")
    L = [f"// {HEADER.format(lib=lib)} - do not edit: regenerated on Add Reference, Build and Run.",
         f"// Call the library like a normal C# class:  {cls}.Function(args)  (any language behind it;",
         "// the calls go through the RAD Hub, values are JSON: numbers, strings, bools, lists, dictionaries).",
         "#nullable disable",
         "",
         f"/// <summary>Reference to the library project {_xml(lib)}.</summary>",
         f"public static class {cls}",
         "{"]
    for fn in _unique(functions):
        ps = _params_of(fn)
        defaults = list(getattr(fn, "param_defaults", None) or [])
        decl, names, decl_defaults = [], [], []
        for k, (n, kind, variadic) in enumerate(ps):
            pn = ident(n, CS_KEYWORDS, "@")
            if variadic and k == len(ps) - 1:
                decl.append(f"params object[] {pn}")
            else:
                t = CS_TYPES.get(kind, "object")
                t = "object" if t in ("dynamic", "void") else t
                d = defaults[k] if k < len(defaults) else None
                if d is not None and not _cs_literal_ok(d, t):
                    d = None
                if d is None and any(x is not None for x in decl_defaults):
                    d = "null" if t in ("object", "string") else "default"   # after an optional one
                decl_defaults.append(d)
                decl.append(f"{t} {pn}" + (f" = {d}" if d is not None else ""))
            names.append((pn, variadic and k == len(ps) - 1))
        if names and names[-1][1]:
            fixed = ", ".join(n for n, _ in names[:-1])
            argexpr = (f"System.Linq.Enumerable.ToArray(System.Linq.Enumerable.Concat(new object[] {{ {fixed} }}, "
                       f"{names[-1][0]} ?? new object[0]))") if fixed else f"{names[-1][0]} ?? new object[0]"
        else:
            argexpr = "new object[] { " + ", ".join(n for n, _ in names) + " }" if names else "new object[0]"
        target = f'"{fn.module}.{fn.name}"'
        rt = _ret_of(fn)
        if rt == "void":
            body = f"Rad.radcall({target}, {argexpr});"
            ret = "void"
        elif rt == "any":
            body, ret = f"Rad.RefCall({target}, {argexpr});", "dynamic"
        else:
            ret = CS_TYPES[rt]
            body = f"Rad.radcall<{ret}>({target}, {argexpr});"
        if fn.doc:
            L.append(f"    /// <summary>{_xml(fn.doc)}</summary>")
        L.append(f"    public static {ret} {ident(fn.name, CS_KEYWORDS, '@')}({', '.join(decl)}) => {body}")
    L += ["}", ""]
    return {f"{lib}.ref.cs": "\n".join(L)}


JAVA_TYPES = {"double": "double", "int": "int", "long": "long", "string": "String", "bool": "boolean",
              "void": "void", "any": "Object"}
JAVA_CALL = {"double": "Rad.radcallDouble", "int": "Rad.radcallInt", "long": "Rad.radcallLong",
             "string": "Rad.radcallString", "bool": "Rad.radcallBool", "any": "Rad.radcall"}


def java_proxy(lib: str, functions) -> dict[str, str]:
    cls = ident(lib, JAVA_KEYWORDS)
    L = [f"// {HEADER.format(lib=lib)} - do not edit: regenerated on Add Reference, Build and Run.",
         f"// Call the library like a normal Java class:  {cls}.function(args)  (any language behind it;",
         "// the calls go through the RAD Hub; untyped results are Object: Long, Double, String, Boolean, List, Map).",
         "",
         f"/** Reference to the library project {lib}. */",
         f"final class {cls} {{",
         f"    private {cls}() {{ }}"]
    for fn in _unique(functions):
        ps = _params_of(fn)
        decl, names = [], []
        for k, (n, kind, variadic) in enumerate(ps):
            pn = ident(n, JAVA_KEYWORDS)
            if variadic and k == len(ps) - 1:
                decl.append(f"Object... {pn}")
            else:
                decl.append(f"{JAVA_TYPES.get(kind, 'Object') if kind != 'void' else 'Object'} {pn}")
            names.append((pn, variadic and k == len(ps) - 1))
        if names and names[-1][1]:
            fixed = ", ".join(n for n, _ in names[:-1])
            last = names[-1][0]
            argexpr = (f"Rad.refArgs(new Object[] {{ {fixed} }}, {last})" if fixed else
                       f"({last} == null ? new Object[0] : {last})")
        else:
            argexpr = "new Object[] { " + ", ".join(n for n, _ in names) + " }" if names else "new Object[0]"
        target = f'"{fn.module}.{fn.name}"'
        rt = _ret_of(fn)
        if fn.doc:
            L.append(f"    /** {fn.doc.replace('*/', '* /')} */")
        sig = f"public static {JAVA_TYPES.get(rt, 'Object')} {ident(fn.name, JAVA_KEYWORDS)}({', '.join(decl)})"
        if rt == "void":
            L.append(f"    {sig} {{ Rad.radcall({target}, {argexpr}); }}")
        else:
            L.append(f"    {sig} {{ return {JAVA_CALL.get(rt, 'Rad.radcall')}({target}, {argexpr}); }}")
    L += ["}", ""]
    return {f"{lib}.ref.java": "\n".join(L)}


def _ps_name(s: str) -> str:
    return re.sub(r"[^\w-]", "_", s)


def ps_proxy(lib: str, functions) -> dict[str, str]:
    lname = _ps_name(lib)
    L = [f"# {HEADER.format(lib=lib)} - do not edit: regenerated on Add Reference, Build and Run.",
         f"# Call the library:  {lname}.Function arg1 arg2   or   ${lname}.Function(arg1, arg2)",
         "# (any language behind it; the calls go through the RAD Hub, values are JSON).",
         ""]
    methods = []
    for fn in _unique(functions):
        ps = _params_of(fn)
        variadic = bool(ps) and ps[-1][2]
        pn = [_ps_name(n) for n, _k, _v in (ps[:-1] if variadic else ps)]
        fname = f"{lname}.{_ps_name(fn.name)}"
        target = "'" + f"{fn.module}.{fn.name}".replace("'", "''") + "'"
        call_args = " ".join(f"${p}" for p in pn) + (" @args" if variadic else "")
        params = ", ".join(f"${p}" for p in pn)
        if fn.doc:
            L.append(f"# {fn.doc}")
        L.append(f"function {fname}({params}) {{")      # extra arguments of a variadic function: $args
        L.append(f"    radcall {target} {call_args}".rstrip())
        L.append("}")
        methods.append((_ps_name(fn.name), params, f"{fname} {call_args}".rstrip()))
    L += ["", f"# ${lname}.Function(args) - the same functions as methods of one object",
          f"$script:{lname} = New-Object psobject"]
    for name, params, call in methods:
        L.append(f"$script:{lname} | Add-Member -MemberType ScriptMethod -Name '{name}' -Force "
                 f"-Value {{ param({params}) {call} }}")
    L.append("")
    return {f"{lib}.ref.ps1": "\n".join(L)}


# ====================================================================== IntelliSense on proxies
def proxy_members(folder: Path, obj: str, lang: str) -> list[tuple[str, str]]:
    """[(name, signature)] read from the generated <obj>.ref.<ext> in *folder* (empty if none)."""
    ext = {"cs": ".cs", "java": ".java", "ps": ".ps1"}[lang]
    p = None
    try:
        for f in Path(folder).glob(f"*.ref{ext}"):
            if f.name[:-len(ext) - 4].lower() == obj.lower():
                p = f
                break
    except OSError:
        return []
    if p is None:
        return []
    try:
        text = p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    out, doc = [], ""
    for line in text.splitlines():
        s = line.strip()
        dm = re.match(r"^(?:///\s*<summary>(.*)</summary>|/\*\*\s*(.*?)\s*\*/|#\s+(?!AUTO|Call|\(|\$)(.*))$", s)
        if dm:
            doc = next(g for g in dm.groups() if g is not None)
            continue
        if lang == "ps":
            m = re.match(r"^function\s+[\w-]+\.([\w-]+)\s*(\(([^)]*)\))?", s)
            if m:
                sig = f"{m.group(1)}({m.group(3) or ''})"
                out.append((m.group(1), sig + (f" - {doc}" if doc else "")))
            doc = ""
            continue
        m = re.match(r"^public static ([\w<>\[\]]+) @?(\w+)\(([^)]*)\)", s)
        if m:
            sig = f"{m.group(1)} {m.group(2)}({m.group(3)})"
            out.append((m.group(2), sig + (f" - {doc}" if doc else "")))
        doc = ""
    return out
