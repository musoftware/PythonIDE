def make_export(name: str, params: list[str], module: str, doc: str = "", kind: str = "function"):
    return ExportedFunction(name, list(params), module, doc, kind)


def is_private(name: str) -> bool:
    return name.startswith("_") or is_event_handler(name)


def ident(name: str, fallback: str = "Lib") -> str:
    """A valid identifier (JS/PHP/...) made from a project name."""
    s = re.sub(r"\W", "_", str(name))
    if not s:
        return fallback
    return "_" + s if s[0].isdigit() else s


def mask_code(text: str, hash_comments: bool = False, php: bool = False) -> str:
    """Same-length copy of *text* with comments and the contents of string literals
    (and JS regex literals) replaced by spaces, so brackets can be counted safely.
    php=True: only the code inside <?php ... ?> is kept, heredocs are blanked."""
    out = list(text)
    n = len(text)

    def blank(a, b):
        for k in range(max(a, 0), min(b, n)):
            if out[k] != "\n":
                out[k] = " "

    i = 0
    prev = ""            # last significant character (to tell a regex from a division)
    if php:
        j = text.find("<?php")
        if j < 0:
            j = text.find("<?")
        if j < 0:
            blank(0, n)
            return "".join(out)
        blank(0, j + (5 if text.startswith("<?php", j) else 2))
        i = j + (5 if text.startswith("<?php", j) else 2)
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if php and c == "?" and nxt == ">":
            j = text.find("<?php", i)
            if j < 0:
                blank(i, n)
                break
            blank(i, j + 5)
            i = j + 5
            continue
        if (c == "/" and nxt == "/") or (hash_comments and c == "#" and nxt != "["):
            j = text.find("\n", i)
            j = n if j < 0 else j
            if php:                                   # "?>" ends a PHP line comment
                k = text.find("?>", i, j)
                j = k if k >= 0 else j
            blank(i, j)
            i = j
            continue
        if c == "/" and nxt == "*":
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            blank(i, j)
            i = j
            continue
        if php and c == "<" and text.startswith("<<<", i):
            m = re.match(r"<<<[ \t]*([\"']?)(\w+)\1\r?\n", text[i:])
            if m:
                end = re.compile(rf"^[ \t]*{m.group(2)}\b", re.M).search(text, i + m.end())
                j = end.end() if end else n
                blank(i + 3, j)
                i, prev = j, "x"
                continue
        if c in "\"'" or (c == "`" and not php):
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == c:
                    break
                if c != "`" and text[j] == "\n" and not php:
                    break
                j += 1
            blank(i + 1, j)
            i, prev = j + 1, c
            continue
        if not php and c == "/":
            word = re.search(r"(\w+)\s*$", text[max(0, i - 12):i])
            if prev == "" or prev in "(,=:[!&|?{};+-*%<>~^" or (word and word.group(1) in (
                    "return", "typeof", "case", "in", "of", "void", "yield", "await")):
                j, cls = i + 1, False
                while j < n and text[j] != "\n":
                    if text[j] == "\\":
                        j += 2
                        continue
                    if text[j] == "[":
                        cls = True
                    elif text[j] == "]":
                        cls = False
                    elif text[j] == "/" and not cls:
                        break
                    j += 1
                blank(i + 1, j)
                i, prev = j + 1, "/"
                continue
        if not c.isspace():
            prev = c
        i += 1
    return "".join(out)


def depths(masked: str) -> list[int]:
    """Bracket depth ({ ( [) at each position of masked code."""
    d, out = 0, [0] * (len(masked) + 1)
    for i, c in enumerate(masked):
        out[i] = d
        if c in "{([":
            d += 1
        elif c in "})]":
            d = max(0, d - 1)
    out[len(masked)] = d
    return out


def balanced(masked: str, i: int, open_: str = "(", close: str = ")") -> int:
    """Index of the bracket that closes masked[i] (an *open_*), or -1."""
    d = 0
    for j in range(i, len(masked)):
        c = masked[j]
        if c == open_:
            d += 1
        elif c == close:
            d -= 1
            if d == 0:
                return j
    return -1


def split_top(s: str, sep: str = ",") -> list[str]:
    """Split at *sep* outside brackets (also <...> generics, ignoring "=>")."""
    out, d, cur = [], 0, []
    for k, c in enumerate(s):
        if c in "([{" or (c == "<" and not s.startswith("<=", k)):
            d += 1
        elif c in ")]}" or (c == ">" and (k == 0 or s[k - 1] != "=")):
            d = max(0, d - 1)
        if c == sep and d == 0:
            out.append("".join(cur))
            cur = []
        else:
            cur.append(c)
    out.append("".join(cur))
    return [p for p in (x.strip() for x in out) if p]


def js_param_names(params: str) -> list[str]:
    """Parameter names of a JS/TS parameter list (types, defaults, modifiers removed)."""
    names = []
    for i, p in enumerate(split_top(params)):
        p = re.sub(r"^(?:(?:public|private|protected|readonly|override)\s+)+", "", p)
        m = re.match(r"(?:\.\.\.)?\s*([A-Za-z_$][\w$]*)", p)
        if m and m.group(1) == "this" and re.match(r"this\s*:", p):
            continue                          # TS "this" parameter is not a real argument
        names.append(m.group(1) if m else f"arg{i + 1}")
    return names


def doc_before(text: str, pos: int, hash_comments: bool = False) -> str:
    """First line of the doc comment (/** */ block or // lines) right above *pos*."""
    lines = text[:pos].splitlines()
    if lines and not text[:pos].endswith("\n"):
        lines = lines[:-1]                     # text before the match on the same line
    k = len(lines) - 1
    while k >= 0 and re.match(r"^\s*(@|#\[)", lines[k]):    # decorators / attributes
        k -= 1
    if k < 0:
        return ""
    last = lines[k].strip()
    body: list[str] = []
    if last.endswith("*/"):
        j = k
        while j >= 0 and "/*" not in lines[j]:
            j -= 1
        if j < 0:
            return ""
        block = "\n".join(lines[j:k + 1])
        block = block[block.find("/*") + 2:block.rfind("*/")]
        body = [re.sub(r"^\s*\*+ ?", "", ln).strip() for ln in block.lstrip("*").splitlines()]
    else:
        prefixes = ("//", "#") if hash_comments else ("//",)
        j = k
        while j >= 0 and lines[j].strip().startswith(prefixes) and not lines[j].strip().startswith("#["):
            body.insert(0, lines[j].strip().lstrip("/#").strip())
            j -= 1
    for ln in body:
        if ln and not ln.startswith("@") and REF_MARK not in ln:
            return ln
    return ""


def _js_signature(masked: str, at: int):
    """At masked[at] (after a name): optional <generics>, then (params). Returns (params, close)."""
    i = at
    while i < len(masked) and masked[i] in " \t":
        i += 1
    if i < len(masked) and masked[i] == "<":
        i = balanced(masked, i, "<", ">") + 1
        if i <= 0:
            return None
        while i < len(masked) and masked[i] in " \t\r\n":
            i += 1
    if i >= len(masked) or masked[i] != "(":
        return None
    j = balanced(masked, i)
    if j < 0:
        return None
    return masked[i + 1:j], j


def _js_kind(masked: str, close: int) -> str:
    return "sub" if re.match(r"\s*:\s*void\b", masked[close + 1:close + 40]) else "function"


def _js_function_value(masked: str, at: int):
    """Value starting at *at*: function expression / arrow function -> (params, close), else None."""
    m = re.compile(r"\s*(?:async[ \t]+)?(?:function\b[ \t]*\*?[ \t]*[\w$]*)?").match(masked, at)
    k = m.end()
    is_fn = "function" in m.group(0)
    if k < len(masked) and re.match(r"[A-Za-z_$][\w$]*[ \t]*=>", masked[k:k + 80]) and not is_fn:
        name = re.match(r"[A-Za-z_$][\w$]*", masked[k:]).group(0)
        return name, k + len(name) - 1
    sig = _js_signature(masked, k)
    if sig is None:
        return None
    if not is_fn and not re.match(r"\s*(?::[^=;{]*?)?=>", masked[sig[1] + 1:sig[1] + 200]):
        return None
    return sig


def js_exports(path: Path, text: str) -> list:
    """Public functions of a JavaScript / TypeScript file.

    Files that use module.exports / exports.x / export only publish what they export;
    plain scripts (the IDE's default) publish every top-level function."""
    module = Path(path).stem
    if REF_MARK in text[:400] or module.lower() in RUNTIME_FILES or module.lower().endswith(".ref"):
        return []
    masked = mask_code(text)
    dep = depths(masked)
    funcs: dict[str, tuple] = {}           # name -> (params, doc, kind, pos)
    exported: dict[str, tuple] = {}        # exported name -> (params | alias, doc, kind, pos)
    explicit = False

    def add_fn(name, sig, pos, kind, target):
        first = target.get(name, (None, None, None, pos))[3]      # overloads: keep the first position
        target[name] = (js_param_names(sig[0]), doc_before(text, pos), kind, first)

    rx_fn = re.compile(r"^[ \t]*(export[ \t]+(?:default[ \t]+)?)?(?:async[ \t]+)?function\b[ \t]*\*?[ \t]*"
                       r"([A-Za-z_$][\w$]*)", re.M)
    for m in rx_fn.finditer(masked):
        if dep[m.start()] != 0:
            continue
        sig = _js_signature(masked, m.end())
        if sig is None:
            continue
        rest = masked[sig[1] + 1:sig[1] + 200]
        if not re.match(r"\s*(?::[^{;]*)?\{", rest):        # TS overload / declaration without a body
            if m.group(2) in funcs:
                continue
        add_fn(m.group(2), sig, m.start(), _js_kind(masked, sig[1]), funcs)
        if m.group(1):
            explicit = True
            exported[m.group(2)] = funcs[m.group(2)]

    rx_var = re.compile(r"^[ \t]*(export[ \t]+)?(?:const|let|var)[ \t]+([A-Za-z_$][\w$]*)[ \t]*"
                        r"(?::[^=\n;]*)?=", re.M)
    for m in rx_var.finditer(masked):
        if dep[m.start()] != 0:
            continue
        val = _js_function_value(masked, m.end())
        if val is None:
            continue
        add_fn(m.group(2), val, m.start(), _js_kind(masked, val[1]), funcs)
        if m.group(1):
            explicit = True
            exported[m.group(2)] = funcs[m.group(2)]

    # exports.name = ...   module.exports.name = ...
    for m in re.finditer(r"^[ \t]*(?:module[ \t]*\.[ \t]*)?exports[ \t]*\.[ \t]*([A-Za-z_$][\w$]*)[ \t]*=(?!=)",
                         masked, re.M):
        if dep[m.start()] != 0:
            continue
        explicit = True
        name = m.group(1)
        val = _js_function_value(masked, m.end())
        eol = masked.find("\n", m.end())
        alias = re.match(r"[ \t]*([A-Za-z_$][\w$]*)[ \t]*;?[ \t]*\r?$", masked[m.end():eol if eol >= 0 else None])
        if val is not None:
            exported[name] = (js_param_names(val[0]), doc_before(text, m.start()), _js_kind(masked, val[1]),
                              m.start())
        elif alias:
            exported[name] = (alias.group(1), doc_before(text, m.start()), "function", m.start())

    # module.exports = { a, b: c, d(x) {...}, e: function (y) {...}, f: (z) => ... }
    for m in re.finditer(r"^[ \t]*module[ \t]*\.[ \t]*exports[ \t]*=[ \t]*\{", masked, re.M):
        if dep[m.start()] != 0:
            continue
        explicit = True
        o = m.end() - 1
        c = balanced(masked, o, "{", "}")
        if c < 0:
            continue
        body = masked[o + 1:c]
        off = o + 1
        for part in split_top(body):
            pos = off + body.find(part)
            em = re.match(r"(?:async[ \t]+)?\*?[ \t]*([A-Za-z_$][\w$]*|[\"'][^\"']*[\"'])[ \t]*", part)
            if not em:
                continue
            key = em.group(1).strip("\"' ")
            rest = part[em.end():]
            if not rest:                                   # shorthand: { add }
                exported[key] = (key, doc_before(text, pos), "function", pos)
            elif rest.startswith("("):                     # method: add(a, b) { ... }
                j = balanced(rest, 0)
                exported[key] = (js_param_names(rest[1:j]), doc_before(text, pos), "function", pos)
            elif rest.startswith(":"):
                val = _js_function_value(part, em.end() + 1)
                alias = re.fullmatch(r":\s*([A-Za-z_$][\w$]*)\s*", rest)
                if alias and not re.search(r"=>", rest):
                    exported[key] = (alias.group(1), doc_before(text, pos), "function", pos)
                elif val is not None:
                    exported[key] = (js_param_names(val[0]), doc_before(text, pos), "function", pos)

    # export { a, b as c }
    for m in re.finditer(r"^[ \t]*export[ \t]*\{([^}]*)\}", masked, re.M):
        if dep[m.start()] != 0:
            continue
        explicit = True
        for item in m.group(1).split(","):
            parts = re.split(r"\s+as\s+", item.strip())
            if parts[0]:
                exported[parts[-1].strip()] = (parts[0].strip(), "", "function", m.start())

    if explicit:
        items = []
        for name, (params, doc, kind, pos) in exported.items():
            if isinstance(params, str):                    # alias of a top-level function
                target = funcs.get(params)
                if target is None:
                    continue
                params, doc, kind = target[0], doc or target[1], target[2]
            items.append((pos, name, params, doc, kind))
    else:
        items = [(pos, name, params, doc, kind) for name, (params, doc, kind, pos) in funcs.items()]
    out, seen = [], set()
    for _pos, name, params, doc, kind in sorted(items, key=lambda t: t[0]):
        if name in seen or is_private(name) or name == "default":
            continue
        seen.add(name)
        out.append(make_export(name, params, module, doc, kind))
    return out


def unique_functions(functions) -> list:
    """Drop duplicate names (first one wins) and names that are not identifiers."""
    out, seen = [], set()
    for f in functions:
        if not re.fullmatch(r"[A-Za-z_]\w*", f.name or "") or f.name.lower() in seen:
            continue
        seen.add(f.name.lower())
        out.append(f)
    return out


def safe_params(params, keywords=()) -> list[str]:
    out = []
    for i, p in enumerate(params):
        p = re.sub(r"^[.*&$]+", "", str(p)).strip()
        p = re.match(r"[A-Za-z_]\w*", p)
        p = p.group(0) if p else f"arg{i + 1}"
        if p in keywords or p in out:
            p = f"{p}_{i + 1}"
        out.append(p)
    return out


def ref_index_lines(lib: str, functions, sep: str = ".", prefix: str = "// ") -> list[str]:
    """Machine-readable list of the proxy's functions (also read by IntelliSense)."""
    out = []
    for f in functions:
        line = f"{prefix}@radref {lib}{sep}{f.name}({', '.join(safe_params(f.params))})"
        if f.doc:
            line += f" - {f.doc}"
        out.append(line.rstrip())
    return out


def read_ref_index(folder: Path, lib: str, exts: tuple[str, ...]) -> list[tuple[str, str, str]]:
    """(name, signature, doc) of the functions in folder/<lib>.ref.<ext> (from its @radref lines)."""
    for ext in exts:
        p = Path(folder) / f"{lib}.ref{ext}"
        if not p.is_file():
            continue
        try:
            text = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        out = []
        for m in re.finditer(r"@radref\s+\w+(?:\.|::|_)(\w+)(\([^)]*\))(?:\s+-\s+(.*))?", text):
            out.append((m.group(1), m.group(1) + m.group(2), (m.group(3) or "").strip()))
        return out
    return []


def ref_libs(folder: Path, exts: tuple[str, ...]) -> list[str]:
    try:
        return sorted({f.name[:-len(ext) - 4] for f in Path(folder).iterdir() for ext in exts
                       if f.name.lower().endswith(f".ref{ext}")})
    except OSError:
        return []


