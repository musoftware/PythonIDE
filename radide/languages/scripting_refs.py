"""Shared helpers for References (docs/CONTRACTS.md section 7) in the scripting languages
(Lua, Ruby, Perl, Dart): building ExportedFunction records, recognising event handlers,
reading doc comments and cleaning parameter names for the generated proxies.
"""
from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass
class _ExportedFunction:            # used only until radide.references / base provide the real one
    name: str
    params: list
    module: str
    doc: str = ""
    kind: str = "function"


def exported_function_class():
    """The ExportedFunction dataclass of the engine (falls back to a compatible local one)."""
    for modname in ("radide.languages.base", "radide.references", "radide.solution"):
        try:
            mod = __import__(modname, fromlist=["ExportedFunction"])
        except Exception:  # noqa: BLE001 - modules written by other agents may be missing or broken
            continue
        cls = getattr(mod, "ExportedFunction", None)
        if cls is not None:
            return cls
    return _ExportedFunction


def make_export(name: str, params: list[str], module: str, doc: str = "", kind: str = "function"):
    return exported_function_class()(name=name, params=list(params), module=module, doc=doc, kind=kind)


def _event_names() -> set[str]:
    names: set[str] = set()
    try:
        from .. import controls
        for attr in ("COMMON_EVENTS", "FORM_EVENTS", "MOUSE_EVENTS", "KEY_EVENTS", "FOCUS_EVENTS"):
            names |= {e.lower() for e in getattr(controls, attr, [])}
        for ct in getattr(controls, "CONTROL_TYPES", {}).values():
            names |= {e.lower() for e in (getattr(ct, "events", None) or [])}
    except Exception:  # noqa: BLE001 - catalogue edited by other agents
        pass
    names |= {"click", "load", "change", "textchanged", "tick", "timer", "dblclick", "doubleclick",
              "selectedindexchanged", "valuechanged", "checkedchanged", "unload", "resize"}
    return names


_EVENTS: set[str] | None = None


def is_handler(name: str) -> bool:
    """True for event handler names <Owner>_<Event> (cmdGo_Click, Form1_Load, mnuExit_Click)."""
    global _EVENTS
    if "_" not in name.strip("_"):
        return False
    if _EVENTS is None:
        _EVENTS = _event_names()
    return name.rsplit("_", 1)[1].lower() in _EVENTS


def is_public(name: str) -> bool:
    return bool(name) and not name.startswith("_") and not is_handler(name)


def doc_above(lines: list[str], index: int, prefixes: tuple[str, ...]) -> str:
    """First line of the comment block directly above line *index* (comment markers stripped)."""
    block: list[str] = []
    i = index - 1
    while i >= 0:
        s = lines[i].strip()
        p = next((p for p in prefixes if s.startswith(p)), None)
        if p is None:
            break
        block.insert(0, s[len(p):].strip())
        i -= 1
    for text in block:
        if text and not set(text) <= set("-=#*/"):
            return text
    return ""


def split_params(text: str) -> list[str]:
    """Split a parameter list on top-level commas."""
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([{<":
            depth += 1
        elif ch in ")]}>":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out if p.strip()]


def is_variadic(param: str) -> bool:
    p = param.strip()
    return p.startswith(("*", "...", "@")) or "..." in p or p.startswith("params ") or p in ("%", "@_")


def proxy_params(params: list[str], reserved: set[str]) -> tuple[list[str], bool]:
    """Identifiers usable in a generated proxy + whether the function takes any number of arguments."""
    names: list[str] = []
    variadic = False
    for i, raw in enumerate(params):
        if is_variadic(raw):
            variadic = True
            break
        base = re.split(r"[=:]", raw, 1)[0]
        ids = re.findall(r"[A-Za-z_]\w*", base)
        name = ids[-1] if ids else ""
        if not name or name in reserved or name in names or name.startswith("__"):
            name = f"arg{i + 1}"
        names.append(name)
    return names, variadic


def header(lib: str, comment: str) -> str:
    try:
        from ..references import proxy_header
        text = proxy_header(lib)
    except Exception:  # noqa: BLE001 - engine module written by another agent
        text = f"AUTO-GENERATED by RAD IDE (reference to {lib}) - do not edit, regenerated on build"
    return f"{comment} {text}\n"


def valid_ident(name: str) -> bool:
    return bool(re.fullmatch(r"[A-Za-z_]\w*", name or ""))
