def create_lines(plugin, form, user_code: str, client: str, parent_expr) -> list[str]:
    """Lines (without indent) appended to <Form>_Create; [] when the form has nothing for this runtime."""
    n = form.name
    plan = fx_plan(form, "ring")
    vplan = variant_plan(form)
    panes = two_panes(form)
    if not (plan or vplan or panes):
        return []
    has = lambda h: plugin.find_handler(user_code, h) >= 0      # noqa: E731
    L: list[str] = []
    widgets: dict[str, str] = {}

    def wid(name: str) -> str:
        if name not in widgets:
            var = f"nW{len(widgets) + 1}"
            c = form.find(name) if name else None
            L.append(f"{var} = {_widget_row(plugin, form, c, n, client)}")
            widgets[name] = var
        return widgets[name]

    respect = 1 if (plan or {}).get("reduced_motion", True) else 0
    L.append("# Animations / layout sizes (RAD IDE): runtime in _radfx.ring")
    L.append(f"RadFx_Init({n}, {respect})")
    sbvar: dict[str, str] = {}
    if plan:
        for i, sb in enumerate(plan["storyboards"], 1):
            w = wid(sb["target"])
            tracks = ", ".join(f"[{_q(prop)}, [{', '.join(_key(k) for k in keys)}]]" for _t, prop, keys in sb["tracks"])
            done = f"{sb['fx']}_Completed()" if has(f"{sb['fx']}_Completed") else ""
            var = f"nFx{i}"
            sbvar[sb["fx"]] = var
            L.append(f"{var} = RadFx_Add({_q(n + '.' + sb['fx'])}, {w}, [{tracks}], {int(sb['count'])}, "
                     f"{1 if sb['repeat'] else 0}, {1 if sb['autoreverse'] else 0}, {int(sb.get('delayMs', 0))}, "
                     f"{1 if sb.get('restore') else 0}, {int(sb['duration'])}, {_q(done)})")
        for sb in plan["storyboards"]:
            for nxt in sb["chain"]:
                L.append(f"RadFx_Chain({sbvar[sb['fx']]}, {sbvar[nxt]})")
        by_src: dict[tuple, list] = {}
        for t in plan["triggers"]:
            v = sbvar.get(t["fx"])
            if v is None:
                continue
            if t["on"] in ("click", "hover"):
                src = t["source"] or t["target"]
                by_src.setdefault((src, t["on"]), []).append((v, t))
            elif t["on"] == "timer":
                L += [f"oFxT = new qTimer({n})", f"oFxT.setInterval({max(1, int(t['intervalMs'] or 1000))})",
                      f"oFxT.setTimeoutEvent(\"RadFx_Begin(\" + {v} + \")\")", "oFxT.start()", "RadFx_Keep(oFxT)"]
        for (src, on), lst in by_src.items():
            obj = n if not src else src
            L += [f"oFxE = new qAllEvents({obj})", "nFxE = RadFx_Keep(oFxE)"]
            code = " + \" \" + ".join(f"\"RadFx_Begin(\" + {v} + \")\"" for v, _t in lst)
            code += " + \" RadFx_Pass(\" + nFxE + \")\""
            if on == "click":
                L.append(f"oFxE.setMouseButtonReleaseEvent({code})")
            else:
                L.append(f"oFxE.setEnterEvent({code})")
                leave = " + \" \" + ".join(f"\"RadFx_Leave(\" + {v} + \", '{t['leave']}')\"" for v, t in lst)
                leave += " + \" RadFx_Pass(\" + nFxE + \")\""
                L.append(f"oFxE.setLeaveEvent({leave})")
                L.append(f"{obj}.setMouseTracking(true)")
            L.append(f"{obj}.installEventFilter(oFxE)")
    # layout sizes: rows for RadVar_Apply
    if vplan:
        rows = []
        for s in vplan["sizes"]:
            mw, xw, mh, xh, orient, posture, span, fold = when_tuple(s.get("when") or {})
            nums = ", ".join(_n(v) if v is not None else '""' for v in (mw, xw, mh, xh))
            rows.append(f"[{_q(s['id'])}, {nums}, {_q(orient or '')}, {_q(posture or '')}, {_q(span or '')}, "
                        f"{_q(fold or '')}]")
        L.append(f"{n}_VSizes = [{', '.join(rows)}]")
        from ..variants.model import FORM_RUNTIME_PROPS, RUNTIME_PROPS
        ctl_rows = []
        names = []
        for vid, ctl in (vplan.get("controls") or {}).items():
            for name in ctl:
                if name not in names:
                    names.append(name)
        form_ov = vplan.get("form") or {}
        if form_ov:
            base = {k: form.props.get(k, "") for ov in form_ov.values() for k in ov if k in FORM_RUNTIME_PROPS}
            ovs = ", ".join(f"[{_q(vid)}, [{', '.join(f'[{_q(k)}, {_ring_val(v)}]' for k, v in ov.items())}], []]"
                            for vid, ov in form_ov.items())
            ctl_rows.append(f"[{wid('')}, {n}.pObject, [], [{', '.join(f'[{_q(k)}, {_ring_val(v)}]' for k, v in base.items())}], "
                            f"[{ovs}]]")
        for name in names:
            c = form.find(name)
            if c is None:
                continue
            base_spec = (vplan.get("base") or {}).get(name)
            props_used = []
            ovs = []
            for vid, ctl in (vplan.get("controls") or {}).items():
                ov = ctl.get(name)
                if not ov:
                    continue
                pr = {k: v for k, v in (ov.get("props") or {}).items() if k in RUNTIME_PROPS}
                props_used += [k for k in pr if k not in props_used]
                place = ov.get("place")
                ovs.append(f"[{_q(vid)}, [{', '.join(f'[{_q(k)}, {_ring_val(v)}]' for k, v in pr.items())}], "
                           f"[{', '.join(_n(x) for x in place) if place else ''}]]")
            base = ", ".join(f"[{_q(k)}, {_ring_val(c.props.get(k, _DEFAULTS.get(k, '')))}]" for k in props_used)
            parent = parent_expr(form, c, client)
            spec = ", ".join(_n(x) for x in base_spec) if base_spec else ""
            ctl_rows.append(f"[{wid(name)}, {parent}.pObject, [{spec}], [{base}], [{', '.join(ovs)}]]")
        L.append(f"{n}_VCtl = [{', '.join(ctl_rows)}]")
    for i, tp in enumerate(panes, 1):
        start, end = tp["panes"]
        ps = f"{start}.pObject" if start else "NULL"
        pe = f"{end}.pObject" if end else "NULL"
        L.append(f"{n}_Pane{i} = [{tp['name']}.pObject, {ps}, {pe}, {_q(tp['mode'])}, {_n(tp['ratio'])}, "
                 f"{2 if tp['single'] == 'End' else 1}, {1 if tp['hinge_aware'] else 0}]")
    return L


def filter_lines(form, client: str) -> list[str]:
    """Resize filters of the layout sizes / TwoPanes, installed AFTER the Anchor / Dock filters: Qt calls the
    filter installed last first, so they run first, place the anchored controls themselves (the
    <Form>_ApplySizes function) and pass the event on."""
    n = form.name
    L: list[str] = []
    if variant_plan(form):
        L += ["", "# layout sizes: re-applied when the window is resized",
              f"oFxV = new qAllEvents({client})", "nFxV = RadFx_Keep(oFxV)",
              f"oFxV.setResizeEvent(\"{n}_ApplySizes() RadFx_Pass(\" + nFxV + \")\")",
              f"{client}.installEventFilter(oFxV)", f"{n}_ApplySizes()"]
    for i, tp in enumerate(two_panes(form), 1):
        var = f"{n}_Pane{i}"
        L += [f"oFxP = new qAllEvents({tp['name']})", "nFxP = RadFx_Keep(oFxP)",
              f"oFxP.setResizeEvent(\"RadPane_Place({var}) RadFx_Pass(\" + nFxP + \")\")",
              f"{tp['name']}.installEventFilter(oFxP)", f"RadPane_Place({var})"]
    return L


def load_lines(form) -> list[str]:
    """Statements run after <Form>_Load: the On load animations."""
    plan = fx_plan(form, "ring")
    if not plan:
        return []
    out = []
    for i, sb in enumerate(plan["storyboards"], 1):
        if trigger_of(plan, sb["fx"])["on"] == "load":
            out.append(f"RadFx_Begin(nFx{i})")
    return out


_DEFAULTS = {"Visible": True, "Text": "", "FontSize": 9, "FontBold": False, "BackColor": "", "ForeColor": ""}


def _ring_val(v) -> str:
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return _n(v)
    return _q(v)


def globals_(form) -> list[str]:
    out = []
    if variant_plan(form):
        out += [f"{form.name}_VSizes", f"{form.name}_VCtl"]
    out += [f"{form.name}_Pane{i}" for i in range(1, len(two_panes(form)) + 1)]
    return out


def api_lines(form, client_lay: str = "") -> list[str]:
    """Functions of the form for user code (after <Form>_Show)."""
    n = form.name
    plan = fx_plan(form, "ring")
    vplan = variant_plan(form)
    L: list[str] = []
    if plan:
        show: dict[str, list[str]] = {}
        hide: dict[str, list[str]] = {}
        for sb in plan["storyboards"]:
            on = trigger_of(plan, sb["fx"])["on"]
            if on in ("show", "hide") and sb["target"]:
                (show if on == "show" else hide).setdefault(sb["target"], []).append(sb["fx"])
        L += [f"func {n}_BeginAnimation cId", f"    RadFx_Begin(RadFx_ByName({_q(n + '.')} + cId))", "",
              f"func {n}_StopAnimation cId", f"    RadFx_Stop(RadFx_ByName({_q(n + '.')} + cId))", "",
              f"# Visible with the On show / On hide animations:  {n}_SetVisible(\"Label1\", false)",
              f"func {n}_SetVisible cName, lOn",
              "    nW = 0"]
        for name in sorted(set(show) | set(hide)):
            L.append(f"    if lower(cName) = {_q(name.lower())}")
            L.append(f"        RadFx_SetVisible(RadFx_WidgetOf({name}.pObject), lOn, "
                     f"[{', '.join(f'RadFx_ByName({_q(n + chr(46) + fx)})' for fx in show.get(name, []))}], "
                     f"[{', '.join(f'RadFx_ByName({_q(n + chr(46) + fx)})' for fx in hide.get(name, []))}])")
            L.append("        return")
            L.append("    ok")
        L += ["    eval(cName + \".setVisible(\" + lOn + \")\")", ""]
    if vplan:
        L += [f"func {n}_ApplySizes"]
        if client_lay:
            L.append(f"    RadQt_Place({client_lay})")
        L += [f"    return RadVar_Apply({n}_VSizes, {n}_VCtl, {_client_of(form)}.pObject)", "",
              f"func {n}_CurrentSizes",
              f"    return RadVar_Match({n}_VSizes, QWidget_width({_client_of(form)}.pObject), "
              f"QWidget_height({_client_of(form)}.pObject))", ""]
    return L


def _client_of(form) -> str:
    menu = form.menu()
    items = menu.props.get("Items", []) if menu else []
    strips = [c for c in form.nonvisual() if c.type == "ToolStrip" and c.props.get("Items")]
    return f"{form.name}_Client" if (items or strips) else form.name


