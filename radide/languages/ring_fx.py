TEXT_KIND = {"Label": 1, "LinkLabel": 1, "StatusBar": 1, "Button": 2, "CheckBox": 2, "RadioButton": 2,
             "TextBox": 3, "GroupBox": 4}


def _q(s) -> str:
    """Ring string literal (Ring has no escapes: pick a quote the text does not contain)."""
    s = str(s if s is not None else "")
    for qch in ('"', "'", "`"):
        if qch not in s:
            return f"{qch}{s}{qch}"
    return '"' + s.replace('"', "'") + '"'


def _n(v) -> str:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return "0"
    return str(int(f)) if f.is_integer() else repr(round(f, 4))


def _key(k) -> str:
    """A keyframe [ms, value, ease] as the Ring row [ms, kind, a, b, c, s, ease]."""
    ms, v = int(k[0]), k[1]
    ease = str(k[2]) if len(k) > 2 and k[2] else ""
    if isinstance(v, bool):
        row = (5, 1 if v else 0, 0, 0, "")
    elif isinstance(v, dict):
        if "reveal" in v:
            row = (4, v.get("reveal", 1), 0, 0, "")
        else:
            row = (1, v.get("m", 1), v.get("d", 0), v.get("f", 0), str(v.get("of") or ""))
        if not isinstance(v.get("d", 0), (int, float)):
            row = (6, 0, 0, 0, "")
    elif isinstance(v, str):
        row = (3, 0, 0, 0, "") if v == "$parent" else (2, 0, 0, 0, v)
    else:
        row = (0, v, 0, 0, "")
    kind, a, b, c, s = row
    return f"[{ms}, {kind}, {_n(a)}, {_n(b)}, {_n(c)}, {_q(s)}, {_q(ease)}]"


def _parent_color(form, c) -> str:
    """Background colour behind control *c* (its container's, or the form's)."""
    p = form.find(c.parent) if c is not None and c.parent else None
    while p is not None:
        if p.props.get("BackColor"):
            return str(p.props["BackColor"])
        p = form.find(p.parent) if p.parent else None
    return str(form.props.get("BackColor") or "#f0f0f0")


def _widget_row(plugin, form, c, var: str, client: str) -> str:
    """RadFx_Widget(...) registration of control *c* (None = the window)."""
    if c is None:
        fp = form.props
        return (f"RadFx_Widget({var}.pObject, 1, 5, {_q(fp.get('BackColor') or '')}, \"\", \"\", 9, 0, 0, \"\", \"\", "
                f"{_q(fp.get('Text') or '')}, 1, \"\")")
    p, t = c.props, c.type
    kind = TEXT_KIND.get(t, 0)
    if t == "TextBox" and p.get("Multiline"):
        kind = 6
    pre = "border-top:1px solid palette(mid);padding-left:4px;" if t == "StatusBar" else ""
    post = f"text-align:{str(p['TextAlign']).lower()};" if t == "Button" and p.get("TextAlign", "Center") != "Center" \
        else ""
    text = p.get("Text", "") if kind else ""
    obj = f"{c.name}.pObject"
    return (f"RadFx_Widget({obj}, 0, {kind}, {_q(p.get('BackColor') or '')}, {_q(p.get('ForeColor') or '')}, "
            f"{_q(p.get('FontName') or 'Segoe UI')}, {int(p.get('FontSize', 9) or 9)}, "
            f"{1 if p.get('FontBold') else 0}, {1 if p.get('FontItalic') else 0}, {_q(pre)}, {_q(post)}, "
            f"{_q(text)}, {1 if p.get('Visible', True) else 0}, {_q(_parent_color(form, c))})")


