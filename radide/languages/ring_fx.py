"""Animations (motion presets), layout sizes and TwoPane for RingQt forms (plan MOTION_VARIANTS_FOLDABLES,
slice D).

``RING_FX`` is the runtime written next to the project as ``_radfx.ring`` (with ``_radqt.ring``); the designer
file of a form ``load``s it only when the form has animations, layout sizes or a TwoPane, so other forms are
generated exactly as before.

Runtime (Ring):
    RadFx_Begin(n) / RadFx_Stop(n) / RadFx_Leave(n, cMode)      storyboard n (from RadFx_Add)
    <Form>_BeginAnimation("fx1") / <Form>_StopAnimation("fx1")  by animation id
    <Form>_SetVisible("lblInfo", false)                          plays the control's On show / On hide animation
    <Form>_CurrentSizes()                                        list of the layout sizes that apply now
A 15 ms qTimer moves every running storyboard (same easings / relative keyframes as the Python runtime:
start * m + d + f * start(of), colour blends, typewriter).  RingQt has no opacity effect: a child control
fades through rgba() colours of its style sheet (a window uses setWindowOpacity).  Reduced motion:
RADIDE_REDUCED_MOTION=1 shows the end at once.  Layout sizes match the client area of the window, the
posture / span / fold come from RADIDE_POSTURE, RADIDE_SPAN and RADIDE_HINGE.
"""
