"""Helpers shared by the Python, Ring and VB6 plugins for Solution References
(docs/CONTRACTS.md section 7.2): exported functions of a library and reference proxies."""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

PROXY_MARK = "AUTO-GENERATED by RAD IDE (reference to"


@dataclass
class _FallbackExportedFunction:
    name: str
    params: list[str] = field(default_factory=list)
    module: str = ""
    doc: str = ""
    kind: str = "function"


def exported_function_class():
    """The engine's ExportedFunction dataclass (base.py / references.py), or a compatible fallback."""
    try:
        from .base import ExportedFunction  # type: ignore[attr-defined]
        return ExportedFunction
    except ImportError:
        pass
    try:
        from ..references import ExportedFunction  # type: ignore[attr-defined]
        return ExportedFunction
    except ImportError:
        return _FallbackExportedFunction


def make_function(name: str, params: list[str], module: str, doc: str = "", kind: str = "function"):
    return exported_function_class()(name=name, params=list(params), module=module, doc=doc, kind=kind)


def is_proxy_text(text: str) -> bool:
    return PROXY_MARK in "\n".join(text.splitlines()[:3])


def is_proxy_file(path: Path) -> bool:
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            head = "".join(f.readline() for _ in range(3))
    except OSError:
        return False
    return PROXY_MARK in head


def proxy_files(folder: Path, pattern: str) -> list[Path]:
    """Reference proxies (generated files) of a project folder matching *pattern*."""
    try:
        return sorted(p for p in Path(folder).glob(pattern) if p.is_file() and is_proxy_file(p))
    except OSError:
        return []


_EVENTS: set[str] | None = None
_VB_EVENTS = {"click", "dblclick", "change", "gotfocus", "lostfocus", "timer", "load", "unload", "queryunload",
              "activate", "deactivate", "resize", "terminate", "initialize", "nodeclick", "itemclick",
              "selchange", "afteredit", "keydown", "keyup", "keypress", "mousedown", "mouseup", "mousemove",
              "mouseenter", "mouseleave", "mousewheel", "paint", "scroll", "show", "tick"}


def event_names() -> set[str]:
    """Lower-case event names; ``X_<event>`` functions are event handlers, never exported."""
    global _EVENTS
    if _EVENTS is None:
        names = set(_VB_EVENTS)
        try:
            from ..controls import CONTROL_TYPES, FORM_EVENTS
            names |= {e.lower() for e in FORM_EVENTS}
            for ct in CONTROL_TYPES.values():
                names |= {e.lower() for e in ct.all_events()}
        except Exception:  # noqa: BLE001 - the static list is enough
            pass
        _EVENTS = names
    return _EVENTS


def is_event_handler(name: str) -> bool:
    owner, sep, event = name.rpartition("_")
    return bool(sep and owner and event.lower() in event_names())


def first_line(text: str) -> str:
    for ln in (text or "").strip().splitlines():
        if ln.strip():
            return ln.strip()
    return ""
