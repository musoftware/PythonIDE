"""PHP language plugin (GUI Bridge + php CLI).

Form code files are ordinary PHP files: every ``function <Control>_<Event>($e)`` is an
event handler. The generated ``_radmain.php`` includes the project's modules and form
code (radgui.php) and calls the handlers by name; composer packages are autoloaded
when ``vendor/autoload.php`` exists.
"""
