"""PHP language plugin (GUI Bridge + php CLI).

Form code files are ordinary PHP files: every ``function <Control>_<Event>($e)`` is an
event handler. The generated ``_radmain.php`` includes the project's modules and form
code (radgui.php) and calls the handlers by name; composer packages are autoloaded
when ``vendor/autoload.php`` exists.
"""
from __future__ import annotations

import re
from pathlib import Path

from ..controls import CONTROL_TYPES
from ..model import Form, Project
from .base import Completion, PackageManager
from .bridgebase import CLIENTS, BridgeLanguagePlugin
from .javascript import EXTRA_PROPS, METHODS

PHP_CLIENT = CLIENTS / "php"

API = {
    "rad_set": "rad_set($obj, $prop, $value)  - set a property: rad_set('lblOut', 'Caption', 'Hi')",
    "rad_get": "rad_get($obj, $prop): string  - read a property: rad_get('txtA', 'Text')",
    "rad_num": "rad_num($obj, $prop): float  - read a property as a number",
    "rad_call": "rad_call($obj, $method, ...$args): string  - rad_call('lstLog', 'AddItem', 'text')",
    "rad_msgbox": "rad_msgbox($text)  - show a message box",
    "rad_input": "rad_input($prompt): string  - ask the user for text",
    "rad_show": "rad_show($form)", "rad_hide": "rad_hide($form)",
    "rad_end": "rad_end()  - quit the program",
    "radcall": "radcall('Module.func', ...$args)  - call a function of any project module (any language)",
}

PHP_KEYWORDS = """abstract and array as break callable case catch class clone const continue declare default do
    echo else elseif empty enddeclare endfor endforeach endif endswitch endwhile enum extends final finally fn for
    foreach function global goto if implements include include_once instanceof insteadof interface isset list
    match namespace new or print private protected public readonly require require_once return static switch
    throw trait try unset use var while xor yield true false null self parent""".split()
PHP_BUILTINS = list(API) + """strlen strtoupper strtolower trim explode implode str_replace substr strpos
    sprintf printf number_format round floor ceil abs intval floatval is_numeric count array_map array_filter
    array_keys array_values in_array json_encode json_decode date time file_get_contents file_put_contents
    var_dump print_r""".split()


class PhpBridgePlugin(BridgeLanguagePlugin):
    id = "php"
    display_name = "PHP (GUI Bridge)"
    code_ext = ".php"
    tool_names = ["php"]
    tool_hints = [r"C:\tools\php81\php.exe", r"C:\php\php.exe", r"C:\xampp\php\php.exe",
                  r"C:\laragon\bin\php\php.exe"]
    install_hint = "Install PHP 8 (https://windows.php.net/download or 'choco install php') and add it to PATH."
    case_sensitive = False          # PHP keywords and function names are case-insensitive
    line_comments = ["//", "#"]
    block_comment = ("/*", "*/")
    string_quotes = ['"', "'"]
    keywords = PHP_KEYWORDS
    builtins = PHP_BUILTINS
    handler_regex = r"^[ \t]*function[ \t]+&?[ \t]*(\w+_\w+)[ \t]*\("
    main_file = "_radmain.php"
    package_manager = PackageManager(
        name="Composer", tool="composer",
        list_cmd=["composer", "show", "--direct", "--no-interaction"],
        search_cmd=["composer", "search", "{query}", "--no-interaction"],
        install_cmd=["composer", "require", "{name}", "--no-interaction"],
        uninstall_cmd=["composer", "remove", "{name}", "--no-interaction"],
        init_cmd=["composer", "init", "--no-interaction", "--name=radide/app", "--type=project"],
        manifest="composer.json",
        search_url="https://packagist.org/?query={query}",
    )

    # ------------------------------------------------------------ templates
    def generate_designer(self, form: Form, user_code: str) -> str:
        lines = ["<?php", f"// AUTO-GENERATED by RAD IDE - form {form.name} is drawn by the IDE (GUI Bridge). "
                          "Controls:"]
        lines += [f"//   {c.name}: {c.type}" for c in form.controls]
        return "\n".join(lines) + "\n"

    def new_code(self, form: Form, is_startup: bool) -> str:
        n = form.name
        return ("<?php\n"
                f"// Event handlers for {n}. A handler is a function named <Control>_<Event>($e).\n"
                "// Controls: rad_get('txtA', 'Text'), rad_set('lblOut', 'Caption', $x),\n"
                "//           rad_call('lstLog', 'AddItem', $x). Also rad_msgbox, rad_input, rad_end.\n"
                "// Other modules: radcall('Module.func', ...$args). Composer packages are autoloaded.\n\n"
                f"function {n}_Load($e)\n"
                "{\n"
                "    // runs when the form is shown\n"
                "}\n")

    def module_template(self, name: str) -> str:
        return ("<?php\n"
                f"// Module {name}. Its functions can be called\n"
                f"//   - directly from the PHP forms of this project: add(2, 3)\n"
                f"//   - from any other language through RAD Hub: radcall(\"{name}.add\", 2, 3)\n"
                "// Call other modules (any language) the same way: radcall('Helpers.greet', 'Ann')\n"
                "// Arguments and results are JSON values (number, string, bool, null, array).\n\n"
                "function add($a, $b)\n"
                "{\n"
                "    return $a + $b;\n"
                "}\n")

    def find_handler(self, code: str, name: str) -> int:
        return self._find_line(code, rf"^\s*function\s+&?\s*{re.escape(name)}\s*\(", re.I)

    def add_handler(self, code, name, form, args=None):
        lines = code.rstrip("\n").splitlines()
        end = len(lines)
        if lines and lines[-1].strip() == "?>":
            end -= 1
        stub = [f"function {name}($e)", "{", "    ", "}"]
        if end > 0 and lines[end - 1].strip():
            stub.insert(0, "")
        lines[end:end] = stub
        return "\n".join(lines) + "\n", end + len(stub) - 2

    def on_file_removed(self, code: str, filename: str) -> str:
        return code

    # ------------------------------------------------------------ project / run
    def my_forms(self, project: Project) -> list[str]:
        langs = getattr(project, "form_languages", None) or {}
        mine = [f for f in project.forms if langs.get(f, project.language) == self.id]
        if not mine:
            mine = [f for f in project.forms if (project.folder / self.code_file(f)).exists()]
        return mine

    def code_files(self, project: Project) -> list[str]:
        skip = {self.main_file.lower(), "radgui.php", "radworker.php"}
        mods = [m for m in project.modules if m.lower().endswith(".php") and m.lower() not in skip]
        return mods + [self.code_file(f) for f in self.my_forms(project)]

    def client_files(self) -> dict[str, Path]:
        return {"radgui.php": PHP_CLIENT / "radgui.php"}

    def main_source(self, project: Project):
        files = ",\n".join(f"    __DIR__ . '/{f}'" for f in self.code_files(project))
        return self.main_file, ("<?php\n"
                                "// AUTO-GENERATED by RAD IDE - main program for the GUI Bridge (do not edit)\n"
                                "require_once __DIR__ . '/radgui.php';\n"
                                f"rad_run_main([\n{files}\n]);\n")

    def php(self) -> str:
        return self.tool() or "php"

    def run_command(self, folder: Path, project: Project) -> list[str]:
        return [self.php(), "-d", "display_errors=stderr", "-d", "log_errors=0", self.main_file]

    def worker_command(self, folder: Path, module_file: str) -> list[str] | None:
        return [self.php(), "-d", "display_errors=stderr", "-d", "log_errors=0",
                str(PHP_CLIENT / "radworker.php"), module_file]

    # ------------------------------------------------------------ IntelliSense
    def completions(self, code, line, col, path, names=None):
        names = names or {}
        lines = code.splitlines()
        before = lines[line][:col] if line < len(lines) else ""
        m = re.search(r"\brad_(?:set|get|num|call)\s*\(\s*([\"'])(\w+)\1\s*,\s*[\"']\w*$", before, re.I)
        if m:
            return self._members(names.get(m.group(2), ""))
        if re.search(r"[\"']\w*$", before):
            return [Completion(n, "control", t) for n, t in names.items()]
        if re.search(r"(->|::)\w*$", before):
            return []
        out = [Completion(k, "keyword") for k in self.keywords]
        out += [Completion(k, "function", d) for k, d in API.items()]
        out += [Completion(b, "function") for b in self.builtins if b not in API]
        out += [Completion(f"'{n}'", "control", t) for n, t in names.items()]
        seen = {c.name.lower() for c in out}
        for w in re.findall(r"\$?[A-Za-z_]\w{2,}", code):
            if w.lower() not in seen:
                seen.add(w.lower())
                out.append(Completion(w, "variable"))
        return out

    def _members(self, ctype: str) -> list[Completion]:
        out, seen = [], set()
        ct = CONTROL_TYPES.get(ctype)
        for p in ([p.name for p in ct.prop_defs()] if ct else []) + EXTRA_PROPS + ["Caption"]:
            if p not in seen:
                seen.add(p)
                out.append(Completion(p, "property", ctype))
        return out + [Completion(mt, "method", ctype) for mt in METHODS]

    def calltip(self, code, line, col, path, names=None):
        lines = code.splitlines()
        before = lines[line][:col] if line < len(lines) else ""
        m = re.search(r"\b(rad\w*)\s*\([^()]*$", before, re.I)
        return API.get(m.group(1).lower(), "") if m else ""


PLUGIN = PhpBridgePlugin()
