"""Fortran language plugin (GUI Bridge + gfortran)."""
from __future__ import annotations

import os
import re
import shutil
import sys
from pathlib import Path

from ..controls import FORM_EVENTS
from ..model import Form
from .base import Completion, LanguagePlugin, RunSpec

IDE_ROOT = Path(__file__).resolve().parent.parent.parent
RADGUI = Path(__file__).resolve().parent.parent / "runtimes" / "radgui.f90"
HELPERS = {
    "rad_set": "call rad_set(obj, prop, value)  - set a property (text)",
    "rad_get": "s = rad_get(obj, prop)  - read a property as text",
    "rad_call": "call rad_call(obj, method, arg)  - e.g. call rad_call('lstLog', 'AddItem', 'x')",
    "rad_msgbox": "call rad_msgbox(text)", "rad_num": "x = rad_num(text)  - text to real(8)",
    "rad_str": "s = rad_str(x)  - real(8) to text", "rad_end": "call rad_end()  - quit the program",
    "rad_args": "event arguments as text (X Y Button KeyCode KeyChar)",
}


class FortranBridgePlugin(LanguagePlugin):
    id = "fortran-bridge"
    display_name = "Fortran (GUI Bridge, gfortran)"
    code_ext = ".f90"
    interpreter_names = ["gfortran"]
    interpreter_hints = [r"C:\msys64\ucrt64\bin\gfortran.exe", r"C:\msys64\mingw64\bin\gfortran.exe",
                         r"C:\MinGW\bin\gfortran.exe"]
    case_sensitive = False
    line_comments = ["!"]
    block_comment = None
    string_quotes = ['"', "'"]
    keywords = """program end module use implicit none contains subroutine function call if then else
        elseif endif do while enddo select case default exit cycle return integer real double precision
        character logical complex parameter dimension allocatable allocate deallocate intent in out inout
        write read print format open close stop true false and or not len trim adjustl""".split()
    builtins = list(HELPERS) + ["abs", "sqrt", "sin", "cos", "exp", "log", "mod", "int", "nint", "real",
                                "dble", "max", "min", "sum", "size", "index", "len_trim", "achar", "iachar"]

    def find_interpreter(self, configured: str = "") -> str:
        # the program runs under the IDE's Python bridge; gfortran is looked up when building
        return sys.executable

    def compiler(self) -> str:
        return LanguagePlugin.find_interpreter(self, "")

    # ------------------------------------------------------------ code
    def module_name(self, form_name: str) -> str:
        return f"{form_name.lower()}_code"

    def new_code(self, form: Form, is_startup: bool) -> str:
        n = form.name
        return (f"! Event handlers for {n}. Use rad_set / rad_get / rad_call to work with the controls.\n"
                f"module {self.module_name(n)}\n"
                f"  use radgui\n"
                f"  implicit none\n"
                f"contains\n\n"
                f"  subroutine {n}_Load()\n"
                f"    ! runs when the form is shown\n"
                f"  end subroutine {n}_Load\n\n"
                f"end module {self.module_name(n)}\n")

    def module_template(self, name: str) -> str:
        return f"module {name.lower()}\n  implicit none\ncontains\nend module {name.lower()}\n"

    def generate_designer(self, form: Form, user_code: str) -> str:
        """Per-form dispatcher: routes bridge events to the handler subroutines."""
        n = form.name
        handlers = re.findall(r"^\s*subroutine\s+(\w+)\s*(?:\(\s*\))?\s*$", user_code, re.I | re.M)
        L = [f"! AUTO-GENERATED by RAD IDE from {n}.form - do not edit (changes will be lost)",
             f"subroutine {n.lower()}_dispatch(key, handled)",
             f"  use {self.module_name(n)}",
             "  implicit none",
             "  character(len=*), intent(in) :: key",
             "  logical, intent(out) :: handled",
             "  handled = .true.",
             "  select case (key)"]
        for h in handlers:
            L += [f"  case ('{h}')", f"    call {h}()"]
        L += ["  case default", "    handled = .false.", "  end select",
              f"end subroutine {n.lower()}_dispatch", ""]
        return "\n".join(L)

    def handler_for(self, form, ctrl, event):
        if ctrl is not None and ctrl.type == "MenuStrip":
            return f"{event}_Click"
        return f"{ctrl.name if ctrl else form.name}_{event}"

    def events_for(self, ctrl):
        if ctrl is None:
            return list(FORM_EVENTS)
        return super().events_for(ctrl)

    def find_handler(self, code: str, name: str) -> int:
        return self._find_line(code, rf"^\s*subroutine\s+{re.escape(name)}\b", re.I)

    def add_handler(self, code, name, form, args=None):
        lines = code.rstrip("\n").splitlines()
        idx = next((i for i in range(len(lines) - 1, -1, -1)
                    if re.match(r"^\s*end\s+module\b", lines[i], re.I)), len(lines))
        stub = [f"  subroutine {name}()", "    ", f"  end subroutine {name}", ""]
        lines[idx:idx] = stub
        return "\n".join(lines) + "\n", idx + 1

    # ------------------------------------------------------------ build / run
    def _handlers(self, folder: Path) -> list[str]:
        out = []
        for f in folder.glob("*.f90"):
            if f.stem.endswith("_designer") or f.name.startswith("_") or f.name == "radgui.f90":
                continue
            out += re.findall(r"^\s*subroutine\s+(\w+)", f.read_text(encoding="utf-8", errors="replace"), re.I | re.M)
        return out

    def _write_main(self, folder: Path, forms: list[str]) -> None:
        L = ["! AUTO-GENERATED by RAD IDE - main program for the GUI Bridge", "program radmain",
             "  use radgui", "  implicit none", "  logical :: handled", "  character(len=600) :: key",
             "  do while (rad_next_event())", "    key = trim(rad_obj) // '_' // trim(rad_ev)", "    handled = .false."]
        for f in forms:
            L.append(f"    if (.not. handled) call {f.lower()}_dispatch(trim(key), handled)")
        L += ["    call rad_done()", "  end do", "end program radmain", ""]
        (folder / "_radmain.f90").write_text("\n".join(L), encoding="utf-8")

    def run_spec(self, folder: Path, startup_form: str, interpreter: str) -> RunSpec:
        from ..model import Project
        project = Project.load(folder)
        shutil.copy2(RADGUI, folder / "radgui.f90")
        self._write_main(folder, project.forms)
        gfortran = self.compiler()
        sources = ["radgui.f90"] + [m for m in project.modules] + \
                  [self.code_file(f) for f in project.forms] + [self.designer_file(f) for f in project.forms] + \
                  ["_radmain.f90"]
        exe = "_radapp.exe" if os.name == "nt" else "_radapp"
        if gfortran:
            build = f'"{gfortran}" -o {exe} ' + " ".join(sources)
        else:
            build = ('echo gfortran was not found. Install it (for example MSYS2: pacman -S '
                     'mingw-w64-ucrt-x86_64-gcc-fortran) and add it to PATH. && exit 1')
        env = dict(os.environ, PYTHONPATH=str(IDE_ROOT), PYTHONUNBUFFERED="1",
                   RAD_HANDLERS=",".join(self._handlers(folder)))
        return RunSpec(sys.executable, ["-u", "-m", "radide.runtimes.bridge", str(folder), "--build", build,
                                        "--", str(folder / exe)], folder, env)

    # ------------------------------------------------------------ IntelliSense
    def completions(self, code, line, col, path, names=None):
        out = [Completion(k, "keyword") for k in self.keywords]
        out += [Completion(h, "function", d) for h, d in HELPERS.items()]
        out += [Completion(f"'{n}'", "control", t) for n, t in (names or {}).items()]
        return out

    def calltip(self, code, line, col, path, names=None):
        before = code.splitlines()[line][:col] if line < len(code.splitlines()) else ""
        m = re.search(r"(rad_\w+)\s*\([^()]*$", before, re.I)
        return HELPERS.get(m.group(1).lower(), "") if m else ""


PLUGIN = FortranBridgePlugin()
