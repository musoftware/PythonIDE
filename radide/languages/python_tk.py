    def generate_designer(self, form: Form, user_code: str) -> str:
        fp = form.props
        n = form.name
        used = lambda ctrl: set(self.used_events(form, ctrl, user_code))
        timers = [c for c in form.nonvisual() if c.type == "Timer"]
        strip = next((c for c in form.nonvisual() if c.type == "ToolStrip"), None)
        dialogs = [c for c in form.nonvisual() if c.type in DIALOG_KIND]
        client = "self._client" if strip is not None else "self.root"
        specs = place_specs(form)
        blend = self._blend(form, "tk")      # Expression Blend: states / storyboards / bindings (8.7)
        L = [HEADER.format(form=n),
             "import os",
             "import tkinter as tk",
             "from tkinter import ttk",
             self._runtime(form).rstrip("\n") + (blend["runtime"].rstrip("\n") if blend else ""), "", "",
             f"class {n}Designer:",
             "    def __init__(self, master=None):",
             "        self.root = tk.Tk() if master is None else tk.Toplevel(master)",
             f"        self.root.title({fp['Text']!r})",
             f"        w, h = {int(fp['Width'])}, {int(fp['Height']) + (TOOLSTRIP_H if strip else 0)}"]
        if fp.get("StartPosition", "CenterScreen") == "CenterScreen":
            L += ["        x = (self.root.winfo_screenwidth() - w) // 2",
                  "        y = (self.root.winfo_screenheight() - h) // 3",
                  "        self.root.geometry(f\"{w}x{h}+{x}+{y}\")"]
        else:
            L.append("        self.root.geometry(f\"{w}x{h}\")")
        if fp.get("BackColor"):
            L.append(f"        self.root.configure(bg=\"{fp['BackColor']}\")")
        if fp.get("FormBorderStyle") == "FixedSingle":
            L.append("        self.root.resizable(False, False)")
        if fp.get("TopMost"):
            L.append("        self.root.attributes(\"-topmost\", True)")
        if fp.get("WindowState") == "Maximized":
            L.append("        self.root.state(\"zoomed\")")
        icon = fp.get("Icon")
        if icon:
            if str(icon).lower().endswith(".ico"):
                L.append(f"        self.root.iconbitmap(self._res({icon!r}))")
            else:
                L += [f"        self._icon = tk.PhotoImage(file=self._res({icon!r}))",
                      "        self.root.iconphoto(True, self._icon)"]
        L.append("        self._radio = tk.StringVar(value=\"\")")
        L.append("        self._places = {}")
        menu = form.menu()
        if menu is not None and menu.props.get("Items"):
            L.append("")
            L += ["        " + s for s in self._menu(menu)]
        if strip is not None:
            L.append("")
            L += ["        " + s for s in self._toolstrip(strip, fp)]
        # create in Tab order (Tk focus order = creation order), then restore z-order
        ordered = form.ordered()
        by_tab = self._tab_order(form)
        for c in by_tab:
            L.append("")
            L += ["        " + s for s in self._control(c, used(c), self._master(form, c, client),
                                                         specs.get(c.name))]
        if [c.name for c in by_tab] != [c.name for c in ordered]:
            L.append("")
            L += [f"        self.{c.name}.lift()" for c in ordered]
        for t in timers:
            p = t.props
            L += ["", f"        self.{t.name} = _Timer(self.root, {int(p['Interval'])}, "
                      f"self._ev(\"{t.name}_Tick\"), {bool(p['Enabled'])})"]
        for d in dialogs:
            props = {k: d.props[k] for k in DIALOG_PROPS[d.type] if k in d.props}
            args = "".join(f", {k}={v!r}" for k, v in props.items())
            L += ["", f"        self.{d.name} = _CommonDialog(self.root, {DIALOG_KIND[d.type]!r}{args})"]
        # form events
        fe = used(None)
        L.append("")
        for ev in ("Click", "DoubleClick", "MouseDown", "MouseUp", "MouseMove", "MouseWheel",
                   "KeyDown", "KeyUp", "KeyPress"):
            if ev in fe:
                mouse = ev.startswith(("Mouse", "Click", "Double"))
                L.append(self._bind_line(client if mouse else "self.root", ev, f"{n}_{ev}", own=mouse))
        if "Resize" in fe:
            L.append(f"        self._bind(self.root, \"<Configure>\", \"{n}_Resize\", own=True)")
        if "Activated" in fe:
            L.append(f"        self._bind(self.root, \"<FocusIn>\", \"{n}_Activated\", own=True)")
        if "Deactivate" in fe:
            L.append(f"        self._bind(self.root, \"<FocusOut>\", \"{n}_Deactivate\", own=True)")
        if fe & {"FormClosing", "FormClosed"}:
            L.append("        self.root.protocol(\"WM_DELETE_WINDOW\", self._on_close)")
        if blend:
            L += blend["init"]
        L.append(f"        self.root.after(0, self._ev(\"{n}_Load\"))")
        if blend:
            L += blend["after_load"]
        L.append(DISPATCH.replace("{form}", n).rstrip("\n"))
        if blend:
            L += blend["methods"]
        L.append("")
        return "\n".join(L)

    @staticmethod
    def _blend(form: Form, toolkit: str):
        """Visual states, storyboards and data bindings (radide/features/states.py), or None."""
        try:
            from ..features.states import python_blend
        except ImportError:
            return None
        return python_blend(form, toolkit)

    @staticmethod
    def _runtime(form: Form) -> str:
        """Runtime classes needed by the form (the big ones only when used)."""
        types = {c.type for c in form.controls}
        out = RUNTIME + RUNTIME_ENABLE
        if types & {"ListView", "DataGridView", "TreeView"}:
            out += RUNTIME_TREE
        if "DateTimePicker" in types:
            out += RUNTIME_DATE
        if types & set(DIALOG_KIND):
            out += RUNTIME_DIALOG
        return out

    @staticmethod
    def _master(form: Form, c, client: str = "self.root") -> str:
        if not c.parent:
            return client
        parent = form.find(c.parent)
        if parent is not None and parent.type == "TabControl":
            return f"self.{c.parent}_pages[{tab_page(c)}]"
        return f"self.{c.parent}"

    @staticmethod
    def _toolstrip(strip, fp) -> list[str]:
        n = strip.name
        out = [f"self.{n} = tk.Frame(self.root, bd=1, relief=\"raised\")",
               f"self.{n}.place(x=0, y=0, relwidth=1, height={TOOLSTRIP_H})",
               f"self.{n}_buttons = {{}}"]
        for it in strip.props.get("Items", []):
            text = it.get("Text", "")
            if text == "-":
                out.append(f"ttk.Separator(self.{n}, orient=\"vertical\").pack(side=\"left\", fill=\"y\", "
                           f"padx=3, pady=3)")
                continue
            name = it.get("Name", "")
            if it.get("Items"):        # a drop-down button
                out.append(f"_b = tk.Menubutton(self.{n}, text={text!r}, relief=\"flat\", padx=6)")
                out.append("_b.menu = tk.Menu(_b, tearoff=0)")
                out.append("_b.configure(menu=_b.menu)")
                for sub in it["Items"]:
                    if sub.get("Text") == "-":
                        out.append("_b.menu.add_separator()")
                    elif sub.get("Name"):
                        out.append(f"_b.menu.add_command(label={sub['Text']!r}, "
                                   f"command=self._ev(\"{sub['Name']}_Click\"))")
            else:
                out.append(f"_b = tk.Button(self.{n}, text={text!r}, relief=\"flat\", padx=6, "
                           f"command=self._ev(\"{name}_Click\"))")
            out.append("_b.pack(side=\"left\", padx=1, pady=1)")
            if name:
                out.append(f"self.{n}_buttons[{name!r}] = _b")
        bg = f", bg=\"{fp['BackColor']}\"" if fp.get("BackColor") else ""
        out += [f"self._client = tk.Frame(self.root, bd=0, highlightthickness=0{bg})",
                f"self._client.place(x=0, y={TOOLSTRIP_H}, relwidth=1, relheight=1, height=-{TOOLSTRIP_H})"]
        return out

    @staticmethod
    def _tab_order(form: Form):
        out = []

        def visit(parent):
            kids = sorted(form.children(parent), key=lambda c: int(c.props.get("TabIndex", 0)))
            for c in kids:
                out.append(c)
                if c.ctype.container:
                    visit(c.name)
        visit("")
        return out

    @staticmethod
    def _bind_line(widget: str, ev: str, handler: str, own=False) -> str:
        kind = event_args(ev)
        args = [widget, f"\"{TK_SEQ[ev]}\"", f"\"{handler}\""]
        if kind:
            args.append(f"\"{kind}\"")
        if ev == "KeyPress":
            args.append("chars_only=True")
        if own:
            args.append("own=True")
        return f"        self._bind({', '.join(args)})"

    def _menu(self, menu) -> list[str]:
        out = [f"self.{menu.name} = tk.Menu(self.root, tearoff=0)"]
        counter = [0]

        def build(var: str, items: list):
            for it in items:
                if it.get("Text") == "-":
                    out.append(f"{var}.add_separator()")
                elif it.get("Items"):
                    counter[0] += 1
                    sub = f"_m{counter[0]}"
                    out.append(f"{sub} = tk.Menu({var}, tearoff=0)")
                    out.append(f"{var}.add_cascade(label={it['Text']!r}, menu={sub})")
                    build(sub, it["Items"])
                else:
                    out.append(f"{var}.add_command(label={it['Text']!r}, "
                               f"command=self._ev(\"{it['Name']}_Click\"))")
        build(f"self.{menu.name}", menu.props["Items"])
        out.append(f"self.root.config(menu=self.{menu.name})")
        return out

    def _control(self, c, used: set[str], master: str | None = None, place=None) -> list[str]:
        p, n, t = c.props, c.name, c.type
        if master is None:
            master = f"self.{c.parent}" if c.parent else "self.root"
        ev = lambda e: f'self._ev("{n}_{e}")'
        opts = [f"font={_font(p)}"]
        out: list[str] = []
        native: set[str] = set()          # events handled by widget options
        align = p.get("TextAlign", "Left")
        if t == "Button":
            opts += [f"text={p['Text']!r}", f"command={ev('Click')}", f"anchor={ANCHOR[align]!r}"] + _colors(p)
            out.append(f"self.{n} = tk.Button({master}, {', '.join(opts)})")
            native.add("Click")
        elif t == "Label":
            opts += [f"text={p['Text']!r}", f"anchor={ANCHOR[align]!r}",
                     f"justify={JUSTIFY[align]!r}"] + _colors(p)
            out.append(f"self.{n} = tk.Label({master}, {', '.join(opts)})")
        elif t == "TextBox" and p.get("Multiline"):
            opts += ["wrap=\"word\"", "undo=True"] + _colors(p)
            out.append(f"self.{n} = tk.Text({master}, {', '.join(opts)})")
            out.append(f"self.{n}.insert(\"1.0\", {p['Text']!r})")
            out.append(f"self.{n}.edit_modified(False)")
            if "TextChanged" in used:
                out.append(f"self.{n}.bind(\"<<Modified>>\", lambda _e: (self.{n}.edit_modified(False), "
                           f"{ev('TextChanged')}()))")
            native.add("TextChanged")
            if p.get("ReadOnly"):
                out.append(f"self.{n}.configure(state=\"disabled\")")
        elif t == "TextBox":
            out.append(f"self.{n}_var = tk.StringVar(value={p['Text']!r})")
            opts += [f"textvariable=self.{n}_var", f"justify={JUSTIFY[align]!r}"] + _colors(p)
            if p.get("PasswordChar"):
                opts.append(f"show={str(p['PasswordChar'])[:1]!r}")
            if p.get("ReadOnly"):
                opts.append("state=\"readonly\"")
            out.append(f"self.{n} = tk.Entry({master}, {', '.join(opts)})")
            if int(p.get("MaxLength") or 0) > 0:
                m = int(p["MaxLength"])
                out.append(f"self.{n}_var.trace_add(\"write\", lambda *_: len(self.{n}_var.get()) > {m} "
                           f"and self.{n}_var.set(self.{n}_var.get()[:{m}]))")
            if "TextChanged" in used:
                out.append(f"self.{n}_var.trace_add(\"write\", {ev('TextChanged')})")
            native.add("TextChanged")
        elif t == "CheckBox":
            out.append(f"self.{n}_var = tk.BooleanVar(value={bool(p['Checked'])})")
            opts += [f"text={p['Text']!r}", f"variable=self.{n}_var", "anchor=\"w\"",
                     f"command={ev('CheckedChanged')}"] + _colors(p)
            out.append(f"self.{n} = tk.Checkbutton({master}, {', '.join(opts)})")
            native.add("CheckedChanged")
        elif t == "RadioButton":
            opts += [f"text={p['Text']!r}", "variable=self._radio", f"value={n!r}",
                     "anchor=\"w\"", f"command={ev('CheckedChanged')}"] + _colors(p)
            out.append(f"self.{n} = tk.Radiobutton({master}, {', '.join(opts)})")
            if p["Checked"]:
                out.append(f"self._radio.set({n!r})")
            native.add("CheckedChanged")
        elif t == "ListBox":
            opts += ["exportselection=False"] + _colors(p)
            out.append(f"self.{n} = tk.Listbox({master}, {', '.join(opts)})")
            for it in split_items(p["Items"]):
                out.append(f"self.{n}.insert(tk.END, {it!r})")
            out.append(f"self.{n}.bind(\"<<ListboxSelect>>\", {ev('SelectedIndexChanged')})")
            native.add("SelectedIndexChanged")
        elif t == "ComboBox":
            items = split_items(p["Items"])
            state = "readonly" if p.get("DropDownStyle", "DropDownList") == "DropDownList" else "normal"
            out.append(f"self.{n}_var = tk.StringVar()")
            opts += [f"values={items!r}", f"state={state!r}", f"textvariable=self.{n}_var"]
            out.append(f"self.{n} = ttk.Combobox({master}, {', '.join(opts)})")
            out.append(f"self.{n}.bind(\"<<ComboboxSelected>>\", {ev('SelectedIndexChanged')})")
            if "TextChanged" in used:
                out.append(f"self.{n}_var.trace_add(\"write\", {ev('TextChanged')})")
            native |= {"SelectedIndexChanged", "TextChanged"}
        elif t == "PictureBox":
            opts = _colors(p, fg=False) or ["bd=0"]
            out.append(f"self.{n} = tk.Label({master}, {', '.join(opts)})")
            if p.get("Image"):
                out.append(f"self.{n}_image = tk.PhotoImage(file=self._res({p['Image']!r}))")
                out.append(f"self.{n}.configure(image=self.{n}_image)")
        elif t == "ProgressBar":
            out.append(f"self.{n} = ttk.Progressbar({master}, maximum={int(p['Maximum'])}, "
                       f"value={int(p['Value'])})")
        elif t == "NumericUpDown":
            out.append(f"self.{n}_var = tk.IntVar(value={int(p['Value'])})")
            opts += [f"from_={int(p['Minimum'])}", f"to={int(p['Maximum'])}",
                     f"textvariable=self.{n}_var", f"command={ev('ValueChanged')}"] + _colors(p)
            out.append(f"self.{n} = tk.Spinbox({master}, {', '.join(opts)})")
            native.add("ValueChanged")
        elif t == "TrackBar":
            out.append(f"self.{n}_var = tk.IntVar(value={int(p['Value'])})")
            opts = [f"from_={int(p['Minimum'])}", f"to={int(p['Maximum'])}", "orient=\"horizontal\"",
                    "showvalue=False", f"variable=self.{n}_var",
                    f"command=lambda _v: {ev('ValueChanged')}()"] + _colors(p, fg=False)
            out.append(f"self.{n} = tk.Scale({master}, {', '.join(opts)})")
            native.add("ValueChanged")
        elif t == "Panel":
            out.append(f"self.{n} = tk.Frame({master}, {', '.join(_colors(p, fg=False) or ['bd=0'])})")
        elif t == "GroupBox":
            opts += [f"text={p['Text']!r}"] + _colors(p)
            out.append(f"self.{n} = tk.LabelFrame({master}, {', '.join(opts)})")
        elif t == "TabControl":
            pages = split_items(p.get("TabPages", "")) or ["TabPage1"]
            out.append(f"self.{n} = ttk.Notebook({master})")
            out.append(f"self.{n}_pages = []")
            out.append(f"for _text in {pages!r}:")
            out.append(f"    _page = tk.Frame(self.{n}, bd=0, highlightthickness=0"
                       + (f", bg=\"{p['BackColor']}\"" if p.get("BackColor") else "") + ")")
            out.append(f"    self.{n}.add(_page, text=_text)")
            out.append(f"    self.{n}_pages.append(_page)")
            sel = int(p.get("SelectedIndex", 0) or 0)
            if 0 < sel < len(pages):
                out.append(f"self.{n}.select({sel})")
            if "SelectedIndexChanged" in used:
                out.append(f"self._bind_tabs(self.{n}, \"{n}_SelectedIndexChanged\")")
            native.add("SelectedIndexChanged")
        elif t == "TreeView":
            out.append(f"self.{n} = _TreeView({master}, {[path for path, _ in tree_paths(p.get('Nodes'))]!r}, "
                       f"font={_font(p)})")
            out.append(f"self.{n}.bind(\"<<TreeviewSelect>>\", {ev('SelectedIndexChanged')})")
            native.add("SelectedIndexChanged")
        elif t == "ListView":
            out.append(f"self.{n} = _ListView({master}, {split_items(p.get('Columns'))!r}, "
                       f"{split_rows(p.get('Items'))!r}, view={p.get('View', 'Details')!r}, font={_font(p)})")
            out.append(f"self.{n}.bind(\"<<TreeviewSelect>>\", {ev('SelectedIndexChanged')})")
            native.add("SelectedIndexChanged")
        elif t == "DataGridView":
            out.append(f"self.{n} = _Grid({master}, {split_items(p.get('Columns'))!r}, "
                       f"{split_rows(p.get('Rows'))!r}, readonly={bool(p.get('ReadOnly'))}, "
                       f"on_change={ev('CellChanged')}, font={_font(p)})")
            out.append(f"self.{n}.bind(\"<<TreeviewSelect>>\", {ev('SelectedIndexChanged')})")
            native |= {"SelectedIndexChanged", "CellChanged"}
        elif t == "DateTimePicker":
            opts += [f"fmt={p.get('Format', 'Short')!r}", f"on_change={ev('ValueChanged')}"] + _colors(p)
            out.append(f"self.{n} = _DatePicker({master}, {str(p.get('Value') or '')!r}, {', '.join(opts)})")
            native.add("ValueChanged")
        elif t == "LinkLabel":
            style = " ".join(s for s, on in (("bold", p.get("FontBold")), ("italic", p.get("FontItalic")),
                                             ("underline", True)) if on)
            font = f"({(p.get('FontName') or 'Segoe UI')!r}, {int(p.get('FontSize', 9))}, {style!r})"
            opts = [f"font={font}", f"text={p['Text']!r}", "anchor=\"w\"", "cursor=\"hand2\"",
                    f"fg=\"{p.get('LinkColor') or '#0066CC'}\""] + _colors(p, fg=False)
            out.append(f"self.{n} = tk.Label({master}, {', '.join(opts)})")
            out.append(f"self.{n}.bind(\"<ButtonRelease-1>\", lambda _e: {ev('Click')}(), add=\"+\")")
            native.add("Click")
        elif t == "StatusBar":
            opts += [f"text={p['Text']!r}", "anchor=\"w\"", "relief=\"sunken\"", "bd=1", "padx=4"] + _colors(p)
            out.append(f"self.{n} = tk.Label({master}, {', '.join(opts)})")
        elif t == "ActiveX":
            text = f"ActiveX: {p.get('ProgID', '')}" + "\nActiveX controls need the Python (PySide6) language"
            out.append(f"self.{n} = tk.Label({master}, text={text!r}, relief=\"groove\", bg=\"#ffffff\", "
                       f"fg=\"#606060\", wraplength={max(40, int(p['Width']) - 8)}, font={_font(p)})")
        # generic events (bound only when a handler exists)
        for e in sorted(used - native):
            if e in TK_SEQ:
                out.append(self._bind_line(f"self.{n}", e, f"{n}_{e}").strip())
        if p.get("ToolTip"):
            out.append(f"_ToolTip(self.{n}, {p['ToolTip']!r})")
        if not p["Enabled"] and t in ("TabControl", "TreeView", "ListView", "DataGridView", "DateTimePicker",
                                      "LinkLabel", "StatusBar"):
            out.append(f"_set_enabled(self.{n}, False)")
        elif not p["Enabled"] and t not in ("Panel", "GroupBox", "PictureBox", "ProgressBar", "ActiveX"):
            out.append(f"self.{n}.configure(state=\"disabled\")")
        geo = place.tk_options() if place is not None else {
            "x": int(p["Left"]), "y": int(p["Top"]), "width": int(p["Width"]), "height": int(p["Height"])}
        geo["bordermode"] = "outside"
        out.append(f"self._places[{n!r}] = {geo!r}")
        if p["Visible"]:
            out.append(f"self.{n}.place(**self._places[{n!r}])")
        return out

