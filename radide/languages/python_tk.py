    @staticmethod
    def _insert_import(code: str, line: str) -> str:
        lines = code.splitlines()
        last = -1
        for i, ln in enumerate(lines):
            if ln.startswith(("import ", "from ")):
                last = i
        lines.insert(last + 1, line)
        return "\n".join(lines) + "\n"

    # ---------------------------------------------------------------- events
    def find_handler(self, code: str, name: str) -> int:
        return self._find_line(code, rf"^\s+def\s+{name}\s*\(")

    def add_handler(self, code: str, name: str, form: Form, args: str | None = None) -> tuple[str, int]:
        lines = code.splitlines()
        sig = f"    def {name}(self, e):" if args else f"    def {name}(self):"
        stub = [sig, "        pass", ""]
        idx = self._find_line(code, r"^if\s+__name__\s*==")
        if idx < 0:
            idx = len(lines)
        else:
            while idx > 0 and not lines[idx - 1].strip():   # step above blank lines
                idx -= 1
            stub = [""] + stub[:-1]
        lines[idx:idx] = stub
        cursor = idx + (2 if stub[0] == "" else 1)
        return "\n".join(lines) + "\n", cursor

