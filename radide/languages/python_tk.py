class _CommonDialog:
    """OpenFileDialog / SaveFileDialog / ColorDialog / FontDialog / FolderBrowserDialog.
    ShowDialog() returns "OK" or "Cancel" and fills FileName / Color / FontName, FontSize /
    SelectedPath. ShowOpen / ShowSave / ShowColor / ShowFont / ShowFolder work on any of them."""

    def __init__(self, root, kind, **props):
        self.root, self.Kind = root, kind
        self.Title, self.Filter, self.FileName, self.InitialDirectory = "", "All files|*.*", "", ""
        self.Color, self.FontName, self.FontSize, self.SelectedPath = "#000000", "Segoe UI", 9, ""
        for k, v in props.items():
            setattr(self, k, v)

    def ShowDialog(self):
        return {"open": self.ShowOpen, "save": self.ShowSave, "color": self.ShowColor,
                "font": self.ShowFont, "folder": self.ShowFolder}[self.Kind]()

    def _filetypes(self):
        parts = [p.strip() for p in str(self.Filter or "").split("|")]
        out = []
        for i in range(0, len(parts) - 1, 2):
            pats = tuple(x.strip() for x in parts[i + 1].split(";") if x.strip()) or ("*.*",)
            out.append((parts[i], pats if len(pats) > 1 else pats[0]))
        return out or [("All files", "*.*")]

    def _file_options(self):
        opts = {"parent": self.root, "filetypes": self._filetypes()}
        if self.Title:
            opts["title"] = self.Title
        folder = self.InitialDirectory or (os.path.dirname(self.FileName) if self.FileName else "")
        if folder:
            opts["initialdir"] = folder
        if self.FileName:
            opts["initialfile"] = os.path.basename(self.FileName)
        return opts

    def _done(self, prop, value):
        if not value:
            return "Cancel"
        setattr(self, prop, str(value))
        return "OK"

    def ShowOpen(self):
        from tkinter import filedialog
        return self._done("FileName", filedialog.askopenfilename(**self._file_options()))

    def ShowSave(self):
        from tkinter import filedialog
        opts = self._file_options()
        first = opts["filetypes"][0][1]
        first = first[0] if isinstance(first, tuple) else first
        if first.startswith("*.") and "*" not in first[2:]:
            opts["defaultextension"] = first[1:]
        return self._done("FileName", filedialog.asksaveasfilename(**opts))

    def ShowColor(self):
        from tkinter import colorchooser
        opts = {"parent": self.root, "title": self.Title or "Color"}
        if self.Color:
            opts["color"] = self.Color
        result = colorchooser.askcolor(**opts)
        return self._done("Color", result[1] if result else None)

    def ShowFolder(self):
        from tkinter import filedialog
        opts = {"parent": self.root, "mustexist": True}
        if self.Title:
            opts["title"] = self.Title
        if self.SelectedPath:
            opts["initialdir"] = self.SelectedPath
        return self._done("SelectedPath", filedialog.askdirectory(**opts))

    def ShowFont(self):
        result = _FontPicker(self.root, self.FontName, self.FontSize, self.Title or "Font").result
        if not result:
            return "Cancel"
        self.FontName, self.FontSize = result
        return "OK"


