    def worker_command(self, folder: Path, module_file: str) -> list[str] | None:
        """RAD Hub worker: serves this module's functions to the other languages."""
        worker = Path(__file__).resolve().parent.parent / "runtimes" / "clients" / "python" / "radworker.py"
        return [self.find_interpreter(""), "-u", str(worker), module_file]

    def on_form_added(self, startup_code: str, form_name: str) -> str:
        return self._insert_import(startup_code, f"from {form_name} import {form_name}  "
                                                 f"# show with: {form_name}(master=self.root)")

    def on_file_added(self, startup_code: str, filename: str) -> str:
        return self._insert_import(startup_code, f"import {Path(filename).stem}")

    @staticmethod
    def _insert_import(code: str, line: str) -> str:
        lines = code.splitlines()
        last = -1
        for i, ln in enumerate(lines):
            if ln.startswith(("import ", "from ")):
                last = i
        lines.insert(last + 1, line)
        return "\n".join(lines) + "\n"

    # ---------------------------------------------------------------- events
    def find_handler(self, code: str, name: str) -> int:
        return self._find_line(code, rf"^\s+def\s+{name}\s*\(")

    def add_handler(self, code: str, name: str, form: Form, args: str | None = None) -> tuple[str, int]:
        lines = code.splitlines()
        sig = f"    def {name}(self, e):" if args else f"    def {name}(self):"
        stub = [sig, "        pass", ""]
        idx = self._find_line(code, r"^if\s+__name__\s*==")
        if idx < 0:
            idx = len(lines)
        else:
            while idx > 0 and not lines[idx - 1].strip():   # step above blank lines
                idx -= 1
            stub = [""] + stub[:-1]
        lines[idx:idx] = stub
        cursor = idx + (2 if stub[0] == "" else 1)
        return "\n".join(lines) + "\n", cursor

    # ------------------------------------------------------------------- run
    def run_spec(self, folder: Path, startup_form: str, interpreter: str) -> RunSpec:
        env = dict(os.environ, PYTHONUNBUFFERED="1")
        return RunSpec(interpreter, ["-u", self.code_file(startup_form)], folder, env)

    def debug_spec(self, folder, startup_form, interpreter, breakpoints) -> RunSpec:
        env = dict(os.environ, PYTHONUNBUFFERED="1", RADDBG_BP=self.breakpoints_env(breakpoints),
                   RADDBG_ROOT=str(folder))
        return RunSpec(interpreter, ["-u", str(AGENT), self.code_file(startup_form)], folder, env)

    # ------------------------------------------------------------ completion
    _jedi_warm = False

    def _script(self, code: str, path: Path):
        import jedi
        if not PythonTkPlugin._jedi_warm:
            PythonTkPlugin._jedi_warm = True
            jedi.settings.case_insensitive_completion = True
        return jedi.Script(code, path=str(path), project=jedi.Project(str(path.parent)))

    def completions(self, code, line, col, path, names=None):
        from .base import Completion
        try:
            script = self._script(code, path)
            out = []
            for c in script.complete(line + 1, col)[:400]:
                if c.name.startswith("__") and not c.name.endswith("__"):
                    continue
                detail = ""
                if c.type in ("function", "class"):
                    try:
                        sigs = c.get_signatures()
                        detail = sigs[0].to_string() if sigs else c.description
                    except Exception:  # noqa: BLE001
                        detail = c.description
                else:
                    detail = c.description
                out.append(Completion(c.name, c.type, detail))
            # handlers' VB-style objects first: controls of the form
            ctrl = {n.lower() for n in (names or {})}
            out.sort(key=lambda c: (c.name.lower() not in ctrl, c.name.startswith("_"), c.name.lower()))
            return out
        except Exception:  # noqa: BLE001
            return super().completions(code, line, col, path, names)

    def calltip(self, code, line, col, path, names=None):
        try:
            sigs = self._script(code, path).get_signatures(line + 1, col)
        except Exception:  # noqa: BLE001
            return ""
        if not sigs:
            return ""
        s = sigs[0]
        params = [p.to_string() for p in s.params]
        idx = s.index if s.index is not None else -1
        shown = ", ".join(f"<b>{p}</b>" if i == idx else p for i, p in enumerate(params))
        doc = (s.docstring(raw=True) or "").strip().splitlines()
        return f"{s.name}({shown})" + (f"<br><i>{doc[0][:120]}</i>" if doc else "")


