class _Rows(ttk.Treeview):
    """Base of ListView / DataGridView: rows of cells (strings), indexes start at 0."""

    def __init__(self, master, columns=(), rows=(), font=None, headings=True, **kw):
        cols = list(columns) or ["Column1"]
        ids = [f"c{i}" for i in range(len(cols))]
        super().__init__(master, columns=ids, show="headings" if headings else "", selectmode="browse", **kw)
        if font is not None:
            style = f"rad{id(self)}.Treeview"
            st = ttk.Style(self)
            st.configure(style, font=font)
            try:
                import tkinter.font as tkfont
                st.configure(style, rowheight=tkfont.Font(self, font=font).metrics("linespace") + 6)
            except tk.TclError:
                pass
            self.configure(style=style)
        self.Columns = cols
        for i, c in zip(ids, cols):
            self.heading(i, text=c)
            self.column(i, width=80, minwidth=30, stretch=True)
        for r in rows:
            self.AddRow(*r)

    # -- rows
    def AddRow(self, *cells):
        vals = [str(c) for c in cells] + [""] * (len(self.Columns) - len(cells))
        return self.insert("", "end", values=vals[:len(self.Columns)])

    AddItem = AddRow

    def RemoveRow(self, index):
        self.delete(self.get_children()[int(index)])

    RemoveItem = RemoveRow

    def Clear(self):
        self.delete(*self.get_children())

    @property
    def RowCount(self):
        return len(self.get_children())

    @property
    def ColumnCount(self):
        return len(self.Columns)

    def GetRow(self, index):
        return [str(v) for v in self.item(self.get_children()[int(index)], "values")]

    def GetCell(self, row, col):
        vals = self.GetRow(row)
        col = int(col)
        return vals[col] if col < len(vals) else ""

    def SetCell(self, row, col, value):
        iid = self.get_children()[int(row)]
        vals = [str(v) for v in self.item(iid, "values")]
        vals += [""] * (len(self.Columns) - len(vals))
        vals[int(col)] = str(value)
        self.item(iid, values=vals)

    @property
    def Rows(self):
        return [self.GetRow(i) for i in range(self.RowCount)]

    @property
    def SelectedIndex(self):
        sel = self.selection()
        return self.index(sel[0]) if sel else -1

    @SelectedIndex.setter
    def SelectedIndex(self, index):
        kids = self.get_children()
        index = int(index)
        if 0 <= index < len(kids):
            self.selection_set(kids[index])
            self.see(kids[index])
        else:
            self.selection_remove(self.selection())

    def SetColumns(self, columns):
        rows = self.Rows
        self.Columns = list(columns) or ["Column1"]
        ids = [f"c{i}" for i in range(len(self.Columns))]
        self.configure(columns=ids)
        for i, c in zip(ids, self.Columns):
            self.heading(i, text=c)
        self.Clear()
        for r in rows:
            self.AddRow(*r)


