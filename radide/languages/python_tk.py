class _DatePicker(tk.Spinbox):
    """DateTimePicker: a validated entry; the arrows / Up / Down change the day (or second).
    Value is "YYYY-MM-DD" (Format Time: "HH:MM:SS")."""
    FORMATS = {"Short": "%Y-%m-%d", "Long": "%A, %d %B %Y", "Time": "%H:%M:%S"}

    def __init__(self, master, value="", fmt="Short", on_change=None, **kw):
        import datetime
        self._dt = datetime
        self.Format = fmt if fmt in self.FORMATS else "Short"
        self._on_change = on_change
        self._var = tk.StringVar()
        super().__init__(master, textvariable=self._var, from_=0, to=1, increment=1,
                         command=(master.register(self._spin), "%d"), **kw)
        self._value = self._parse(value) or datetime.datetime.now().replace(microsecond=0)
        self._show()
        self.bind("<Return>", self._commit, add="+")
        self.bind("<FocusOut>", self._commit, add="+")
        self.bind("<Up>", lambda _e: self._spin("up") or "break", add="+")
        self.bind("<Down>", lambda _e: self._spin("down") or "break", add="+")

    def _parse(self, text):
        text = str(text or "").strip()
        if not text:
            return None
        fmts = [self.FORMATS[self.Format], "%Y-%m-%d", "%Y-%m-%d %H:%M:%S", "%H:%M:%S", "%H:%M", "%d/%m/%Y"]
        for f in fmts:
            try:
                d = self._dt.datetime.strptime(text, f)
            except ValueError:
                continue
            if f.startswith("%H"):
                base = getattr(self, "_value", None) or self._dt.datetime.now()
                d = base.replace(hour=d.hour, minute=d.minute, second=d.second, microsecond=0)
            return d
        return None

    def _show(self):
        self._var.set(self._value.strftime(self.FORMATS[self.Format]))

    def _set(self, d):
        old = self._value
        self._value = d
        self._show()
        if d != old and self._on_change is not None:
            self._on_change()

    def _commit(self, _e=None):
        d = self._parse(self._var.get())
        if d is None:
            self.bell()
            self._show()
        else:
            self._set(d)

    def _spin(self, direction):
        step = 1 if direction == "up" else -1
        delta = self._dt.timedelta(seconds=step) if self.Format == "Time" else self._dt.timedelta(days=step)
        self._set(self._value + delta)

    @property
    def Value(self):
        return self._value.strftime("%H:%M:%S" if self.Format == "Time" else "%Y-%m-%d")

    @Value.setter
    def Value(self, text):
        d = text if isinstance(text, self._dt.datetime) else self._parse(text)
        if d is None:
            raise ValueError(f"not a valid date/time: {text!r}")
        self._set(d)

    @property
    def DateTime(self):
        return self._value
