class _Timer:
    """VB-like Timer: set Interval (ms) and Enabled; calls tick() every Interval."""

    def __init__(self, root, interval, tick, enabled=False):
        self.root, self.Interval, self._tick, self._job = root, interval, tick, None
        self._enabled = False
        self.Enabled = enabled

    @property
    def Enabled(self):
        return self._enabled

    @Enabled.setter
    def Enabled(self, value):
        self._enabled = bool(value)
        if self._job is not None:
            self.root.after_cancel(self._job)
            self._job = None
        if self._enabled:
            self._job = self.root.after(max(1, int(self.Interval)), self._fire)

