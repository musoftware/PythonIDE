class _Grid(_Rows):
    """DataGridView: double-click (or F2 / Return) a cell to edit it unless ReadOnly.
    on_change() is called after an edit; CurrentRow / CurrentColumn tell which cell."""

    def __init__(self, master, columns=(), rows=(), readonly=False, on_change=None, font=None):
        super().__init__(master, columns, rows, font=font)
        self.ReadOnly = readonly
        self.CurrentRow, self.CurrentColumn = -1, -1
        self._on_change = on_change
        self._editor = None
        self.bind("<Double-Button-1>", self._begin_edit, add="+")
        self.bind("<F2>", self._begin_edit, add="+")
        self.bind("<Return>", self._begin_edit, add="+")
        self.bind("<ButtonRelease-1>", self._track, add="+")

    def _track(self, ev):
        row, col = self.identify_row(ev.y), self.identify_column(ev.x)
        if row:
            self.CurrentRow = self.index(row)
        if col:
            self.CurrentColumn = int(col[1:]) - 1

    def _begin_edit(self, ev=None):
        if self.ReadOnly:
            return
        if ev is not None and getattr(ev, "x", None) is not None and ev.type == tk.EventType.ButtonPress:
            self._track(ev)
        if self.CurrentRow < 0:
            sel = self.selection()
            if not sel:
                return
            self.CurrentRow = self.index(sel[0])
        if self.CurrentColumn < 0:
            self.CurrentColumn = 0
        self.EditCell(self.CurrentRow, self.CurrentColumn)
        return "break"

    def EditCell(self, row, col):
        """Open an editor over cell (row, col)."""
        self._end_edit(commit=False)
        kids = self.get_children()
        if not (0 <= row < len(kids)) or not (0 <= col < len(self.Columns)):
            return
        iid = kids[row]
        self.see(iid)
        self.update_idletasks()
        box = self.bbox(iid, f"c{col}")
        if not box:
            return
        x, y, w, h = box
        var = tk.StringVar(value=self.GetCell(row, col))
        ed = tk.Entry(self, textvariable=var, relief="solid", bd=1)
        ed.place(x=x, y=y, width=w, height=h)
        ed.select_range(0, "end")
        ed.focus_set()
        self._editor = (ed, var, row, col)
        ed.bind("<Return>", lambda _e: self._end_edit(True) or "break")
        ed.bind("<Escape>", lambda _e: self._end_edit(False) or "break")
        ed.bind("<FocusOut>", lambda _e: self._end_edit(True))

    def _end_edit(self, commit=True):
        if self._editor is None:
            return
        ed, var, row, col = self._editor
        self._editor = None
        new = var.get()
        ed.destroy()
        if commit and new != self.GetCell(row, col):
            self.SetCell(row, col, new)
            self.CurrentRow, self.CurrentColumn = row, col
            if self._on_change is not None:
                self._on_change()


class _TreeView(ttk.Treeview):
    """TreeView whose nodes are addressed by path ("Root/Child"); the path is the item id."""

    def __init__(self, master, nodes=(), font=None):
        super().__init__(master, show="tree", selectmode="browse")
        if font is not None:
            style = f"rad{id(self)}.Treeview"
            ttk.Style(self).configure(style, font=font)
            self.configure(style=style)
        for path in nodes:
            self.AddNode(path)
        for iid in self.get_children():
            self.item(iid, open=True)

    def AddNode(self, path, text=None):
        """Add 'Parent/Child' (parents are created as needed). Returns the path."""
        parts = [p.strip() for p in str(path).split("/") if p.strip()]
        parent = ""
        for i, part in enumerate(parts):
            iid = "/".join(parts[:i + 1])
            if not self.exists(iid):
                label = text if (text is not None and i == len(parts) - 1) else part
                self.insert(parent, "end", iid=iid, text=label)
            parent = iid
        return parent

    def RemoveNode(self, path):
        if self.exists(path):
            self.delete(path)

    def Clear(self):
        self.delete(*self.get_children())

    @property
    def SelectedNode(self):
        sel = self.selection()
        return sel[0] if sel else ""

    @SelectedNode.setter
    def SelectedNode(self, path):
        if path and self.exists(path):
            self.see(path)
            self.selection_set(path)

    @property
    def SelectedText(self):
        sel = self.selection()
        return self.item(sel[0], "text") if sel else ""

    @property
    def Nodes(self):
        out = []

        def walk(parent):
            for iid in self.get_children(parent):
                out.append(iid)
                walk(iid)
        walk("")
        return out
