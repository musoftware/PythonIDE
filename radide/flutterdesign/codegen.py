def emit_value(kind: str, value, owner: str = "") -> X | None:
    if value is None:
        return None
    if M.is_code(value):
        return Raw(value["$code"])
    if kind == "button_style":
        return x_button_style(value, owner or "ElevatedButton")
    if kind == "nav_items":
        return x_nav_items(value, owner)
    fn = VALUE_EMITTERS.get(kind)
    return fn(value) if fn else Raw(json.dumps(value))


# ================================================================================ tree -> Dart
@dataclass
class Field:
    name: str
    type: str
    init: str
    dispose: bool = False


@dataclass
class GenContext:
    fields: dict = field(default_factory=dict)       # name -> Field
    handlers: dict = field(default_factory=dict)     # handler -> params
    uses_anim: bool = False
    uses_google_fonts: bool = False
    uses_cupertino: bool = False
    screens_used: set = field(default_factory=set)   # push:<Screen> targets (imported)
    warnings: list = field(default_factory=list)


def _field_name(node: dict, spec: M.WidgetSpec) -> str:
    return node.get("name") or f"_{node.get('id', 'w0')}"


def _value_assign(spec: M.WidgetSpec, event_sig: str, fname: str) -> str:
    if spec.value_type == "bool" and event_sig.startswith("bool?"):
        return f"{fname} = value ?? false"
    return f"{fname} = value"


def _nav_action(h: str) -> str | None:
    if h == "back":
        return "() => Navigator.pop(context)"
    if h.startswith("nav:"):
        return f"() => Navigator.pushNamed(context, {dart_string(h[4:])})"
    if h.startswith("replace:"):
        return f"() => Navigator.pushReplacementNamed(context, {dart_string(h[8:])})"
    if h.startswith("push:"):
        cls = h[5:]
        return f"() => Navigator.push(context, MaterialPageRoute(builder: (context) => const {cls}()))"
    return None


class TreeGen:
    def __init__(self, ctx: GenContext):
        self.ctx = ctx

    def node(self, n: dict) -> X:
        a = n.get("anim")
        if a and a.get("type") and n.get("type") in PARENT_DATA and (n.get("slots") or {}).get("child"):
            # Positioned / Expanded / Flexible must stay direct children of their Stack / Flex:
            # the animation wraps their child instead (the importer lifts it back)
            inner = dict(n["slots"]["child"])
            if not inner.get("anim"):
                inner["anim"] = a
                n = dict(n, slots=dict(n["slots"], child=inner))
                n.pop("anim")
        x = self._node(n)
        if n.get("anim") and (n.get("type") in PARENT_DATA or n.get("type") == "Spacer"):
            self.ctx.warnings.append(f"{n.get('id')}: a {n.get('type')} cannot be animated (animate its child)")
            return x
        return self.wrap_anim(x, n.get("anim"))

    def wrap_anim(self, x: X, a: dict | None) -> X:
        if a and a.get("type"):
            self.ctx.uses_anim = True
            named = [("type", Lit(f"RadFxType.{a['type']}"))]
            for k in ("delayMs", "durationMs"):
                if a.get(k) not in (None, ""):
                    named.append((k, x_num(int(a[k]))))
            for k in ("offsetX", "offsetY", "scale"):
                if a.get(k) is not None:
                    named.append((k, x_num(a[k])))
            if a.get("curve"):
                named.append(("curve", Lit(a["curve"])))
            named.append(("child", x))
            x = Call("RadFx", named=named)
        return x

    def nodes(self, lst) -> list[X]:
        return [self.node(c) for c in lst if isinstance(c, dict)]

    def _node(self, n: dict) -> X:
        t = n.get("type", "")
        if t == "Code":
            return self._code_node(n)
        spec0 = M.CATALOG.get(t)
        if spec0 is None:
            self.ctx.warnings.append(f"{n.get('id')}: unknown widget {t!r} generated as a placeholder")
            return Raw(f"const Placeholder() /* unknown widget {t} */")
        ctor = n.get("ctor") or (None if spec0.unnamed_ctor else spec0.default_ctor)
        spec = spec0.resolved(ctor)
        if spec.library == "cupertino":
            self.ctx.uses_cupertino = True
        props = dict(n.get("props") or {})
        events = dict(n.get("events") or {})
        slots = n.get("slots") or {}
        pos: list[tuple[int, X]] = []
        named: list[tuple[str, X]] = []
        tail: list[tuple[str, X]] = []
        name = f"{t}.{ctor}" if ctor else t
        nonconst = False

        # ---- stateful binding (named inputs)
        if spec.needs_name:
            fname = _field_name(n, spec)
            vt = spec.value_type
            if vt == "TextEditingController":
                self.ctx.fields[fname] = Field(fname, vt, "TextEditingController()", dispose=True)
                named.append(("controller", Raw(fname)))
            elif spec.value_prop:
                init = props.get(spec.value_prop)
                if vt == "bool":
                    init_s = "true" if init else "false"
                elif vt == "double":
                    init_s = dart_num(float(init if isinstance(init, (int, float)) else 0.5))
                elif vt == "int":
                    init_s = str(int(init or 0))
                else:
                    init_s = dart_string(init) if init else "null"
                self.ctx.fields[fname] = Field(fname, vt, init_s)
                props.pop(spec.value_prop, None)
                named.append((spec.value_prop, Raw(fname)))
                ev = next(iter(spec.events))           # the value-changed event
                sig = spec.events[ev]
                h = events.pop(ev, None)
                assign = _value_assign(spec, sig, fname)
                if h and not _nav_action(h):
                    self._handler(h, sig)
                    cb = f"(value) {{\n setState(() => {assign});\n {h}(value);\n}}"
                else:
                    cb = f"(value) => setState(() => {assign})"
                named.append((ev, Raw(cb)))
            nonconst = True

        # ---- properties
        for k, v in props.items():
            ps = spec.props.get(k)
            if t == "DropdownButton" and k in ("items", "hint"):
                continue
            if ps is None:
                if M.is_code(v):
                    named.append((k, Raw(v["$code"])))
                else:
                    self.ctx.warnings.append(f"{n.get('id')}: {t} has no property {k!r} - skipped")
                continue
            x = emit_value(ps.kind, v, t)
            if x is None:
                continue
            if ps.kind == "text_style" and isinstance(v, dict) and v.get("googleFont"):
                self.ctx.uses_google_fonts = True
            if ps.kind in ("input_decoration", "button_style") and isinstance(v, dict):
                for sub in ("hintStyle", "labelStyle", "textStyle"):
                    if isinstance(v.get(sub), dict) and v[sub].get("googleFont"):
                        self.ctx.uses_google_fonts = True
            if ps.positional is not None:
                pos.append((ps.positional, x))
            else:
                named.append((k, x))
        if t == "DropdownButton":
            items = props.get("items") or []
            lst = x_string_list(items) or Lst([])
            mapper = Raw(f"{lst.render()}.map((item) => DropdownMenuItem(value: item, child: Text(item))).toList()")
            if props.get("hint") is not None:
                named.append(("hint", Call("Text", [x_str(props["hint"])])))
            named.append(("items", mapper))
            name = "DropdownButton<String>"

        # ---- events
        for ev, h in events.items():
            if not h:
                continue
            sig = spec.events.get(ev, "")
            nav = _nav_action(h)
            if nav:
                if h.startswith("push:"):
                    self.ctx.screens_used.add(h[5:])
                named.append((ev, Raw(nav)))
            else:
                self._handler(h, sig)
                named.append((ev, Raw(h)))
            nonconst = True
        for ev in spec.required_events:
            if ev not in events and not any(k == ev for k, _ in named):
                named.append((ev, Raw("() {}")))
                nonconst = True

        # ---- slots (child last)
        for s, ss in spec.slots.items():
            v = slots.get(s)
            if v is None or (isinstance(v, list) and not v):
                continue
            x = Lst(self.nodes(v)) if ss.multi else self.node(v)
            (tail if s == "child" else named).append((s, x))
        for s, v in slots.items():
            if s not in spec.slots:
                self.ctx.warnings.append(f"{n.get('id')}: {t} has no slot {s!r} - skipped")
        if spec.children:
            kids = n.get("children") or []
            tail.append((spec.children, Lst(self.nodes(kids))))
        if t == "DefaultTabController" and "length" not in props:
            named.insert(0, ("length", Lit(str(self._count_tabs(n)))))

        pos.sort(key=lambda p: p[0])
        multiline = bool(tail) or len(named) > 2
        call = Call(name, [x for _i, x in pos], named + tail, const_ctor=spec.const_ctor and not nonconst,
                    multiline=multiline)
        return call

    @staticmethod
    def _count_tabs(n: dict) -> int:
        for c, *_ in M.walk_node(n):
            if c.get("type") == "TabBar":
                return max(1, len(c.get("children") or []))
        return 2

    def _handler(self, h: str, sig: str) -> None:
        old = self.ctx.handlers.get(h)
        if old is not None and old != sig:
            self.ctx.warnings.append(f"handler {h} is used with different parameters ({old!r} / {sig!r})")
            return
        self.ctx.handlers[h] = sig

    def _code_node(self, n: dict) -> X:
        code = str((n.get("props") or {}).get("code") or "const SizedBox()")
        slots = n.get("slots") or {}

        def sub(m):
            v = slots.get(m.group(1))
            if v is None:
                return "const SizedBox()"
            if isinstance(v, list):
                return ", ".join(x.render() for x in self.nodes(v))
            return self.node(v).render()
        return Raw(re.sub(r"#\{slot:(\w+)\}", sub, code))


