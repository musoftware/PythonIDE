def _dart_exe() -> str:
    try:
        from ..languages.flutter import dart_exe
        return dart_exe()
    except Exception:  # noqa: BLE001
        return shutil.which("dart") or ""


def format_dart(code: str, language_version: str = "latest") -> str:
    """``dart format`` (Flutter SDK) through stdin; the built-in line breaker when dart is missing / fails."""
    exe = _dart_exe()
    if exe:
        try:
            r = subprocess.run([exe, "format", "-o", "show", f"--language-version={language_version}"],
                               input=code, capture_output=True, text=True, timeout=60, encoding="utf-8",
                               errors="replace", creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            if r.returncode == 0 and r.stdout.strip():
                return r.stdout if r.stdout.endswith("\n") else r.stdout + "\n"
        except (OSError, subprocess.TimeoutExpired):
            pass
    from ..mobile.codegen_dart import format_dart as simple
    return simple(code, 100)


