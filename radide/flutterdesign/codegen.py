def new_events_code(cls: str, designer_file: str) -> str:
    return (f"// {cls} screen - event handlers. This file is yours: the Flutter designer only adds new handler\n"
            f"// stubs. Named widgets are fields (txtEmail.text, chkRemember); call setState(() {{ ... }}) after\n"
            f"// changing values shown on the screen. Extra imports: Screen properties > Imports.\n"
            f"part of '{designer_file}';\n\n"
            f"class {cls}Events extends {cls}Designer {{\n"
            f"}}\n")


def _class_body_end(code: str, cls_rx: str) -> int:
    """Index of the closing brace of the class matched by *cls_rx* (-1 when not found)."""
    m = re.search(cls_rx, code, re.M)
    if not m:
        return -1
    i = code.find("{", m.end())
    if i < 0:
        return -1
    depth, j, n = 0, i, len(code)
    while j < n:
        ch = code[j]
        if ch in "'\"":
            q3 = code[j:j + 3] in ("'''", '"""')
            qq = code[j:j + 3] if q3 else ch
            j += len(qq)
            while j < n and code[j:j + len(qq)] != qq:
                j += 2 if code[j] == "\\" else 1
            j += len(qq)
            continue
        if code.startswith("//", j):
            k = code.find("\n", j)
            j = n if k < 0 else k
            continue
        if code.startswith("/*", j):
            k = code.find("*/", j + 2)
            j = n if k < 0 else k + 2
            continue
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return j
        j += 1
    return -1


def add_missing_handlers(user_code: str | None, screen: M.Screen, handlers: dict[str, str], cls: str,
                         designer_file: str) -> str:
    code = user_code if user_code and user_code.strip() else new_events_code(cls, designer_file)
    have = set(re.findall(r"\b(?:void|Future<void>|FutureOr<void>)\s+(\w+)\s*\(", code))
    missing = [(h, sig) for h, sig in handlers.items() if h not in have]
    if not missing:
        return code
    end = _class_body_end(code, rf"^\s*class\s+{re.escape(cls)}Events\b")
    stubs = []
    for h, sig in missing:
        stubs += ["", "  @override", f"  void {h}({sig}) {{", "    // TODO", "  }"]
    block = "\n".join(stubs) + "\n"
    if end < 0:   # the class was renamed / removed: append a new one
        return code.rstrip("\n") + "\n\n" + f"class {cls}Events extends {cls}Designer {{" + block + "}\n"
    before = code[:end].rstrip(" \t")
    if before.endswith("{\n") or before.endswith("{"):
        block = block.lstrip("\n")
        if not before.endswith("\n"):
            before += "\n"
    elif not before.endswith("\n"):
        before += "\n"
    return before + block + code[end:]


