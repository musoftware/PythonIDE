def x_nav_items(v, owner: str) -> X | None:
    if v is None:
        return None
    c = _code(v)
    if c:
        return c
    items = []
    for it in v:
        if M.is_code(it):
            items.append(Raw(it["$code"]))
            continue
        if owner == "NavigationBar":
            items.append(Call("NavigationDestination", named=[
                ("icon", x_icon_widget(it.get("icon"))), ("selectedIcon", x_icon_widget(it.get("activeIcon"))),
                ("label", x_str(it.get("label", "")))]))
        else:
            items.append(Call("BottomNavigationBarItem", named=[
                ("icon", x_icon_widget(it.get("icon"))), ("activeIcon", x_icon_widget(it.get("activeIcon"))),
                ("label", x_str(it.get("label")))]))
    return Lst(items)


