def x_icon_widget(v) -> X | None:
    """An icon name used where a widget is expected (InputDecoration.prefixIcon, nav items)."""
    if v is None:
        return None
    return _code(v) or Call("Icon", [Lit(str(v))])


def x_image(v) -> X | None:
    if v is None:
        return None
    c = _code(v)
    if c:
        return c
    src = v.get("src", "")
    if v.get("source") == "network":
        return Call("NetworkImage", [x_str(src)])
    if v.get("source") == "file":
        return Raw(f"FileImage(File({dart_string(src)}))")
    return Call("AssetImage", [x_str(src)])


def x_gradient(v) -> X | None:
    if v is None:
        return None
    c = _code(v)
    if c:
        return c
    colors = Lst([x_color(c) for c in v.get("colors", [])])
    stops = Lst([x_num(s) for s in v["stops"]]) if v.get("stops") else None
    t = v.get("type", "linear")
    if t == "radial":
        return Call("RadialGradient", named=[("center", x_alignment(v.get("center"))),
                                             ("radius", x_num(v.get("radius"))), ("colors", colors),
                                             ("stops", stops)])
    if t == "sweep":
        return Call("SweepGradient", named=[("center", x_alignment(v.get("center"))),
                                            ("startAngle", x_num(v.get("startAngle"))),
                                            ("endAngle", x_num(v.get("endAngle"))), ("colors", colors),
                                            ("stops", stops)])
    return Call("LinearGradient", named=[("begin", x_alignment(v.get("begin"))), ("end", x_alignment(v.get("end"))),
                                         ("colors", colors), ("stops", stops)])


def x_shadows(v) -> X | None:
    if v is None:
        return None
    c = _code(v)
    if c:
        return c
    items = []
    for s in v:
        if M.is_code(s):
            items.append(Raw(s["$code"]))
            continue
        items.append(Call("BoxShadow", named=[("color", x_color(s.get("color"))), ("blurRadius", x_num(s.get("blur"))),
                                              ("spreadRadius", x_num(s.get("spread"))),
                                              ("offset", x_offset(s.get("offset")))]))
    return Lst(items)


