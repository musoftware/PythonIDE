@dataclass
class GeneratedScreen:
    class_name: str
    designer_path: str        # relative to the project folder (lib/screens/login.dart)
    designer_code: str
    events_path: str
    events_code: str          # the user file after adding missing stubs (== input when nothing changed)
    uses_anim: bool
    uses_google_fonts: bool
    warnings: list


def screen_files(screen: M.Screen) -> tuple[str, str]:
    s = M.snake(screen.name)
    return f"lib/screens/{s}.dart", f"lib/screens/{s}_events.dart"


def _theme_wrap(theme: dict, tree: X, ctx: GenContext) -> X:
    if not theme:
        return tree
    seed, bright = theme.get("seedColor"), theme.get("brightness")
    named = []
    bx = Lit("Brightness.dark" if bright == "dark" else "Brightness.light") if bright else None
    if seed:
        named.append(("colorScheme", Call("ColorScheme.fromSeed", named=[("seedColor", x_color(seed)),
                                                                          ("brightness", bx)], const_ctor=False)))
    elif bx is not None:
        named.append(("brightness", bx))
    if theme.get("background"):
        named.append(("scaffoldBackgroundColor", x_color(theme["background"])))
    if theme.get("fontFamily"):
        ctx.uses_google_fonts = True
        named.append(("textTheme", Call("GoogleFonts.getTextTheme", [x_str(theme["fontFamily"])], const_ctor=False)))
    if not named:
        return tree
    data = Call("ThemeData", named=named, const_ctor=False, multiline=True)
    body = Raw(f"Builder(builder: (context) => {tree.render()})")
    return Call("Theme", named=[("data", data), ("child", body)], const_ctor=False, multiline=True)


def _import_line(spec: str) -> str:
    """'package:x/y.dart' -> import line; 'dart:math as math' keeps the prefix."""
    uri, _, prefix = spec.partition(" as ")
    return f"import '{uri.strip()}' as {prefix.strip()};" if prefix.strip() else f"import '{uri.strip()}';"


def _handler_decl(name: str, sig: str) -> str:
    return f"  void {name}({sig});"


_USER_OVERRIDE_RX = re.compile(r"@override\s+(?:void|Future<void>|FutureOr<void>)\s+(\w+)\s*\(([^)]*)\)")


def user_overrides(user_code: str) -> dict[str, str]:
    """@override handler methods of the user file: name -> parameter list."""
    return {m.group(1): " ".join(m.group(2).split()) for m in _USER_OVERRIDE_RX.finditer(user_code or "")
            if m.group(1) not in STATE_METHODS}


def generate_screen(screen: M.Screen | dict, user_code: str | None = None, src_name: str = "",
                    format_code: bool = True) -> GeneratedScreen:
    scr = screen if isinstance(screen, M.Screen) else M.Screen(screen)
    cls = M.class_name(scr.name)
    dpath, epath = screen_files(scr)
    dfile, efile = Path(dpath).name, Path(epath).name
    ctx = GenContext()
    tree_x = TreeGen(ctx).node(scr.tree)
    tree_x = _theme_wrap(scr.data.get("theme") or {}, tree_x, ctx)
    code = scr.data.get("code") or {}
    # ---- handlers: used ones + @override methods of the user file (keeps it compiling after a removal)
    handlers = dict(ctx.handlers)
    for h, params in user_overrides(user_code or "").items():
        handlers.setdefault(h, params)
    # ---- imports
    imports = ["package:flutter/material.dart"]
    if ctx.uses_cupertino:
        imports.append("package:flutter/cupertino.dart")
    if ctx.uses_google_fonts:
        imports.append("package:google_fonts/google_fonts.dart")
    if ctx.uses_anim:
        imports.append("../radfx.dart")
    imports += [f"{M.snake(c)}.dart" for c in sorted(ctx.screens_used) if c != cls]
    extra = [i for i in (scr.data.get("imports") or []) if i not in imports]
    pkg = sorted(i for i in imports + extra if i.startswith(("dart:", "package:")))
    rel = [i for i in imports + extra if not i.startswith(("dart:", "package:"))]
    dart_imports = sorted(i for i in pkg if i.startswith("dart:"))
    pkg_imports = [i for i in pkg if i.startswith("package:")]
    L = [HEADER.format(src=src_name or f"{scr.name}{M.SCREEN_EXT}", events=efile).rstrip("\n")]
    L += [_import_line(i) for i in dart_imports]
    if dart_imports:
        L.append("")
    L += [_import_line(i) for i in pkg_imports]
    if rel:
        L.append("")
        L += [_import_line(i) for i in rel]
    L += ["", f"part '{efile}';", "",
          f"class {cls} extends StatefulWidget {{",
          f"  const {cls}({{super.key}});", "",
          f"  static const route = {dart_string(scr.route)};", "",
          "  @override",
          f"  State<{cls}> createState() => {cls}Events();",
          "}", "",
          f"/// The designed part of the {cls} screen; event handlers are in {cls}Events ({efile}).",
          f"abstract class {cls}Designer extends State<{cls}> {{"]
    fields = list(ctx.fields.values())
    for f in fields:
        if f.type == "TextEditingController":
            L.append(f"  final {f.name} = TextEditingController();")
        elif f.init == "null":
            L.append(f"  {f.type} {f.name};")
        else:
            L.append(f"  {f.type} {f.name} = {f.init};")
    if fields:
        L.append("")
    for h, params in handlers.items():
        L.append(_handler_decl(h, params))
    if handlers:
        L.append("")
    disp = [f for f in fields if f.dispose]
    if disp:
        L += ["  @override", "  void dispose() {"] + [f"    {f.name}.dispose();" for f in disp] + \
             ["    super.dispose();", "  }", ""]
    L += ["  @override", "  Widget build(BuildContext context) {"]
    prelude = (code.get("prelude") or "").strip()
    if prelude:
        L += ["    " + ln for ln in prelude.splitlines()]
    L.append(f"    return {tree_x.render()};")
    L.append("  }")
    members = (code.get("members") or "").strip()
    if members:
        L.append("")
        L += ["  " + ln if ln.strip() else "" for ln in members.splitlines()]
    L += ["}", ""]
    designer = "\n".join(L)
    if format_code:
        designer = format_dart(designer)
    events_code = add_missing_handlers(user_code, scr, ctx.handlers, cls, dfile)
    return GeneratedScreen(cls, dpath, designer, epath, events_code, ctx.uses_anim, ctx.uses_google_fonts,
                           ctx.warnings)


