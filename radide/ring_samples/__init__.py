# ======================================================================== Ring location
def find_ring_root(exe_hint: str = "") -> Path | None:
    """The Ring folder (the one holding bin/ring.exe and samples/), or None."""
    cands = []
    if exe_hint:
        p = Path(exe_hint)
        cands += [p.parent.parent, p.parent]
    env = os.environ.get("RING_HOME") or os.environ.get("RINGHOME")
    if env:
        cands.append(Path(env))
    w = shutil.which("ring")
    if w:
        cands.append(Path(w).resolve().parent.parent)
    cands += [Path(h) for h in RING_HINTS]
    for c in cands:
        try:
            if (c / "bin" / ("ring.exe" if os.name == "nt" else "ring")).exists():
                return c.resolve()
        except OSError:
            continue
    return None


def ring_exe(root: Path) -> Path:
    return Path(root) / "bin" / ("ring.exe" if os.name == "nt" else "ring")


# ======================================================================== helpers
def _read(p: Path) -> str:
    try:
        data = p.read_bytes()
    except OSError:
        return ""
    for enc in ("utf-8", "cp1256", "latin-1"):
        try:
            return data.decode(enc)
        except UnicodeDecodeError:
            continue
    return data.decode("latin-1", "replace")


def pretty(name: str) -> str:
    """"UsingQClipboard" -> "Using QClipboard", "ex1_basicwindow" -> "Ex1 basicwindow"."""
    s = re.sub(r"[_\-]+", " ", name).strip()
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z][a-z])", " ", s)
    s = re.sub(r"\s+", " ", s)
    return (s[:1].upper() + s[1:]) if s else name


def leading_comment(text: str, limit: int = 600) -> str:
    """The comment block at the top of a Ring file (# // /* */ or a leading string used as a comment)."""
    lines = text.lstrip("\ufeff").splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    if i < len(lines) and lines[i].strip().startswith("/*"):
        buf = []
        first = lines[i].strip()[2:]
        if "*/" in first:
            buf.append(first.split("*/")[0])
        else:
            buf.append(first)
            i += 1
            while i < len(lines) and "*/" not in lines[i]:
                buf.append(lines[i])
                i += 1
            if i < len(lines):
                buf.append(lines[i].split("*/")[0])
        out = [b.strip(" \t*") for b in buf]
    else:
        while i < len(lines):
            s = lines[i].strip()
            if s.startswith("#") or s.startswith("//"):
                out.append(s.lstrip("#/ \t-=*"))
                i += 1
            elif not s and out:
                break
            else:
                break
    text = "\n".join(x for x in out if x.strip() and not re.fullmatch(r"[=\-*#~_ ]+", x)).strip()
    return text[:limit]


def readme_text(folder: Path, limit: int = 600) -> str:
    for n in ("README.md", "readme.md", "ReadMe.md", "README.txt"):
        p = folder / n
        if p.exists():
            lines = []
            for ln in _read(p).splitlines():
                s = ln.strip()
                if not s or re.fullmatch(r"[=\-#*]+", s) or s.startswith("!["):
                    if lines and not s:
                        lines.append("")
                    continue
                lines.append(s.lstrip("# "))
            return "\n".join(lines).strip()[:limit]
    return ""


def loads_of(text: str) -> list[str]:
    no_comments = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return [m.group(1).strip() for m in _LOAD_RX.finditer(no_comments)]


def _strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"(?m)(#|//).*$", "", text)


def classify(libs: list[str], text: str, category: list[str]) -> str:
    low = {Path(x).name.lower() for x in libs}
    if low & GAME_LIBS:
        return "game"
    if low & GUI_LIBS or any(x.startswith("opengl") for x in low):
        return "gui"
    if low & WEB_LIBS or _WEB_RX.search(text):
        return "web"
    for c in category[1:3]:
        k = KIND_BY_FOLDER.get(c.lower())
        if k:
            return k
    if _GUI_RX.search(text):
        return "gui"
    return "console"


# ======================================================================== scanning
def scan(root: Path, include_docs: bool = True) -> list[dict]:
    """Every example of the installed Ring: samples, applications, extension tutorials, library tests
    and the code examples of the Ring documentation."""
    root = Path(root)
    entries: list[dict] = []
    for rel, top, source in SOURCES:
        base = root / rel
        if base.is_dir():
            entries += _scan_tree(root, base, top, source)
    if include_docs:
        entries += scan_docs(root)
    return entries


def _scan_tree(root: Path, base: Path, top: str, source: str) -> list[dict]:
    files = [p for p in base.rglob("*.ring") if not p.name.lower().startswith(("_radide_run", "_raddbg_run"))]
    info: dict[Path, dict] = {}
    loaded: set[Path] = set()
    for f in files:
        text = _read(f)
        local, libs = [], []
        for ld in loads_of(text):
            target = (f.parent / ld.replace("\\", "/"))
            try:
                target = target.resolve()
            except OSError:
                pass
            if target.exists() and target.suffix.lower() == ".ring":
                local.append(target)
                if target != f.resolve():
                    loaded.add(target)
            else:
                libs.append(ld.replace("\\", "/"))
        info[f.resolve()] = {"text": text, "local": local, "libs": libs, "path": f}
    by_dir: dict[Path, list[Path]] = {}
    for key, d in info.items():
        if key in loaded:
            continue                        # a helper file that another example loads
        by_dir.setdefault(d["path"].parent, []).append(key)
    out = []
    for folder, keys in sorted(by_dir.items(), key=lambda kv: str(kv[0]).lower()):
        rel_parts = folder.relative_to(base).parts
        single = len(keys) == 1 and rel_parts
        for key in sorted(keys, key=lambda k: str(k).lower()):
            d = info[key]
            deps, libs, seen, texts = [], list(d["libs"]), {key}, [d["text"]]
            stack = list(d["local"])
            while stack:                   # local files it loads, transitively
                t = stack.pop()
                if t in seen:
                    continue
                seen.add(t)
                deps.append(t)
                td = info.get(t)
                if td is None:
                    td = {"text": _read(t), "local": [], "libs": loads_of(_read(t))}
                texts.append(td["text"])
                libs += [x for x in td["libs"] if x not in libs]
                stack += td.get("local", [])
            dirs = [folder] + [p.parent for p in deps]
            try:
                common = Path(os.path.commonpath([str(x) for x in dirs]))
                common.relative_to(base)
            except ValueError:
                common = folder
            if single:
                category = [top, *rel_parts[:-1]]
                title = pretty(rel_parts[-1])
            else:
                category = [top, *rel_parts]
                title = pretty(key.stem)
            stripped = _strip_comments("\n".join(texts))
            desc = leading_comment(d["text"]) or (readme_text(folder) if source == "applications" or single else "")
            kind = classify(libs, stripped, category)
            rel_folder = folder.relative_to(root).as_posix()
            files_rel = [d["path"].name] + sorted({os.path.relpath(p, folder).replace("\\", "/") for p in deps})
            out.append({
                "id": f"{rel_folder}/{d['path'].name}",
                "title": title,
                "category": category,
                "source": source,
                "folder": rel_folder,
                "main": d["path"].name,
                "files": files_rel,
                "root": common.relative_to(root).as_posix(),
                "description": desc,
                "kind": kind,
                "libs": sorted({Path(x).name.lower() for x in libs}),
                "input": bool(kind == "console" and _INPUT_RX.search(stripped)),
            })
    return out


# ======================================================================== documentation examples
_HEAD_CHARS = set("=-~^*#\"'`+.:_")


def parse_doc(text: str) -> tuple[str, list[dict]]:
    """(chapter title, examples) of one Sphinx source (.txt/.rst) of the Ring documentation.
    Example: {"index", "line" (1-based line of the code-block directive), "heading", "code",
    "expected" (the "Output:" block after it, or None), "intro" (the paragraph before it)}."""
    lines = text.splitlines()
    title = ""
    heading = ""
    para: list[str] = []
    last_para = ""
    examples: list[dict] = []
    section_para = ""            # first real paragraph of the current section (for "Example:" intros)
    i = 0
    n = len(lines)

    def trivial(s: str) -> bool:
        return bool(re.fullmatch(r"\s*(\w+(\s+\w+)?\s*(\(\d+\))?\s*:?)?\s*", s or ""))

    def is_rule(s: str) -> bool:
        s = s.rstrip()
        return len(s) >= 3 and len(set(s)) == 1 and s[0] in _HEAD_CHARS

    def block_at(j: int) -> tuple[list[str], int]:
        """Indented content of a directive at line j-1; returns (lines, next index)."""
        body: list[str] = []
        k = j
        while k < n and not lines[k].strip():
            k += 1
        if k >= n:
            return body, k
        ind = len(lines[k]) - len(lines[k].lstrip())
        if ind == 0:
            return body, k
        while k < n:
            ln = lines[k]
            if ln.strip() and (len(ln) - len(ln.lstrip())) < ind:
                break
            body.append(ln[ind:] if len(ln) >= ind else ln.strip())
            k += 1
        while body and not body[-1].strip():
            body.pop()
        return body, k

    while i < n:
        s = lines[i].rstrip()
        st = s.strip()
        if i + 1 < n and st and not st.startswith("..") and is_rule(lines[i + 1]) \
                and len(lines[i + 1].rstrip()) >= len(st) - 1 and not is_rule(s):
            heading = st
            if not title:
                title = st
            para, last_para, section_para = [], "", ""
            i += 2
            continue
        if is_rule(s):
            i += 1
            continue
        if st.startswith(".. code-block::") or st.startswith(".. code::"):
            lang = st.split("::", 1)[1].strip().lower()
            body, nxt = block_at(i + 1)
            intro = " ".join(para).strip() or last_para
            is_output = bool(re.match(r"^\s*(the\s+)?output\b", intro, re.I))
            is_syntax = bool(re.match(r"^(syntax|the syntax)\b", intro, re.I))
            if trivial(intro) and section_para:
                intro = section_para
            if lang == "ring" and body and not is_output and not is_syntax:
                expected = None
                k = nxt
                while k < n and not lines[k].strip():
                    k += 1
                if k < n and re.match(r"^\s*(the\s+)?output", lines[k], re.I) and lines[k].strip().endswith(":"):
                    k += 1
                    while k < n and not lines[k].strip():
                        k += 1
                    if k < n and lines[k].strip().startswith(".. code-block::"):
                        ob, _ = block_at(k + 1)
                        expected = "\n".join(ob)
                examples.append({"index": len(examples) + 1, "line": i + 1, "heading": heading,
                                 "code": "\n".join(body) + "\n", "expected": expected,
                                 "intro": re.sub(r"[`*]|:ref:|\.\. \w+::", "", intro).strip()[:400]})
            para, last_para = [], ""
            i = nxt
            continue
        if st.startswith(".."):
            _b, nxt = block_at(i + 1)
            if "code" in st:
                para, last_para = [], ""
            i = max(nxt, i + 1)
            continue
        if not st:
            if para:
                last_para = " ".join(para).strip()
                if not section_para and not trivial(last_para):
                    section_para = last_para
            para = []
        else:
            para.append(st)
        i += 1
    return title, examples


def scan_docs(root: Path) -> list[dict]:
    base = Path(root) / DOCS_SOURCES
    out = []
    if not base.is_dir():
        return out
    for f in sorted(base.glob("*.txt")):
        title, examples = parse_doc(_read(f))
        if not examples:
            continue
        chapter = title or pretty(f.stem)
        counts: dict[str, int] = {}
        for ex in examples:
            h = ex["heading"] or chapter
            counts[h] = counts.get(h, 0) + 1
            t = h if counts[h] == 1 else f"{h} ({counts[h]})"
            code = ex["code"]
            libs = loads_of(code)
            stripped = _strip_comments(code)
            kind = classify(libs, stripped, ["Documentation"])
            out.append({
                "id": f"docs/{f.stem}/{ex['index']}",
                "title": t,
                "category": ["Documentation", chapter],
                "source": "docs",
                "folder": "",
                "main": "example.ring",
                "files": ["example.ring"],
                "root": "",
                "description": ex["intro"],
                "kind": kind,
                "libs": sorted({Path(x).name.lower() for x in libs}),
                "input": bool(kind == "console" and _INPUT_RX.search(stripped)),
                "doc": {"file": f"{DOCS_SOURCES}/{f.name}", "line": ex["line"], "index": ex["index"]},
                "has_expected": ex["expected"] is not None,
            })
    return out


_DOC_CACHE: dict[str, list[dict]] = {}


def doc_example(root: Path, entry: dict) -> dict | None:
    """The code (+ expected output) of a documentation example, read from the installed docs."""
    d = entry.get("doc") or {}
    f = Path(root) / d.get("file", "")
    key = str(f)
    if key not in _DOC_CACHE:
        _DOC_CACHE[key] = parse_doc(_read(f))[1] if f.exists() else []
    exs = _DOC_CACHE[key]
    for ex in exs:                       # the line is the stable key; the index is the fallback
        if ex["line"] == d.get("line"):
            return ex
    idx = d.get("index", 0)
    return exs[idx - 1] if 0 < idx <= len(exs) else None


# ======================================================================== code / paths
def main_path(root: Path, entry: dict) -> Path:
    return Path(root) / entry["folder"] / entry["main"]


def code_of(root: Path, entry: dict) -> str:
    if entry.get("source") == "docs":
        ex = doc_example(root, entry)
        return ex["code"] if ex else ""
    return _read(main_path(root, entry))


def docs_work_dir() -> Path:
    """Where documentation examples are written to run them (never inside the Ring folder)."""
    base = Path(os.environ.get("TEMP") or os.environ.get("TMP") or Path.home()) / "RAD IDE" / "RingDocExamples"
    base.mkdir(parents=True, exist_ok=True)
    return base


def materialize_doc(root: Path, entry: dict, folder: Path | None = None) -> Path:
    """Write a documentation example to *folder* (default: a temp folder); returns the .ring file."""
    ex = doc_example(root, entry)
    if folder is None:
        folder = docs_work_dir() / entry["id"].replace("/", "_")
    folder.mkdir(parents=True, exist_ok=True)
    f = folder / entry["main"]
    head = f"# {entry['title']}\n# From the Ring documentation: {entry['doc']['file'].split('/')[-1]}" \
           f" (line {entry['doc']['line']})\n\n"
    f.write_text(head + (ex["code"] if ex else "# example not found in the installed documentation\n"),
                 encoding="utf-8")
    return f


def run_target(root: Path, entry: dict) -> tuple[Path, Path]:
    """(file to run, working folder) for running *entry* in place (docs: a temp copy)."""
    if entry.get("source") == "docs":
        f = materialize_doc(root, entry)
        return f, f.parent
    f = main_path(root, entry)
    return f, f.parent


def default_projects_dir() -> Path:
    docs = Path.home() / "Documents"
    try:
        from PyQt6.QtCore import QStandardPaths
        loc = QStandardPaths.writableLocation(QStandardPaths.StandardLocation.DocumentsLocation)
        if loc:
            docs = Path(loc)
    except Exception:  # noqa: BLE001 - core works without Qt
        pass
    return docs / "RAD IDE Projects" / "RingSamples"


_COPY_SKIP = shutil.ignore_patterns("_radide_run.ring", "_raddbg_run.ring", "*.exe.tmp", ".git")
PROJECT_LANGUAGE = "ring-script"


def safe_name(s: str) -> str:
    s = re.sub(r"[^\w\-. ]+", "_", s).strip(" ._")
    return s[:60] or "RingSample"


def make_project(root: Path, entry: dict, dest_parent: Path | None = None, name: str | None = None) -> Path:
    """Copy the sample into a new folder (Documents\\RAD IDE Projects\\RingSamples\\<name>) and write a
    project.radproj (language ring-script: runs the sample's main file). The Ring folder is only read.
    Returns the project folder."""
    root = Path(root)
    dest_parent = Path(dest_parent or default_projects_dir())
    base_name = safe_name(name or entry["title"])
    dest = dest_parent / base_name
    k = 2
    while dest.exists():
        dest = dest_parent / f"{base_name}_{k}"
        k += 1
    if entry.get("source") == "docs":
        materialize_doc(root, entry, dest)
        main_rel = entry["main"]
        modules = [main_rel]
    else:
        src_root = root / (entry.get("root") or entry["folder"])
        src_root_r = src_root.resolve()
        ring_r = root.resolve()
        if src_root_r == ring_r or ring_r not in src_root_r.parents:
            raise ValueError(f"refusing to copy {src_root}")
        shutil.copytree(src_root, dest, ignore=_COPY_SKIP)
        main_abs = main_path(root, entry).resolve()
        main_rel = main_abs.relative_to(src_root_r).as_posix()
        modules = [main_rel] + [
            (Path(main_rel).parent / f).as_posix() for f in entry.get("files", [])[1:]]
        modules = [os.path.normpath(m).replace("\\", "/") for m in modules]
        modules = [m for i, m in enumerate(modules) if m not in modules[:i] and not m.startswith("..")]
    startup = main_rel[:-5] if main_rel.lower().endswith(".ring") else main_rel
    proj = {"name": dest.name, "language": PROJECT_LANGUAGE, "forms": [], "startup": startup,
            "modules": modules,
            "ring_sample": {"id": entry["id"], "title": entry["title"], "kind": entry.get("kind", ""),
                            "from": str(main_path(root, entry)) if entry.get("source") != "docs"
                            else str(root / entry["doc"]["file"])}}
    (dest / "project.radproj").write_text(json.dumps(proj, indent=2), encoding="utf-8")
    return dest


