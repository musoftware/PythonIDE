"""Ring Samples gallery - the core (no Qt).

Everything is read from the *installed* Ring (C:\\ring\\ring by default); nothing of Ring is copied into
the repository. ``index.json`` next to this file is generated by ``tools/index_ring_samples.py`` (scan +
optional headless test run); when it is missing or was made for another Ring folder the gallery scans
the installed Ring live with :func:`scan`.

An entry (one runnable example) is a dict::

    id          "samples/UsingQt/Clipboard/UsingQClipboard.ring" | "docs/lists/3"
    title       "Using QClipboard"
    category    ["Samples", "UsingQt", "Clipboard"]
    source      samples | applications | extensions | libraries | docs
    folder      folder of the main file, relative to the Ring root ("" for docs)
    main        main file name (docs: "example.ring")
    files       the main file + the local files it loads (relative to *folder*)
    root        folder that holds main + every loaded file (what "Open as Project" copies)
    description leading comments of the main file / README / the text before a doc example
    kind        console | gui | game | web
    libs        Ring libraries it loads ("guilib.ring", "raylib.ring" ...)
    input       True when it reads the keyboard (give / getchar ...)
    doc         docs only: {"file": "documents/build/html/_sources/x.txt", "line": 123}
    test        {"status": ok|input|fail|timeout, "reason": ..., "seconds": ..., "output": ...} (after --test)
"""
