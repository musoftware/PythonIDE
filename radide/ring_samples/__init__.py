def error_reason(output: str) -> str:
    """A short, readable reason from Ring's error output."""
    m = _ERR_RX.search(output)
    low = output.lower()
    if "can't open file" in low:
        f = re.search(r"Can't open file\s+([^\r\n]+)", output, re.I)
        name = f.group(1).strip() if f else ""
        return f"missing file/library: {name}" if name else "missing file"
    if "dynamic library" in low or "loadlib" in low or ("dll" in low and "error" in low):
        line = next((ln for ln in output.splitlines() if "librar" in ln.lower() or "dll" in ln.lower()), "")
        return f"missing library: {line.strip()[:160]}"
    r = _RAISE_RX.search(output)
    if r and not m:
        return f"the program raised an error: {r.group(1).strip()[:140]}"
    if m:
        code = f"{m.group(1)}{m.group(2)}"
        msg = m.group(3).strip()
        if code == "R3" or "without definition" in msg.lower():
            return f"calls an undefined function ({code}): {msg[:140]}"
        if m.group(1) == "C":
            return f"compile error ({code}): {msg[:140]}"
        return f"runtime error ({code}): {msg[:140]}"
    g = _LINE_ERR_RX.search(output)                 # "Line 15 Can't change a constant" (raise in a library)
    if g:
        return f"the program raised an error: {g.group(1).strip()[:140]}"
    tail = [ln for ln in output.strip().splitlines() if ln.strip()]
    return tail[-1][:160] if tail else ""


def classify_run(entry: dict, output: str, rc: int | None, timed_out: bool, seconds: float,
                 expected: str | None = None) -> dict:
    """The test record of one headless run."""
    kind = entry.get("kind", "console")
    has_err = bool(_ERR_RX.search(output) or _RAISE_RX.search(output)) or "can't open file" in output.lower()
    res = {"seconds": round(seconds, 2)}
    head = output.strip()[:240]
    if head:
        res["output"] = head
    if timed_out:
        if has_err:
            res.update(status="fail", reason=error_reason(output))
        elif kind in ("gui", "game"):
            res.update(status="ok", reason="window opened; closed by the test after %ds" % int(seconds))
        elif kind == "web":
            res.update(status="ok", reason="server started; stopped by the test")
        elif entry.get("input"):
            res.update(status="input", reason="waits for keyboard input")
        else:
            res.update(status="timeout", reason="still running after %ds (long computation or endless loop)"
                       % int(seconds))
        return res
    if has_err or (rc not in (0, None)):
        reason = error_reason(output) or f"exit code {rc}"
        if entry.get("input"):
            res.update(status="input", reason="reads keyboard input (test input gave: %s)" % reason)
        else:
            res.update(status="fail", reason=reason)
        return res
    if entry.get("input"):
        res.update(status="input", reason="reads keyboard input (finished with the test input)")
    elif kind in ("gui", "game"):
        res.update(status="ok", reason="finished without opening a lasting window")
    else:
        res.update(status="ok")
    if expected is not None:
        norm = lambda s: re.sub(r"\s+", " ", s).strip()  # noqa: E731
        res["matches_doc_output"] = norm(expected) == norm(output) or norm(expected) in norm(output)
    return res


