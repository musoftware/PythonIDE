"""Native mode of RAD C# projects: the program is a real WinForms exe, no GUI Bridge and no Python (no Qt here).

project.radproj ``"dotnetRuntime"``: "native" (default) or "bridge" (the IDE draws the form, the program is a
console process - the previous behaviour, kept for projects that want it).

In native mode _build/csharp/RadApp.csproj (still the NuGet manifest and the project csharp-ls / the quick fixes
read) is a WinExe that

* compiles the project's *.cs: the user's code, <Form>_designer.cs (the RadControl fields: lblOut.Text = "Hi") and
  <Form>.Designer.cs - the WinForms InitializeComponent generated from <Form>.form (read-only, like Visual
  Studio's Form1.Designer.cs; radide/deploy/native/dotnet_winforms.py writes the code);
* compiles gen/RadProgram.g.cs (Main: registers the forms, runs the startup form);
* references RadIDE.Runtime.dll (radide/dotnet/runtime_lib.py): Rad.MsgBox / InputBox / Show / radcall, RadControl,
  RadEvent, the form host - the same API as the GUI Bridge client, so the code does not change;
* has System.Windows.Forms / System.Drawing in its implicit usings (MessageBox.Show(...) works as in Visual Studio).

F5 runs bin/native/<Name>.exe (radide/dotnet/native_run.py), Build > Publish still makes the single-file exe.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

MODE_KEY = "dotnetRuntime"
NATIVE, BRIDGE = "native", "bridge"
MARKER = "radmode:native"
GEN_DIR = "gen"
OUT_DIR = "bin/native/"
DESIGNER_SUFFIX = ".Designer.cs"
DESIGNER_HEADER = "// <auto-generated> RAD IDE native WinForms designer code"

NATIVE_CSPROJ = """<Project Sdk="Microsoft.NET.Sdk">
  <!-- RAD IDE build project ({marker}): a real WinForms exe that references RadIDE.Runtime.dll.
       Compiles the project's *.cs (with the generated <Form>.Designer.cs) and gen/*.cs. NuGet packages are added
       here (Project > Packages, or: dotnet add _build/csharp/RadApp.csproj package <Name>).
       Switch back to the GUI Bridge: "{key}": "bridge" in project.radproj. -->
  <PropertyGroup>
    <OutputType>WinExe</OutputType>
    <TargetFramework>{tfm}-windows</TargetFramework>
    <UseWindowsForms>true</UseWindowsForms>
    <AssemblyName>{name}</AssemblyName>
    <RootNamespace>RadApp</RootNamespace>
    <StartupObject>RadNative.RadProgram</StartupObject>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>disable</Nullable>
    <LangVersion>latest</LangVersion>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <OutDir>{out}</OutDir>
    <GenerateDocumentationFile>false</GenerateDocumentationFile>
    <SatelliteResourceLanguages>en</SatelliteResourceLanguages>
    <NoWarn>$(NoWarn);CS0168;CS0219;CS8981;CS1998;CS0162;CS0414;CS0649;CS0169;CA1416;WFO1000;WFAC010</NoWarn>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="../../*.cs" />
    <Compile Include="{gen}/*.cs" />
    <Using Include="Rad" Static="true" />
    <Reference Include="RadIDE.Runtime">
      <HintPath>{runtime}</HintPath>
    </Reference>
{refs}  </ItemGroup>
{packages}</Project>
"""

_PKG_RX = re.compile(r"[ \t]*<PackageReference\b[^>]*?/>|[ \t]*<PackageReference\b[^>]*>.*?</PackageReference>", re.S)


# ====================================================================== mode
def _radproj(folder: Path) -> Path:
    return Path(folder) / "project.radproj"


def mode(folder: Path) -> str:
    """"native" for a C# program with forms; "bridge" when project.radproj says so, and for class libraries and
    programs without C# forms (a console program, a module other languages call with radcall)."""
    from ..model import Project
    try:
        project = Project.load(Path(folder))
    except Exception:  # noqa: BLE001 - no / broken project.radproj
        return BRIDGE
    if str(project.extra.get(MODE_KEY, NATIVE)).lower() == BRIDGE or project.kind != "app":
        return BRIDGE
    # forms of several languages share the IDE's form host (GUI Bridge): only all-C# programs run natively
    if project.language != "csharp-bridge" or not project.forms or \
            any(project.form_language(n) != "csharp-bridge" for n in project.forms):
        return BRIDGE
    return NATIVE


def is_native(folder: Path) -> bool:
    return mode(folder) == NATIVE


def set_mode(folder: Path, value: str) -> None:
    """Write "dotnetRuntime" into project.radproj (the other keys are kept as they are)."""
    p = _radproj(folder)
    data = json.loads(p.read_text(encoding="utf-8-sig"))
    data[MODE_KEY] = BRIDGE if value == BRIDGE else NATIVE
    p.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


# ====================================================================== csproj
def csproj_is_native(text: str) -> bool:
    return MARKER in text


def packages_xml(text: str) -> list[str]:
    """The <PackageReference> elements of an existing csproj (kept when the template changes)."""
    return [m.group(0).strip() for m in _PKG_RX.finditer(text or "")]


def with_packages(template: str, packages: list[str]) -> str:
    """*template* (a csproj) with *packages* in their own <ItemGroup> before </Project>."""
    if not packages:
        return template
    block = "  <ItemGroup>\n" + "".join(f"    {p}\n" for p in packages) + "  </ItemGroup>\n"
    i = template.rstrip().rfind("</Project>")
    return template[:i] + block + template[i:]


def exe_name(folder: Path) -> str:
    try:
        name = json.loads(_radproj(folder).read_text(encoding="utf-8-sig")).get("name") or Path(folder).name
    except (OSError, ValueError):
        name = Path(folder).name
    name = re.sub(r"[^A-Za-z0-9_.-]", "_", name).strip("._") or "RadApp"
    return name


def _references(folder: Path, forms) -> str:
    """ProjectReference / Reference of the control libraries the forms use (RadIDE.Controls ...)."""
    from ..deploy.native.dotnet_winforms import control_map
    cmap = control_map(folder)
    used = {(cmap.get(c.type) or {}).get("reference") for f in forms for c in f.controls}
    out = []
    for name, r in sorted(cmap["__references__"].items()):
        if name not in used:
            continue
        if r.get("project") and Path(r["project"]).is_file():
            prop = r.get("targetsProperty")
            extra = f' AdditionalProperties="{prop}=net8.0-windows"' if prop else ""
            out.append(f'    <ProjectReference Include="{r["project"]}"{extra} />\n')
        elif r.get("dll") and Path(r["dll"]).is_file():
            out.append(f'    <Reference Include="{Path(r["dll"]).stem}"><HintPath>{r["dll"]}</HintPath></Reference>\n')
    return "".join(out)


def csproj_text(folder: Path, tfm: str, runtime_dll: Path, packages: list[str], forms=()) -> str:
    text = NATIVE_CSPROJ.format(marker=MARKER, key=MODE_KEY, tfm=tfm, name=exe_name(folder), out=OUT_DIR, gen=GEN_DIR,
                                runtime=runtime_dll, refs=_references(folder, forms), packages="")
    return with_packages(text, packages)


# ====================================================================== generated code
def designer_path(folder: Path, form: str) -> Path:
    return Path(folder) / f"{form}{DESIGNER_SUFFIX}"


def is_generated_designer(p: Path) -> bool:
    try:
        with open(p, encoding="utf-8-sig", errors="replace") as fh:
            return fh.readline().startswith(DESIGNER_HEADER)
    except OSError:
        return False


def _write_if_changed(p: Path, text: str, bom: bool = True) -> None:
    try:
        if p.read_text(encoding="utf-8-sig") == text:
            return
    except OSError:
        pass
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8-sig" if bom else "utf-8")


def generate(folder: Path, build_dir: Path) -> list[str]:
    """Write <Form>.Designer.cs for every C# form and gen/RadProgram.g.cs; remove the generated designers of forms
    that are gone. Returns the problems the native build reports (animations it cannot play ...), as notes."""
    from ..deploy.native import dotnet_winforms as D
    from ..deploy.native._forms import load_forms
    from ..languages import get_plugin
    from ..model import Project
    folder = Path(folder)
    project = Project.load(folder)
    forms = load_forms(folder, project, "csharp-bridge")
    plugin = get_plugin("csharp-bridge")
    handlers = set(plugin.handlers_in_project(folder, project))
    cmap = D.control_map(folder)
    names = set()
    for f in forms:
        names.add(f.name.lower())
        code_file = folder / plugin.code_file(f.name)       # <Form>_designer.cs (RadControl fields), as the IDE
        user = code_file.read_text(encoding="utf-8", errors="replace") if code_file.is_file() else ""   # writes it
        _write_if_changed(folder / plugin.designer_file(f.name), plugin.generate_designer(f, user), bom=False)
        body = D._Gen(f, handlers, cmap).code()
        text = "\n".join([
            f"{DESIGNER_HEADER} from {f.name}.form - do not edit, changes are lost </auto-generated>",
            f"// The {f.name} form as WinForms code (like Visual Studio's {f.name}.Designer.cs). Change the form",
            "// in the designer; the event handlers (<Control>_<Event>) are in the form's code file.",
            "#nullable disable",
            "namespace RadNative",
            "{",
            *["    " + ln if ln else "" for ln in body.splitlines()],
            "}", ""])
        _write_if_changed(designer_path(folder, f.name), text)
    for p in folder.glob("*" + DESIGNER_SUFFIX):
        if p.name[:-len(DESIGNER_SUFFIX)].lower() not in names and is_generated_designer(p):
            p.unlink()
    from types import SimpleNamespace
    cfg = SimpleNamespace(app_name=project.name)
    _write_if_changed(Path(build_dir) / GEN_DIR / "RadProgram.g.cs",
                      D.program_cs(project, cfg, forms, None, sorted(handlers)))
    return [msg for f in forms for msg in _motion_notes(f)]


def _motion_notes(form) -> list[str]:
    try:
        from ..motion import native_plan
        return list(native_plan.notes(form, "winforms"))
    except Exception:  # noqa: BLE001
        return []


def remove_generated(folder: Path) -> None:
    """Bridge mode: the generated <Form>.Designer.cs would not compile there (no WinForms)."""
    for p in Path(folder).glob("*" + DESIGNER_SUFFIX):
        if is_generated_designer(p):
            p.unlink()


def form_inputs(folder: Path) -> list[Path]:
    """Files the generated code depends on (for the up-to-date check)."""
    folder = Path(folder)
    out = sorted(folder.glob("*.form")) + [_radproj(folder)]
    if (folder / "dotnet.controls.json").is_file():
        out.append(folder / "dotnet.controls.json")
    return out


def exe_path(folder: Path, build_dir: Path) -> Path:
    return Path(build_dir) / OUT_DIR / f"{exe_name(folder)}.exe"
