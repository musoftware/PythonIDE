"""Modification report of an ECU project: what changed against the original (maps, byte ranges, checksums),
as plain text (written beside every Build output) or as a self-contained HTML page."""
from __future__ import annotations

import html

from ..checksum.blocks import hx

MAX_RANGES = 400
MAX_BYTES_SHOWN = 32


def _hexs(b: bytes) -> str:
    s = b[:MAX_BYTES_SHOWN].hex(" ").upper()
    return s + (" ..." if len(b) > MAX_BYTES_SHOWN else "")


def _collect(ep, data: bytes, results, against: str = "original"):
    from .model import sha256
    orig = ep.version_bytes(against)
    diff = ep.diff(against, "work", orig, data)
    head = [("Project", ep.name), ("Original", ep.original or "-"),
            ("Original SHA-256", ep.original_sha256 or "-"), ("Compared with", ep.label(against)),
            ("Modified image SHA-256", sha256(bytes(data))), ("Size", f"{len(data):,} bytes"),
            ("Changed", diff.summary())]
    return orig, diff, head


def modification_report(ep, data: bytes, results=None, against: str = "original") -> str:
    from .model import now
    orig, diff, head = _collect(ep, data, results, against)
    out = [f"Modification report - {ep.name}", f"Generated by RAD IDE {now()}", ""]
    out += [f"{k}: {v}" for k, v in head]
    out += ["", "Note: changes to vehicle software can affect safety, warranty and emissions legality. "
                "Keep the original and follow local laws.", ""]
    if diff.maps:
        out.append(f"Changed maps ({len(diff.maps)}):")
        out += ["  " + m.line() for m in diff.maps]
        out.append("")
    if results:
        out.append("Checksums:")
        out += ["  " + r.line() for r in results]
        out.append("")
    out.append(f"Changed byte ranges ({len(diff.ranges)}):")
    for s, e in diff.ranges[:MAX_RANGES]:
        tag = ""
        if (s, e) in diff.checksum_spans:
            tag = "  [checksum]"
        elif (s, e) in diff.unmapped and diff.maps:
            tag = "  [outside known maps]"
        out.append(f"  {hx(s)}-{hx(e - 1)} ({e - s} bytes){tag}")
        out.append(f"     old: {_hexs(orig[s:e])}")
        out.append(f"     new: {_hexs(bytes(data[s:e]))}")
    if len(diff.ranges) > MAX_RANGES:
        out.append(f"  ... {len(diff.ranges) - MAX_RANGES} more ranges")
    if ep.versions:
        out += ["", "Versions:"]
        out += [f"  {v.id} {v.name} ({v.created}){' - ' + v.note if v.note else ''}" for v in ep.versions]
    return "\n".join(out) + "\n"


def modification_report_html(ep, data: bytes, results=None, against: str = "original") -> str:
    from .model import now
    orig, diff, head = _collect(ep, data, results, against)
    e = html.escape
    rows = "".join(f"<tr><th>{e(k)}</th><td>{e(str(v))}</td></tr>" for k, v in head)
    parts = [f"""<!doctype html><html><head><meta charset="utf-8"><title>Modification report - {e(ep.name)}</title>
<style>body{{font:14px Segoe UI,Arial,sans-serif;margin:24px;color:#222;background:#fff}}
table{{border-collapse:collapse;margin:8px 0 18px}}td,th{{border:1px solid #ccc;padding:4px 8px;text-align:left;
vertical-align:top}}th{{background:#f3f3f3}}code{{font:12px Consolas,monospace}}.n{{color:#8a5a00}}
.ok{{color:#176c17}}.bad{{color:#b00020}}</style></head><body>
<h1>Modification report - {e(ep.name)}</h1><p>Generated by RAD IDE {e(now())}</p><table>{rows}</table>
<p class="n">Changes to vehicle software can affect safety, warranty and emissions legality. Keep the original
and follow local laws.</p>"""]
    if diff.maps:
        parts.append("<h2>Changed maps</h2><table><tr><th>Map</th><th>Kind</th><th>Address</th><th>Cells changed"
                     "</th><th>Largest change</th></tr>")
        for m in diff.maps:
            parts.append(f"<tr><td>{e(m.name)}</td><td>{e(m.kind)}</td><td><code>{hx(m.address)}</code></td>"
                         f"<td>{m.cells_changed}/{m.cells}</td><td>{m.max_delta:+g} {e(m.unit)}</td></tr>")
        parts.append("</table>")
    if results:
        parts.append("<h2>Checksums</h2><table><tr><th>Block</th><th>Stored at</th><th>Result</th></tr>")
        for r in results:
            cls = "ok" if r.ok else "bad"
            parts.append(f"<tr><td>{e(r.name)}</td><td><code>{hx(r.store)}</code></td>"
                         f"<td class='{cls}'>{e(r.line().split(': ', 1)[-1])}</td></tr>")
        parts.append("</table>")
    parts.append(f"<h2>Changed byte ranges ({len(diff.ranges)})</h2><table><tr><th>Range</th><th>Bytes</th>"
                 "<th>Old</th><th>New</th></tr>")
    for s, en in diff.ranges[:MAX_RANGES]:
        parts.append(f"<tr><td><code>{hx(s)}-{hx(en - 1)}</code></td><td>{en - s}</td>"
                     f"<td><code>{e(_hexs(orig[s:en]))}</code></td><td><code>{e(_hexs(bytes(data[s:en])))}</code>"
                     "</td></tr>")
    parts.append("</table></body></html>")
    return "\n".join(parts)


__all__ = ["modification_report", "modification_report_html"]
