"""Analyze in Ghidra: headless import of a firmware image with the detected language and base address, then
export the function list and decompiled C (shown read-only in the IDE).

Uses the Ghidra the IDE already finds / downloads for the EXE importer (radide/importers/exe/native.py:
GHIDRA_HOME, %LOCALAPPDATA%\\RADIDE\\tools\\ghidra*) and a JDK found the same way. Raw images use Ghidra's
BinaryLoader with ``-loader-baseAddr``; ELF files use Ghidra's ELF loader. Entry points (vector table entries,
reset vector) are passed to the export script, which disassembles and creates functions there first.
"""
from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from .arch import ARCH_INFO

SCRIPT_NAME = "RadFirmwareExport.java"
GHIDRA_SCRIPT = r'''
import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.address.*;
import java.io.*;

public class RadFirmwareExport extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] a = getScriptArgs();
        String out = a[0];
        int maxDecomp = a.length > 1 ? Integer.parseInt(a[1]) : 200;
        String entries = a.length > 2 ? a[2] : "";
        AddressSpace sp = currentProgram.getAddressFactory().getDefaultAddressSpace();
        if (entries.length() > 0) {
            for (String e : entries.split(",")) {
                if (e.isEmpty()) continue;
                try {
                    Address ad = sp.getAddress(Long.parseUnsignedLong(e, 16));
                    if (getFunctionAt(ad) == null) {
                        disassemble(ad);
                        createFunction(ad, null);
                    }
                } catch (Exception ex) { }
            }
            analyzeChanges(currentProgram);
        }
        PrintWriter w = new PrintWriter(new OutputStreamWriter(new FileOutputStream(out), "UTF-8"));
        w.println("//@@LANGUAGE " + currentProgram.getLanguageID() + " " + currentProgram.getImageBase());
        FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
        java.util.List<Function> all = new java.util.ArrayList<>();
        while (it.hasNext()) {
            Function f = it.next();
            if (f.isExternal()) continue;
            all.add(f);
            w.println("//@@FUNC " + f.getName() + " " + f.getEntryPoint() + " " + f.getBody().getNumAddresses());
        }
        DecompInterface d = new DecompInterface();
        d.openProgram(currentProgram);
        int n = 0;
        for (Function f : all) {
            if (monitor.isCancelled() || n >= maxDecomp) break;
            if (f.isThunk()) continue;
            DecompileResults r = d.decompileFunction(f, 30, monitor);
            if (r != null && r.decompileCompleted()) {
                w.println("//@@FUNCTION " + f.getName() + " " + f.getEntryPoint());
                w.println(r.getDecompiledFunction().getC());
                n++;
            }
        }
        w.close();
    }
}
'''


@dataclass
class GhidraFunction:
    name: str
    address: int
    size: int = 0


@dataclass
class GhidraResult:
    functions: list[GhidraFunction] = field(default_factory=list)
    decompiled: dict[str, str] = field(default_factory=dict)       # name -> C
    language: str = ""
    error: str = ""
    log: str = ""
    seconds: float = 0.0

    @property
    def ok(self) -> bool:
        return not self.error and bool(self.functions)

    def c_text(self) -> str:
        parts = [f"// Decompiled by Ghidra ({self.language}) - read-only view generated by RAD IDE\n"]
        for f in self.functions:
            c = self.decompiled.get(f.name)
            if c:
                parts.append(f"// ---- {f.name} @ 0x{f.address:X}\n{c.strip()}\n")
        return "\n".join(parts)


def find_ghidra() -> str | None:
    try:
        from ...importers.exe.native import find_ghidra as _f
        return _f()
    except Exception:  # noqa: BLE001 - the importer is optional
        return None


def find_jdk_for(headless: str) -> str | None:
    try:
        from ...importers.exe.native import _ghidra_java_min, find_jdk
        return find_jdk(_ghidra_java_min(headless))
    except Exception:  # noqa: BLE001
        return None


def language_for(arch: str) -> str:
    return ARCH_INFO.get(arch, {}).get("ghidra", "")


def available() -> tuple[bool, str]:
    g = find_ghidra()
    if not g:
        return False, ("Ghidra is not installed. Download it from Tools > Import > EXE (Ghidra) or put it in "
                       "%LOCALAPPDATA%\\RADIDE\\tools\\ghidra.")
    if not find_jdk_for(g):
        return False, "Ghidra was found but no suitable JDK (put one in %LOCALAPPDATA%\\RADIDE\\tools\\jdk*)."
    return True, g


def command(headless: str, workdir: Path, binary: Path, out: Path, arch: str = "", base: int | None = None,
            raw: bool = True, entries: list[int] | None = None, max_decompile: int = 200,
            timeout_per_file: int = 600) -> list[str]:
    cmd = [headless, str(workdir), "radfw", "-import", str(binary)]
    lang = language_for(arch)
    if raw:
        if lang:
            cmd += ["-processor", lang]
        cmd += ["-loader", "BinaryLoader"]
        if base is not None:
            cmd += ["-loader-baseAddr", f"0x{base:X}"]
    cmd += ["-analysisTimeoutPerFile", str(timeout_per_file), "-scriptPath", str(workdir), "-postScript",
            SCRIPT_NAME, str(out), str(max_decompile), ",".join(f"{e:X}" for e in (entries or [])[:256]),
            "-deleteProject", "-overwrite"]
    return cmd


def parse_output(text: str) -> GhidraResult:
    res = GhidraResult()
    cur, buf = None, []

    def flush():
        if cur:
            res.decompiled[cur] = "\n".join(buf).strip()
    for line in text.splitlines():
        if line.startswith("//@@LANGUAGE "):
            res.language = line.split(" ", 1)[1].strip()
        elif line.startswith("//@@FUNC "):
            p = line.split()
            try:
                res.functions.append(GhidraFunction(p[1], int(p[2].split(":")[-1], 16), int(p[3])))
            except (IndexError, ValueError):
                pass
        elif line.startswith("//@@FUNCTION "):
            flush()
            cur, buf = line.split()[1], []
        else:
            buf.append(line)
    flush()
    return res


def analyze(binary, workdir, arch: str = "", base: int | None = None, raw: bool | None = None,
            entries: list[int] | None = None, max_decompile: int = 200, timeout: int = 1800,
            progress=None) -> GhidraResult:
    """Run Ghidra headless on *binary* (raw image or ELF). Never raises; ``error`` says what went wrong."""
    import time
    progress = progress or (lambda _m: None)
    t0 = time.time()
    binary = Path(binary)
    ok, info = available()
    if not ok:
        return GhidraResult(error=info)
    if raw is None:
        raw = binary.read_bytes()[:4] != b"\x7fELF"
    if raw and not language_for(arch):
        return GhidraResult(error=f"Ghidra has no language for '{arch}'.")
    jdk = find_jdk_for(info)
    work = Path(workdir) / "ghidra"
    work.mkdir(parents=True, exist_ok=True)
    (work / SCRIPT_NAME).write_text(GHIDRA_SCRIPT, encoding="utf-8")
    out = work / "export.txt"
    out.unlink(missing_ok=True)
    cmd = command(info, work, binary, out, arch, base, raw, entries, max_decompile)
    env = dict(os.environ, JAVA_HOME=jdk or "")
    if jdk:
        env["PATH"] = str(Path(jdk) / "bin") + os.pathsep + env.get("PATH", "")
    progress("Running Ghidra headless analysis (this can take a few minutes) ...")
    try:
        cp = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, env=env, stdin=subprocess.DEVNULL,
                            errors="replace", creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    except (OSError, subprocess.TimeoutExpired) as e:
        return GhidraResult(error=f"Ghidra failed: {e}", seconds=time.time() - t0)
    log = (cp.stdout or "") + (cp.stderr or "")
    if not out.is_file():
        tail = [ln for ln in log.splitlines() if ln.strip()][-4:]
        return GhidraResult(error="Ghidra produced no output" + (": " + " | ".join(tail) if tail else ""),
                            log=log[-20000:], seconds=time.time() - t0)
    res = parse_output(out.read_text(encoding="utf-8", errors="replace"))
    res.log = log[-20000:]
    res.seconds = time.time() - t0
    if not res.functions:
        res.error = "Ghidra found no functions (check the CPU and the base address)."
    return res


def sanitize_name(name: str) -> str:
    return re.sub(r"[^\w.]", "_", name)
