"""Synthetic firmware images for tests, the demo ECU project and the course (no Qt, no vehicle data).

``build_image()`` returns a 256 KB big-endian "PowerPC-style" image written from scratch by RAD IDE: a small code
area (real PPC instructions), an identification string block, a calibration area with Bosch-style maps
(``nx, ny, x axis, y axis, data`` as 16-bit big-endian words) and two checksums (a 16-bit sum over the calibration
area and a CRC32 over the whole image). The answers (map addresses, sizes, checksum profiles) come back with it,
so tests can check the map finder and checksum code against known truth.
"""
from __future__ import annotations

import math
import struct
import zlib

SIZE = 0x40000
CAL_START = 0x10000
CAL_END = 0x18000                 # the 16-bit sum is stored in the last word of the calibration area
ID_TEXT = (b"RADIDE-ECU-DEMO\x00SW 1.00 SYNTHETIC TEST IMAGE\x00"
           b"Generated by RAD IDE - contains no manufacturer software or vehicle data\x00")

# PowerPC big-endian instructions (decode with capstone CS_ARCH_PPC + CS_MODE_BIG_ENDIAN)
_PPC_FUNC = [0x9421FFF0,          # stwu r1,-16(r1)
             0x7C0802A6,          # mflr r0
             0x90010014,          # stw r0,20(r1)
             0x3C600001,          # lis r3,1          (r3 = 0x10000: the calibration area)
             0x60630000,          # ori r3,r3,0
             0xA0830000,          # lhz r4,0(r3)
             0x38840001,          # addi r4,r4,1
             0x7C832214,          # add r4,r3,r4
             0x80010014,          # lwz r0,20(r1)
             0x7C0803A6,          # mtlr r0
             0x38210010,          # addi r1,r1,16
             0x4E800020]          # blr


def _u16(v: float) -> int:
    return max(0, min(0xFFFF, int(round(v))))


def _map_block(name, xs, ys, fn, factor=1.0, unit="", x_unit="", y_unit=""):
    nx, ny = len(xs), len(ys)
    body = struct.pack(">HH", nx, ny) + struct.pack(f">{nx}H", *xs) + struct.pack(f">{ny}H", *ys)
    vals = [_u16(fn(x, y) / factor) for y in ys for x in xs]
    body += struct.pack(f">{nx * ny}H", *vals)
    return body, {"name": name, "rows": ny, "cols": nx, "cell": "u16be", "factor": factor, "unit": unit,
                  "x_cell": "u16be", "y_cell": "u16be", "x_unit": x_unit, "y_unit": y_unit, "header": 4,
                  "values": vals}


def _curve_block(name, xs, fn, factor=1.0, unit="", x_unit=""):
    n = len(xs)
    body = struct.pack(">H", n) + struct.pack(f">{n}H", *xs)
    vals = [_u16(fn(x) / factor) for x in xs]
    body += struct.pack(f">{n}H", *vals)
    return body, {"name": name, "rows": 1, "cols": n, "cell": "u16be", "factor": factor, "unit": unit,
                  "x_cell": "u16be", "y_cell": "", "x_unit": x_unit, "y_unit": "", "header": 2, "values": vals}


def sum16_be(data: bytes, start: int, end: int) -> int:
    return sum(struct.unpack_from(f">{(end - start) // 2}H", data, start)) & 0xFFFF


def crc32(data: bytes, start: int, end: int) -> int:
    return zlib.crc32(bytes(data[start:end])) & 0xFFFFFFFF


def checksum_profiles(size: int = SIZE) -> list[dict]:
    """The two checksums of the demo image, in the order they must be fixed."""
    return [{"name": "Calibration sum16", "algo": "sum16be", "start": CAL_START, "end": CAL_END - 2,
             "store": CAL_END - 2, "width": 2, "endian": "big"},
            {"name": "Image CRC32", "algo": "crc32", "start": 0, "end": size - 4, "store": size - 4,
             "width": 4, "endian": "big"}]


def fix_checksums(data: bytearray) -> bytearray:
    struct.pack_into(">H", data, CAL_END - 2, sum16_be(data, CAL_START, CAL_END - 2))
    struct.pack_into(">I", data, len(data) - 4, crc32(data, 0, len(data) - 4))
    return data


def build_image(variant: int = 0) -> tuple[bytes, list[dict], list[dict]]:
    """(image bytes, maps [{name, address, x_addr, y_addr, rows, cols, cell, ...}], checksum profiles).
    *variant* changes the code area and the map values slightly (a second "software version")."""
    d = bytearray(b"\xFF" * SIZE)
    # reset vector area: a branch to the first function
    struct.pack_into(">I", d, 0x100, 0x48000100)          # b 0x200
    off = 0x200
    k = 0
    while off < 0x3000:
        for ins in _PPC_FUNC:
            if ins == 0x38840001:
                ins = 0x38840000 | ((k + variant) & 0x7FFF)   # addi r4,r4,k
            struct.pack_into(">I", d, off, ins)
            off += 4
        k += 1
    d[0x8000:0x8000 + len(ID_TEXT)] = ID_TEXT
    d[CAL_START:CAL_END] = bytes(CAL_END - CAL_START)
    rpm16 = [600 + i * 427 for i in range(16)]
    load16 = [10 + i * 6 for i in range(16)]
    bump = 1.0 + variant * 0.02
    blocks = [
        _map_block("Ignition advance", rpm16, load16,
                   lambda r, l: (8 + 28 * math.sin(min(r, 5200) / 5200 * math.pi / 2) - l * 0.12) * bump + 20,
                   factor=0.1, unit="deg (+20)", x_unit="rpm", y_unit="load %"),
        _map_block("Fuel injection time", rpm16[:12], load16,
                   lambda r, l: (400 + l * 38 + r * 0.05) * bump, factor=1.0, unit="us",
                   x_unit="rpm", y_unit="load %"),
        _map_block("Boost target", [1000 + i * 600 for i in range(10)], [20 + i * 10 for i in range(8)],
                   lambda r, t: (1000 + min(r, 4000) * 0.12 * t / 100) * bump, factor=1.0, unit="mbar",
                   x_unit="rpm", y_unit="pedal %"),
        _curve_block("Warm-up enrichment", [i * 20 for i in range(10)],
                     lambda t: 1000 + max(0, 90 - t) * 4, factor=0.1, unit="%", x_unit="coolant C (+40)"),
    ]
    maps = []
    at = CAL_START + 0x40
    for body, meta in blocks:
        d[at:at + len(body)] = body
        hdr = meta.pop("header")
        x_addr = at + hdr
        y_addr = x_addr + 2 * meta["cols"] if meta["rows"] > 1 else 0
        data_addr = x_addr + 2 * meta["cols"] + (2 * meta["rows"] if meta["rows"] > 1 else 0)
        meta.update(address=data_addr, x_addr=x_addr, y_addr=y_addr, block=at)
        maps.append(meta)
        at = (at + len(body) + 0x40) & ~0x1F
    # single value: rev limiter
    struct.pack_into(">H", d, at, 6800 + variant * 100)
    maps.append({"name": "Rev limiter", "rows": 1, "cols": 1, "cell": "u16be", "factor": 1.0, "unit": "rpm",
                 "x_cell": "", "y_cell": "", "x_unit": "", "y_unit": "", "address": at, "x_addr": 0, "y_addr": 0,
                 "block": at, "values": [6800 + variant * 100]})
    fix_checksums(d)
    return bytes(d), maps, checksum_profiles(len(d))


def write_demo(folder, name: str = "demo") -> dict:
    """Write <folder>/<name>.ori (the original), <name>_v2.bin (a second version) and maps.json; returns paths."""
    import json
    from pathlib import Path
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    data, maps, profiles = build_image(0)
    data2, _m2, _p2 = build_image(1)
    ori = folder / f"{name}.ori"
    ori.write_bytes(data)
    v2 = folder / f"{name}_v2.bin"
    v2.write_bytes(data2)
    meta = folder / f"{name}_maps.json"
    meta.write_text(json.dumps({"maps": [{k: v for k, v in m.items() if k != "values"} for m in maps],
                                "checksums": profiles}, indent=1), encoding="utf-8")
    return {"original": ori, "version2": v2, "meta": meta}


__all__ = ["SIZE", "CAL_START", "CAL_END", "build_image", "checksum_profiles", "fix_checksums", "sum16_be",
           "crc32", "write_demo"]
