"""Kivy code generation: .form -> KV rule + Python screen class (CONTRACTS 10.1).

Files of a Kivy project:
    <Form>.py            user code: ``class <Form>(<Form>Designer)`` with VB-style handlers
                         (``def btnGo_Click(self): self.lblOut.text = "Hi " + self.txtName.text``)
    <Form>_designer.py   AUTO-GENERATED: the KV layout (Builder.load_string) + event wiring
    radkivy.py           runtime copied into the project: screens / navigation (ShowForm, CloseForm),
                         MsgBox / InputBox / Toast, the mobile widgets (app bar, bottom navigation, list ...)
Run: ``python <Startup>.py`` (desktop window the size of the phone); Android: Buildozer (see buildozer.spec).
"""
from __future__ import annotations

from .codegen_common import (align_word, color_hex, ensure_types, font_px, form_children, items, num, to_int,
                             truthy)

HEADER = ("# AUTO-GENERATED by RAD IDE from {form}.form - do not edit: changes are lost when the form is saved.\n"
          "# Write your code in {form}.py.\n")


def kv_color(value):
    h = color_hex(value)
    if not h:
        return None
    a, r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4, 6))
    return f"({r:.3f}, {g:.3f}, {b:.3f}, {a:.3f})"


def _r(v) -> str:
    v = round(float(v), 3)
    return str(int(v)) if v.is_integer() else str(v)


def _lin(base, rel, dim: str) -> str:
    """dp(base) + rel * <dim> as KV."""
    out = f"dp({_r(base)})"
    if rel:
        out += f" + {_r(rel)} * {dim}"
    return out


class _Proxy:
    def __init__(self, ctrl, dy: int = 0):
        self.ctrl = ctrl
        self.props = dict(ctrl.props)
        for k in ("Left", "Top", "Width", "Height"):
            self.props[k] = to_int(self.props.get(k), 0)
        self.props["Top"] -= dy
        self.type = ctrl.type


class KivyFormGen:
    def __init__(self, form):
        ensure_types()
        self.form = form
        self.binds: list[str] = []          # python lines for __init__ (event wiring)
        self._kids: dict[str, list[str]] = {}   # child widgets kept back by widget_head() (see tail())
        from .kivy_fx import KivyFx         # animations / layout sizes / TwoPane (radkivyfx.py)
        self.fx = KivyFx(form)

    # ------------------------------------------------------------ widgets
    def common(self, c, ind: str) -> list[str]:
        p = c.props
        out = []
        if not truthy(p.get("Enabled", True)):
            out.append(f"{ind}disabled: True")
        return out

    def text_props(self, c, ind: str, color_key="color") -> list[str]:
        p = c.props
        out = []
        fs = font_px(p)
        if fs:
            out.append(f"{ind}font_size: sp({_r(fs)})")
        fc = kv_color(p.get("ForeColor"))
        if fc:
            out.append(f"{ind}{color_key}: {fc}")
        if truthy(p.get("FontBold")):
            out.append(f"{ind}bold: True")
        if truthy(p.get("FontItalic")):
            out.append(f"{ind}italic: True")
        return out

    def bg(self, c, ind: str, radius: int = 0) -> list[str]:
        col = kv_color(c.props.get("BackColor"))
        if not col:
            return []
        shape = f"RoundedRectangle:\n{ind}        radius: [dp({radius})]" if radius else "Rectangle:"
        return [f"{ind}canvas.before:", f"{ind}    Color:", f"{ind}        rgba: {col}",
                f"{ind}    {shape}", f"{ind}        pos: self.pos", f"{ind}        size: self.size"]

    def bind(self, c, signal: str, events, make_event: str = "None"):
        names = [f"{c.name}_{e}" for e in events]
        self.binds.append(f"        self._bind(self.{c.name}, {signal!r}, {names!r}, {make_event})")

    def widget(self, c, ind: str) -> list[str]:
        """KV lines for control *c* (class line + properties, then its child widgets), without its position."""
        own, kids = self._widget(c, ind)
        return own + kids

    def widget_head(self, c, ind: str) -> list[str]:
        """Like :meth:`widget` without the child widgets: KV wants every property of a widget (its size and
        position too, which the caller adds) before its children - :meth:`tail` gives them afterwards."""
        own, kids = self._widget(c, ind)
        if kids:
            self._kids[c.name] = kids
        return own

    def tail(self, name: str) -> list[str]:
        """The child widgets :meth:`widget_head` kept back for control *name* (and a TwoPane's panes)."""
        return self._kids.pop(name, []) + self.fx.take_tail(name)

    def _widget(self, c, ind: str) -> tuple[list[str], list[str]]:
        t, p, n = c.type, c.props, c.name
        i2 = ind + "    "
        text = p.get("Text", "")
        L: list[str]
        kids: list[str] = []
        if t == "Button":
            L = [f"{ind}Button:", f"{i2}text: {text!r}"] + self.text_props(c, i2)
            bc = kv_color(p.get("BackColor"))
            if bc:
                L += [f"{i2}background_normal: ''", f"{i2}background_color: {bc}"]
            self.bind(c, "on_release", ("Click", "Tap"))
        elif t in ("Label", "LinkLabel"):
            halign = {"Center": "center", "Right": "right"}.get(p.get("TextAlign"), "left")
            L = [f"{ind}RadLabel:", f"{i2}text: {text!r}", f"{i2}halign: {halign!r}"] + self.text_props(c, i2)
            if not kv_color(p.get("ForeColor")):
                L.append(f"{i2}color: app.fg if app else (0, 0, 0, 1)")
            L += self.bg(c, i2)
            self.bind(c, "on_tap", ("Click", "Tap"))
        elif t in ("TextBox", "MTextField"):
            L = [f"{ind}TextInput:", f"{i2}text: {text!r}",
                 f"{i2}multiline: {truthy(p.get('Multiline'))}",
                 f"{i2}write_tab: False"]
            if p.get("Hint"):
                L.append(f"{i2}hint_text: {p.get('Hint')!r}")
            if truthy(p.get("Password")) or str(p.get("PasswordChar") or ""):
                L.append(f"{i2}password: True")
            if truthy(p.get("ReadOnly")):
                L.append(f"{i2}readonly: True")
            fs = font_px(p)
            if fs:
                L.append(f"{i2}font_size: sp({_r(fs)})")
            if not truthy(p.get("Multiline")):
                L.append(f"{i2}padding: [dp(8), (self.height - self.line_height) / 2]")
            self.bind(c, "text", ("Changed", "TextChanged"), "lambda w, v: RadEvent(Text=v)")
            self.bind(c, "on_text_validate", ("Submitted",), "lambda w: RadEvent(Text=w.text)")
        elif t in ("CheckBox", "RadioButton", "Switch"):
            cls = "RadSwitch" if t == "Switch" else "RadCheckBox"
            L = [f"{ind}{cls}:", f"{i2}text: {('' if text == n else text)!r}",
                 f"{i2}active: {truthy(p.get('Checked'))}"]
            if t == "RadioButton":
                L.append(f"{i2}group: {('radio_' + (c.parent or self.form.name))!r}")
            self.bind(c, "active", ("Changed", "CheckedChanged", "Click"), "lambda w, v: RadEvent(Value=v)")
        elif t in ("MSlider", "TrackBar", "NumericUpDown"):
            lo, hi = num(p.get("Minimum"), 0), num(p.get("Maximum"), 100)
            L = [f"{ind}Slider:", f"{i2}min: {_r(lo)}", f"{i2}max: {_r(hi if hi > lo else lo + 1)}",
                 f"{i2}value: {_r(num(p.get('Value'), lo))}", f"{i2}step: 1"]
            self.bind(c, "value", ("Changed", "ValueChanged"), "lambda w, v: RadEvent(Value=v)")
        elif t == "ProgressBar":
            lo, hi = num(p.get("Minimum"), 0), num(p.get("Maximum"), 100)
            L = [f"{ind}ProgressBar:", f"{i2}max: {_r(max(1, hi - lo))}", f"{i2}value: {_r(num(p.get('Value'), 0) - lo)}"]
        elif t == "ComboBox":
            vals = items(p.get("Items"))
            L = [f"{ind}Spinner:", f"{i2}values: {vals!r}", f"{i2}text: {(vals[0] if vals else '')!r}"]
            self.bind(c, "text", ("SelectedIndexChanged", "Changed"),
                      "lambda w, v: RadEvent(Index=list(w.values).index(v) if v in w.values else -1, Text=v)")
        elif t in ("ListBox", "MListView"):
            tpl = str(p.get("ItemTemplate") or "title")
            L = [f"{ind}RadList:", f"{i2}items: {items(p.get('Items'))!r}", f"{i2}template: {tpl!r}"]
            L += self.text_props(c, i2)
            self.bind(c, "on_tap", ("Tap", "Click", "SelectedIndexChanged", "Changed"),
                      "lambda w, i: RadEvent(Index=i, Text=w.selected_item)")
        elif t in ("PictureBox", "MImage"):
            img = str(p.get("Image") or "")
            L = [f"{ind}RadImage:", f"{i2}source: {img!r}",
                 f"{i2}fit_mode: {({'cover': 'cover', 'fill': 'fill'}.get(str(p.get('Fit', '')).lower(), 'contain'))!r}"]
            self.bind(c, "on_tap", ("Click", "Tap"))
        elif t == "MIcon":
            L = [f"{ind}RadIcon:", f"{i2}icon: {str(p.get('Icon') or 'star')!r}"] + self.text_props(c, i2)
            self.bind(c, "on_tap", ("Click", "Tap"))
        elif t == "Fab":
            L = [f"{ind}RadFab:", f"{i2}icon: {str(p.get('Icon') or 'add')!r}",
                 f"{i2}text: {('' if text == n else text)!r}"]
            bc = kv_color(p.get("BackColor"))
            if bc:
                L.append(f"{i2}fab_color: {bc}")
            self.bind(c, "on_release", ("Click", "Tap"))
        elif t == "AppBar":
            drawer = next((d for d in form_children(self.form, "") if d.type == "Drawer"), None)
            L = [f"{ind}RadAppBar:", f"{i2}title: {str(p.get('Title') or text or self.form.props.get('Text', ''))!r}",
                 f"{i2}actions: {items(p.get('Actions'))!r}"]
            if drawer is not None:
                L.append(f"{i2}menu_items: {items(drawer.props.get('Items'))!r}")
            bc = kv_color(p.get("BackColor"))
            if bc:
                L.append(f"{i2}bar_color: {bc}")
            self.bind(c, "on_action", ("Click", "Tap"), "lambda w, i, a: RadEvent(Index=i, Action=a, Text=a)")
            if drawer is not None:
                self.binds.append(f"        self._bind(self.{n}, 'on_menu', {[drawer.name + '_Tap', drawer.name + '_Click']!r}, "
                                  "lambda w, i, a: RadEvent(Index=i, Text=a))")
        elif t in ("BottomNav", "MTabBar"):
            key = "Tabs" if t == "MTabBar" else "Items"
            L = [f"{ind}RadTabs:", f"{i2}items: {items(p.get(key))!r}",
                 f"{i2}selected_index: {to_int(p.get('SelectedIndex'), 0)}",
                 f"{i2}bottom: {t == 'BottomNav'}"]
            self.bind(c, "on_changed", ("Changed", "SelectedIndexChanged", "Click"),
                      "lambda w, i: RadEvent(Index=i, Text=w.selected_item)")
        elif t == "MWebView":
            L = [f"{ind}RadWebLink:", f"{i2}url: {str(p.get('Url') or '')!r}"]
        elif t in ("Column", "Row"):
            al = align_word(p.get("Align"))
            L = [f"{ind}BoxLayout:", f"{i2}orientation: {'vertical' if t == 'Column' else 'horizontal'!r}",
                 f"{i2}spacing: dp({to_int(p.get('Spacing'), 0)})", f"{i2}padding: dp({to_int(p.get('Padding'), 0)})"]
            L += self.bg(c, i2)
            for k in form_children(self.form, n):
                kids += self.flex_child(k, t, al, i2)
            if al != "between":
                kids.append(f"{i2}Widget:")        # fills the rest (children keep their size)
        elif t == "TwoPane":
            L = self.fx.two_pane_lines(self, c, ind)
        elif t in ("Card", "Stack", "Panel", "GroupBox"):
            L = [f"{ind}RadCard:" if t == "Card" else f"{ind}FloatLayout:"]
            if t == "Card":
                L.append(f"{i2}elevation: {to_int(p.get('Elevation'), 1)}")
                col = kv_color(p.get("BackColor"))
                if col:
                    L.append(f"{i2}card_color: {col}")
            else:
                L += self.bg(c, i2)
            if t == "GroupBox":
                kids += [f"{i2}RadLabel:", f"{i2}    text: {text!r}", f"{i2}    size_hint: 1, None",
                         f"{i2}    height: dp(20)", f"{i2}    pos: self.parent.x + dp(8), self.parent.top - dp(20)"]
            kids += self.place_children(form_children(self.form, n), to_int(p.get("Width")), to_int(p.get("Height")),
                                     0, f"w_{n}", i2)
            if t == "Card":
                self.bind(c, "on_tap", ("Tap", "Click"))
        else:
            L = [f"{ind}RadLabel:", f"{i2}text: {(t + ' ' + n)!r}"]
        L.insert(1, f"{i2}id: w_{n}")
        L += self.common(c, i2)
        return L, kids

    def flex_child(self, k, kind: str, al: str, ind: str) -> list[str]:
        L = self.widget_head(k, ind)
        i2 = ind + "    "
        w, h = to_int(k.props.get("Width")), to_int(k.props.get("Height"))
        if kind == "Column":
            L += [f"{i2}size_hint_y: None", f"{i2}height: dp({h})"]
            if al == "stretch":
                L.append(f"{i2}size_hint_x: 1")
            else:
                L += [f"{i2}size_hint_x: None", f"{i2}width: dp({w})"]
                if al in ("center", "end"):
                    L.append(f"{i2}pos_hint: {{'center_x': 0.5}}" if al == "center" else f"{i2}pos_hint: {{'right': 1}}")
        else:
            L += [f"{i2}size_hint_x: None", f"{i2}width: dp({w})"]
            if al == "stretch":
                L.append(f"{i2}size_hint_y: 1")
            else:
                L += [f"{i2}size_hint_y: None", f"{i2}height: dp({h})"]
        return L + self.tail(k.name)

    def place_children(self, kids, cw: int, ch: int, dy: int, box: str, ind: str) -> list[str]:
        """Absolute placement inside a FloatLayout whose KV id is *box* (Anchor / Dock aware)."""
        from ..layout import group_places
        proxies = [_Proxy(k, dy) for k in kids]
        places = group_places(proxies, cw, ch)
        out = []
        for px in proxies:
            pl = places[id(px)]
            L = self.widget_head(px.ctrl, ind)
            i2 = ind + "    "
            wexpr, hexpr = _lin(pl.w, pl.rw, f"{box}.width"), _lin(pl.h, pl.rh, f"{box}.height")
            geo = self.fx.geometry(px.ctrl.name, box, (pl.x, pl.y, pl.w, pl.h, pl.rx, pl.ry, pl.rw, pl.rh))
            if geo:                                    # layout sizes move / resize it
                L += [f"{i2}size_hint: None, None", f"{i2}size: {geo['size']}", f"{i2}x: {geo['x']}",
                      f"{i2}top: {geo['top']}"]
            else:
                L += [f"{i2}size_hint: None, None",
                      f"{i2}size: {wexpr}, {hexpr}",
                      f"{i2}x: {box}.x + {_lin(pl.x, pl.rx, f'{box}.width')}",
                      f"{i2}top: {box}.top - ({_lin(pl.y, pl.ry, f'{box}.height')})"]
            if not truthy(px.ctrl.props.get("Visible", True)):
                L += [f"{i2}opacity: 0", f"{i2}disabled: True"]
                self.binds.append(f"        self.{px.ctrl.name}.visible = False")
            L += self.tail(px.ctrl.name)          # children (TwoPane: its panes) after its own properties
            out += L
        return out

    # ------------------------------------------------------------ screen
    def generate(self) -> str:
        f, n = self.form, self.form.name
        top = form_children(f, "")
        drawer_names = {c.name for c in top if c.type == "Drawer"}
        kids = [c for c in top if c.name not in drawer_names]
        W, H = to_int(f.props.get("Width"), 360), to_int(f.props.get("Height"), 640)
        bg = kv_color(f.props.get("BackColor")) or "app.bg if app else (1, 1, 1, 1)"
        kv = [f"<{n}Designer>:",
              "    canvas.before:",
              "        Color:",
              f"            rgba: {bg}",
              "        Rectangle:",
              "            pos: self.pos",
              "            size: self.size",
              "    FloatLayout:",
              "        id: w__body"]
        kv += self.place_children(kids, W, H, 0, "w__body", "        ")
        timers = [c for c in f.controls if c.type == "Timer"]
        names = [c.name for c in f.controls if not c.ctype.nonvisual and c.name not in drawer_names]
        L = [HEADER.format(form=n).rstrip("\n"),
             "# flake8: noqa",
             "from kivy.lang import Builder",
             "",
             "from radkivy import RadEvent, RadScreen, RadTimer, run_app  # noqa: F401",
             *self.fx.imports(),
             "",
             "KV = '''",
             *[line.replace("'''", "\\'\\'\\'") for line in kv],
             "'''",
             "Builder.load_string(KV)",
             "",
             "",
             f"class {n}Designer(RadScreen):",
             f"    form_name = {n!r}",
             f"    design_size = ({W}, {H})",
             f"    title = {str(f.props.get('Text') or n)!r}",
             *self.fx.class_lines(),
             "",
             "    def __init__(self, **kw):",
             f"        kw.setdefault('name', {n!r})",
             "        super().__init__(**kw)"]
        for nm in names:
            L.append(f"        self.{nm} = self.ids['w_{nm}']")
        for c in drawer_names:
            L.append(f"        self.{c} = None  # the drawer is the menu of the app bar")
        for t in timers:
            L.append(f"        self.{t.name} = RadTimer({max(1, to_int(t.props.get('Interval'), 100))}, "
                     f"{truthy(t.props.get('Enabled'))}, lambda: self._call({[t.name + '_Tick']!r}, None))")
        L += self.binds
        if self.fx.active:
            L += self.fx.init_lines()
            L += self.fx.method_lines()
        L.append("")
        return "\n".join(L)


def generate_designer(form) -> str:
    return KivyFormGen(form).generate()


def new_user_code(form_name: str, is_startup: bool) -> str:
    n = form_name
    run = (f"\n\nif __name__ == \"__main__\":\n"
           f"    run_app({n!r})\n")
    return (f"# {n} screen - write your event handlers here (double-click a control in the designer).\n"
            f"# Controls: self.lblHello.text = 'Hi'; self.txtName.text; self.swOn.active; self.lstItems.add_item('x')\n"
            f"# Screens: self.ShowForm('Form2')  self.CloseForm()   Dialogs: self.MsgBox('...'), self.Toast('...')\n"
            f"from {n}_designer import {n}Designer, RadEvent, run_app  # noqa: F401\n\n\n"
            f"class {n}({n}Designer):\n"
            f"    def {n}_Load(self):\n"
            f"        pass\n" + run)


