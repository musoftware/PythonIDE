def material_icons() -> set[str]:
    """Names of Icons.* in the installed Flutter SDK (a small built-in list otherwise)."""
    global _ICONS
    if _ICONS is None:
        names: set[str] = set()
        try:
            from ..languages.flutter import flutter_root
            root = flutter_root()
            if root:
                f = Path(root) / "packages" / "flutter" / "lib" / "src" / "material" / "icons.dart"
                text = f.read_text(encoding="utf-8", errors="replace")
                names = set(re.findall(r"^\s*static const IconData (\w+) =", text, re.M))
        except Exception:  # noqa: BLE001
            names = set()
        _ICONS = names or set(_ICON_FALLBACK)
    return _ICONS


def icon_expr(name, default: str = "circle") -> str:
    key = icon_key(name)
    icons = material_icons()
    if key and key[0].isdigit():
        key = "n" + key
    if key in icons:
        return f"Icons.{key}"
    if key + "_outlined" in icons:
        return f"Icons.{key}_outlined"
    return f"Icons.{default}"


def has_icon(name) -> bool:
    key = icon_key(name)
    return bool(key) and key in material_icons()


# --------------------------------------------------------------------------- Dart literals
def dstr(value) -> str:
    s = str(value if value is not None else "")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$").replace("\n", "\\n").replace("\r", "")
    return f"'{s}'"


def dnum(value) -> str:
    v = num(value, 0)
    return str(int(v)) if float(v).is_integer() else repr(round(v, 2))


def dcolor(value) -> str | None:
    h = color_hex(value)
    return f"const Color(0x{h})" if h else None


def dlist(values) -> str:
    return "[" + ", ".join(dstr(v) for v in values) + "]"


