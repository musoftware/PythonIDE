def format_dart(code: str, width: int = 110) -> str:
    """Break long generated lines like dart format does: one argument / statement per line inside the
    outermost bracket that is too long, recursively (strings and interpolations are respected)."""
    out = []
    for line in code.splitlines():
        if len(line) <= width:
            out.append(line)
            continue
        indent = len(line) - len(line.lstrip())
        out += _fmt(line.strip(), indent, width)
    return "\n".join(out) + "\n"


def _scan(s: str):
    """Yield (index, char, depth) for characters outside string literals."""
    depth, i, q = 0, 0, ""
    while i < len(s):
        ch = s[i]
        if q:
            if ch == "\\":
                i += 2
                continue
            if ch == q:
                q = ""
            elif ch == "$" and s[i + 1:i + 2] == "{":          # ${...} inside a string: skip it
                j, d = i + 2, 1
                while j < len(s) and d:
                    d += {"{": 1, "}": -1}.get(s[j], 0)
                    j += 1
                i = j
                continue
            i += 1
            continue
        if ch in "'\"":
            q = ch
        elif ch in "([{":
            yield i, ch, depth
            depth += 1
            i += 1
            continue
        elif ch in ")]}":
            depth -= 1
        yield i, ch, depth
        i += 1


def _split(body: str, sep: str) -> list[str]:
    parts, last = [], 0
    for i, ch, d in _scan(body):
        if d == 0 and ch == sep:
            parts.append(body[last:i + (1 if sep == ";" else 0)].strip())
            last = i + 1
    tail = body[last:].strip()
    if tail:
        parts.append(tail)
    return [p for p in parts if p]


def _fmt(s: str, indent: int, width: int) -> list[str]:
    pad = " " * indent
    if indent + len(s) <= width:
        return [pad + s]
    # the bracket pair with the largest span decides where to break
    stack, best = [], None
    for i, ch, d in _scan(s):
        if ch in "([{":
            stack.append((i, ch))
        elif ch in ")]}" and stack:
            j, op = stack.pop()
            if i - j > 2 and (best is None or i - j > best[1] - best[0]):
                best = (j, i, op)
    if best is None:
        return [pad + s]
    j, i, op = best
    head, body, tail = s[:j + 1], s[j + 1:i], s[i:]
    out = [pad + head]
    if op == "{":
        for st in _split(body, ";"):
            out += _fmt(st, indent + 2, width)
    else:
        for arg in _split(body, ","):
            out += _fmt(arg + ",", indent + 2, width)
    out += _fmt(tail, indent, width) if len(tail) + indent > width else [pad + tail]
    return out


