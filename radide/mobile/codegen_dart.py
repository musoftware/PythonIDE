def _state_init(c) -> str:
    """Constructor call of the state object of control *c*."""
    p, t = c.props, c.type
    cls = STATE_CLASS.get(t, "RadControl")
    args = [dstr(c.name)]
    text = p.get("Text", "")
    if t == "AppBar":
        text = p.get("Title") or text
    if t in ("Fab", "Card", "MIcon", "MImage", "PictureBox", "MWebView", "Column", "Row", "Stack", "Panel",
             "ListBox", "ComboBox", "MListView", "BottomNav", "MTabBar", "MSlider", "TrackBar", "ProgressBar"):
        if text == c.name:
            text = ""
    if text:
        args.append(f"text: {dstr(text)}")
    if not truthy(p.get("Visible", True)):
        args.append("visible: false")
    if not truthy(p.get("Enabled", True)):
        args.append("enabled: false")
    bc, fc = dcolor(p.get("BackColor")), dcolor(p.get("ForeColor"))
    if bc:
        args.append(f"backColor: {bc}")
    if fc:
        args.append(f"foreColor: {fc}")
    fs = font_px(p)
    if fs:
        args.append(f"fontSize: {fs}")
    if cls == "RadCheckControl" and truthy(p.get("Checked")):
        args.append("checked: true")
    if cls == "RadValueControl":
        lo, hi = num(p.get("Minimum"), 0), num(p.get("Maximum"), 100)
        args.append(f"minimum: {dnum(lo)}, maximum: {dnum(hi if hi > lo else lo + 1)}, value: {dnum(p.get('Value', lo))}")
    if cls == "RadListControl":
        key = {"MTabBar": "Tabs", "AppBar": "Actions"}.get(t, "Items")
        args.append(f"items: {dlist(items(p.get(key, '')))}")
        sel = p.get("SelectedIndex", 0 if t in ("BottomNav", "MTabBar") else -1)
        args.append(f"selectedIndex: {to_int(sel, -1)}")
    if cls == "RadImageControl":
        args.append(f"image: {dstr(image_path(p.get('Image', '')))}")
    if cls == "RadWebControl":
        args.append(f"url: {dstr(p.get('Url', ''))}")
    if t == "MTextField" or t == "TextBox":
        pass
    return f"{cls}({', '.join(args)})"


def image_path(value: str) -> str:
    """Image property -> what Image.* loads: URLs stay, project files become assets/<name>."""
    s = str(value or "").strip().replace("\\", "/")
    if not s or re.match(r"^(https?:)?//", s) or s.startswith("assets/"):
        return s
    return "assets/" + s.rsplit("/", 1)[-1]


