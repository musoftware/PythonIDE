    def w_Drawer(self, c, s, p, en):
        return self.drawer(c)

    def drawer(self, c) -> str:
        s = c.name
        call = self.fire(c, ("Tap", "Click", "Changed", "SelectedIndexChanged"),
                         f"RadEvent(Index: i, Text: RadIcons.label({s}.items[i]))")
