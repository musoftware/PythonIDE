# --------------------------------------------------------------------------- JS literals
def jstr(value) -> str:
    return json.dumps(str(value if value is not None else ""), ensure_ascii=False)


def jnum(value) -> str:
    v = num(value, 0)
    return str(int(v)) if float(v).is_integer() else repr(round(v, 2))


def jcolor(value) -> str | None:
    h = color_hex(value)
    if not h:
        return None
    a, rgb = h[:2], h[2:]
    return jstr("#" + rgb + ("" if a == "FF" else a))


def rn_icon(name, default: str = "circle") -> str:
    """Material icon name as @expo/vector-icons spells it ('shopping_cart' -> 'shopping-cart')."""
    key = icon_key(name) or default
    return key.replace("_", "-")


def image_source(value: str) -> str:
    """Image property -> JS expression: URLs stay strings, project files become require('./assets/<name>')."""
    s = str(value or "").strip().replace("\\", "/")
    if not s:
        return '""'
    if re.match(r"^(https?:)?//|^data:", s):
        return jstr(s)
    return f"require({jstr('./assets/' + s.rsplit('/', 1)[-1])})"


def component_name(form_name: str) -> str:
    return form_name


# --------------------------------------------------------------------------- control objects
LIST_TYPES = ("ListBox", "MListView", "BottomNav", "Drawer", "MTabBar", "AppBar", "ComboBox")
VALUE_TYPES = ("MSlider", "TrackBar", "ProgressBar", "NumericUpDown")
CHECK_TYPES = ("CheckBox", "RadioButton", "Switch")
NO_TEXT = ("Fab", "Card", "MIcon", "MImage", "PictureBox", "MWebView", "Column", "Row", "Stack", "Panel", "ListBox",
           "ComboBox", "MListView", "BottomNav", "MTabBar", "MSlider", "TrackBar", "ProgressBar")


def control_init(c) -> str:
    """``new RadControl(this, 'name', {...})`` for control *c*."""
    p, t = c.props, c.type
    props: list[str] = []
    text = p.get("Text", "")
    if t == "AppBar":
        text = p.get("Title") or text
    if t in NO_TEXT and text == c.name:
        text = ""
    if text:
        props.append(f"Text: {jstr(text)}")
    if not truthy(p.get("Visible", True)):
        props.append("Visible: false")
    if not truthy(p.get("Enabled", True)):
        props.append("Enabled: false")
    bc, fc = jcolor(p.get("BackColor")), jcolor(p.get("ForeColor"))
    if bc:
        props.append(f"BackColor: {bc}")
    if fc:
        props.append(f"ForeColor: {fc}")
    fs = font_px(p)
    if fs:
        props.append(f"FontSize: {fs}")
    if t in CHECK_TYPES and truthy(p.get("Checked")):
        props.append("Checked: true")
    if t in VALUE_TYPES:
        lo, hi = num(p.get("Minimum"), 0), num(p.get("Maximum"), 100)
        props.append(f"Minimum: {jnum(lo)}, Maximum: {jnum(hi if hi > lo else lo + 1)}, "
                     f"Value: {jnum(p.get('Value', lo))}")
    if t in LIST_TYPES:
        key = {"MTabBar": "Tabs", "AppBar": "Actions"}.get(t, "Items")
        props.append("Items: [" + ", ".join(jstr(v) for v in items(p.get(key, ""))) + "]")
        sel = p.get("SelectedIndex", 0 if t in ("BottomNav", "MTabBar") else -1)
        props.append(f"SelectedIndex: {to_int(sel, -1)}")
    if t in ("MImage", "PictureBox"):
        props.append(f"Image: {image_source(p.get('Image', ''))}")
    if t == "MWebView":
        props.append(f"Url: {jstr(p.get('Url', ''))}")
    return f"new RadControl(this, {jstr(c.name)}, {{{', '.join(props)}}})"


# --------------------------------------------------------------------------- generator
class RnFormGen:
    def __init__(self, form):
        ensure_types()
        self.form = form

    def attrs(self, c, style: str) -> str:
        return f"form={{this}} c={{this.{c.name}}} style={{{style}}}"

    def widget(self, c, style: str) -> str:
        """JSX of control *c* placed with *style* (a JS expression)."""
        t, p = c.type, c.props
        a = self.attrs(c, style)
        fn = getattr(self, "w_" + t, None)
        if fn is not None:
            return fn(c, a, p)
        if t in ("Column", "Row"):
            return self.flex(c, style)
        if t in ("Stack", "Panel"):
            return f"<R.Container {a}>{self.inner_stack(c)}</R.Container>"
        return f"<R.Unknown {a} type={jstr(t)} />"

    # ----------------------------------------------------------------- simple controls
    def w_Button(self, c, a, p):
        return f"<R.Button {a} />"

    def w_Label(self, c, a, p):
        align = {"Center": "center", "Right": "right"}.get(str(p.get("TextAlign") or ""), "left")
        extra = f' align="{align}"' if align != "left" else ""
        if truthy(p.get("FontBold")):
            extra += " bold"
        if truthy(p.get("FontItalic")):
            extra += " italic"
        return f"<R.Label {a}{extra} />"

    w_LinkLabel = w_Label

    def w_TextBox(self, c, a, p):
        extra = " outlined={false}"
        if truthy(p.get("Multiline")):
            extra += " multiline"
        if truthy(p.get("ReadOnly")):
            extra += " readOnly"
        if str(p.get("PasswordChar") or ""):
            extra += " password"
        if to_int(p.get("MaxLength"), 0) > 0:
            extra += f" maxLength={{{to_int(p.get('MaxLength'))}}}"
        return f"<R.TextField {a}{extra} />"

    def w_MTextField(self, c, a, p):
        extra = f" hint={{{jstr(p.get('Hint', ''))}}}" if p.get("Hint") else ""
        if truthy(p.get("Password")):
            extra += " password"
        return f"<R.TextField {a}{extra} />"

    def w_CheckBox(self, c, a, p):
        return f"<R.Check {a} />"

    def w_RadioButton(self, c, a, p):
        group = [o.name for o in form_children(self.form, c.parent) if o.type == "RadioButton"]
        return f"<R.Check {a} radio group={{[{', '.join(jstr(g) for g in group)}]}} />"

    def w_Switch(self, c, a, p):
        return f"<R.Switch {a} />"

    def w_MSlider(self, c, a, p):
        return f"<R.Slider {a} />"

    w_TrackBar = w_MSlider

    def w_ProgressBar(self, c, a, p):
        return f"<R.Progress {a} />"

    def w_NumericUpDown(self, c, a, p):
        return f"<R.Numeric {a} />"

    def w_ListBox(self, c, a, p):
        return f"<R.ListView {a} simple />"

    def w_MListView(self, c, a, p):
        fields = [f.strip().lower() for f in str(p.get("ItemTemplate") or "title").split("|") if f.strip()]
        return f"<R.ListView {a} template={{[{', '.join(jstr(f) for f in fields)}]}} />"

    def w_ComboBox(self, c, a, p):
        return f"<R.ComboBox {a} />"

    def w_MImage(self, c, a, p):
        fit = {"cover": "cover", "fill": "stretch", "stretch": "stretch", "none": "center", "fitwidth": "contain",
               "fitheight": "contain", "zoom": "contain", "stretchimage": "stretch", "centerimage": "center",
               "normal": "center"}.get(str(p.get("Fit") or p.get("SizeMode") or "contain").lower(), "contain")
        return f'<R.Picture {a} fit="{fit}" />'

    w_PictureBox = w_MImage

    def w_MIcon(self, c, a, p):
        size = max(12, min(to_int(p.get("Width"), 32), to_int(p.get("Height"), 32)))
        return f"<R.Icon {a} icon={jstr(rn_icon(p.get('Icon') or 'star'))} size={{{size}}} />"

    def w_MWebView(self, c, a, p):
        return f"<R.WebView {a} />"

    def w_MTabBar(self, c, a, p):
        return f"<R.TabBar {a} />"

    def w_AppBar(self, c, a, p):          # an app bar inside a container (the form's own one is the screen's)
        return f"<R.Label {a} align=\"center\" />"

    def w_BottomNav(self, c, a, p):
        return f"<R.BottomNav form={{this}} c={{this.{c.name}}} height={{{to_int(p.get('Height'), 80)}}} />"

    def w_Fab(self, c, a, p):
        return self.fab(c)

    def w_Drawer(self, c, a, p):
        return self.drawer(c)

    def w_Card(self, c, a, p):
        return (f"<R.Container {a} card elevation={{{to_int(p.get('Elevation', 1), 1)}}}>"
                f"{self.inner_stack(c)}</R.Container>")

    def w_GroupBox(self, c, a, p):
        return f"<R.Group {a}>{self.inner_stack(c)}</R.Group>"

    # ----------------------------------------------------------------- slots
    def fab(self, c) -> str:
        return f"<R.Fab form={{this}} c={{this.{c.name}}} icon={jstr(rn_icon(c.props.get('Icon') or 'add'))} />"

    def drawer(self, c) -> str:
        return f"<R.Drawer form={{this}} c={{this.{c.name}}} width={{{max(200, to_int(c.props.get('Width'), 280))}}} />"

    # ----------------------------------------------------------------- containers
    def inner_stack(self, c) -> str:
        """Children of a free-placement container, at their design rectangles (Anchor uses the design size)."""
        from ..layout import group_places
        kids = form_children(self.form, c.name)
        if not kids:
            return ""
        cw, ch = to_int(c.props.get("Width"), 0), to_int(c.props.get("Height"), 0)
        proxies = [_Proxy(k, 0) for k in kids]
        places = group_places(proxies, cw, ch)
        out = []
        for px in proxies:
            x, y, w, h = places[id(px)].rect(cw, ch)
            k = px.ctrl
            style = f"{{ position: 'absolute', left: {x}, top: {y}, width: {w}, height: {h} }}"
            out.append(f"{{this.{k.name}.Visible && {self.widget(k, style)}}}")
        return "".join(out)

    def flex(self, c, style: str) -> str:
        kids = form_children(self.form, c.name)
        al = align_word(c.props.get("Align"))
        dir_ = "column" if c.type == "Column" else "row"
        out = []
        for k in kids:
            w, h = to_int(k.props.get("Width"), 0), to_int(k.props.get("Height"), 0)
            if dir_ == "column":
                st = f"{{ height: {h} }}" if al == "stretch" else f"{{ width: {w}, height: {h} }}"
            else:
                st = f"{{ width: {w} }}" if al == "stretch" else f"{{ width: {w}, height: {h} }}"
            out.append(f"{{this.{k.name}.Visible && {self.widget(k, st)}}}")
        return (f"<R.Flex {self.attrs(c, style)} dir=\"{dir_}\" spacing={{{to_int(c.props.get('Spacing'), 0)}}} "
                f"align=\"{al}\" padding={{{to_int(c.props.get('Padding'), 0)}}}>{''.join(out)}</R.Flex>")

    # ----------------------------------------------------------------- screen
    def generate(self, user_file: str) -> str:
        from ..layout import group_places
        f, n = self.form, self.form.name
        top = form_children(f, "")
        appbar = next((c for c in top if c.type == "AppBar"), None)
        bottom = next((c for c in top if c.type == "BottomNav"), None)
        drawer = next((c for c in top if c.type == "Drawer"), None)
        fab = next((c for c in top if c.type == "Fab"), None)
        slots = {id(x) for x in (appbar, bottom, drawer, fab) if x is not None}
        body_kids = [c for c in top if id(c) not in slots]
        dy = 0
        if appbar is not None:
            ah = to_int(appbar.props.get("Height"), 56)
            if appbar.props.get("Dock") == "Top":
                dy = ah
            elif to_int(appbar.props.get("Top"), 0) <= 8:
                dy = to_int(appbar.props.get("Top"), 0) + ah
        bh = to_int(bottom.props.get("Height"), 80) if bottom is not None else 0
        fw, fh = to_int(f.props.get("Width"), 360), to_int(f.props.get("Height"), 640)
        body_h = max(1, fh - dy - bh)
        content_h = max([to_int(c.props.get("Top")) + to_int(c.props.get("Height")) - dy for c in body_kids
                         if c.props.get("Dock") in (None, "", "None")] or [0]) + 8
        design_h = max(body_h, content_h)

        visual = [c for c in f.controls if not c.ctype.nonvisual]
        timers = [c for c in f.controls if c.type == "Timer"]
        other_nv = [c for c in f.controls if c.ctype.nonvisual and c.type != "Timer"]

        L = [HEADER.format(form=n, user=user_file).rstrip("\n"),
             "import React from 'react';",
             "import { R, RadControl, RadForm, RadTimer } from './radapp';", "",
             "/* eslint-disable */",
             f"export class {n}Designer extends RadForm {{",
             f"  static formName = {jstr(n)};",
             f"  static designWidth = {fw};",
             f"  static designHeight = {design_h};", "",
             "  constructor(props) {",
             "    super(props);"]
        for c in visual + other_nv:
            L.append(f"    this.{c.name} = {control_init(c)};")
        for c in timers:
            L.append(f"    this.{c.name} = new RadTimer(this, {jstr(c.name)}, "
                     f"{max(1, to_int(c.props.get('Interval'), 100))}, "
                     f"{'true' if truthy(c.props.get('Enabled')) else 'false'});")
        L += ["  }", ""]
        proxies = [_Proxy(k, dy) for k in body_kids]
        places = group_places(proxies, fw, design_h)
        children = []
        for px in proxies:
            pl = places[id(px)]
            k = px.ctrl
            style = (f"this.P({jnum(pl.x)}, {round(pl.rx, 3)}, {jnum(pl.y)}, {round(pl.ry, 3)}, "
                     f"{jnum(pl.w)}, {round(pl.rw, 3)}, {jnum(pl.h)}, {round(pl.rh, 3)})")
            children.append(f"        {{this.{k.name}.Visible && {self.widget(k, style)}}}")
        bg = jcolor(f.props.get("BackColor"))
        title = jstr(f.props.get("Text") or n)
        screen = ["form={this}", f"designHeight={{{design_h}}}"]
        if bg:
            screen.append(f"backColor={{{bg}}}")
        if appbar is not None:
            a = appbar.name
            screen.append(f"appBar={{this.{a}.Visible && <R.AppBar form={{this}} c={{this.{a}}} "
                          f"height={{{to_int(appbar.props.get('Height'), 56)}}} title={{{title}}}"
                          f"{' drawer' if drawer is not None else ''} />}}")
        if bottom is not None:
            screen.append(f"bottom={{this.{bottom.name}.Visible && {self.w_BottomNav(bottom, '', bottom.props)}}}")
        if fab is not None:
            screen.append(f"fab={{this.{fab.name}.Visible && {self.fab(fab)}}}")
        if drawer is not None:
            screen.append(f"drawer={{{self.drawer(drawer)}}}")
        L += ["  render() {",
              "    return (",
              "      <R.Screen " + ("\n        ".join(screen)) + ">",
              *children,
              "      </R.Screen>",
              "    );",
              "  }",
              "}", ""]
        return "\n".join(L)


def generate_designer(form, user_file: str) -> str:
    return RnFormGen(form).generate(user_file)


def new_user_code(form_name: str, is_startup: bool, body: str = "") -> str:
    n = form_name
    body = body or (f"  {n}_Load(e) {{\n    \n  }}\n")
    return (f"// {n} - write your event handlers here (double-click a control in the designer).\n"
            f"// Controls: this.lblHello.Text = 'Hi'; this.txtName.Text; this.lstItems.AddItem('title|subtitle');\n"
            f"// Screens: this.ShowForm('Form2', args) / this.CloseForm() / this.FormArgs\n"
            f"// Dialogs: this.MsgBox('...'), this.Toast('...'), await this.InputBox('...'), await this.Confirm('...')\n"
            f"import {{ {n}Designer }} from './{n}_designer';\n"
            f"import {{ RadApp }} from './radapp';\n\n"
            f"export default class {n} extends {n}Designer {{\n"
            f"{body}"
            f"}}\n")


