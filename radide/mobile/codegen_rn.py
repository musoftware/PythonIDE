def generate_app(title: str, forms: list[tuple[str, str]], startup: str) -> str:
    """App.js - forms = [(form name, title)]."""
    L = ["// AUTO-GENERATED by RAD IDE (the screens of the project) - do not edit: it is rewritten on every run.",
         "import React from 'react';",
         "import { View } from 'react-native';",
         "import { NavigationContainer } from '@react-navigation/native';",
         "import { createNativeStackNavigator } from '@react-navigation/native-stack';",
         "import { SafeAreaProvider, SafeAreaView } from 'react-native-safe-area-context';",
         "import { StatusBar } from 'expo-status-bar';",
         "import { navigationRef, RadHost } from './radapp';"]
    for name, _t in forms:
        L.append(f"import {name} from './{name}';")
    first = startup if any(n == startup for n, _ in forms) else (forms[0][0] if forms else "")
    L += ["", "const Stack = createNativeStackNavigator();", "",
          "export default function App() {",
          "  return (",
          "    <SafeAreaProvider>",
          "      <SafeAreaView style={{ flex: 1 }} edges={['top', 'bottom']}>",
          "        <View style={{ flex: 1 }}>",
          f"          <NavigationContainer ref={{navigationRef}} documentTitle={{{{ formatter: (o, r) => "
          f"(o && o.title) || {jstr(title)} }}}}>",
          f"            <Stack.Navigator initialRouteName={jstr(first)} screenOptions={{{{ headerShown: false }}}}>"]
    for name, t in forms:
        L.append(f"              <Stack.Screen name={jstr(name)} component={{{name}}} options={{{{ title: {jstr(t)} }}}} />")
    L += ["            </Stack.Navigator>",
          "          </NavigationContainer>",
          "          <RadHost />",
          "        </View>",
          "      </SafeAreaView>",
          "      <StatusBar style=\"auto\" />",
          "    </SafeAreaProvider>",
          "  );",
          "}", ""]
    return "\n".join(L)


