def package_json(slug: str) -> str:
    data = {"name": slug, "version": "1.0.0", "main": "index.js",
            "scripts": {"start": "expo start", "android": "expo start --android", "ios": "expo start --ios",
                        "web": "expo start --web", "export:web": "expo export --platform web"},
            "dependencies": dict(DEPENDENCIES), "private": True}
    return json.dumps(data, indent=2) + "\n"


def app_json(name: str, slug: str, orientation: str = "portrait") -> str:
    data = {"expo": {"name": name, "slug": slug, "version": "1.0.0", "orientation": orientation,
                     "userInterfaceStyle": "light",
                     "android": {"package": "org.radide." + re.sub(r"[^a-z0-9]", "", slug.lower()) or "app"},
                     "web": {"bundler": "metro", "output": "single"}}}
    return json.dumps(data, indent=2) + "\n"


def slug_of(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name)
    s = re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-").lower()
    return s or "rad-app"


