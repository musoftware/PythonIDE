"""React Native (Expo) code generation: .form -> JSX screen (CONTRACTS 10.1, optional item).

Files of an Expo project (folder = the Expo project root):
    <Form>.jsx            user code: ``export default class <Form> extends <Form>Designer`` with VB-style handlers
                          (``btnGo_Click(e) { this.lblOut.Text = `Hi ${this.txtName.Text}`; }``)
    <Form>_designer.jsx   AUTO-GENERATED: ``class <Form>Designer extends RadForm`` - the controls (objects with
                          VB-like properties: Text, Visible, Enabled, Checked, Value, Items, SelectedIndex ...;
                          setting one redraws the screen) and render() (JSX)
    App.js                AUTO-GENERATED: NavigationContainer + native stack, one screen per form
    radapp.js             runtime (rn_runtime.RADAPP_JS)
    index.js, app.json, package.json, babel.config.js (written once)
Absolute placement (with Anchor) is the default; Column / Row / Stack / Card containers lay out their children
like React Native's flexbox does.
"""
