def icon_names() -> list[str]:
    return sorted(ICONS)


def resolve(name: str, fallback: str = "") -> str:
    """'Profile' -> 'person', 'search' -> 'search', unknown -> *fallback*."""
    key = str(name or "").strip().lower().replace(" ", "_")
    if key in ICONS:
        return key
    alias = ALIASES.get(key.replace("_", " "))
    return alias if alias else fallback


_RENDERERS: dict[tuple[str, str], object] = {}


def _renderer(name: str, color: str):
    from PyQt6.QtCore import QByteArray
    from PyQt6.QtSvg import QSvgRenderer
    key = (name, color)
    r = _RENDERERS.get(key)
    if r is None:
        d = ICONS.get(name) or ICONS["circle"]
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'
               f'<path fill="{color}" d="{d}"/></svg>')
        r = QSvgRenderer(QByteArray(svg.encode()))
        _RENDERERS[key] = r
    return r


def draw_icon(p, rect, name: str, color: str = "#1D1B20") -> None:
    """Paint icon *name* (Material name, see ICONS) scaled into *rect* (QRectF / QRect)."""
    from PyQt6.QtCore import QRectF
    _renderer(resolve(name, "circle"), color).render(p, QRectF(rect))


def icon_pixmap(name: str, size: int = 20, color: str = "#1D1B20"):
    from PyQt6.QtCore import QRectF, Qt
    from PyQt6.QtGui import QPainter, QPixmap
    pm = QPixmap(size, size)
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    draw_icon(p, QRectF(0, 0, size, size), name, color)
    p.end()
    return pm


