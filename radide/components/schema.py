_JSON_TYPES = {"string": str, "integer": int, "number": (int, float), "boolean": bool, "object": dict,
               "array": list, "null": type(None)}


def _type_ok(value, t) -> bool:
    if isinstance(t, list):
        return any(_type_ok(value, x) for x in t)
    if t in ("integer", "number") and isinstance(value, bool):
        return False
    return isinstance(value, _JSON_TYPES.get(t, object))


def validate(instance, schema: dict = SCHEMA, path: str = "") -> list[str]:
    """Errors of *instance* against *schema* (a subset of JSON Schema), e.g. ``properties[2].name: ...``."""
    errs: list[str] = []
    where = path or "(root)"
    t = schema.get("type")
    if t is not None and not _type_ok(instance, t):
        return [f"{where}: must be {t if isinstance(t, str) else ' or '.join(t)}"]
    if "enum" in schema and instance not in schema["enum"]:
        errs.append(f"{where}: must be one of {', '.join(map(str, schema['enum']))}")
    if isinstance(instance, str):
        if "pattern" in schema and not re.search(schema["pattern"], instance):
            errs.append(f"{where}: {instance!r} does not match {schema['pattern']}")
        if len(instance) < schema.get("minLength", 0):
            errs.append(f"{where}: too short")
    if isinstance(instance, (int, float)) and not isinstance(instance, bool):
        if "minimum" in schema and instance < schema["minimum"]:
            errs.append(f"{where}: must be >= {schema['minimum']}")
        if "maximum" in schema and instance > schema["maximum"]:
            errs.append(f"{where}: must be <= {schema['maximum']}")
    if isinstance(instance, list):
        if len(instance) < schema.get("minItems", 0):
            errs.append(f"{where}: needs at least {schema['minItems']} items")
        if "maxItems" in schema and len(instance) > schema["maxItems"]:
            errs.append(f"{where}: at most {schema['maxItems']} items")
        if isinstance(schema.get("items"), dict):
            for i, item in enumerate(instance):
                errs += validate(item, schema["items"], f"{path}[{i}]")
    if isinstance(instance, dict):
        for key in schema.get("required", []):
            if key not in instance:
                errs.append(f"{where}: '{key}' is required")
        props = schema.get("properties", {})
        extra = schema.get("additionalProperties", True)
        for key, value in instance.items():
            sub = f"{path}.{key}" if path else key
            if key in props:
                errs += validate(value, props[key], sub)
            elif key.startswith(("x-", "$")):
                continue
            elif extra is False:
                errs.append(f"{where}: unknown key '{key}'")
            elif isinstance(extra, dict):
                errs += validate(value, extra, sub)
    return errs


def _inside(folder: Path, rel: str) -> bool:
    p = Path(rel)
    return not p.is_absolute() and ".." not in p.parts


def validate_manifest(data, folder: Path | None = None, api: str = "1.0") -> list[str]:
    """Schema errors + semantic errors of a component manifest (empty = valid)."""
    errs = validate(data)
    if not isinstance(data, dict):
        return errs
    names = set()
    for i, p in enumerate(data.get("properties") or []):
        if not isinstance(p, dict) or not isinstance(p.get("name"), str):
            continue
        where = f"properties[{i}] ({p['name']})"
        if p["name"].lower() in names:
            errs.append(f"{where}: duplicate property name")
        names.add(p["name"].lower())
        kind = p.get("type")
        if isinstance(kind, str) and not proptypes.is_known(kind):
            errs.append(f"{where}: unknown type {kind!r} (known: {', '.join(proptypes.KINDS)})")
            continue
        nk = proptypes.normalize(kind)
        if nk in ("enum", "flags") and not p.get("choices") and not p.get("choicesFrom") and \
                str(kind).lower() != "dock":
            errs.append(f"{where}: an {nk} property needs 'choices'")
        if "default" in p:
            if not proptypes.check_default(nk, p["default"]):
                errs.append(f"{where}: default {p['default']!r} does not fit type {kind}")
            elif nk == "enum" and p.get("choices") and p["default"] not in p["choices"]:
                errs.append(f"{where}: default {p['default']!r} is not one of the choices")
        if nk == "custom" and not p.get("editor"):
            errs.append(f"{where}: a custom property needs an 'editor' id")
    events = set()
    for i, e in enumerate(data.get("events") or []):
        if isinstance(e, dict) and isinstance(e.get("name"), str):
            if e["name"] in events:
                errs.append(f"events[{i}]: duplicate event {e['name']}")
            events.add(e["name"])
    de = data.get("defaultEvent")
    if isinstance(de, str) and de not in events and not (data.get("commonEvents", True) and de in (
            "Click", "DoubleClick", "MouseDown", "MouseUp", "MouseMove", "KeyDown", "KeyUp", "KeyPress",
            "GotFocus", "LostFocus", "MouseEnter", "MouseLeave", "MouseWheel")):
        errs.append(f"defaultEvent {de!r} is not one of the events")
    files = [(k, data.get(k)) for k in ("icon", "designer", "editors", "help") if isinstance(data.get(k), str)]
    for tid, tgt in (data.get("targets") or {}).items() if isinstance(data.get("targets"), dict) else ():
        if not re.match(TARGET, str(tid)):
            errs.append(f"targets: bad target id {tid!r} (use the language plugin id, e.g. python-tk)")
        if isinstance(tgt, dict):
            if tgt.get("file"):
                files.append((f"targets.{tid}.file", tgt["file"]))
                if not tgt.get("class"):
                    errs.append(f"targets.{tid}: 'class' is required with 'file'")
            for j, f in enumerate(tgt.get("files") or []):
                files.append((f"targets.{tid}.files[{j}]", f))
            if tgt.get("emit"):
                files.append((f"targets.{tid}.emit", tgt["emit"]))
            tpl = tgt.get("template")
            if isinstance(tpl, dict):
                for j, f in enumerate(tpl.get("files") or []):
                    files.append((f"targets.{tid}.template.files[{j}]", f))
    for key, rel in files:
        if not isinstance(rel, str):
            continue
        if not _inside(Path("."), rel):
            errs.append(f"{key}: must be a relative path inside the package")
        elif folder is not None and not (Path(folder) / rel).is_file():
            errs.append(f"{key}: file not found: {rel}")
    req = (data.get("requires") or {}).get("radide") if isinstance(data.get("requires"), dict) else None
    if isinstance(req, str):
        m = re.match(r"\s*>=?\s*(\d+)(?:\.(\d+))?", req)
        if m:
            need = (int(m.group(1)), int(m.group(2) or 0))
            have = tuple(int(x) for x in api.split(".")[:2])
            if need > have:
                errs.append(f"needs RAD IDE component API {req} (this IDE has {api})")
    return errs


def version_key(v: str) -> tuple:
    """'1.10.0-beta' -> sortable key (pre-releases sort before the release)."""
    m = re.match(r"^(\d+(?:\.\d+)*)(?:[-+](.*))?$", str(v or "0"))
    if not m:
        return ((0,), 0, "")
    nums = tuple(int(x) for x in m.group(1).split("."))
    nums = nums + (0,) * (4 - len(nums))
    return (nums, 0 if m.group(2) else 1, m.group(2) or "")


def schema_document() -> dict:
    """The schema as published in docs/component.schema.json (``$schema`` allowed in manifests so editors
    such as VS Code validate and complete component.json)."""
    import copy
    doc = copy.deepcopy(SCHEMA)
    doc["properties"]["$schema"] = {"type": "string"}
    return doc


