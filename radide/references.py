"""References between the projects of a solution (docs/CONTRACTS.md section 7.2).

A project that references a library calls the library's public functions as code of its own
language. The **library's** plugin lists them (``plugin.exported_functions(path, text)``); the
**consumer's** plugin writes proxy files into the consumer folder
(``plugin.reference_proxy(lib, functions)``) whose functions forward to RAD Hub
(``radcall("<module>.<name>", args...)``). Which proxy files were written is remembered in the
consumer's project.radproj (``"reference_files": {"MathLib": ["MathLib.py"]}``) so that stale
ones are removed when a reference is removed or the library's functions change.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

PROXY_MARK = "AUTO-GENERATED by RAD IDE"


@dataclass
class ExportedFunction:
    name: str                 # function name as written in the library
    params: list[str] = field(default_factory=list)   # parameter names (no types needed)
    module: str = ""          # file stem that defines it (RAD Hub module name)
    doc: str = ""             # first doc line / comment, shown in IntelliSense
    kind: str = "function"    # "function" | "sub" (no return value)

    @property
    def target(self) -> str:
        """The RAD Hub call name: "<module>.<name>"."""
        return f"{self.module}.{self.name}"


def proxy_header(lib: str) -> str:
    """Text every generated proxy file must contain (put it in a comment)."""
    return f"{PROXY_MARK} (reference to {lib}) - do not edit, regenerated on build"


def is_proxy_file(path: Path, lib: str | None = None) -> bool:
    """True when *path* is a proxy file generated by update_proxies (looks at the first 2 KB)."""
    try:
        with open(path, "rb") as f:
            head = f.read(2048).decode("utf-8", errors="replace")
    except OSError:
        return False
    if lib is None:
        return PROXY_MARK in head
    return f"{PROXY_MARK} (reference to {lib})" in head


# ============================================================================ library side
def code_files(project) -> list[Path]:
    """User code files of a project: modules and form code files (no designer files, no proxies)."""
    from .languages import plugin_for_form
    out: list[Path] = []
    seen: set[str] = set()
    proxies = {f.lower() for files in project.reference_files.values() for f in files}

    def add(name: str):
        p = Path(project.folder) / name
        if name.lower() in seen or name.lower() in proxies or not p.is_file():
            return
        seen.add(name.lower())
        out.append(p)

    for m in project.modules:
        add(m)
    for form in project.forms:
        try:
            add(plugin_for_form(project, form).code_file(form))
        except KeyError:
            continue
    return [p for p in out if not is_proxy_file(p)]


def exports_of(project, log=None) -> list[ExportedFunction]:
    """Public functions of a (library) project, found by each code file's language plugin.
    The first definition of a name wins (names are case-insensitively unique)."""
    from .languages import plugin_for_module
    out: list[ExportedFunction] = []
    seen: set[str] = set()
    for path in code_files(project):
        plugin = plugin_for_module(project, path.name)
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
            funcs = plugin.exported_functions(path, text) or []
        except Exception as e:  # noqa: BLE001 - one broken plugin/file must not stop the others
            if log is not None:
                log(f"*** {plugin.display_name}: cannot read the functions of {path.name}: {e}")
            continue
        for fn in funcs:
            if not fn.module:
                fn.module = path.stem
            if fn.name.lower() in seen:
                continue
            seen.add(fn.name.lower())
            out.append(fn)
    return out


# ============================================================================ consumer side
def _safe_rel(folder: Path, rel: str) -> Path | None:
    """*rel* inside *folder* (None when it would escape the folder)."""
    p = (folder / rel).resolve()
    try:
        p.relative_to(folder.resolve())
    except ValueError:
        return None
    return p


def update_proxies(solution, project, log=None) -> list[Path]:
    """Regenerate the proxy files of every reference of *project* (a Project or a name).

    Returns the files that were (re)written - files whose content did not change are not
    rewritten. Proxy files of references that were removed (or that the consumer plugin no longer
    generates) are deleted, but only if they still carry the AUTO-GENERATED mark. The project's
    ``reference_files`` is updated and project.radproj saved when it changed."""
    from .languages import get_plugin
    if isinstance(project, str):
        project = solution.project(project)
        if project is None:
            return []
    folder = Path(project.folder)
    try:
        plugin = get_plugin(project.language)
    except KeyError:
        return []
    written: list[Path] = []
    new_files: dict[str, list[str]] = {}
    for ref in project.references:
        lib = solution.project(ref)
        if lib is None:
            if log is not None:
                log(f"*** {project.name}: referenced project '{ref}' is not in the solution")
            if ref in project.reference_files:          # keep its proxies until it comes back
                new_files[ref] = list(project.reference_files[ref])
            continue
        lib_name = solution.name_of(lib)
        funcs = exports_of(lib, log)
        try:
            files = plugin.reference_proxy(lib_name, funcs) or {}
        except Exception as e:  # noqa: BLE001
            if log is not None:
                log(f"*** {plugin.display_name}: cannot generate the reference to {lib_name}: {e}")
            if ref in project.reference_files:
                new_files[ref] = list(project.reference_files[ref])
            continue
        names: list[str] = []
        for rel, content in files.items():
            target = _safe_rel(folder, rel)
            if target is None:
                if log is not None:
                    log(f"*** {plugin.display_name}: proxy path {rel!r} is outside the project")
                continue
            names.append(str(Path(rel).as_posix()))
            try:
                old = target.read_text(encoding="utf-8") if target.exists() else None
            except OSError:
                old = None
            if old != content:
                if target.exists() and old is not None and not is_proxy_file(target):
                    if log is not None:
                        log(f"*** {project.name}: {rel} exists and is not a generated proxy - not replaced")
                    names.pop()
                    continue
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
                written.append(target)
        if names:
            new_files[ref] = names
    # stale proxies
    keep = {n.lower() for files in new_files.values() for n in files}
    for files in project.reference_files.values():
        for rel in files:
            if rel.lower() in keep:
                continue
            target = _safe_rel(folder, rel)
            if target is not None and target.is_file() and is_proxy_file(target):
                try:
                    target.unlink()
                except OSError as e:
                    if log is not None:
                        log(f"*** cannot delete the old proxy {rel}: {e}")
    if new_files != project.reference_files:
        project.reference_files = new_files
        project.save()
    return written


def refresh_all(solution, log=None) -> dict[str, list[Path]]:
    """update_proxies for every project of the solution (libraries first).
    Returns {project name: written files} for the projects where something was written."""
    try:
        projects = solution.build_order()
    except ValueError:
        projects = solution.all_projects()
    out: dict[str, list[Path]] = {}
    for p in projects:
        if not p.references and not p.reference_files:
            continue
        files = update_proxies(solution, p, log)
        if files:
            out[solution.name_of(p)] = files
    return out
